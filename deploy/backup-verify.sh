#!/bin/sh
#
# Проверка копий на сервере — та, что возможна БЕЗ закрытого ключа.
#
# Запускается таймером (deploy/systemd/grafik-backup-verify.timer) раз в
# сутки после копирования.
#
# --- Что здесь можно проверить, а что нельзя --------------------------------
#
# Закрытого ключа на сервере нет намеренно (см. `backup.sh`), поэтому
# расшифровать и развернуть копию здесь нечем. Остаётся то, что ломается
# чаще всего и молча:
#
#   * копии вообще нет — таймер не сработал, диск кончился, пароль базы
#     сменили, а в api.env забыли;
#   * копия старая — последняя удачная была неделю назад, а с тех пор
#     каждая ночь падала, и никто не смотрел;
#   * копия не копия — пустой или обрезанный файл;
#   * файл не шифрованный — ушла бы наружу незашифрованная база.
#
# Настоящее восстановление проверяется отдельно и на другой машине:
# `deploy/restore-check.sh`, раз в месяц, руками. Так и должно быть: только
# на той машине есть закрытый ключ.
#
#   Использование: backup-verify.sh

set -eu

DIR=${GRAFIK_BACKUP_DIR:-/var/backups/grafik13}

# Сколько часов копия имеет право быть старой. 26, а не 24: таймер
# запускается раз в сутки с разбросом, и ровно сутки давали бы ложную
# тревогу через ночь.
MAX_AGE_HOURS=${GRAFIK_BACKUP_MAX_AGE_HOURS:-26}
MIN_BYTES=${GRAFIK_BACKUP_MIN_BYTES:-4096}

say() { printf '%s %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"; }
die() { say "ОШИБКА: $*" >&2; exit 1; }

[ -d "$DIR" ] || die "нет каталога копий: $DIR"

# Самая свежая копия. `ls -t` здесь уместен: имена свои, без пробелов и
# переводов строк — их задаёт `backup.sh`.
LAST=$(ls -1t "$DIR"/grafik13-*.dump.age 2> /dev/null | head -n 1 || true)
[ -n "$LAST" ] || die "в каталоге нет ни одной копии: $DIR"

AGE_SECONDS=$(( $(date +%s) - $(stat -c %Y "$LAST") ))
AGE_HOURS=$(( AGE_SECONDS / 3600 ))
[ "$AGE_HOURS" -le "$MAX_AGE_HOURS" ] \
  || die "последняя копия старше $MAX_AGE_HOURS ч: $LAST ($AGE_HOURS ч)"

SIZE=$(stat -c %s "$LAST")
[ "$SIZE" -ge "$MIN_BYTES" ] || die "копия мала: $LAST ($SIZE байт)"

# Заголовок age: первая строка файла — «age-encryption.org/v1». Проверка
# грубая, зато отвечает на вопрос, который дороже всех: не лежит ли тут
# незашифрованная выгрузка базы.
HEAD=$(head -c 21 "$LAST")
[ "$HEAD" = "age-encryption.org/v1" ] || die "это не шифрованный age-файл: $LAST"

# Незашифрованных выгрузок в каталоге быть не должно вовсе — ни забытых
# руками, ни оставшихся от прерванной копии.
STRAY=$(find "$DIR" -maxdepth 1 -type f ! -name '*.age' | wc -l)
[ "$STRAY" -eq 0 ] || die "в каталоге $STRAY файл(ов) без шифрования"

COUNT=$(find "$DIR" -maxdepth 1 -type f -name 'grafik13-*.dump.age' | wc -l)
say "копии в порядке: последняя $LAST, $AGE_HOURS ч, $SIZE байт, всего $COUNT"
