#!/usr/bin/env bash
#
# Резервная копия базы: выгрузка, шифрование, срок хранения.
#
# Запускается таймером systemd (deploy/systemd/grafik-backup.timer) на самом
# сервере. Руками — так же: `/opt/grafik13/backup.sh`.
#
# bash, а не sh, из-за одной настройки: `pipefail`. Без неё падение
# `pg_dump` в середине конвейера оставило бы «успешно зашифрованный»
# обрубок, и узналось бы об этом при восстановлении.
#
# --- Почему шифруется открытым ключом ---------------------------------------
#
# Копия базы — это все адреса почты, хэши и зашифрованные блобы людей.
# Лежит она на том же сервере (плюс там, куда её унесут), и если шифровать
# её паролем, пароль придётся держать рядом: у того, кто получил сервер,
# будет и копия, и ключ к ней.
#
# Поэтому `age` с ОТКРЫТЫМ ключом: на сервере лежит только он, расшифровать
# им нельзя. Закрытый ключ хранит владелец вне сервера. Взломавший сервер
# получит доступ к живой базе — с этим ничего не сделать, — но не к архиву
# за месяц.
#
# Обратная сторона честная: потерял закрытый ключ — потерял все копии.
# Поэтому порядок восстановления описан в deploy/README.md и проверяется
# `deploy/restore-check.sh` не реже раза в месяц.
#
# --- Почему не непрерывное архивирование ------------------------------------
#
# База маленькая (десятки мегабайт), а окно потери в сутки допустимо:
# данные человека живут ещё и у него в браузере, сервер — копия, а не
# источник истины. Непрерывное архивирование (WAL) стоило бы дороже, чем
# стоит потеря суток, и его тоже надо было бы проверять.
#
#   Использование: backup.sh
#   Переменные:    GRAFIK_BACKUP_DIR, GRAFIK_BACKUP_RECIPIENTS,
#                  GRAFIK_COMPOSE, GRAFIK_BACKUP_KEEP_DAYS

set -euo pipefail

# --- Настройки (у всех есть запасное значение) ------------------------------

# Куда класть копии.
DIR=${GRAFIK_BACKUP_DIR:-/var/backups/grafik13}

# Файл с получателями age: открытые ключи, по одному на строку.
RECIPIENTS=${GRAFIK_BACKUP_RECIPIENTS:-/etc/grafik13/backup-recipients.txt}

# Боевой состав — из него берётся запущенный контейнер базы.
COMPOSE=${GRAFIK_COMPOSE:-/opt/grafik13/compose.prod.yml}

# Сколько дней хранить. Тридцать — то, что обещано в карте данных
# (docs/legal/data-map.md) и в политике: удаление аккаунта догоняет копии в
# течение месяца, и держать их дольше обещанного нельзя.
KEEP=${GRAFIK_BACKUP_KEEP_DAYS:-30}

# Ниже этого размера копия заведомо не копия, а огарок.
MIN_BYTES=${GRAFIK_BACKUP_MIN_BYTES:-4096}

say() { printf '%s %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"; }
die() { say "ОШИБКА: $*" >&2; exit 1; }

# --- Проверки до работы -----------------------------------------------------

command -v age > /dev/null || die "нет age: apt install age"
command -v docker > /dev/null || die "нет docker"
[ -s "$RECIPIENTS" ] || die "нет получателей или файл пуст: $RECIPIENTS"
[ -f "$COMPOSE" ] || die "нет состава: $COMPOSE"

install -d -m 700 "$DIR"

NAME="grafik13-$(date -u +%Y%m%d-%H%M%S).dump.age"
TARGET="$DIR/$NAME"
DRAFT="$TARGET.part"

# Черновик убирается при любом выходе: прерванная копия не должна остаться
# под именем готовой — её бы однажды попытались развернуть.
trap 'rm -f "$DRAFT"' EXIT

# --- Выгрузка ---------------------------------------------------------------

say "выгружаю базу в $NAME"

# `exec -T` — в живой контейнер и без выделения терминала: иначе в поток
# попадут управляющие последовательности и копия окажется битой.
#
# `--format=custom` — свой формат pg_dump: сжат, восстанавливается
# выборочно (`pg_restore`) и не зависит от порядка таблиц, в отличие от
# текстового.
docker compose -f "$COMPOSE" exec -T postgres \
    pg_dump --username=grafik --dbname=grafik --format=custom --compress=6 \
  | age --encrypt --recipients-file "$RECIPIENTS" --output "$DRAFT"

SIZE=$(stat -c %s "$DRAFT")
[ "$SIZE" -ge "$MIN_BYTES" ] || die "копия подозрительно мала: $SIZE байт"

# Готовое имя появляется последним действием: всё, что лежит в каталоге без
# `.part`, — заведомо целая копия.
mv -- "$DRAFT" "$TARGET"
chmod 400 "$TARGET"
trap - EXIT

say "готово: $TARGET ($SIZE байт)"

# --- Срок хранения ----------------------------------------------------------

# Удаляются только свои файлы и только по своему шаблону: каталог мог
# оказаться общим, и чужое из него стирать нельзя.
GONE=$(find "$DIR" -maxdepth 1 -type f -name 'grafik13-*.dump.age' \
         -mtime "+$KEEP" -print -delete | wc -l)

say "старше $KEEP дней удалено: $GONE"

# Остаток показывается в журнале намеренно: по строке в `systemctl status`
# видно, что копии есть и сколько их, без захода в каталог.
LEFT=$(find "$DIR" -maxdepth 1 -type f -name 'grafik13-*.dump.age' | wc -l)
say "копий в каталоге: $LEFT"
