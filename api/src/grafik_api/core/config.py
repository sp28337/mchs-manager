"""Настройки приложения.

Один источник: переменные окружения с префиксом `GRAFIK_`. Префикс не
украшение — в контейнере рядом живут переменные postgres, uvicorn и самого
Python, и `ENV` или `DEBUG` без префикса однажды совпадут с чужими.

Значения по умолчанию здесь — только безопасные: такие, при которых
приложение поднимется на машине разработчика и не включит ничего лишнего в
бою. Секретов среди них нет и не будет: пароль базы, ключи и перец
приходят из окружения (шаг 13), иначе они попадут в git.
"""

from __future__ import annotations

import ipaddress
from functools import lru_cache
from typing import Literal

from pydantic import Field, SecretStr, field_validator, model_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

#: Разобранный перечень доверенных прокси: адреса или сети.
Networks = tuple[ipaddress.IPv4Network | ipaddress.IPv6Network, ...]

Env = Literal["dev", "test", "prod"]

# Уровни ровно те, что понимает `logging`. Перечислением, а не строкой:
# опечатка в переменной окружения должна падать при старте с внятным
# сообщением, а не глотать половину журнала молча.
LogLevel = Literal["DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"]


class Settings(BaseSettings):
    """Что приложение знает о себе и об окружении."""

    model_config = SettingsConfigDict(
        env_prefix="GRAFIK_",
        env_file=".env",
        env_file_encoding="utf-8",
        # Лишняя переменная в окружении — не повод не запуститься: рядом с
        # нами в контейнере живёт чужое окружение целиком.
        extra="ignore",
    )

    env: Env = "dev"

    log_level: LogLevel = "INFO"

    # Строка подключения к базе. Значение по умолчанию ведёт на сервис из
    # docker-compose.yml: так `docker compose up` работает без .env, а
    # пароль `grafik` в нём — заведомо разработческий (см. комментарий в
    # самом compose-файле).
    database_url: str = "postgresql+psycopg://grafik:grafik@postgres:5432/grafik"

    # --- Боевой запуск ---------------------------------------------------

    #: Сколько рабочих процессов поднимает gunicorn (шаг 13).
    #:
    #: Единица — не экономия, а условие работы счётчика обращений: он
    #: живёт в памяти процесса, и при нескольких процессах заявленный
    #: предел пришлось бы делить между ними (см. `core/limits.py`).
    #: Нагрузка у приложения почти целиком на ожидании базы, а оно
    #: асинхронное: один процесс справляется с ней весь.
    workers: int = Field(default=1, ge=1)

    #: Кому верить, когда он говорит, что обратился не он, а другой
    #: (`X-Forwarded-For`). Адреса или сети через запятую.
    #:
    #: Петля доверена всегда — её не подделать снаружи. В бою сюда
    #: добавляется адрес шлюза docker-сети: nginx стоит на хозяине
    #: машины, и контейнер видит его обращения не с `127.0.0.1`, а со
    #: шлюза моста.
    trusted_proxies: str = ""

    # --- Секреты ---------------------------------------------------------
    #
    # Значения по умолчанию заведомо разработческие и в бою запрещены
    # (см. проверку ниже). Хранить их здесь нельзя: файл в git.

    #: Перец для хэша проверочного значения пароля. Лежит в окружении, а не
    #: в базе: украденной базы не должно хватать для подбора пароля.
    pepper: SecretStr = SecretStr("перец-только-для-разработки")

    #: Ключ подписи access-токенов (HS256).
    jwt_secret: SecretStr = SecretStr("подпись-только-для-разработки")

    # --- Почта -----------------------------------------------------------

    #: Куда сдавать письма. Пусто — не отправлять вовсе (письмо только
    #: отметится в журнале): так удобно поднимать приложение там, где
    #: почты нет, и так ведут себя тесты.
    smtp_host: str = "mailpit"
    smtp_port: int = 1025
    #: STARTTLS. В разработке почтовая ловушка его не просит, в бою —
    #: обязателен, если отправщик не на этой же машине.
    smtp_tls: bool = False
    smtp_user: str = ""
    smtp_password: SecretStr = SecretStr("")

    #: Обратный адрес. В нём видно, кто пишет, и что отвечать некуда.
    mail_from: str = "График 1 3 <noreply@grafik13.ru>"

    #: Адрес сайта — из него собираются ссылки в письмах.
    public_url: str = "https://grafik13.ru"

    # --- Сроки -----------------------------------------------------------

    #: Жизнь access-токена, секунды. Он живёт в памяти вкладки, и 15 минут —
    #: разумный предел для украденного токена.
    access_ttl: int = 15 * 60

    #: Жизнь refresh-токена, дни. Каждое обновление выдаёт новый.
    refresh_ttl_days: int = 30

    #: Жизнь одноразовой ссылки из письма, часы. Сутки — чтобы письмо
    #: успели прочитать вечером, а не в ту же минуту.
    link_ttl_hours: int = 24

    @field_validator("log_level", mode="before")
    @classmethod
    def _upper(cls, value: object) -> object:
        """`debug` в переменной окружения — это тоже DEBUG.

        Регистр здесь не несёт смысла, а спотыкаться об него при отладке в
        три часа ночи — обидно.
        """
        return value.upper() if isinstance(value, str) else value

    @model_validator(mode="after")
    def _секреты_в_бою_обязательны(self) -> Settings:
        """В прод нельзя уехать с разработческим секретом.

        Проверка при старте, а не при первом входе: приложение, поднятое с
        перцем из репозитория, лучше не поднять вовсе — иначе об этом
        узнают по утечке.
        """
        if self.env != "prod":
            return self

        слабые = [
            имя
            for имя, значение in (
                ("GRAFIK_PEPPER", self.pepper),
                ("GRAFIK_JWT_SECRET", self.jwt_secret),
            )
            if "разработки" in значение.get_secret_value()
            or len(значение.get_secret_value()) < 32
        ]

        if слабые:
            raise ValueError(
                "в боевом окружении нужны свои длинные значения: " + ", ".join(слабые)
            )

        return self

    @model_validator(mode="after")
    def _прокси_разбираются(self) -> Settings:
        """Проверить перечень доверенных прокси при старте.

        Опечатка в адресе шлюза не должна выясняться в тот момент, когда
        в журнале понадобился настоящий адрес клиента.
        """
        # Вызовом, а не обращением к свойству: результат не нужен,
        # нужен разбор — он и падает.
        trusted_networks(self.trusted_proxies)
        return self

    @property
    def trusted_networks(self) -> Networks:
        """Доверенные прокси сетями.

        Отдельный адрес — это сеть из одного адреса, поэтому всё
        приводится к сетям: сравнение одно, а в настройке можно написать
        и `172.28.0.1`, и `172.28.0.0/24`.
        """
        return trusted_networks(self.trusted_proxies)

    @property
    def docs_enabled(self) -> bool:
        """Отдавать ли /docs и /openapi.json.

        В бою — нет. Это не «безопасность через неизвестность»: закрытые
        ручки остаются закрытыми, но публиковать полное описание схем,
        лимитов и кодов ошибок без нужды незачем, а черновик описания и так
        лежит в репозитории.
        """
        return self.env != "prod"


@lru_cache(maxsize=8)
def trusted_networks(перечень: str) -> Networks:
    """Разобрать перечень доверенных прокси.

    Кэш — потому что вызывается на каждый запрос, а строка настройки за
    время жизни процесса не меняется. Размер кэша мал осознанно: разных
    строк в процессе бывает одна, в тестах — несколько.
    """
    сети: list[ipaddress.IPv4Network | ipaddress.IPv6Network] = []

    for кусок in перечень.split(","):
        кусок = кусок.strip()
        if not кусок:
            continue
        try:
            # `strict=False` — чтобы `172.28.0.1/24` не было ошибкой:
            # человек имел в виду сеть, а не придирку к битам.
            сети.append(ipaddress.ip_network(кусок, strict=False))
        except ValueError as error:
            raise ValueError(
                f"GRAFIK_TRUSTED_PROXIES: {кусок!r} — не адрес и не сеть"
            ) from error

    return tuple(сети)


@lru_cache
def get_settings() -> Settings:
    """Настройки процесса.

    Кэш — чтобы окружение читалось один раз, а не на каждый запрос, и чтобы
    объект был один и тот же: по нему сравнивают, а не копируют. В тестах
    кэш сбрасывается через `get_settings.cache_clear()`.
    """
    return Settings()
