"""Контекст запроса: то, что должно попадать в каждую запись журнала.

Почему `ContextVar`, а не глобальная переменная: запросов одновременно
много, они обрабатываются вперемешку, и обычная переменная перезатиралась бы
чужим значением. `ContextVar` в асинхронном коде отдаёт каждой задаче своё
значение — именно для этого он и сделан.

Почему отдельный модуль, а не внутри `logging.py`: значение ставит
прослойка, идентификатор пользователя будет ставить проверка токена (шаг 7),
а читает фильтр журналирования. Общая зависимость всех трёх — вот она, и
тянуть ради неё `logging` в каждое место незачем.

В журналах человек — это `user_id` (uuid) и только он: ни адреса почты, ни
чего-либо ещё опознающего там быть не должно (раздел 9 контракта).
"""

from __future__ import annotations

from contextvars import ContextVar

# «-» вместо None: в журнале поле всегда на месте, и запрос «покажи записи,
# у которых нет request_id» не превращается в поиск отсутствующего ключа.
NO_VALUE = "-"

request_id_var: ContextVar[str] = ContextVar("request_id", default=NO_VALUE)
user_id_var: ContextVar[str] = ContextVar("user_id", default=NO_VALUE)


# Ставят значение те, кто знает, когда оно появляется: прослойка —
# идентификатор запроса, проверка токена — идентификатор пользователя
# (шаг 7). Оба обязаны вернуть контекст на место методом `reset` с меткой,
# которую отдал `set`: контекст живёт дольше запроса, и иначе следующий
# запрос в той же задаче унаследовал бы чужой идентификатор.
#
# Обёрток над `set` здесь нет: однострочник, прячущий `set`, только мешает
# увидеть, что метку надо сохранить и вернуть.


def get_request_id() -> str:
    """Идентификатор текущего запроса или «-», если его нет."""
    return request_id_var.get()


def get_user_id() -> str:
    """Идентификатор текущего пользователя или «-», если он не опознан."""
    return user_id_var.get()
