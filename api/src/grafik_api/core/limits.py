"""Лимиты и квоты из раздела 7 контракта — и счётчик обращений.

Числа собраны в одном месте не для красоты: они обещаны в контракте, на
них рассчитывает фронт, и разъехаться они не должны.
"""

from __future__ import annotations

import time
from collections import deque
from collections.abc import Callable
from dataclasses import dataclass
from math import ceil

#: Источник времени. Подменяется в тестах, чтобы не ждать окно вживую.
Clock = Callable[[], float]

# --- Размеры ---------------------------------------------------------------

#: Размер одного блоба. Год смен с отпусками и заметками — 50–200 КиБ.
MAX_BLOB_BYTES = 1024 * 1024

#: Элементов в одной отправке: запрос обозрим, откат дешёв.
MAX_ITEMS_PER_PUSH = 50

#: Тело запроса целиком — отсечка до разбора JSON.
MAX_BODY_BYTES = 8 * 1024 * 1024

#: Элементов на аккаунт: профилей у человека единицы, 200 — с запасом.
MAX_ITEMS_PER_ACCOUNT = 200

#: Объём аккаунта с историей. Выше — разговор с человеком, а не рост молчком.
MAX_ACCOUNT_BYTES = 50 * 1024 * 1024

#: Страница выборки изменений.
PAGE_SIZE = 50


# --- Частота ---------------------------------------------------------------


@dataclass(frozen=True)
class Limit:
    """Сколько обращений за сколько секунд."""

    requests: int
    seconds: int


#: `POST /sync` — на аккаунт.
SYNC = Limit(requests=60, seconds=60)

#: `POST /auth/login` — на пару (аккаунт, адрес IP). Защита от перебора.
LOGIN = Limit(requests=10, seconds=15 * 60)

#: `POST /auth/register` — на адрес IP.
REGISTER = Limit(requests=5, seconds=60 * 60)

#: `POST /auth/params` — на адрес IP. Защита от перебора адресов.
PARAMS = Limit(requests=30, seconds=60)

#: `POST /auth/recover/start` — на адрес IP. Письмо стоит денег и нервов
#: получателя: завалить чужой ящик письмами о восстановлении нельзя.
RECOVER = Limit(requests=5, seconds=60 * 60)

#: `GET /account/export` — на аккаунт. Выгрузка тяжёлая: это все блобы
#: аккаунта в одном ответе.
EXPORT = Limit(requests=10, seconds=60 * 60)

#: `POST /account/password` и `DELETE /account` — на аккаунт. Обе ручки
#: проверяют проверочное значение, то есть годятся для перебора.
SENSITIVE = Limit(requests=10, seconds=15 * 60)


class RateLimiter:
    """Скользящее окно в памяти процесса.

    Хранит время обращений по ключу и отвечает, сколько ждать, если их
    стало больше дозволенного.

    --- Почему счётчик остался в памяти ------------------------------------

    На шаге 6 здесь стояла оговорка: счётчик живёт в памяти процесса, и при
    нескольких рабочих процессах каждый считает своё, так что настоящий
    предел оказывается кратно выше заявленного; на шаге 13 он должен был
    переехать в общее хранилище. Шаг 13 пришёл — и решение оказалось
    другим, потому что общее хранилище стоит дороже, чем кажется.

    Общим хранилищем могли быть Redis или наша же база. Redis — это ещё
    один демон на том же маленьком сервере, ещё один пароль и ещё одно
    место, где может не хватить памяти. База — это запись на каждое
    обращение к защищённой ручке, причём запись, которая обязана пережить
    откат транзакции запроса (отказ ведь откатывает всё), то есть ещё одно
    соединение и ещё одна транзакция на запрос.

    Дешевле оказалось убрать причину: **рабочий процесс один**
    (`GRAFIK_WORKERS=1`, см. `gunicorn.conf.py`). Работа у приложения почти
    вся на ожидании базы, и асинхронный процесс справляется с ней весь;
    процессорного в запросе — один argon2id на вход, 19 МиБ и десятки
    миллисекунд.

    А если процессов всё-таки станет несколько — предел **делится** между
    ними (`процессов` в конструкторе). Делёж неточен в обратную сторону:
    каждому процессу достаётся своя доля, и человек, которому не повезло
    попасть дважды в один процесс, упрётся в предел раньше заявленного.
    Для защиты от перебора ошибаться надо именно в эту сторону.

    Память не растёт бесконтрольно: просроченные отметки выкидываются при
    обращении к ключу, а когда ключей становится слишком много — у всех
    сразу.
    """

    #: Сколько ключей держим, прежде чем пройтись по всем и выкинуть пустые.
    SWEEP_AT = 10_000

    def __init__(self, clock: Clock | None = None, процессов: int = 1) -> None:
        self._clock = clock or time.monotonic
        self._hits: dict[str, deque[float]] = {}
        self._процессов = max(1, процессов)

    def hit(self, key: str, limit: Limit) -> int | None:
        """Отметить обращение.

        Возвращает `None`, если можно, и число секунд до следующей попытки,
        если предел исчерпан. Отметка в последнем случае не ставится: иначе
        тот, кто долбит в закрытую дверь, продлевал бы себе запрет
        бесконечно.
        """
        limit = self._доля(limit)
        now = self._clock()
        edge = now - limit.seconds

        hits = self._hits.setdefault(key, deque())
        while hits and hits[0] <= edge:
            hits.popleft()

        if len(hits) >= limit.requests:
            # Освободится, когда самая старая отметка выйдет из окна.
            # Округление вверх: ответить «подожди 0 секунд» — значит
            # пригласить на повторную попытку, которая снова упрётся.
            return max(1, ceil(hits[0] + limit.seconds - now))

        hits.append(now)

        if len(self._hits) > self.SWEEP_AT:
            self._sweep(edge)

        return None

    def reset(self) -> None:
        """Забыть всё. Нужно тестам, в бою не вызывается."""
        self._hits.clear()

    def _доля(self, limit: Limit) -> Limit:
        """Часть предела, приходящаяся на этот процесс.

        Деление с округлением вниз, но не до нуля: предел в ноль обращений
        закрыл бы ручку совсем, а это не «строже», а «сломано».
        """
        if self._процессов == 1:
            return limit

        return Limit(
            requests=max(1, limit.requests // self._процессов),
            seconds=limit.seconds,
        )

    def _sweep(self, edge: float) -> None:
        for key in list(self._hits):
            hits = self._hits[key]
            while hits and hits[0] <= edge:
                hits.popleft()
            if not hits:
                del self._hits[key]
