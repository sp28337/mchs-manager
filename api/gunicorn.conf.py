"""Настройка боевого запуска: gunicorn + ASGI-воркер uvicorn.

Зачем вообще gunicorn, если uvicorn умеет сам: нужен **присматривающий**.
Мастер-процесс следит за рабочим, перезапускает его после падения, умеет
мягкую остановку по сигналу и мягкую перезагрузку по `SIGHUP` — то есть
всё то, что иначе пришлось бы поручать systemd и перезапускать уже
контейнер целиком.

Класс воркера — `uvicorn_worker.UvicornWorker`, а не `-k asgi`, появившийся
у gunicorn в версии 24: свой ASGI-воркер gunicorn пока помечает бетой, а
главное — в разработке приложение и так бежит под uvicorn. Один и тот же
разбор HTTP в разработке и в бою дороже, чем минус одна зависимость:
расхождение здесь означает ошибку, которая видна только в бою.

Файл читается самим gunicorn как обычный Python, поэтому настройки берутся
из того же `Settings`, что и у приложения, — второго места, где задано
число процессов, быть не должно. Имена, которых gunicorn не знает (всё с
подчёркиванием ниже), он молча пропускает.
"""

from __future__ import annotations

from grafik_api.core.config import get_settings
from grafik_api.core.logging import logging_config

_настройки = get_settings()

# --- Куда слушать -----------------------------------------------------------

# Все адреса контейнера, а не петля: обращение приходит снаружи его сетевого
# пространства — от nginx с хозяина машины. Наружу порт не смотрит: в
# `deploy/compose.prod.yml` он публикуется на `127.0.0.1` хозяина.
bind = "0.0.0.0:8000"

# Приложение можно не указывать в командной строке — значит, и не потерять
# при правке запуска.
wsgi_app = "grafik_api.main:app"

proc_name = "grafik-api"

# --- Процессы ---------------------------------------------------------------

workers = _настройки.workers
worker_class = "uvicorn_worker.UvicornWorker"

# Приложение импортируется мастером ДО ответвления рабочих. Две причины, и
# вторая важнее первой:
#
#   * память: разделяемые страницы кода и зависимостей не копируются на
#     каждый процесс, а на маленьком сервере это десятки мегабайт;
#   * ошибка импорта (опечатка в настройках, слабый секрет в бою) валит
#     мастер сразу и с внятным сообщением. Без предзагрузки она валила бы
#     рабочего, мастер поднимал бы нового, тот падал бы снова — и так до
#     порога перезапусков, то есть «сервис не работает, а почему, читайте в
#     журнале».
#
# Движок базы при импорте не создаётся (он в жизненном цикле), поэтому
# соединения между процессами не разделяются — ровно та ловушка, из-за
# которой предзагрузку обычно и боятся включать.
preload_app = True

# --- Сроки ------------------------------------------------------------------

# Запрос, который не ответил за полминуты, — это не медленный запрос, а
# зависший: самый тяжёлый у нас (выгрузка всех блобов) укладывается в
# секунды.
timeout = 30

# Столько мастер ждёт рабочего при мягкой остановке. Не меньше `timeout`:
# иначе мягкая остановка обрывает запросы, которым по сроку ещё можно
# отвечать.
graceful_timeout = 30

# Держать соединение открытым между запросами. nginx проксирует без
# keepalive по умолчанию, но если его включить (`proxy_http_version 1.1` +
# пустой `Connection`), пять секунд — то, что нужно: рукопожатие TLS уже
# сделано снаружи, а внутри экономится установка TCP.
keepalive = 5

# --- Перезапуск рабочих -----------------------------------------------------

# Перезапуск после N запросов — лекарство от медленных утечек памяти. При
# ОДНОМ рабочем процессе оно дороже болезни: пока новый поднимается, отвечать
# некому, и человек видит 502 на ровном месте. Поэтому включается только
# когда процессов несколько и смена одного незаметна.
#
# Разброс нужен, чтобы процессы не перезапустились все сразу: без него
# «каждые 2000 запросов» однажды совпадёт у всех.
max_requests = 2000 if workers > 1 else 0
max_requests_jitter = 200 if workers > 1 else 0

# --- Журнал -----------------------------------------------------------------

# Строку доступа пишет наша прослойка — с идентификатором запроса,
# длительностью и кодом. Журнал доступа gunicorn дал бы вторую строку о том
# же, причём с IP в стандартном формате: персональные данные в журнале
# приложения нам не нужны.
accesslog = None

# Ошибки — в stdout, оттуда их забирает драйвер логов Docker. Файлов из
# приложения мы не пишем: несколько процессов в один файл — это гонка.
errorlog = "-"
loglevel = _настройки.log_level.lower()

# Тот же JSON, что у приложения, — иначе мастер-процесс писал бы в общий
# поток своим текстовым форматом, и сборщик логов спотыкался бы на его
# строках. Подробности про `gunicorn.error` — в `core/logging.py`.
logconfig_dict = logging_config(_настройки.env, _настройки.log_level)

# Перехватывать `print` и чужой вывод в stdout нельзя: `capture_output`
# перенаправляет поток в файл журнала, а у нас журнал и есть stdout.
capture_output = False

# --- Управляющий сокет ------------------------------------------------------

# С версии 25.1 gunicorn открывает unix-сокет для `gunicornc` (посмотреть
# рабочих, добавить, перезагрузить) — по умолчанию в
# `$XDG_RUNTIME_DIR/gunicorn.ctl`, а без этой переменной в
# `$HOME/.gunicorn/gunicorn.ctl`, создавая каталог сам.
#
# В нашем контейнере он не создастся ни там, ни там: у пользователя
# `grafik` домашнего каталога нет (`--no-create-home`), а файловая система
# смонтирована только для чтения. Беды не случится — gunicorn напишет
# предупреждение и продолжит, — но предупреждение на каждом старте,
# которое ничего не значит, хуже отсутствия сокета: его начинают
# расследовать.
#
# Управляем мы не им: перезапуск — `docker compose up -d api`, остановка —
# сигнал от docker, число процессов — `GRAFIK_WORKERS`. Поэтому выключен.
control_socket_disable = True
