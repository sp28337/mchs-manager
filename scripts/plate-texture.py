"""
Из фотографии рифлёного листа — бесшовная плитка карты рельефа для подвала.

    python3 scripts/plate-texture.py

Читает `assets/plate-source.jpeg`, кладёт `public/textures/plate.webp`.

--- Зачем скрипт, а если можно положить фотографию как есть ------------------

Нельзя. Снимок сделан с рук: лист повёрнут почти на три градуса, освещён
неравномерно, да ещё и снят чуть под углом. Положи такой файл повтором в
подвал — и получишь клетку из светлых и тёмных пятен со сдвигом рисунка на
каждом стыке. Здесь снимается и то, и другое.

Скрипт лежит в репозитории не для того, чтобы его запускали: плитка уже
собрана и закоммичена. Он объясняет ЧИСЛА — откуда взялись векторы решётки и
точка выреза, которые иначе выглядели бы взятыми с потолка, — и позволяет
пересобрать плитку, если однажды сменится исходник.

--- Что делается и в каком порядке -------------------------------------------

1. ВИРОВНАТЬ ОСВЕЩЕНИЕ. Кадр делится на собственную сильно размытую копию.
   Размытие в 120 точек шире любой чечевицы, но уже виньетки, поэтому рельеф
   переживает деление, а неравномерность света — нет. Замерено: до правки
   центр кадра ярче углов на 54 уровня из 255.

2. ВЫПРЯМИТЬ РЕШЁТКУ. Векторы периода сняты автокорреляцией: вправо
   (424.56, −19.98), вниз (14.99, 438.56) — то есть поворот и небольшой сдвиг
   между осями. Аффинное преобразование переводит их в строго горизонтальный
   и вертикальный периоды ровно по 424 точки. Числа уточнены в три круга:
   выпрямили, замерили, что осталось, поджали.

3. ВЫРЕЗАТЬ ОДИН ПЕРИОД. Плитка в один период сходится сама с собой по
   построению. Точка выреза (1024, 300) не выбрана на глаз, а найдена
   перебором по кадру: у неё наименьшее расхождение противоположных краёв —
   6.85 по горизонтали и 7.30 по вертикали из 255. Стык при таком
   расхождении глазом не находится.

4. ПРИВЕСТИ К СЕРЕДИНЕ ШКАЛЫ. Плитка идёт в CSS режимом `overlay`, и её
   средняя яркость обязана быть ровно 128: тогда подложка берёт цвет из
   палитры темы, а снимок отдаёт только светотень, ничего не осветляя и не
   затемняя в целом. Это и есть весь секрет того, как один файл служит и
   светлой теме, и тёмной.
"""

import numpy as np
from PIL import Image, ImageFilter

SRC = "assets/plate-source.jpeg"
DST = "public/textures/plate.webp"

P = 424                    # сторона плитки: один период решётки
AX, AY = 424.56, -19.98    # период вправо в координатах исходника
BX, BY = 14.99, 438.56     # период вниз
OX, OY = 1024, 300         # точка выреза с наименьшим швом
BLUR = 120                 # радиус размытия для выравнивания освещения
QUALITY = 86


def main() -> None:
    im = Image.open(SRC).convert("L")
    a = np.asarray(im, np.float32)

    blur = np.asarray(im.filter(ImageFilter.GaussianBlur(BLUR)), np.float32)
    flat = np.clip(a / np.maximum(blur, 1.0) * float(blur.mean()), 0, 255)

    # PIL ждёт ОБРАТНОЕ отображение: для каждой точки плитки — откуда её взять
    # в исходнике. Поэтому векторы решётки идут в матрицу как есть, поделённые
    # на сторону плитки.
    tile = Image.fromarray(flat.astype(np.uint8)).transform(
        (P, P),
        Image.AFFINE,
        (AX / P, BX / P, OX, AY / P, BY / P, OY),
        resample=Image.BICUBIC,
    )

    t = np.asarray(tile, np.float32)
    t = np.clip(t - t.mean() + 128.0, 0, 255)

    Image.fromarray(t.astype(np.uint8)).save(DST, "WEBP", quality=QUALITY, method=6)
    print(f"{DST}: {P}x{P}, средняя {t.mean():.1f}")


if __name__ == "__main__":
    main()
