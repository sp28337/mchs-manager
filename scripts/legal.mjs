/**
 * Юридические документы: проверка и манифест.
 *
 * ```
 * node scripts/legal.mjs          # проверить (так же, как в CI)
 * node scripts/legal.mjs write    # пересобрать манифест для сервера
 * ```
 *
 * --- Зачем это нужно -------------------------------------------------------
 *
 * Текст документов лежит в `docs/legal/*.md` и больше нигде: сайт собирает
 * страницы из этих файлов, а сервер хранит в записи о согласии версию
 * документа. Чтобы «с какой именно редакцией человек согласился» осталось
 * доказуемым, сервер отдаёт в `GET /legal/documents` версию и `sha256`
 * ровно того текста, который человек читал. Хэши считаются здесь и
 * ложатся в манифест рядом с кодом сервера: в образ сервера папка `docs/`
 * не попадает, а выдумывать хэш на ходу нельзя.
 *
 * --- Что проверяется -------------------------------------------------------
 *
 * 1. Головной блок на месте и заполнен.
 * 2. У опубликованного документа (`status: published`) не осталось
 *    подстановок `{{…}}` и указана дата вступления в силу. Это та самая
 *    проверка из чек-листа публикации (`docs/legal/README.md`): документ с
 *    `{{ФИО_ОПЕРАТОРА}}` на живом сайте — хуже отсутствующего.
 * 3. Каждая встреченная подстановка перечислена в таблице README: иначе
 *    при публикации её некому будет заполнить.
 * 4. Версии совпадают в трёх местах: в самом документе, в манифесте
 *    сервера и в `src/features/sync/legal.ts` (их браузер отправляет при
 *    регистрации). Разойдись они — сервер отвергнет регистрацию кодом
 *    `consent_required`, а человек увидит отказ, причины которого в
 *    интерфейсе нет.
 * 5. Манифест не устарел: пересобранный совпадает с лежащим в репозитории.
 * 6. Архив редакций (`docs/legal/archive/<id>/<версия>.md`): файл назван датой
 *    версии, в его головном блоке тот же `id` и та же `version`. По архиву сайт
 *    собирает наглядное сравнение для окна «Документы обновились»: перепутанная
 *    редакция показала бы человеку не те правки.
 * 7. Внутренние документы (`docs/legal/internal/`, карта данных) тоже имеют
 *    головной блок с версией, помечены `public: false`, не имеют адреса
 *    (чтобы их нельзя было случайно вывести страницей) и перечислены в
 *    своём README. Их текст не хэшируется: сервер их не отдаёт.
 *
 * --- Что считается текстом документа ---------------------------------------
 *
 * Хэшируется **тело** — всё после головного блока, без краевых пробелов.
 * Головной блок это метаданные (заголовок, версия, адрес), и правка в них
 * не меняет того, что человек прочитал. Опубликованный текст при этом
 * совпадает с телом байт в байт: подстановки к моменту публикации
 * заполнены в самом файле.
 */

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { argv, exit } from "node:process";

const КОРЕНЬ = new URL("..", import.meta.url).pathname;

/** Публикуемые документы: `id` → файл. Карта данных внутренняя, её здесь нет. */
const ДОКУМЕНТЫ = {
  policy: "docs/legal/privacy-policy.md",
  consent: "docs/legal/consent.md",
  terms: "docs/legal/terms.md",
  cookies: "docs/legal/cookies.md",
};

/** Внутренние документы: публикации нет, проверка есть. */
const ВНУТРЕННИЕ = "docs/legal/internal";
const КАРТА = "docs/legal/data-map.md";

const МАНИФЕСТ = "api/src/grafik_api/core/legal_manifest.json";
const ВЕРСИИ_ФРОНТА = "src/features/sync/legal.ts";
const README = "docs/legal/README.md";

const ОБЯЗАТЕЛЬНЫЕ = ["id", "title", "version", "status", "url"];

function читать(путь) {
  return readFileSync(`${КОРЕНЬ}${путь}`, "utf-8");
}

/** Головной блок и тело документа. */
export function разобрать(текст) {
  const блок = /^---\n([\s\S]*?)\n---\n?/.exec(текст);

  if (блок === null) return { поля: null, тело: текст };

  const поля = {};

  for (const строка of блок[1].split("\n")) {
    const пара = /^([a-z_]+):\s*(.*)$/.exec(строка);
    if (пара === null) continue;

    const значение = пара[2].replace(/^"(.*)"$/, "$1").trim();
    поля[пара[1]] = значение === "null" || значение === "" ? null : значение;
  }

  return { поля, тело: текст.slice(блок[0].length).trim() };
}

/** Хэш текста документа — тот же, что отдаёт сервер. */
export function хэш(тело) {
  return createHash("sha256").update(тело, "utf-8").digest("hex");
}

/**
 * Внутренние документы: что у них проверяется.
 *
 * Их текст не хэшируется и наружу не отдаётся, поэтому требований меньше.
 * Но три вещи важны и здесь: версия (по ней видно, какая редакция
 * утверждена), пометка `public: false` и **отсутствие адреса** — адрес в
 * головном блоке означал бы страницу, а модель угроз на сайте не нужна
 * никому.
 */
function проверить_внутренние(подстановки) {
  const беды = [];
  const файлы = [
    КАРТА,
    ...readdirSync(`${КОРЕНЬ}${ВНУТРЕННИЕ}`)
      .filter((имя) => имя.endsWith(".md"))
      .sort()
      .map((имя) => `${ВНУТРЕННИЕ}/${имя}`),
  ];

  const свой_readme = читать(`${ВНУТРЕННИЕ}/README.md`);
  const имена = new Set();

  for (const файл of файлы) {
    const { поля, тело } = разобрать(читать(файл));

    if (поля === null) {
      беды.push(`${файл}: нет головного блока`);
      continue;
    }

    for (const ключ of ["id", "title", "version", "status"]) {
      if (поля[ключ] === undefined || поля[ключ] === null) {
        беды.push(`${файл}: в головном блоке нет «${ключ}»`);
      }
    }

    if (поля.public !== "false") {
      беды.push(`${файл}: внутренний документ помечается «public: false»`);
    }

    if (поля.url !== undefined) {
      беды.push(`${файл}: у внутреннего документа не бывает адреса (url)`);
    }

    if (поля.status !== "draft" && поля.status !== "published") {
      беды.push(`${файл}: status «${поля.status}» — бывает draft или published`);
    }

    if (поля.id !== null && имена.has(поля.id)) {
      беды.push(`${файл}: id «${поля.id}» уже занят другим документом`);
    }
    имена.add(поля.id);

    for (const подстановка of тело.match(/\{\{[^}]+\}\}/g) ?? []) {
      подстановки.add(подстановка);
    }

    // Пакет должен оставаться обозримым: документ, которого нет в
    // перечне, не найдёт ни оператор, ни проверяющий.
    const имя = файл.split("/").pop();
    if (файл.startsWith(ВНУТРЕННИЕ) && имя !== "README.md") {
      if (!свой_readme.includes(имя)) {
        беды.push(`${ВНУТРЕННИЕ}/README.md: документ ${имя} не перечислен`);
      }
    }
  }

  return беды;
}

/**
 * Архив прошлых редакций.
 *
 * Редакция, на которую человек уже согласился, должна быть доступна: он вправе
 * прочитать именно тот текст и увидеть, чем он отличается от нового. Поэтому
 * перед правкой текста по существу прежняя редакция кладётся сюда (README,
 * «Архив редакций»). Здесь проверяется только то, что файл лежит там, где его
 * будут искать: имя — дата версии, а `id` и `version` в головном блоке те же.
 */
function проверить_архив() {
  const беды = [];

  for (const id of Object.keys(ДОКУМЕНТЫ)) {
    const папка = `docs/legal/archive/${id}`;
    let имена;

    try {
      имена = readdirSync(`${КОРЕНЬ}${папка}`);
    } catch {
      continue;
    }

    for (const имя of имена.sort()) {
      const файл = `${папка}/${имя}`;
      const версия = /^(\d{4}-\d{2}-\d{2})\.md$/.exec(имя)?.[1];

      if (версия === undefined) {
        беды.push(`${файл}: имя архивной редакции — дата версии, например 2026-10-11.md`);
        continue;
      }

      const { поля } = разобрать(читать(файл));

      if (поля === null) {
        беды.push(`${файл}: нет головного блока`);
        continue;
      }

      if (поля.id !== id) беды.push(`${файл}: id «${поля.id}», ожидался «${id}»`);
      if (поля.version !== версия) {
        беды.push(`${файл}: версия «${поля.version}» не совпадает с именем файла`);
      }
    }
  }

  return беды;
}

function собрать() {
  const беды = [];
  const манифест = {};
  const подстановки = new Set();

  for (const [id, файл] of Object.entries(ДОКУМЕНТЫ)) {
    const { поля, тело } = разобрать(читать(файл));

    if (поля === null) {
      беды.push(`${файл}: нет головного блока`);
      continue;
    }

    for (const ключ of ОБЯЗАТЕЛЬНЫЕ) {
      if (поля[ключ] === undefined || поля[ключ] === null) {
        беды.push(`${файл}: в головном блоке нет «${ключ}»`);
      }
    }

    if (поля.id !== id) беды.push(`${файл}: id «${поля.id}», ожидался «${id}»`);

    if (поля.status !== "draft" && поля.status !== "published") {
      беды.push(`${файл}: status «${поля.status}» — бывает draft или published`);
    }

    const найденные = тело.match(/\{\{[^}]+\}\}/g) ?? [];
    for (const подстановка of найденные) подстановки.add(подстановка);

    if (поля.status === "published") {
      if (найденные.length > 0) {
        беды.push(
          `${файл}: опубликован, но в тексте остались подстановки: ${[
            ...new Set(найденные),
          ].join(", ")}`,
        );
      }
      if (поля.effective_from === null || поля.effective_from === undefined) {
        беды.push(`${файл}: опубликован, но нет даты вступления в силу`);
      }
    }

    манифест[id] = {
      title: поля.title,
      version: поля.version,
      effective_from: поля.effective_from ?? null,
      status: поля.status,
      url: поля.url,
      sha256: хэш(тело),
    };
  }

  беды.push(...проверить_внутренние(подстановки));
  беды.push(...проверить_архив());

  // Каждая подстановка должна быть в таблице README: иначе при публикации
  // её некому будет заполнить.
  const readme = читать(README);
  for (const подстановка of подстановки) {
    if (!readme.includes(подстановка)) {
      беды.push(`${README}: подстановка ${подстановка} не описана в таблице`);
    }
  }

  // Версии, которые отправляет браузер.
  const фронт = читать(ВЕРСИИ_ФРОНТА);
  for (const [id, документ] of Object.entries(манифест)) {
    const строка = new RegExp(`${id}:\\s*"([^"]+)"`).exec(фронт);

    if (строка === null) {
      беды.push(`${ВЕРСИИ_ФРОНТА}: нет версии документа «${id}»`);
    } else if (строка[1] !== документ.version) {
      беды.push(
        `${ВЕРСИИ_ФРОНТА}: версия «${id}» — ${строка[1]}, в документе ${документ.version}`,
      );
    }
  }

  return { манифест, беды };
}

function текстМанифеста(манифест) {
  return `${JSON.stringify(манифест, null, 2)}\n`;
}

const { манифест, беды } = собрать();
const собранный = текстМанифеста(манифест);
const команда = argv[2] ?? "check";

if (команда === "write") {
  writeFileSync(`${КОРЕНЬ}${МАНИФЕСТ}`, собранный, "utf-8");
  console.log(`${МАНИФЕСТ}: пересобран`);
} else {
  let лежит = null;
  try {
    лежит = читать(МАНИФЕСТ);
  } catch {
    беды.push(`${МАНИФЕСТ}: нет файла — соберите его: node scripts/legal.mjs write`);
  }

  if (лежит !== null && лежит !== собранный) {
    беды.push(
      `${МАНИФЕСТ}: устарел — пересоберите: node scripts/legal.mjs write`,
    );
  }
}

if (беды.length > 0) {
  console.error("Документы не в порядке:\n");
  for (const беда of беды) console.error(`  • ${беда}`);
  console.error("");
  exit(1);
}

const состояния = Object.entries(манифест)
  .map(([id, документ]) => `${id} ${документ.version} (${документ.status})`)
  .join(", ");

const внутренних = readdirSync(`${КОРЕНЬ}${ВНУТРЕННИЕ}`).filter((имя) =>
  имя.endsWith(".md"),
).length;

console.log(
  `Документы в порядке: ${состояния}; внутренних — ${внутренних + 1}`,
);
