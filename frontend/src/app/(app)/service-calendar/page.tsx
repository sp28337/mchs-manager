import { redirect } from "next/navigation";

/**
 * Пункт меню ведёт на календарь БЕЗ года, а страницы без года не бывает:
 * календарь — документ конкретного года. Отправляем на текущий.
 *
 * Не на следующий, хотя размечают обычно именно его: расчёт нормы идёт
 * по текущему году каждый день, а разметка будущего — работа нескольких
 * дней в декабре. Переключатель лет стоит на самой странице.
 */
export default function ServiceCalendarIndexPage() {
  redirect(`/service-calendar/${new Date().getUTCFullYear()}`);
}
