"use client";

import { useEffect } from "react";

/**
 * Цвет бумаги для верха окна.
 *
 * Это те же значения, что у `--fps-paper` в `globals.css`, и держит их в
 * согласии проверка `window-top.test.ts`: она читает таблицу стилей и
 * сверяет обе темы. Расходиться им нельзя, а взять их прямо из CSS —
 * нельзя тем более: вебкит на айфоне отдавал вычисленное значение
 * свойства ещё не пересчитанным, и цвет отставал на переключение.
 */
export const PAPER = {
  light: "#ffffff",
  dark: "#1f2023",
} as const;

/** Правило одно и для метки, и для перекраски, и для разметки окна. */
export function paperOf(root: Element): string {
  return root.classList.contains("dark") ? PAPER.dark : PAPER.light;
}

/**
 * Слои НАД кромкой окна: продолжение дымки и его липкий близнец. Оба
 * закреплённые, оба лежат целиком выше видимой части страницы.
 */
const ABOVE_EDGE = ".veil-over, .veil-anchor > span";

/**
 * Верх окна следует за темой.
 *
 * --- Что было не так ------------------------------------------------------
 *
 * На айфоне после смены темы верхняя полоса браузера — та, где адрес, —
 * оставалась в прежнем цвете: на светлой теме тёмной, на тёмной белой.
 *
 * Полосу сафари не красит произвольно: он ПРОДОЛЖАЕТ ею страницу, беря
 * цвет с её верхнего края. А верхний край у нас — не бумага, а слой
 * `.veil-over`: продолжение дымки, закреплённое ЦЕЛИКОМ выше видимой
 * части окна (`top: -20rem`). Заливка у него `var(--fps-paper)`, и при
 * смене темы она обязана меняться.
 *
 * Не менялась. Слой лежит вне видимой части, а такие слои браузер
 * перерисовывает лениво — незачем рисовать то, чего не видно. То, что его
 * всё-таки видно (сквозь полупрозрачную полосу браузера и через цвет
 * этой полосы), браузеру неизвестно.
 *
 * Отсюда и «отставание на шаг», которое сбивало с толку три захода: цвет
 * там не случайный и не застывший навсегда, а именно ПРЕДЫДУЩИЙ — тот, с
 * которым слой в последний раз рисовали.
 *
 * --- Что делается ---------------------------------------------------------
 *
 * Два независимых средства, оба дешёвые, оба срабатывают на одно и то же
 * событие — смену класса темы на корне документа.
 *
 * ПЕРВОЕ. Слои над кромкой перерисовываются принудительно: заливка
 * ставится на них прямой строкой (не переменной, чтобы не зависеть от
 * пересчёта), а затем слой на мгновение снимается с отрисовки и
 * возвращается. Снятие с возвратом — не суеверие: оно уничтожает
 * подготовленный слой и заставляет собрать его заново, чего одна лишь
 * правка цвета не гарантирует. Ни на разметку, ни на прокрутку это не
 * влияет: `.veil-over` закреплён, а близнец лежит абсолютом внутри
 * пустого по высоте якоря.
 *
 * ВТОРОЕ. Метка `theme-color`: ею страница может назвать цвет полосы
 * прямо, не полагаясь на догадку браузера. Ставится она пересозданием
 * узла, а не правкой `content`, — правку вебкит замечает не всегда.
 *
 * Одного второго не хватило (проверено выпуском), потому что оно лечит
 * лишь ЦВЕТ ПОЛОСЫ, а под самой полосой оставался тот же слой с прежней
 * заливкой — его видно в просвете. Одного первого, возможно, хватило бы,
 * но проверить это с настольного браузера нечем, а цена второго — один
 * узел в шапке документа.
 *
 * --- Почему слушается КЛАСС, а не хук тем ---------------------------------
 *
 * Тот же приём, что у лампы: тему на корень кладёт классом сам
 * `next-themes`, и класс — единственное место, где она уже разрешена в
 * конкретную. «Как в системе» к этому времени превращено в светлую или
 * тёмную, а хук вернул бы слово «system», по которому цвета не выбрать.
 *
 * Первую установку метки делает не этот компонент, а короткая вставка в
 * разметке окна: она выполняется ДО первой отрисовки. Перекраска при
 * первом показе не нужна — слои рисуются сразу в нужном цвете, потому что
 * рисуются впервые.
 */
export function WindowTop() {
  useEffect(() => {
    const root = document.documentElement;

    const setMeta = (colour: string) => {
      const meta = document.head.querySelector<HTMLMetaElement>('meta[name="theme-color"]');
      if (meta?.content === colour) return;

      meta?.remove();
      const fresh = document.createElement("meta");
      fresh.name = "theme-color";
      fresh.content = colour;
      document.head.appendChild(fresh);
    };

    const repaintAboveEdge = (colour: string) => {
      for (const layer of document.querySelectorAll<HTMLElement>(ABOVE_EDGE)) {
        layer.style.backgroundColor = colour;
        layer.style.display = "none";
        // Чтение размера — не мусор: им и вызывается пересчёт, без
        // которого обе правки слились бы в одну и слой не пересобрался.
        void layer.offsetHeight;
        layer.style.display = "";
      }
    };

    let last = "";
    const apply = () => {
      const colour = paperOf(root);
      if (colour === last) return;
      last = colour;
      setMeta(colour);
      repaintAboveEdge(colour);
    };

    apply();
    const watcher = new MutationObserver(apply);
    watcher.observe(root, { attributes: true, attributeFilter: ["class"] });
    return () => watcher.disconnect();
  }, []);

  return null;
}
