"use client";

import { useEffect } from "react";

/**
 * Цвет бумаги для верха окна.
 *
 * Это те же значения, что у `--fps-paper` в `globals.css`, и держит их в
 * согласии проверка `window-top.test.ts`: она читает таблицу стилей и
 * сверяет обе темы. Расходиться им нельзя, а взять их прямо из CSS —
 * нельзя тем более: вебкит на айфоне отдавал вычисленное значение
 * свойства ещё не пересчитанным, и цвет отставал на переключение.
 */
export const PAPER = {
  light: "#ffffff",
  dark: "#1f2023",
} as const;

/** Правило одно и для холста, и для слоёв, и для всего остального. */
export function paperOf(root: Element): string {
  return root.classList.contains("dark") ? PAPER.dark : PAPER.light;
}

/**
 * Слои, залитые бумагой: продолжение дымки над кромкой окна и его липкий
 * близнец. Им заливка ставится прямой строкой.
 */
const PAPER_LAYERS = ".veil-over, .veil-anchor > span";

/**
 * Всё закреплённое у верха окна — то, что браузер держит отдельными
 * слоями и может не перерисовать. Заливку трогать нельзя (у дымки её нет
 * вовсе, у неё размытие подложки), а пересобрать слой — можно и нужно.
 */
const TOP_LAYERS = ".veil, .veil-over, .veil-anchor > span, .lamp, .lamp-wash";

/**
 * Верх окна следует за темой.
 *
 * --- Чем всё оказалось ----------------------------------------------------
 *
 * Полосу над страницей — ту, где адрес, — сафари на айфоне красит сам,
 * продолжая ею страницу. Так было всегда и работало: тема менялась, и
 * полоса вместе с ней.
 *
 * Сломал это МАНИФЕСТ, а точнее объявленный в нём `theme_color`. Как
 * только страница называет цвет полосы явно, сафари перестаёт смотреть на
 * саму страницу и берёт названное. А названное он читает ОДИН РАЗ, при
 * загрузке, и больше не перечитывает: меняй метку сколько угодно — до
 * перезагрузки полоса останется той, какой была в момент открытия.
 *
 * Отсюда и всё, что сбивало с толку четыре захода подряд. Полоса
 * показывала не «предыдущую тему» и не «застывший цвет», а тему НА МОМЕНТ
 * ЗАГРУЗКИ СТРАНИЦЫ; полная перезагрузка её чинила; в хроме, где метка
 * перечитывается живьём, всё работало и проверки проходили.
 *
 * Три починки подряд лечили метку — то из вычисленных стилей, то из класса
 * темы, то пересозданием узла, — то есть чинили ровно ту вещь, которая и
 * была причиной.
 *
 * --- Что теперь -----------------------------------------------------------
 *
 * Метки нет. Цвет полосы страница не называет вовсе — ни разметкой, ни
 * манифестом, — и сафари снова красит верх по самой странице, как до
 * появления манифеста. Компонент при загрузке снимает метку, если она
 * вдруг откуда-то возьмётся: одна забытая строка вернула бы всё обратно, и
 * заметить это можно было бы только на телефоне.
 *
 * Раз цвет берётся с самой страницы, страница обязана быть верной сразу и
 * целиком. За это отвечают три вещи, и все три остаются:
 *
 * 1. ХОЛСТ. Цвет ставится на корень документа своей строкой. Область под
 *    часами красит именно холст, и до сих пор он брал цвет по наследству
 *    от тела страницы — теперь называет его прямо.
 *
 * 2. СЛОИ У ВЕРХА ОКНА. Тем, что залиты бумагой, цвет ставится строкой, а
 *    затем все закреплённые слои у верха на мгновение снимаются с
 *    отрисовки и возвращаются. Это уничтожает подготовленный слой и
 *    заставляет собрать его заново — иначе слой над кромкой (он лежит вне
 *    видимой части) и дымка (у неё размытие подложки) могут остаться с
 *    прежними пикселями, и сафари снимет цвет именно с них.
 *
 * 3. ТОЛЧОК ПРОКРУТКОЙ. Страница прокручивается на точку и возвращается.
 *    Цвет верха сафари пересматривает при прокрутке — так у него есть
 *    повод посмотреть на страницу заново прямо сейчас, а не при следующем
 *    касании.
 *
 * --- Почему слушается КЛАСС, а не хук тем ---------------------------------
 *
 * Тот же приём, что у лампы: тему на корень кладёт классом сам
 * `next-themes`, и класс — единственное место, где она уже разрешена в
 * конкретную. «Как в системе» к этому времени превращено в светлую или
 * тёмную, а хук вернул бы слово «system», по которому цвета не выбрать.
 */
export function WindowTop() {
  useEffect(() => {
    const root = document.documentElement;

    // Метка цвета полосы не должна существовать. См. объяснение выше:
    // назвав цвет один раз, страница теряет право менять его до
    // перезагрузки.
    for (const meta of document.head.querySelectorAll('meta[name="theme-color"]')) {
      meta.remove();
    }

    const repaint = (colour: string) => {
      root.style.backgroundColor = colour;

      for (const layer of document.querySelectorAll<HTMLElement>(PAPER_LAYERS)) {
        layer.style.backgroundColor = colour;
      }

      for (const layer of document.querySelectorAll<HTMLElement>(TOP_LAYERS)) {
        layer.style.display = "none";
        // Чтение размера — не мусор: им и вызывается пересчёт, без
        // которого снятие и возврат слились бы в одно и слой не
        // пересобрался.
        void layer.offsetHeight;
        layer.style.display = "";
      }
    };

    /**
     * Толчок прокруткой — следующим кадром, когда всё уже перерисовано.
     *
     * Возврат идёт кадром позже: сделай его тем же, и браузер сложит два
     * перемещения в одно нулевое, а прокрутки, ради которой всё
     * затевалось, не случится вовсе.
     */
    const nudge = () => {
      const y = window.scrollY;
      requestAnimationFrame(() => {
        window.scrollTo({ top: y + 1, behavior: "instant" });
        requestAnimationFrame(() => window.scrollTo({ top: y, behavior: "instant" }));
      });
    };

    let last = paperOf(root);
    // Холст называется сразу: при первом показе он ещё берёт цвет по
    // наследству от тела, и сафари снимает верх с него.
    root.style.backgroundColor = last;

    const watcher = new MutationObserver(() => {
      const colour = paperOf(root);
      if (colour === last) return;
      last = colour;
      repaint(colour);
      nudge();
    });
    watcher.observe(root, { attributes: true, attributeFilter: ["class"] });
    return () => watcher.disconnect();
  }, []);

  return null;
}
