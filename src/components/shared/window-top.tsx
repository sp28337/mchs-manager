"use client";

import { useEffect } from "react";

/**
 * Цвет бумаги для верха окна.
 *
 * Это те же значения, что у `--fps-paper` в `globals.css`, и держит их в
 * согласии проверка `window-top.test.ts`: она читает таблицу стилей и
 * сверяет обе темы. Расходиться им нельзя, а взять их прямо из CSS —
 * нельзя тем более: вебкит на айфоне отдавал вычисленное значение
 * свойства ещё не пересчитанным, и цвет отставал на переключение.
 */
export const PAPER = {
  light: "#ffffff",
  dark: "#1f2023",
} as const;

/** Правило одно и для метки, и для перекраски, и для разметки окна. */
export function paperOf(root: Element): string {
  return root.classList.contains("dark") ? PAPER.dark : PAPER.light;
}

/**
 * Слои, залитые бумагой: продолжение дымки над кромкой окна и его липкий
 * близнец. Им заливка ставится прямой строкой.
 */
const PAPER_LAYERS = ".veil-over, .veil-anchor > span";

/**
 * Всё закреплённое у верха окна — то, что браузер держит отдельными
 * слоями и может не перерисовать. Заливку трогать нельзя (у дымки её нет
 * вовсе, у неё размытие подложки), а пересобрать слой — можно и нужно.
 */
const TOP_LAYERS = ".veil, .veil-over, .veil-anchor > span, .lamp, .lamp-wash";

/**
 * Верх окна следует за темой.
 *
 * --- Почему здесь не одно средство, а пять --------------------------------
 *
 * Полосу над страницей — ту, где адрес, — сафари на айфоне красит сам, и
 * после смены темы она оставалась в прежнем цвете. Чинилось это трижды, и
 * трижды мимо: сперва метка `theme-color` из вычисленных стилей, потом она
 * же из класса темы, потом принудительная перерисовка слоя над кромкой.
 * Ни одно не помогло, а проверить догадку было нечем — сафари на айфоне из
 * разработки недоступен, и каждая проверка стоила выпуска.
 *
 * Поэтому здесь больше нет ставки на одну догадку. Сделано СРАЗУ ВСЁ, чем
 * вообще можно повлиять на цвет этой полосы, — пять независимых средств,
 * каждое дешёвое и безвредное само по себе:
 *
 * 1. ХОЛСТ. Цвет ставится на корень документа своей строкой. Область под
 *    часами красит именно холст, и до сих пор он брал цвет по наследству
 *    от тела страницы — теперь называет его прямо.
 *
 * 2. ЗАЛИВКА СЛОЁВ НАД КРОМКОЙ. Тем слоям, что залиты бумагой, цвет тоже
 *    ставится строкой, а не переменной: переменную нужно пересчитать, а
 *    строку — нет.
 *
 * 3. ПЕРЕСБОРКА СЛОЁВ. Всё закреплённое у верха окна на мгновение
 *    снимается с отрисовки и возвращается. Это уничтожает подготовленный
 *    слой и заставляет собрать его заново — то, чего одна правка цвета не
 *    гарантирует, особенно для слоя, лежащего вне видимой части, и для
 *    дымки, у которой размытие подложки: такие слои вебкит кэширует
 *    особенно охотно.
 *
 * 4. МЕТКА `theme-color`. Ею страница может назвать цвет полосы прямо, не
 *    полагаясь на догадку браузера. Ставится пересозданием узла: правку
 *    `content` вебкит замечает не всегда.
 *
 * 5. ТОЛЧОК ПРОКРУТКОЙ. Страница прокручивается на точку и возвращается
 *    обратно. Цвет полосы сафари пересчитывает при прокрутке — это
 *    единственный момент, когда он заведомо пересматривает, чем красить
 *    верх. Точка незаметна, а положение восстанавливается тем же кадром.
 *
 * Стрельба дробью — плохой способ чинить, когда есть чем прицелиться.
 * Здесь прицелиться нечем: устройства нет, а цена промаха — ещё один
 * выпуск и ещё один заход по кругу.
 *
 * --- Почему слушается КЛАСС, а не хук тем ---------------------------------
 *
 * Тот же приём, что у лампы: тему на корень кладёт классом сам
 * `next-themes`, и класс — единственное место, где она уже разрешена в
 * конкретную. «Как в системе» к этому времени превращено в светлую или
 * тёмную, а хук вернул бы слово «system», по которому цвета не выбрать.
 *
 * Первую установку метки делает не этот компонент, а короткая вставка в
 * разметке окна: она выполняется ДО первой отрисовки. Остальное при первом
 * показе не нужно — слои рисуются сразу в нужном цвете, потому что
 * рисуются впервые.
 */
export function WindowTop() {
  useEffect(() => {
    const root = document.documentElement;

    const setMeta = (colour: string) => {
      const meta = document.head.querySelector<HTMLMetaElement>('meta[name="theme-color"]');
      if (meta?.content === colour) return;

      meta?.remove();
      const fresh = document.createElement("meta");
      fresh.name = "theme-color";
      fresh.content = colour;
      document.head.appendChild(fresh);
    };

    const repaint = (colour: string) => {
      root.style.backgroundColor = colour;

      for (const layer of document.querySelectorAll<HTMLElement>(PAPER_LAYERS)) {
        layer.style.backgroundColor = colour;
      }

      for (const layer of document.querySelectorAll<HTMLElement>(TOP_LAYERS)) {
        layer.style.display = "none";
        // Чтение размера — не мусор: им и вызывается пересчёт, без
        // которого снятие и возврат слились бы в одно и слой не
        // пересобрался.
        void layer.offsetHeight;
        layer.style.display = "";
      }
    };

    /**
     * Толчок прокруткой — следующим кадром, когда всё уже перерисовано.
     *
     * Возврат идёт кадром позже: сделай его тем же, и браузер сложит два
     * перемещения в одно нулевое, а прокрутки, ради которой всё
     * затевалось, не случится вовсе.
     */
    const nudge = () => {
      const y = window.scrollY;
      requestAnimationFrame(() => {
        window.scrollTo({ top: y + 1, behavior: "instant" });
        requestAnimationFrame(() => window.scrollTo({ top: y, behavior: "instant" }));
      });
    };

    let last = "";
    const apply = (first: boolean) => {
      const colour = paperOf(root);
      if (colour === last) return;
      last = colour;

      setMeta(colour);
      if (first) return;

      repaint(colour);
      nudge();
    };

    apply(true);
    const watcher = new MutationObserver(() => apply(false));
    watcher.observe(root, { attributes: true, attributeFilter: ["class"] });
    return () => watcher.disconnect();
  }, []);

  return null;
}
