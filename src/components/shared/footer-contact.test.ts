import { describe, expect, it } from "vitest";

import { letterHref } from "./footer-contact";

/**
 * Обращение человек пишет свободной строкой, а уезжает оно адресом
 * `mailto:`. Значит, в адрес попадает всё, что он набрал: переводы
 * строк, амперсанды, вопросительные знаки, кириллица. Любой из этих
 * знаков, не закодированный как следует, обрывает письмо — и человек
 * отправляет оператору половину фразы, не заметив этого.
 */
describe("письмо из подвала", () => {
  const почта = "grafik1-3@yandex.ru";

  const тело = (адрес: string): string | null =>
    new URLSearchParams(new URL(адрес).search).get("body");

  it("адресат и тема стоят на своих местах", () => {
    const адрес = new URL(letterHref(почта, "Здравствуйте"));
    expect(адрес.protocol).toBe("mailto:");
    expect(адрес.pathname).toBe(почта);
    expect(new URLSearchParams(адрес.search).get("subject")).toBe(
      "Вопрос о приложении «График 1 3»",
    );
  });

  it("амперсанд не разрывает письмо на два поля", () => {
    expect(тело(letterHref(почта, "Смены & отгулы"))).toBe("Смены & отгулы");
  });

  it("перевод строки доезжает переводом строки", () => {
    expect(тело(letterHref(почта, "Первая\nвторая"))).toBe("Первая\nвторая");
  });

  it("кириллица и знаки препинания доезжают целиком", () => {
    const текст = "Прошу сообщить: какие данные обрабатываются? Спасибо!";
    expect(тело(letterHref(почта, текст))).toBe(текст);
  });

  it("пустое обращение даёт пустое тело, а не «undefined»", () => {
    expect(тело(letterHref(почта, ""))).toBe("");
  });
});
