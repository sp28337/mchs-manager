"use client";

import { useEffect } from "react";

/**
 * Цвет бумаги, из которого красится верхняя полоса браузера.
 *
 * Это те же значения, что у `--fps-paper` в `globals.css`, и держит их в
 * согласии проверка `theme-colour.test.ts`: она читает таблицу стилей и
 * сверяет обе темы. Расходиться им нельзя, а взять их прямо из CSS —
 * нельзя тем более, и вот почему.
 *
 * --- Почему не читаем цвет из стилей --------------------------------------
 *
 * Первая попытка так и делала: слушала смену темы и брала вычисленное
 * значение `--fps-paper` с корня документа. В хроме это работало (замерено:
 * четыре переключения подряд, метка совпала с бумагой каждый раз), а на
 * айфоне полоса стала отставать РОВНО НА ОДИН ШАГ: на светлой теме тёмная,
 * на тёмной белая.
 *
 * Отставание на шаг — это подпись под причиной. Значит, метка ставилась
 * исправно, но цветом, который был ДО переключения: вебкит отдавал старое
 * вычисленное значение свойства, потому что стили после смены класса ещё не
 * пересчитал. Наблюдатель за изменениями работает микрозадачей, а
 * пересчёт стилей ей ничего не должен.
 *
 * Поэтому цвет здесь берётся не из стилей, а из самой темы: класс на корне
 * — это и есть источник правды о ней, и он у нас в руках раньше любого
 * пересчёта.
 */
export const PAPER = {
  light: "#ffffff",
  dark: "#1f2023",
} as const;

/** Метку ставит и разметка окна, и этот компонент — правило у них одно. */
export function paperOf(root: Element): string {
  return root.classList.contains("dark") ? PAPER.dark : PAPER.light;
}

/**
 * Цвет верхней полосы браузера.
 *
 * --- Что вообще случилось -------------------------------------------------
 *
 * Полосу над страницей — ту, где адрес, — сафари на айфоне красит само,
 * подбирая цвет под страницу. Пока приложение об этом цвете не заявляло
 * ничего, полоса менялась вместе с темой. Потом появился манифест, а в
 * манифесте `theme_color`, один на все темы: манифест описывает
 * ПРИЛОЖЕНИЕ, а не текущий его вид. Заявленный цвет сафари предпочитает
 * своей догадке — и полоса застряла.
 *
 * --- Почему меткой, а не через `viewport.themeColor` ----------------------
 *
 * Next.js умеет объявить `theme-color` разметкой, в том числе двумя
 * значениями под `prefers-color-scheme`. Здесь это не годится: тема у
 * приложения — ВЫБОР ЧЕЛОВЕКА, а не настройка системы. Тёмная стоит по
 * умолчанию, и у человека со светлой системой разметка дала бы белую
 * полосу над тёмной страницей.
 *
 * --- Почему слушается КЛАСС, а не хук тем ---------------------------------
 *
 * Тот же приём, что у лампы: тему на корень кладёт классом сам
 * `next-themes`, и класс — единственное место, где она уже разрешена в
 * конкретную. «Как в системе» к этому времени превращено в светлую или
 * тёмную, а хук вернул бы слово «system», по которому цвета не выбрать.
 *
 * --- Почему метка пересоздаётся, а не правится ----------------------------
 *
 * Старый узел удаляется, новый добавляется. Правка `content` у живой метки
 * — вещь, которую вебкит замечает не всегда, и проверить это отсюда
 * нечем: на настольном браузере работают оба способа. Пересоздание же
 * работает наверняка и стоит одного узла в шапке документа.
 *
 * Первую установку делает не этот компонент, а короткая вставка в разметке
 * окна: она выполняется ДО первой отрисовки, и полоса не успевает мигнуть
 * чужим цветом. Здесь — только поддержание при переключении.
 */
export function ThemeColour() {
  useEffect(() => {
    const root = document.documentElement;

    const apply = () => {
      const colour = paperOf(root);
      const meta = document.head.querySelector<HTMLMetaElement>('meta[name="theme-color"]');
      if (meta?.content === colour) return;

      meta?.remove();
      const fresh = document.createElement("meta");
      fresh.name = "theme-color";
      fresh.content = colour;
      document.head.appendChild(fresh);
    };

    apply();
    const watcher = new MutationObserver(apply);
    watcher.observe(root, { attributes: true, attributeFilter: ["class"] });
    return () => watcher.disconnect();
  }, []);

  return null;
}
