"use client";

import { useEffect } from "react";

/**
 * Цвет верхней полосы браузера.
 *
 * --- Что сломалось --------------------------------------------------------
 *
 * Полосу над страницей — ту, где адрес, — сафари на айфоне красит сам,
 * подбирая цвет под страницу. Пока приложение об этом цвете не заявляло
 * ничего, полоса меняласьвместе с темой: страница почернела — почернела и
 * она.
 *
 * Потом появился манифест, а в манифесте `theme_color`, и он один на все
 * темы: манифест — свойство приложения, а не текущего его вида. Сафари
 * заявленный цвет предпочитает своей догадке, и полоса застряла тёмной
 * навсегда — даже на светлой теме.
 *
 * --- Почему меткой, а не через `viewport.themeColor` ----------------------
 *
 * Next.js умеет объявить `theme-color` разметкой, в том числе двумя
 * значениями под `prefers-color-scheme`. Здесь это не годится: тема у
 * приложения — ВЫБОР ЧЕЛОВЕКА, а не настройка системы. Тёмная стоит по
 * умолчанию, и у человека со светлой системой разметка дала бы белую
 * полосу над тёмной страницей — ровно ту рассогласованность, ради которой
 * всё и чинится.
 *
 * Поэтому цвет ставится из браузера и по факту: берётся `--fps-paper`,
 * то есть та самая бумага, которой залита страница. Не переписывается
 * руками — читается вычисленным значением с корня документа, и разойтись
 * с палитрой не может.
 *
 * --- Почему слушается КЛАСС, а не хук тем ---------------------------------
 *
 * Тот же приём, что у лампы: тему на корень кладёт классом сам
 * `next-themes`, и класс — единственное место, где она уже разрешена в
 * конкретную. «Как в системе» к этому времени превращено в светлую или
 * тёмную, а хук вернул бы слово «system», по которому цвета не выбрать.
 *
 * Первую установку делает не этот компонент, а короткая вставка в разметке
 * окна: она выполняется ДО первой отрисовки, и полоса не успевает мигнуть
 * чужим цветом. Здесь — только поддержание при переключении.
 */
export function ThemeColour() {
  useEffect(() => {
    const apply = () => {
      const paper = getComputedStyle(document.documentElement)
        .getPropertyValue("--fps-paper")
        .trim();
      if (!paper) return;

      let meta = document.head.querySelector<HTMLMetaElement>('meta[name="theme-color"]');
      if (!meta) {
        meta = document.createElement("meta");
        meta.name = "theme-color";
        document.head.appendChild(meta);
      }
      meta.content = paper;
    };

    apply();
    const watcher = new MutationObserver(apply);
    watcher.observe(document.documentElement, {
      attributes: true,
      attributeFilter: ["class"],
    });
    return () => watcher.disconnect();
  }, []);

  return null;
}
