import { cn } from "@/lib/utils/cn";

/**
 * Надписи-действия в шапке: слово слева, знак справа.
 *
 * --- Откуда такой вид -------------------------------------------------------
 *
 * В шапке слева стоит знак сайта и его название — квадраты и «ГРАФИК 1|3»
 * тем же узким прописным шрифтом. Кнопка справа, нарисованная плашкой с
 * мелким значком из набора, читалась рядом с ними как деталь из другого
 * приложения: два разных языка в одной строке высотой в четыре рема.
 *
 * Поэтому справа — то же самое, только зеркально: слово тем же шрифтом и
 * того же кегля, за ним знак того же размера, что логотип. Строка шапки
 * становится одним предметом с двумя концами, а не плашкой слева и
 * плашкой справа.
 *
 * --- Почему без плашки ------------------------------------------------------
 *
 * Плашки нет и у названия сайта слева — оно ссылка домой и держится одним
 * словом. Для равновесия её не должно быть и справа: заливка там сделала
 * бы правый конец строки тяжелее левого, а никакого преимущества у него
 * нет. Нажимаемость объясняет курсор, наведение — приглушение, фокус —
 * обводка.
 *
 * --- Что у знаков общего ----------------------------------------------------
 *
 * Размер (как у логотипа), геометрия скруглений и один цвет: зелёный
 * `verify` — тот же, которым на сетке отмечена отработанная смена.
 * Сигнальный красный здесь не годится: он означает «требует решения
 * человека» и занят переработкой и отказами. Серое в знаках — `rule-strong`,
 * линовка: это части рисунка, а не его смысл.
 */

/** Слово действия: тот же шрифт, кегль и цвет, что у названия сайта. */
export const HEADER_WORD = cn(
  "font-display text-xl font-bold uppercase leading-none tracking-wide",
  "whitespace-nowrap text-black/80 dark:text-ink",
);

/** Само действие: слово и знак в строку. */
export const HEADER_ACTION = cn(
  // `text-ink` — на случай, если в знаке заведётся `currentColor`: без
  // него ссылка отдаёт цвет браузера по умолчанию. Замечено глазами на
  // светлой теме, когда обводки знака были `currentColor`: квадраты
  // выходили сиреневыми.
  "inline-flex shrink-0 cursor-pointer items-center gap-2 rounded-xs no-underline text-ink",
  "transition-opacity hover:opacity-80",
  "focus-visible:outline-2 focus-visible:outline-offset-4 focus-visible:outline-ink",
);

/** Размер знака — ровно логотип: они стоят в одной строке. */
const ЗНАК = "size-7 shrink-0";

/**
 * Цвет «пустых» частей знака — ровно тот же, что у пустых квадратов
 * логотипа (`ui/logo.tsx`): тёплый серый `#8a8578` в сорока пяти
 * процентах. Не `currentColor` и не линовка: знаки стоят в одной строке
 * с логотипом, и любое расхождение в полутоне читается как разные
 * наборы значков, собранные из разных мест.
 */
export const MARK_EMPTY = { stroke: "#8a8578", opacity: 0.45 } as const;

/**
 * То же самое классами — для значков из набора (`lucide`), которые берут
 * цвет из `currentColor` и своих атрибутов не имеют.
 */
export const MARK_EMPTY_CLASS = "text-[#8a8578] opacity-45";

const ПУСТОЕ = MARK_EMPTY;

/**
 * Дверь — у входа.
 *
 * Открытая дверь, а не стрелка в проём из набора значков: вход в учётную
 * запись это не направление движения, а место, куда входят. Полотно
 * залито зелёным, коробка — линовкой, ручка затемнением на полотне.
 */
export function DoorMark({ className }: { className?: string }) {
  return (
    <svg viewBox="0 0 24 24" fill="none" aria-hidden className={cn(ЗНАК, className)}>
      {/* Коробка занимает рисунок почти целиком — как квадраты логотипа
          (`ui/logo.tsx`): знаки стоят в одной строке и обязаны весить
          одинаково. */}
      <rect
        x="3.6"
        y="1.6"
        width="16.8"
        height="20.8"
        rx="2.8"
        strokeWidth="1.6"
        {...ПУСТОЕ}
      />
      {/* Полотно открыто на зрителя: дальний край короче ближнего, оттого
          трапеция, а не прямоугольник. */}
      <path d="M6 3.8 L16.2 5.6 V18.4 L6 20.2 Z" className="fill-verify" />
      {/* Ручка — затемнение, а не отдельный цвет: полотно одного тона в
          обеих темах, и чёрный с долей прозрачности верен на любой. */}
      <circle cx="14.4" cy="12" r="1" className="fill-black/45" />
    </svg>
  );
}

/**
 * Три полосы — у меню. Они же крестик, когда раздел открыт.
 *
 * --- Почему полосы одного цвета ---------------------------------------------
 *
 * Зелёной средней полосой знак говорил то же, что знак сайта: из
 * нескольких частей занята одна. Но у меню занимать нечего — оно не
 * выбор, а дверь к выбору, — и цвет обещал смысл, которого нет. Теперь
 * все три одинаковы, и зелёное в шапке осталось там, где оно и правда
 * что-то значит: у входа и у перехода к расчёту.
 *
 * --- Почему крестик, а не второй значок ------------------------------------
 *
 * Пока открыт раздел, та же кнопка его закрывает (`header-menu.tsx`), и
 * сказать об этом нужно до нажатия. Подменить знак на крестик из набора
 * значило бы в один миг убрать один предмет и поставить другой: глаз
 * читает это как мигание, а не как превращение.
 *
 * Поэтому крестик — те же самые полосы: средняя гаснет, крайние съезжаются
 * к середине и расходятся на сорок пять градусов. Движение занимает
 * двести миллисекунд и видно целиком, и оно же объясняет, что закрывать
 * будут здесь.
 *
 * Поворот вокруг середины каждой полосы: `transform-box: fill-box` берёт
 * началом отсчёта саму полосу, а не рисунок целиком, — без него полосы
 * уехали бы по дуге вокруг левого верхнего угла. Смещение 7,4 — половина
 * просвета между крайней полосой и средней: от него зависит, сойдутся
 * перекладины ровно в середине или крест выйдет кривым.
 */
export function MenuMark({ cross, className }: { cross?: boolean; className?: string }) {
  const полоса = cn(
    "[transform-box:fill-box] [transform-origin:center]",
    "transition-[translate,rotate,opacity] duration-200 ease-out",
  );

  return (
    <svg viewBox="0 0 24 24" aria-hidden className={cn(ЗНАК, className)}>
      {/* Полосы разведены по всей высоте рисунка: рядом с квадратами
          логотипа сжатая стопка читалась бы как знак поменьше. */}
      <rect
        x="2"
        y="3.4"
        width="20"
        height="2.4"
        rx="1.2"
        fill={ПУСТОЕ.stroke}
        opacity={ПУСТОЕ.opacity}
        className={cn(полоса, cross === true && "translate-y-[7.4px] rotate-45")}
      />
      <rect
        x="2"
        y="10.8"
        width="20"
        height="2.4"
        rx="1.2"
        fill={ПУСТОЕ.stroke}
        opacity={ПУСТОЕ.opacity}
        className={cn(полоса, cross === true && "opacity-0")}
      />
      <rect
        x="2"
        y="18.2"
        width="20"
        height="2.4"
        rx="1.2"
        fill={ПУСТОЕ.stroke}
        opacity={ПУСТОЕ.opacity}
        className={cn(полоса, cross === true && "-translate-y-[7.4px] -rotate-45")}
      />
    </svg>
  );
}

/**
 * Четыре клетки с занятым левым нижним углом — у легенды.
 *
 * Тот же рисунок, что у знака сайта, и занятая клетка в нём — цвета
 * отгула (`rest`): на сетке этим цветом помечен день, которым
 * расплачиваются за переработку. Кнопка открывает легенду — перечень
 * того, чем помечены клетки, — и знак называет её ровно тем, о чём она:
 * клеткой с цветом.
 *
 * Занят левый НИЖНИЙ угол, а не левый верхний: верхний левый занят знаком
 * сайта, и два одинаковых по композиции знака на одном экране читались бы
 * как один и тот же.
 */
export function LegendMark({ className }: { className?: string }) {
  const контур = {
    ...ПУСТОЕ,
    strokeWidth: 1.5,
    rx: 1.75,
    width: 8.5,
    height: 8.5,
  } as const;

  return (
    <svg viewBox="0 0 24 24" fill="none" aria-hidden className={cn(ЗНАК, className)}>
      <rect x="1.75" y="1.75" {...контур} />
      <rect x="13.75" y="1.75" {...контур} />
      <rect x="1" y="13" width="10" height="10" rx="2" className="fill-rest" />
      <rect x="13.75" y="13.75" {...контур} />
    </svg>
  );
}
