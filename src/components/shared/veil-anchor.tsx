"use client";

import { useEffect } from "react";

/**
 * Продолжение дымки над кромкой окна — то, что видно под полупрозрачной
 * верхней строкой браузера.
 *
 * --- Что за полоса и почему до неё не дотягивались ---------------------------
 *
 * У телефонного браузера окон два. Одно — страничное: в нём считается вёрстка,
 * и в нём же стоит всё закреплённое. Другое — видимое: то, что человек
 * действительно видит между строкой адреса и клавиатурой. Обычно они совпадают,
 * но у сафари и у встроенных браузеров верхняя строка полупрозрачна: видимое
 * окно начинается НИЖЕ страничного, а в промежутке между ними видно саму
 * страницу — тот самый уезжающий вверх текст.
 *
 * Всё закреплённое браузер держит по кромке ВИДИМОГО окна, и до промежутка
 * такие слои не достают в принципе: они начинаются ровно там, где он кончается.
 * Ни отрицательные отступы, ни доли высоты, ни `viewport-fit=cover` этого не
 * меняют — промежуток лежит в координатах СТРАНИЦЫ, а не окна.
 *
 * --- Что делает этот слой ----------------------------------------------------
 *
 * Он липкий, то есть живёт в потоке страницы и держится за её верх, а не за
 * кромку видимого окна. Оттуда он и накрывает промежуток — сплошной бумагой
 * вверху и той же долей, что у дымки, внизу, на стыке с ней.
 *
 * Высоту промежутка браузер сообщает сам: `visualViewport.offsetTop` — это
 * расстояние от верха страничного окна до верха видимого. Её и подставляет
 * `--vv-gap`. В настольном браузере она всегда ноль, слой целиком уходит выше
 * кромки и не рисуется вовсе — там не меняется ничего.
 *
 * --- Почему замером, а не «на глаз» ------------------------------------------
 *
 * Высота верхней строки разная у сафари, у приложения с домашнего экрана и у
 * встроенного браузера телеграма, и меняется на ходу: строка сжимается при
 * прокрутке. Любое назначенное число было бы верным ровно в одном случае из
 * трёх, а в остальных оставляло бы либо прореху, либо лишнюю бумагу поперёк
 * страницы.
 */
export function VeilAnchor() {
  useEffect(() => {
    const vv = window.visualViewport;
    if (!vv) return;

    const apply = () => {
      // Отрицательным `offsetTop` не бывает, но округление вниз оставляет
      // полоску в долю точки: полтора десятка таких — уже видимая черта.
      const gap = Math.max(0, Math.ceil(vv.offsetTop));
      document.documentElement.style.setProperty("--vv-gap", `${gap}px`);
    };

    apply();
    // Оба события нужны: при прокрутке верхняя строка сжимается (меняется
    // `resize`), при жесте страницу можно оттянуть внутри окна (`scroll`).
    vv.addEventListener("resize", apply);
    vv.addEventListener("scroll", apply);
    return () => {
      vv.removeEventListener("resize", apply);
      vv.removeEventListener("scroll", apply);
    };
  }, []);

  return (
    <div aria-hidden className="veil-anchor">
      <span />
    </div>
  );
}
