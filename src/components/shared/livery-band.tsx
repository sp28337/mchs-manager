/**
 * Ливрейная полоса — нижняя кромка страницы.
 *
 * --- Что это -------------------------------------------------------------
 *
 * Две белые полосы по красному полю — то, что человек видит на морде
 * КамАЗа, выезжающего из ворот части. Над ними тонкая оранжевая лента:
 * светоотражающая полоса с борта автоцистерны. Три цвета, шестнадцать
 * пикселей, край страницы.
 *
 * --- Почему это не «просто украшение» ------------------------------------
 *
 * Сайт разговаривает с человеком о его табеле, и весь остальной интерфейс
 * намеренно сух: линовка, моноширинные числа, ссылки на приказы. Одного
 * места, где виден не документ, а машина, здесь достаточно — и оно должно
 * быть там, где чтение уже закончено. Внизу, после подвала, оно ничего не
 * перебивает.
 *
 * --- Почему `aria-hidden` ------------------------------------------------
 *
 * Полоса ничего не сообщает и никуда не ведёт. Программе чтения экрана
 * нечего о ней сказать, кроме «графика», а «графика» в конце страницы —
 * это шум, за который человек платит временем.
 *
 * Красный здесь — ливрейный (`--fps-livery-red`), а не сигнальный.
 * Разница объявлена в `globals.css` и существенна: сигнальным цветом в
 * этом интерфейсе помечено то, что требует решения человека, и кромка
 * внизу страницы не должна претендовать на это значение.
 */
export function LiveryBand() {
  return <div aria-hidden className="livery-band w-full" />;
}
