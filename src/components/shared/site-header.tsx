import Link from "next/link";
import type { ReactNode } from "react";

import { Logo } from "@/components/ui/logo";
import { ScheduleMark } from "@/components/shared/schedule-mark";
import { cn } from "@/lib/utils/cn";

/**
 * Шапка сайта.
 *
 * --- Что сюда попало и почему -------------------------------------------
 *
 * Шапка — самое дорогое место на странице, и попасть в неё должно только
 * то, что нужно ОТКУДА УГОДНО. Таких вещей три:
 *
 * * знак и название — они же ссылка домой; без неё с калькулятора некуда
 *   вернуться;
 * * переключатель темы — относится к окну, а не к содержимому, и потому
 *   не имеет своего места ни на одной из страниц;
 * * действие страницы (`action`) — на лендинге это переход к расчёту.
 *
 * Четвёртое — кнопки рабочего экрана (`tools`): настройки и выгрузка
 * профиля в файл. Они ни к какому месту страницы не
 * привязаны и нужны отовсюду. Выгрузка здесь не для симметрии: данные
 * лежат только в браузере, и очистка кэша стирает год внесённых отпусков
 * — кнопка, которая от этого спасает, обязана быть видна не только в
 * подвале, докуда ещё нужно долистать.
 *
 * Больше ничего. Разделов у сайта два, и меню из двух пунктов — это
 * не навигация, а украшение.
 *
 * --- Что уступает место на телефоне --------------------------------------
 *
 * Тесно становится от кнопок рабочего экрана, и сжимаются сперва они: ниже
 * `sm` (640 точек, там три подписи перестают влезать) от кнопок остаются
 * значки, а имя действия достаётся программе чтения из `aria-label`.
 *
 * Ниже 360 точек не хватает и этого: три значка со знаком и названием в
 * строку не встают. Тогда уходит название — с глаз, но не из разметки
 * (`sr-only`), чтобы ссылка домой не осталась безымянной.
 *
 * --- Почему строка не переносится ----------------------------------------
 *
 * Раньше строка была `flex-wrap`, и на промежуточных ширинах кнопки
 * съезжали под название второй строкой — шапка высотой в шесть рем с
 * содержимым, вылезающим за неё. Перенос убран совсем: ширины подобраны
 * так, чтобы содержимое влезало на любом экране, а порядок сжатия задан
 * заранее — сперва кнопки теряют подписи, потом уходит название сайта.
 * Сами кнопки не жмутся никогда: сжатая кнопка это обрезанная подпись, а
 * не выигранное место.
 *
 * --- Почему она не липкая ------------------------------------------------
 *
 * Календарь на год — двенадцать сеток на всю высоту экрана, и полоса,
 * закреплённая сверху, отняла бы у него строку в самом длинном месте.
 */

export interface SiteHeaderProps {
  /** Главное действие страницы. */
  action?: ReactNode;
  /** Кнопки рабочего экрана: настройки и выгрузка. */
  tools?: ReactNode;
  className?: string;
}

export function SiteHeader({ action, tools, className }: SiteHeaderProps) {
  return (
    // Шапка закреплена, но БЕЗ `top`: стоит она там, где стояла бы в
    // потоке, то есть по верхней кромке содержимого страницы. Отступ на
    // полосу под часами задан один раз на `body` (`globals.css`,
    // «Безопасные зоны телефона»), и шапка получает его вместе со всем
    // остальным — собственный отступ здесь сложился бы с ним вдвое.
    <header className={cn("fixed z-100 w-full group", className)}>
      <div className="mx-auto flex h-16 w-full flex-nowrap items-center gap-x-4 py-3 px-6 sm:gap-x-6 2xl:max-w-[2000px]">
        <Link
          href="/"
          // Знак и кнопки помечены не для оформления: на телефоне окно
          // настроек открывается листом во весь экран, и его шапка
          // ЗАМЕЩАЕТ эту — значок настроек уезжает на место знака, а знак
          // и кнопки к этому времени должны уйти. Метка даёт переходу
          // зацепку и точку отсчёта для замера пути (`header-tools.tsx`).
          data-brand
          className="group flex min-w-0 items-center gap-2.5 rounded-xs focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-trace"
        >
          <Logo className="size-7 shrink-0 text-signal" />
          {/* Ниже 360 точек название уходит, оставляя знак.
              -------------------------------------------------------------
              Кнопок в шапке три, и на самом узком телефоне (320 — это
              iPhone SE первых лет) название с ними в строку не помещается:
              замером оно переносилось на вторую строку, «ГРАФИК» над «1 3»,
              и шапка переставала быть строкой.

              Порядок сжатия при этом тот же, что был объявлен всегда:
              сперва кнопки теряют подписи, потом уходит название. Уходит
              оно только с глаз — `sr-only` оставляет его программе чтения,
              и ссылка домой не становится безымянной. */}
          <span className="min-w-0 leading-none max-[359px]:sr-only">
            <span className="block whitespace-nowrap font-display text-black/80 dark:text-ink text-xl font-bold uppercase leading-tight tracking-wide">
              {/* Пробел перед цифрами намеренный: в тексте строки
                  склеиваются, и программа чтения произносит «График13».
                  Сами цифры называют выбранный график и меняются вместе с
                  ним (`ScheduleMark`). */}
              График <ScheduleMark />
            </span>
          </span>
        </Link>

        {/* Кнопки не сжимаются ни при какой ширине: сжатая кнопка — это
            обрезанная подпись, а не выигранное место. Уступает название. */}
        <div data-tools className="ml-auto flex shrink-0 items-center gap-2 sm:gap-3">
          {tools}
          {action}
        </div>
      </div>
    </header>
  );
}
