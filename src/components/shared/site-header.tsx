import Link from "next/link";
import type { ReactNode } from "react";

import { Logo } from "@/components/ui/logo";
import { cn } from "@/lib/utils/cn";

/**
 * Шапка сайта.
 *
 * --- Что сюда попало и почему -------------------------------------------
 *
 * Шапка — самое дорогое место на странице, и попасть в неё должно только
 * то, что нужно ОТКУДА УГОДНО. Таких вещей три:
 *
 * * знак и название — они же ссылка домой; без неё с калькулятора некуда
 *   вернуться;
 * * переключатель темы — относится к окну, а не к содержимому, и потому
 *   не имеет своего места ни на одной из страниц;
 * * действие страницы (`action`) — на лендинге это переход к расчёту.
 *
 * Четвёртое появилось позже — кнопки рабочего экрана (`tools`):
 * настройки, расчёт в деньгах и выгрузка в файл. Они ни к какому месту
 * страницы не привязаны и нужны отовсюду. Выгрузка здесь не для
 * симметрии: данные лежат только в браузере, и очистка кэша стирает год
 * внесённых отпусков — кнопка, которая от этого спасает, обязана быть
 * видна не только в подвале, докуда ещё нужно долистать.
 *
 * Пятое — имя владельца анкеты (`person`). Это заголовок рабочего
 * экрана: чья это переработка. Он стоял первой строкой в самой странице
 * и уезжал вверх при первой же прокрутке — то есть отвечал на свой
 * вопрос только пока на него смотрели. В закреплённой шапке он отвечает
 * всегда и не стоит ни строчки высоты.
 *
 * Больше ничего. Разделов у сайта два, и меню из двух пунктов — это
 * не навигация, а украшение.
 *
 * --- Когда название уступает место ---------------------------------------
 *
 * Только когда места действительно не хватает, и не хватает его ровно по
 * одной причине — кнопкам рабочего экрана. «Калькулятор переработки для
 * пожарных» это две строки, и вместе с ними в телефон они не помещаются.
 *
 * Поэтому решение принимает не страница, а сам факт наличия `tools`: на
 * лендинге кнопок нет, там ничего не теснится, и название остаётся при
 * любой ширине. Связывать это с адресом страницы значило бы держать в
 * шапке знание о том, какие бывают страницы, — и однажды забыть его
 * обновить.
 *
 * Порог — `lg`, замером: знак, имя человека и три кнопки занимают около
 * шестисот семидесяти точек, название сайта — ещё двести; вместе они
 * встают начиная с 1024. Уходит именно НАЗВАНИЕ САЙТА, а не имя: на
 * своей странице он знает, куда пришёл, и «чья это переработка» важнее
 * «как называется сайт». Ссылка домой при этом не немая — подпись
 * остаётся программе чтения, просто перестаёт рисоваться.
 *
 * --- Почему строка не переносится ----------------------------------------
 *
 * Раньше строка была `flex-wrap`, и на промежуточных ширинах кнопки
 * съезжали под название второй строкой — шапка высотой в шесть рем с
 * содержимым, вылезающим за неё. Перенос убран совсем: ширины подобраны
 * так, чтобы содержимое влезало на любом экране, а порядок сжатия задан
 * заранее — сперва три кнопки сворачиваются в одну (`md`), потом уходит
 * название сайта (`lg`). Кнопки не жмутся никогда: сжатая кнопка это
 * обрезанная подпись, а не выигранное место.
 *
 * --- Почему она не липкая ------------------------------------------------
 *
 * Календарь на год — двенадцать сеток на всю высоту экрана, и полоса,
 * закреплённая сверху, отняла бы у него строку в самом длинном месте.
 */

export interface SiteHeaderProps {
  /** Подпись под названием: чем именно занята эта страница. */
  tagline?: string;
  /** Главное действие страницы. */
  action?: ReactNode;
  /** Кнопки рабочего экрана: настройки, деньги, выгрузка. */
  tools?: ReactNode;
  /** Имя владельца анкеты — заголовок рабочего экрана. */
  person?: string;
  className?: string;
}

export function SiteHeader({
  tagline,
  action,
  tools,
  person,
  className,
}: SiteHeaderProps) {
  return (
    <header className={cn("fixed w-full z-100  bg-linear-to-b from-paper from-50% to-transparent h-24", className)}>
      <div className="mx-auto flex h-24 w-full flex-nowrap items-center gap-x-4 py-3 pl-6 pr-6 sm:gap-x-6 lg:pl-9 2xl:max-w-[2000px]">
        <Link
          href="/"
          className="group flex min-w-0 items-center gap-2.5 rounded-xs focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-trace"
        >
          <Logo className="size-7 shrink-0 text-signal" />
          {/* Название скрыто, но не удалено: `sr-only` оставляет его
              программе чтения, и ссылка домой не превращается в безымянную
              картинку. */}
          <span className={cn("min-w-0 leading-none", tools && "max-lg:sr-only")}>
            <span className="block font-display text-black/80 dark:text-ink text-sm font-bold uppercase leading-tight tracking-wide group-hover:underline">
              {/* Пробел перед второй строкой намеренный: `block` делит
                  строки визуально, но в тексте они склеиваются, и
                  программа чтения произносит «переработкидля». */}
              Калькулятор переработки{" "}
              <span className="block text-ink-muted">для пожарных</span>
            </span>
          </span>
        </Link>

        {/* Имя и подпись — одним блоком, отчёркнутым от названия сайта:
            это уже не сайт, а страница. Подпись прячется первой, имя
            остаётся до последнего. */}
        {person || tagline ? (
          <div
            className={cn(
              "min-w-0 border-l border-rule pl-4 sm:pl-6",
              // Своей ширины блок не требует: имя длиной в строку сожмётся
              // многоточием, а не вытолкнет кнопки.
              person ? "" : "hidden lg:block",
            )}
          >
            {person ? (
              <h1 className="truncate text-base leading-tight sm:text-lg">{person}</h1>
            ) : null}
            {tagline ? (
              <p
                className={cn(
                  "truncate text-xs text-ink-muted",
                  person ? "hidden sm:block" : "max-w-xs",
                )}
              >
                {tagline}
              </p>
            ) : null}
          </div>
        ) : null}

        {/* Кнопки не сжимаются ни при какой ширине: сжатая кнопка — это
            обрезанная подпись, а не выигранное место. Уступает название. */}
        <div className="ml-auto flex shrink-0 items-center gap-2 sm:gap-3">
          {tools}
          {action}
        </div>
      </div>
    </header>
  );
}
