import Link from "next/link";
import type { ReactNode } from "react";

import { HeaderMenu, HeaderMenuBone, type OpenSection } from "@/components/shared/header-menu";
import { Logo } from "@/components/ui/logo";
import { ScheduleMark } from "@/components/shared/schedule-mark";
import { cn } from "@/lib/utils/cn";

/**
 * Шапка сайта.
 *
 * --- Что сюда попало и почему -------------------------------------------
 *
 * Шапка — самое дорогое место на странице, и попасть в неё должно только
 * то, что нужно ОТКУДА УГОДНО. Таких вещей две:
 *
 * * знак и название — они же ссылка домой; без неё с калькулятора некуда
 *   вернуться;
 * * меню (`menu` + `HeaderMenu`) — слово и три полосы у правого края. В
 *   нём и действия страницы, и учётная запись: на рабочем экране
 *   настройки, статистика, проводник и выгрузка в файл, на страницах
 *   учётной записи — переход к расчёту, под ними вход или выход.
 *
 * Больше ничего. Здесь было и третье место — «действие страницы» между
 * названием и меню: на посадочной в нём стоял переключатель темы, на
 * странице учётной записи — «ОТКРЫТЬ ГРАФИК». Оба ушли (тема — знаком в
 * угол окна, переход — строкой в меню), и вместе с ними ушло место:
 * правый конец шапки на всех страницах одинаков, и человек находит меню
 * там же, где оставил.
 *
 * Одно исключение — середина строки на рабочем экране (`center`): там
 * стоит выбор учётного периода. Он отвечает на вопрос «за какой срок всё,
 * что под шапкой», — и цифры полосы итога, и сетка считаются по нему, —
 * поэтому стоит над всем этим разом, а не при одном из них.
 *
 * --- Как середина остаётся серединой --------------------------------------
 *
 * Строка с серединой — сетка в три колонки: `1fr auto 1fr`. Крайние
 * колонки делят остаток поровну, и средняя стоит ровно по оси экрана —
 * симметрично знаку сайта и меню, какой бы длины ни были они сами.
 *
 * Сдвиг, когда середине мешает имя профиля, получается из той же сетки,
 * без замера скриптом. У `1fr` нижняя граница — содержимое колонки: если
 * знак сайта с именем шире своей половины, левая колонка раздаётся до их
 * ширины, а остаток уходит правой — и кнопка отъезжает вправо ровно
 * настолько, насколько мешает имя, с тем же зазором, что везде в строке.
 * Скрипт здесь означал бы кадр, нарисованный до замера, — а заглушка
 * рабочего экрана, где скрипта нет вовсе, не совпала бы с расчётом.
 *
 * Обратная сторона: колонка не уже своего содержимого, и очень длинное
 * имя вытолкнуло бы меню за край. Поэтому у имени в такой строке потолок
 * от ширины самой строки (`TITLE_CAP`): за ним оно обрезается
 * многоточием, а меню и кнопка остаются на экране.
 *
 * --- Кто называет открытый раздел ----------------------------------------
 *
 * Правый конец строки, а не название сайта. Раньше было наоборот: знак
 * сайта подменял «ГРАФИК 1|3» на «НАСТРОЙКИ», и на узком экране слово
 * уступало место значку. Беда такого решения в том, что раздел называла
 * ссылка ДОМОЙ: человек читал «НАСТРОЙКИ» и нажимал по ним, ожидая
 * настройки, а уходил на посадочную страницу.
 *
 * Теперь название раздела стоит там, где его и закрывают, — на самой
 * кнопке меню (`menu-section` в `HeaderMenu`), а знак сайта всегда
 * называет сайт.
 *
 * --- Что уступает место на телефоне --------------------------------------
 *
 * С тех пор как действия страницы уехали в меню, в шапке один предмет
 * справа на любом экране, и тесно становится только названию сайта. Оно и
 * уступает: ниже 400 точек от «ГРАФИК 1|3» остаются цифры графика — они
 * называют график самого человека. Уходит слово только с глаз: `sr-only`
 * оставляет его в разметке, и ссылка домой на любой ширине называется
 * полностью.
 *
 * Со средней кнопкой уступает и меню: на узком экране от него остаются
 * три полосы без слова (`compact` у `HeaderMenu`), иначе кнопка периода в
 * строку не встала бы. На самых узких, меньше 360 точек, ещё и просветы
 * ужаты до 12: на 320 точках «1|3», кнопка с самой длинной подписью и три
 * полосы с просветами по 16 встают впритык, без воздуха у краёв.
 *
 * --- Почему строка не переносится ----------------------------------------
 *
 * Раньше строка была `flex-wrap`, и на промежуточных ширинах кнопки
 * съезжали под название второй строкой — шапка высотой в шесть рем с
 * содержимым, вылезающим за неё. Перенос убран совсем: ширины подобраны
 * так, чтобы содержимое влезало на любом экране, а порядок сжатия задан
 * заранее — сперва название теряет слово, потом цифры.
 *
 * --- Почему она не липкая ------------------------------------------------
 *
 * Календарь на год — двенадцать сеток на всю высоту экрана, и полоса,
 * закреплённая сверху, отняла бы у него строку в самом длинном месте.
 */

/**
 * С какой ширины заголовок страницы стоит в шапке (`title`). Страница,
 * отдающая свой заголовок шапке, прячет собственный тем же порогом —
 * `md:hidden` у неё зеркало этого `md:flex`.
 */
const TITLE_FROM = "md:flex md:items-center";

/**
 * Потолок имени в строке с серединой.
 *
 * Отсчитан от ширины самой строки (`cqw` — строка объявлена контейнером),
 * за вычетом всего, что обязано встать в ней рядом с именем при самом
 * длинном содержимом: «ГРАФИК 1|3» (130 точек), кнопка периода — одни
 * часы (44), меню с самым длинным словом — «СТАТИСТИКА» с крестиком
 * (137) — и три просвета по 24. Всё вместе — 383 точки, числа — замер в
 * браузере. Короче потолка имя не обрезается никогда; длиннее —
 * обрезается многоточием, и меню остаётся на экране.
 *
 * Кнопка периода была плашкой с подписью («1-е полугодие» — 145 точек), и
 * потолок отсчитывался от неё (484); с одними часами имени достаётся на
 * сто с лишним точек больше.
 */
const TITLE_CAP = "md:max-w-[calc(100cqw-383px)]";

export interface SiteHeaderProps {
  /**
   * Заголовок страницы — в строке шапки, сразу за знаком сайта. Рабочий
   * экран кладёт сюда имя профиля.
   *
   * Показывается с `md`: на узком экране строка занята названием сайта и
   * меню, и имя там стоит над цифрами, в самой странице. Страница,
   * отдающая заголовок сюда, обязана прятать свой с того же порога
   * (`md:hidden`), иначе имя стояло бы дважды.
   */
  title?: ReactNode;
  /**
   * Середина строки — на рабочем экране кнопка учётного периода.
   *
   * Стоит по оси экрана, а когда мешает имя профиля — сдвигается вправо,
   * вплотную за ним (см. «Как середина остаётся серединой»). На узком
   * экране меню при ней теряет слово и остаётся тремя полосами.
   */
  center?: ReactNode;
  /**
   * Действия страницы — строками в меню (`MenuItem`).
   *
   * Рабочий экран кладёт сюда настройки, статистику, проводник и выгрузку
   * профиля в файл, страницы учётной записи и «нет такой» — переход к
   * расчёту (`OpenScheduleItem`). У остальных страниц своих действий нет,
   * и меню тогда состоит из одной учётной записи — а не вошедшему вместо
   * слова «Меню» показывается «Вход».
   */
  menu?: ReactNode;
  /**
   * Вместо меню — его кость: профиль ещё читается, и действий страницы
   * пока нет (`workspace-skeleton.tsx`). Без неё меню возникало бы в
   * шапке рывком в тот же миг, когда заглушка сменяется расчётом, — а вся
   * заглушка затем и существует, чтобы в этот миг ничего не дёргалось.
   */
  menuBone?: boolean;
  /**
   * Открытый раздел: его имя встаёт вместо слова «Меню», а три полосы
   * складываются в крестик. Нажатие тогда закрывает раздел.
   */
  section?: OpenSection;
  className?: string;
}

export function SiteHeader({
  title,
  center,
  menu,
  menuBone,
  section,
  className,
}: SiteHeaderProps) {
  const centered = center !== undefined;

  // `md:shrink-0` — с `md` название сайта не уступает места
  // заголовку страницы. Рядом с ним с этого порога стоит имя
  // профиля, а имя бывает любой длины: при равном праве сжиматься
  // длинное имя отнимало место у «ГРАФИК 1|3», и от названия
  // оставалось «ГРАФИК» без цифр. Уступать должно имя — у него для
  // этого и есть многоточие. Ниже `md` заголовка в шапке нет, и
  // название сжимается, как прежде, само (`min-w-0`).
  const brand = (
    <Link
      href="/"
      data-brand
      className="group flex min-w-0 items-center gap-2.5 rounded-xs focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ink md:shrink-0"
    >
      <Logo className="size-7 shrink-0 text-signal" />
      {/* `min-w-0` и обрезка — страховка, а не расчёт: меню в шапке не
          жмётся никогда, и слишком длинное название обязано обрезаться
          само, а не выталкивать его за край экрана. */}
      <span
        className={cn(
          "grid min-w-0 overflow-hidden font-display text-xl font-bold uppercase",
          "leading-tight tracking-wide whitespace-nowrap text-black/80 dark:text-ink",
        )}
      >
        <span>
          {/* Ниже 400 точек уходит СЛОВО, а цифры остаются.
              -------------------------------------------------------
              Убирать нужно именно слово. «График» — имя сервиса, и
              человек, добравшийся до своего расчёта, его уже знает; а
              цифры называют ЕГО график, тот самый, что он выбрал, и
              меняются вместе с ним. Из двух половин названия на узком
              экране полезна вторая.

              Порог назначен замером и успел поездить: при трёх кнопках
              в шапке он стоял на 360, при четырёх — на 400, а когда
              кнопки уехали в меню (`header-menu.tsx`), тесниться стало
              незачем. Оставлен на 400: на 360 точках «ГРАФИК 1|3» хоть
              и встаёт рядом с меню, но упирается в него впритык, а
              поле у края экрана читается лучше лишнего слова.

              Уходит слово только с глаз: `sr-only` оставляет его
              программе чтения, и ссылка домой не превращается в «1 3».
              Пробел спрятан вместе со словом — иначе цифры отъезжали
              бы от знака на его ширину.

              Пробел перед цифрами намеренный и там, где слово видно: в
              тексте строки склеиваются, и программа чтения произносит
              «График13».

              С кнопкой периода посередине порог тот же: «ГРАФИК 1|3»,
              кнопка с самой длинной подписью и три полосы меню с
              просветами занимают 335 точек, а строке на 400-точечном
              экране достаётся 352. */}
          <span className="max-[399px]:sr-only">{"График "}</span>
          <ScheduleMark />
        </span>
      </span>
    </Link>
  );

  // Заголовок страницы — сразу за названием сайта, на одной с ним
  // линии. Отступ между ними — те же шесть единиц, что поле шапки у
  // краёв экрана: имя стоит отдельным предметом, а не продолжением
  // «ГРАФИК 1|3», и при этом не отбегает от него к середине строки.
  //
  // `min-w-0` — чтобы длинное имя обрезалось (`truncate` у него
  // самого), а не выталкивало меню за край.
  const heading =
    title === undefined ? null : (
      <div className={cn("hidden min-w-0", TITLE_FROM, centered && TITLE_CAP)}>{title}</div>
    );

  return (
    // Шапка закреплена, но БЕЗ `top`: стоит она там, где стояла бы в
    // потоке, то есть по верхней кромке содержимого страницы. Отступ на
    // полосу под часами задан один раз на `body` (`globals.css`,
    // «Безопасные зоны телефона»), и шапка получает его вместе со всем
    // остальным — собственный отступ здесь сложился бы с ним вдвое.
    <header className={cn("fixed z-100 w-full group", className)}>
      <div
        className={cn(
          "mx-auto h-16 w-full items-center gap-x-4 py-3 px-6 sm:gap-x-6 2xl:max-w-[2000px]",
          centered
            ? // Контейнер — ради потолка имени (`TITLE_CAP`): он отсчитан
              // от ширины этой строки.
              "grid grid-cols-[1fr_auto_1fr] max-[360px]:gap-x-3 [container-type:inline-size]"
            : "flex flex-nowrap",
        )}
      >
        {centered ? (
          // Левая колонка — одним предметом: её ширина и есть то, о что
          // упирается середина. `min-w-0` здесь нет НАМЕРЕННО: с ним нижней
          // границей колонки стал бы ноль, и кнопка стояла бы по оси, даже
          // наехав на имя.
          <div className="flex items-center gap-x-4 max-[360px]:gap-x-3 sm:gap-x-6">
            {brand}
            {heading}
          </div>
        ) : (
          <>
            {brand}
            {heading}
          </>
        )}

        {centered ? <div className="flex justify-center">{center}</div> : null}

        {/* Справа — меню, последним и на каждой странице: правый верхний
            угол это то место, где его ищут, не читая страницу. Оно не
            сжимается — сжатая кнопка это обрезанная подпись, а не
            выигранное место; уступает название сайта. */}
        <div data-tools className="ml-auto flex shrink-0 items-center justify-self-end">
          {menuBone === true ? (
            <HeaderMenuBone compact={centered} />
          ) : (
            <HeaderMenu items={menu} section={section} compact={centered} />
          )}
        </div>
      </div>
    </header>
  );
}
