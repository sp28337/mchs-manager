import type { LucideIcon } from "lucide-react";
import Link from "next/link";
import type { ReactNode } from "react";

import { HeaderMenu, HeaderMenuBone } from "@/components/shared/header-menu";
import { Logo } from "@/components/ui/logo";
import { Materialize } from "@/components/ui/materialize";
import { ScheduleMark } from "@/components/shared/schedule-mark";
import { cn } from "@/lib/utils/cn";

/**
 * Шапка сайта.
 *
 * --- Что сюда попало и почему -------------------------------------------
 *
 * Шапка — самое дорогое место на странице, и попасть в неё должно только
 * то, что нужно ОТКУДА УГОДНО. Таких вещей три:
 *
 * * знак и название — они же ссылка домой; без неё с калькулятора некуда
 *   вернуться;
 * * действие страницы (`action`) — на лендинге это переключатель темы, на
 *   странице учётной записи переход к расчёту;
 * * меню (`menu` + `HeaderMenu`) — кружок с человечком у правого края. В
 *   нём и действия страницы, и учётная запись: на рабочем экране
 *   настройки, статистика, проводник и выгрузка в файл, под ними вход или
 *   выход.
 *
 * Больше ничего. Разделов у сайта два, и меню из двух пунктов — это
 * не навигация, а украшение.
 *
 * --- Что уступает место на телефоне --------------------------------------
 *
 * С тех пор как действия страницы уехали в меню, в шапке один предмет
 * справа на любом экране, и тесно становится только названию сайта. Оно и
 * уступает: ниже 400 точек от «ГРАФИК 1|3» остаются цифры графика — они
 * называют график самого человека. Уходит слово только с глаз: `sr-only`
 * оставляет его в разметке, и ссылка домой на любой ширине называется
 * полностью.
 *
 * Название ОТКРЫТОГО РАЗДЕЛА («Настройки», «Статистика», «Профили») уступает
 * место иначе — не пропадает, а становится своим значком (`BrandLabel`
 * ниже).
 *
 * --- Почему строка не переносится ----------------------------------------
 *
 * Раньше строка была `flex-wrap`, и на промежуточных ширинах кнопки
 * съезжали под название второй строкой — шапка высотой в шесть рем с
 * содержимым, вылезающим за неё. Перенос убран совсем: ширины подобраны
 * так, чтобы содержимое влезало на любом экране, а порядок сжатия задан
 * заранее — сперва кнопки теряют подписи, потом уходит название сайта.
 * Сами кнопки не жмутся никогда: сжатая кнопка это обрезанная подпись, а
 * не выигранное место.
 *
 * --- Почему она не липкая ------------------------------------------------
 *
 * Календарь на год — двенадцать сеток на всю высоту экрана, и полоса,
 * закреплённая сверху, отняла бы у него строку в самом длинном месте.
 */

export interface SiteHeaderProps {
  /** Главное действие страницы. */
  action?: ReactNode;
  /**
   * Действия страницы — строками в меню под кружком (`MenuItem`).
   *
   * Рабочий экран кладёт сюда настройки, статистику, проводник и выгрузку
   * профиля в файл. У остальных страниц своих действий нет, и меню тогда
   * состоит из одной учётной записи — а не вошедшему вместо кружка
   * показывается кнопка «Войти».
   */
  menu?: ReactNode;
  /**
   * Вместо меню — его кость: профиль ещё читается, и действий страницы
   * пока нет (`workspace-skeleton.tsx`). Без неё кружок возникал бы в
   * шапке рывком в тот же миг, когда заглушка сменяется расчётом, — а вся
   * заглушка затем и существует, чтобы в этот миг ничего не дёргалось.
   */
  menuBone?: boolean;
  className?: string;
  /**
   * Чем заменить «График 1|3» рядом со знаком — не убрать знак, а
   * переназвать то, что сейчас показано на экране под ним. Знак при этом
   * не трогается: он называет сайт всегда, вне зависимости от того, что
   * открыто, — рабочий экран, настройки или перечень правок.
   *
   * Задаёт рабочий экран, когда на телефоне вместо графика показаны
   * настройки (`workspace.tsx`, `header-tools.tsx`): человек не уходил со
   * страницы, и название рядом со знаком читает это вслух.
   */
  brandLabel?: ReactNode;
}

export function SiteHeader({
  action,
  menu,
  menuBone,
  className,
  brandLabel,
}: SiteHeaderProps) {
  const settled = brandLabel === undefined;
  return (
    // Шапка закреплена, но БЕЗ `top`: стоит она там, где стояла бы в
    // потоке, то есть по верхней кромке содержимого страницы. Отступ на
    // полосу под часами задан один раз на `body` (`globals.css`,
    // «Безопасные зоны телефона»), и шапка получает его вместе со всем
    // остальным — собственный отступ здесь сложился бы с ним вдвое.
    <header className={cn("fixed z-100 w-full group", className)}>
      <div className="mx-auto flex h-16 w-full flex-nowrap items-center gap-x-4 py-3 px-6 sm:gap-x-6 2xl:max-w-[2000px]">
        <Link
          href="/"
          data-brand
          className="group flex min-w-0 items-center gap-2.5 rounded-xs focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ink"
        >
          <Logo className="size-7 shrink-0 text-signal" />
          <span className="min-w-0 leading-none">
            {/* Обе надписи лежат в одной ячейке грида — так же, как
                приставка «Пере»/«Недо» в `BalanceCaption`: ширина ячейки
                считается по большей из них, и смена не дёргает соседей.
                Гаснет одна, проступает другая — знак рядом с ними не
                шевелится ни на точку. */}
            {/* `min-w-0` и обрезка — страховка, а не расчёт: кнопки в шапке
                не жмутся никогда (см. довод ниже), и слишком длинное
                название обязано обрезаться само, а не выталкивать их за
                край экрана. */}
            <span className="grid min-w-0 overflow-hidden">
              <Materialize
                show={settled}
                ariaHidden={!settled}
                durationClassName="duration-200"
                className="col-start-1 row-start-1 font-display text-black/80 dark:text-ink text-xl font-bold uppercase leading-tight tracking-wide whitespace-nowrap"
              >
                {/* Ниже 400 точек уходит СЛОВО, а цифры остаются.
                    -------------------------------------------------------
                    Кнопок в шапке четыре — со статистикой, — и на телефоне
                    название с ними в строку не влезает: знак ужимается
                    (`min-w-0`) и потому не переносится, а молча уезжает под
                    кнопки. Замером на 360 точках от «ГРАФИК 1|3»
                    оставалось «ГРАФИК 1»: цифры графика, ради которых
                    половина названия и держится, пропадали первыми.

                    Порог ехал вместе с числом кнопок: при трёх он стоял на
                    360 (там из-за них название переносилось на вторую
                    строку), четвёртая отняла ещё полсотни точек. Замером
                    порог теперь ровно между 360 (обрезано) и 400
                    (целиком).

                    Убирать при этом нужно именно слово. «График» — имя
                    сервиса, и человек, добравшийся до своего расчёта, его
                    уже знает; а цифры называют ЕГО график, тот самый, что
                    он выбрал, и меняются вместе с ним. Из двух половин
                    названия на узком экране полезна вторая.

                    Уходит слово только с глаз: `sr-only` оставляет его
                    программе чтения, и ссылка домой не превращается в
                    «1 3». Пробел спрятан вместе со словом — иначе цифры
                    отъезжали бы от знака на его ширину.

                    Пробел перед цифрами намеренный и там, где слово видно:
                    в тексте строки склеиваются, и программа чтения
                    произносит «График13». */}
                {/* Ниже 400 точек уходит СЛОВО, а цифры остаются.
                    -------------------------------------------------------
                    Убирать нужно именно слово. «График» — имя сервиса, и
                    человек, добравшийся до своего расчёта, его уже знает;
                    а цифры называют ЕГО график, тот самый, что он выбрал,
                    и меняются вместе с ним. Из двух половин названия на
                    узком экране полезна вторая.

                    Порог назначен замером и успел поездить: при трёх
                    кнопках в шапке он стоял на 360, при четырёх — на 400,
                    а когда кнопки уехали в меню (`header-menu.tsx`),
                    тесниться стало незачем. Оставлен на 400: на 360
                    точках «ГРАФИК 1|3» хоть и встаёт рядом с кружком, но
                    упирается в него впритык, а поле у края экрана читается
                    лучше лишнего слова.

                    Уходит слово только с глаз: `sr-only` оставляет его
                    программе чтения, и ссылка домой не превращается в
                    «1 3». Пробел спрятан вместе со словом — иначе цифры
                    отъезжали бы от знака на его ширину.

                    Пробел перед цифрами намеренный и там, где слово видно:
                    в тексте строки склеиваются, и программа чтения
                    произносит «График13». */}
                <span className="max-[399px]:sr-only">{"График "}</span>
                <ScheduleMark />
              </Materialize>
              <Materialize
                show={!settled}
                ariaHidden={settled}
                durationClassName="duration-200"
                // Кегль тот же, что у названия сайта, и на любой ширине.
                // Мельче он здесь был затем, чтобы «НАСТРОЙКИ» влезли в
                // остаток строки на узком экране; теперь на узком экране
                // слова нет вовсе — вместо него значок (`BrandLabel`), —
                // и ужимать нечего.
                className="col-start-1 row-start-1 font-display text-black/80 dark:text-ink text-xl tracking-wide font-bold uppercase leading-tight whitespace-nowrap"
              >
                {brandLabel}
              </Materialize>
            </span>
          </span>
        </Link>

        {/* Справа — действие страницы и меню. Ни то, ни другое не
            сжимается: сжатая кнопка это обрезанная подпись, а не
            выигранное место. Уступает название сайта. */}
        <div data-tools className="ml-auto flex shrink-0 items-center gap-2 sm:gap-3">
          {action}
          {/* Меню — последним и на каждой странице: правый верхний угол
              это то место, где его ищут, не читая страницу. */}
          {menuBone === true ? <HeaderMenuBone /> : <HeaderMenu items={menu} />}
        </div>
      </div>
    </header>
  );
}

/**
 * Название открытого раздела рядом со знаком: слово или его значок.
 *
 * --- Почему на узком экране значок, а не слово ------------------------------
 *
 * Слов тут три — «Настройки», «Статистика», «Профили», — и первые два
 * длиннее того места, которое остаётся между знаком и четырьмя кнопками.
 * Замером на 390 точках: «СТАТИСТИКА» просит 101 точку, а есть 86, и
 * название обрезается посреди слова («СТАТИСТИК»). Обрезанное слово хуже
 * отсутствующего: человек читает его как поломку, а не как тесноту.
 *
 * Уступать тут можно двумя способами, и оба пробовали. Мельче кеглем —
 * слово влезает, но строка рядом со знаком начинает жить своей жизнью:
 * «ГРАФИК 1|3» крупный, «НАСТРОЙКИ» мелкие, и шапка выглядит собранной из
 * двух разных. Спрятать совсем — человек теряет единственную надпись,
 * которая говорит, что сейчас открыто.
 *
 * Значок не теряет ничего. Это ТОТ ЖЕ значок, что стоит на кнопке, которой
 * раздел открыли (`header-tools.tsx`): шестерня, столбики, папка. Человек
 * только что по нему нажал, и увидеть его слева — не загадка, а ответ.
 *
 * Ни рамки, ни заливки у него нет: это надпись, а не кнопка. Нажимается всё
 * та же ссылка домой, что и вокруг названия.
 *
 * Слово при этом остаётся программе чтения (`sr-only`): диктор называет
 * раздел словом, а не «изображением».
 *
 * --- Откуда порог -----------------------------------------------------------
 *
 * Замером: на 414 точках «СТАТИСТИКА» влезает ровно впритык (101 из 101), на
 * 390 — уже нет. Порог поставлен на 420 — на запас в две-три точки, чтобы он
 * не зависел от ширины шрифта в конкретном браузере.
 */
export function BrandLabel({
  icon: Icon,
  children,
}: {
  icon: LucideIcon;
  /** Слово: его видно на широком экране и слышно на любом. */
  children: string;
}) {
  return (
    <>
      <Icon
        aria-hidden
        className="inline-block size-6 shrink-0 align-middle min-[420px]:hidden"
      />
      <span className="max-[419px]:sr-only">{children}</span>
    </>
  );
}
