"use client";

import type { LucideIcon } from "lucide-react";
import Link from "next/link";

import { MARK_EMPTY_CLASS } from "@/components/shared/header-action";
import { KNOB, KNOB_ICON, KNOB_NEST, KnobLabel } from "@/components/ui/knob";
import { cn } from "@/lib/utils/cn";

/**
 * Колонка знаков под меню шапки — действия страницы, вынесенные из списка.
 *
 * --- Зачем они вынесены ----------------------------------------------------
 *
 * Настройки, события, статистика, графики и «Сохранить» лежали в списке меню, и
 * до любого из них было два нажатия: открыть меню, выбрать строку. Это пять
 * самых частых действий на экране, а список прятал их ровно там, где на широком
 * экране свободно всё поле справа.
 *
 * С `lg` они стоят под кнопкой меню колонкой знаков — теми же, что у колонки
 * управления сеткой в правом нижнем углу (`grid-dock.tsx`): значок без плашки,
 * подпись выезжает влево при наведении или фокусе с клавиатуры. До `lg` колонки
 * нет и пункты остаются в списке: на телефоне знакам негде стоять, не ложась на
 * сетку.
 *
 * --- Что в меню остаётся ---------------------------------------------------
 *
 * Справка, учётная запись и выход — то, что не относится к расчёту. Выбор того,
 * что показать на месте графика, и меню — теперь два разных предмета, и ни один
 * из них не дублирует другой: строки уходят из списка тем же правилом, каким
 * здесь появляются (`lg`).
 *
 * --- Какой знак горит ------------------------------------------------------
 *
 * Открытый раздел — полной краской чернил, остальные — пустым цветом знаков
 * (`MARK_EMPTY_CLASS`): тот же язык, что у выбранной сетки в нижнем ряду. Нажатие
 * по горящему закрывает раздел — так же, как нажатие по кнопке меню, которая в
 * этот миг сложена крестиком.
 */

/** Место колонки: под кнопкой меню, по правому краю, только с `lg`. */
export const HEADER_RAIL = cn(
  // `top-full` — от нижнего края кнопки меню. `absolute`: колонка висит под
  // шапкой и места в её строке не занимает.
  //
  // `w-max` обязателен: у вынутого из потока блока ширина «по содержимому»
  // упирается в ширину кнопки меню, в которой он лежит, — и подпись, выезжая
  // влево, обрезалась на тех шестидесяти точках, что остаются за вычетом
  // знака («СТАТИСТИКА» читалась «СТИКА»).
  //
  // Правый край сдвинут на восемь точек за край кнопки: знак меню — 28
  // точек, клетка знака колонки — 44, и без сдвига центр значков стоял бы на
  // восемь точек правее центра трёх полос над ними.
  //
  // `mt-13` (52 точки): от кнопки меню до первого знака — пусто на одну клетку
  // знака, как если бы между ними стоял ещё один, невидимый. Кнопка меню ниже
  // клетки знака (28 точек против 44), и отступ считан от её нижнего края: 52 —
  // это 8 до границы клетки, которую меню заняло бы, и 44 самой клетки. Тот же
  // отступ — между колонкой масштаба и темой в правом нижнем углу
  // (`SCALE_KNOBS` в `grid-dock.tsx`).
  "absolute -right-2 top-full mt-13 hidden w-max lg:flex lg:flex-col lg:items-end",
);

/** Горящий знак: чернила названия сайта (`HEADER_WORD`), без прозрачности. */
const ON = "text-black/80 dark:text-ink";

export function RailKnob({
  icon: Icon,
  label,
  caption,
  active,
  href,
  onClick,
}: {
  icon: LucideIcon;
  /** Имя действия: и подпись, что выезжает, и имя для программы чтения. */
  label: string;
  /**
   * Короче имени — подпись, что выезжает, если полное имя для неё длинно: у
   * действий проводника имя «Создать график», а на знаке достаточно «График».
   * Программа чтения всё равно читает `label`.
   */
  caption?: string;
  /**
   * Раздел открыт: знак горит, а нажатие закрывает его. Не задан у действий,
   * которые разделом не являются («Сохранить»): «нажата» у них нечему.
   */
  active?: boolean;
  /** Переход, а не действие: страницы без расчёта ведут к нему ссылкой. */
  href?: string;
  onClick?: () => void;
}) {
  const body = (
    <>
      {/* Подпись — слева: справа у знака кромка окна. Перед значком в
          разметке, чтобы значок стоял на месте, а подпись росла от него
          (`KnobLabel`). */}
      <KnobLabel side="left">{caption ?? label}</KnobLabel>
      <span
        className={cn(KNOB_ICON, "transition-[color,opacity] duration-200", active === true ? ON : MARK_EMPTY_CLASS)}
      >
        <Icon aria-hidden />
      </span>
    </>
  );

  return (
    <div className={cn(KNOB_NEST, "justify-end")}>
      {href !== undefined ? (
        <Link href={href} aria-label={label} className={KNOB}>
          {body}
        </Link>
      ) : (
        <button
          type="button"
          aria-label={label}
          aria-pressed={active}
          onClick={onClick}
          className={KNOB}
        >
          {body}
        </button>
      )}
    </div>
  );
}
