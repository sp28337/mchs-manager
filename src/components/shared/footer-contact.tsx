"use client";

import { Send } from "lucide-react";
import { useId, useState } from "react";

import { Button } from "@/components/ui/button";
import { cn } from "@/lib/utils/cn";

/**
 * Обращение к оператору — формой в подвале, а не одним адресом строкой.
 *
 * --- Почему письмо собирается здесь, а не уходит на сервер -----------------
 *
 * Форма, отправляющая сообщение сама, означала бы новую обработку
 * персональных данных: текст обращения и обратный адрес легли бы на
 * сервер оператора, и это пришлось бы вписать в карту данных, в политику
 * и в уведомление Роскомнадзора. Здесь же на сервер не уходит ничего:
 * кнопка собирает письмо и передаёт его почтовой программе человека.
 *
 * Выигрыш не только в этом. Обращение по правам субъекта (ст. 14 и 20
 * 152-ФЗ) — это то, на что оператор обязан ответить за десять рабочих
 * дней, и человеку нужно доказательство, что он обращался. Письмо,
 * отправленное своей почтой, остаётся у него в «Отправленных» со
 * временем и текстом; сообщение, принятое чужой формой, не оставляет
 * ничего, и подтвердить обращение нечем.
 *
 * Поэтому кнопка и названа «Написать», а не «Отправить», и под ней прямо
 * сказано, что откроется почта и отправит человек сам. Адрес при этом
 * остаётся ссылкой рядом: если почтовой программы в системе нет,
 * обращение переписывают руками, и адрес для этого должен быть на виду.
 *
 * --- Почему длина ограничена ----------------------------------------------
 *
 * Письмо передаётся адресом `mailto:`, а длину адреса браузеры и почтовые
 * программы режут — где-то на двух тысячах знаков, где-то раньше.
 * Обрезанное на полуслове обращение хуже, чем просьба написать короче,
 * поэтому поле не принимает больше полутора тысяч, а остаток знаков
 * показывается, когда их становится мало.
 */
/** Тема письма — одна на все обращения: по ней их видно в ящике пачкой. */
const ТЕМА = "Вопрос о приложении «График 1 3»";

/**
 * Адрес письма, который получает почтовая программа.
 *
 * Вынесено отдельной функцией ради проверки: в обращении бывают и
 * переводы строк, и `&`, и `?`, и кириллица, и каждый из этих знаков
 * способен разорвать адрес так, что письмо приедет обрезанным по
 * середине фразы. `encodeURIComponent` — не украшение, а единственное,
 * что держит текст целым.
 */
export function letterHref(email: string, text: string): string {
  return (
    `mailto:${email}` +
    `?subject=${encodeURIComponent(ТЕМА)}` +
    `&body=${encodeURIComponent(text)}`
  );
}

export function FooterContact({
  email,
  className,
}: {
  email: string;
  className?: string;
}) {
  const [текст, setТекст] = useState("");
  const id = useId();
  const предел = 1500;
  const осталось = предел - текст.length;

  return (
    <section
      aria-labelledby={`${id}-заголовок`}
      className={cn("mx-auto w-full max-w-md text-center", className)}
    >
      <h2
        id={`${id}-заголовок`}
        className="text-xs font-medium uppercase tracking-wide text-ink-muted"
      >
        Вопросы и обращения
      </h2>

      <form
        className="mt-3 space-y-3"
        onSubmit={(событие) => {
          событие.preventDefault();
          window.location.href = letterHref(email, текст);
        }}
      >
        <label htmlFor={`${id}-текст`} className="sr-only">
          Текст обращения
        </label>
        <textarea
          id={`${id}-текст`}
          value={текст}
          maxLength={предел}
          onChange={(событие) => setТекст(событие.target.value)}
          rows={3}
          placeholder="О чём спросить или что поправить"
          // Те же правила, что у однострочного поля (`ui/input.tsx`):
          // своя кромка вместо системного кольца фокуса и чернильная
          // кромка под указателем.
          //
          // Поверхность при этом другая — приподнятая, а не бумага. Поля
          // в приложении стоят на плашках окон и настроек, и бумага под
          // ними читается как углубление; здесь плашки нет, поле стоит
          // прямо на странице, и `bg-paper` означало бы поле, которого
          // не видно вовсе: проверено в тёмной теме — на экране
          // оставался один висящий в воздухе placeholder.
          className={cn(
            "block h-24 w-full resize-none rounded-xl px-3 py-2 transition-all duration-200",
            "bg-paper-raised text-left text-sm text-ink placeholder:text-ink-faint",
            "border border-rule hover:border-ink-muted",
            "focus-visible:border-ink focus-visible:outline-none",
          )}
        />

        <Button type="submit" disabled={текст.trim() === ""} className="sm:w-auto sm:px-6">
          <Send aria-hidden />
          Написать
        </Button>
      </form>

      <p className="mt-3 text-xs text-ink-muted">
        {/* Сказано до нажатия, а не после: человек, нажавший «Написать» и
            увидевший вместо «отправлено» чужое окно почты, решит, что
            что-то сломалось. */}
        Откроется ваша почта с готовым письмом на{" "}
        <a
          href={`mailto:${email}`}
          // Адрес не переносится по дефису: разорванный на «grafik1-» и
          // «3@yandex.ru» он читается как два куска и не копируется
          // двойным нажатием.
          className="whitespace-nowrap text-ink-muted underline hover:text-ink"
        >
          {email}
        </a>{" "}
        — отправите его вы, и копия останется у вас.
        {осталось <= 200 && (
          <>
            {" "}
            <span aria-live="polite">Осталось знаков: {осталось}.</span>
          </>
        )}
      </p>
    </section>
  );
}
