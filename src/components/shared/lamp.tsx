"use client";

import { useEffect, useRef, useState, useSyncExternalStore } from "react";

/**
 * Лампа над страницей.
 *
 * --- Зачем она вообще -----------------------------------------------------
 *
 * До неё страница была равномерно залита бумагой, и это читалось плоско: у
 * листа не было ни верха, ни низа. Первая попытка добавить объём — три
 * едва заметных градиента по углам — не прижилась, и понятно почему: свет
 * БЕЗ ИСТОЧНИКА читается как оформление. Глаз видит, что где-то темнее,
 * не находит причины и записывает это в «так решил дизайнер».
 *
 * Здесь причина видна. Под шапкой висит трубка, она светит, и всё
 * остальное — тёплый налёт на бумаге, блик на верхней кромке блоков,
 * мягкая тень под ними — следствие, которое глаз связывает с ней сам. Тот
 * же градиент, но объяснённый.
 *
 * --- Почему в разметке ОКНА, а не страницы --------------------------------
 *
 * Лампа принадлежит комнате, а не тому, что в комнате лежит. Заводить её
 * на каждой странице значило бы получить три разных света в одном
 * приложении и потерять её при переходе в расчёт — там, где человек
 * проводит всё время.
 *
 * --- Почему цвет хранится в браузере, а не в профиле ----------------------
 *
 * Профиль — это данные о работе человека: смены, отпуска, часы. Цвет лампы
 * к ним не относится ничем, и попасть в выгрузку профиля он не должен:
 * файл с графиком, в котором записано «лампа зелёная», — это уже не файл с
 * графиком. Хранится он там же, где тема оформления: настройка окна, своя
 * на каждом устройстве.
 */

/**
 * Цвета лампы.
 *
 * Не из палитры приложения, и это важно: сигнальный, подтверждающий и след
 * ОЗНАЧАЮТ, и лампа, светящая сигнальным, сказала бы «что-то требует
 * решения». Здесь нужны цвета света, а не смысла.
 *
 * Порядок не случаен: сперва три БЕЛЫХ света — тёплый, нейтральный,
 * холодный, — то есть то, чем лампы и бывают на самом деле, а следом три
 * ЦВЕТНЫХ. Разница между «холодным» и «синим» именно эта: первый белый с
 * голубым отливом, второй — цветная лампа. Перебор идёт от привычного к
 * нарочному.
 *
 * Значения бледные намеренно. Свет — не краска: насыщенный оранжевый дал
 * бы на бумаге пятно, а бледно-янтарный — тёплый оттенок самой бумаги.
 *
 * Сами тройки живут в `globals.css`, при остальных цветах приложения; тут
 * только порядок перебора и названия, которые произносит программа чтения.
 */
export const LAMP_COLOURS = [
  { id: "warm", label: "тёплый" },
  { id: "neutral", label: "нейтральный" },
  { id: "cool", label: "холодный" },
  { id: "green", label: "зелёный" },
  { id: "blue", label: "синий" },
  { id: "pink", label: "розовый" },
] as const;

export type LampColourId = (typeof LAMP_COLOURS)[number]["id"];

/**
 * Каким светит лампа, пока цвет не выбран, — по теме.
 *
 * На графите зеленоватый: тёмная тема этого приложения зелёная по всему —
 * ею отмечена отработанная смена, ею набран заголовок первого экрана, — и
 * лампа над такой комнатой светит её же тоном.
 *
 * На белой бумаге, наоборот, нейтральный. Цветной свет на белом — это уже
 * не свет, а КРАСКА: бумага становится зелёной или розовой, и лист, на
 * котором человек считает часы, перестаёт быть листом. Умолчание обязано
 * быть тем, чего никто не заметит; за цветом человек приходит сам,
 * нажатием.
 *
 * Умолчание СЛЕДИТ за темой: переключил человек тему — сменился и свет,
 * пока он не выбрал цвет сам. После выбора тема на лампу не влияет: свой
 * ответ старше любого умолчания.
 */
function defaultColour(dark: boolean): LampColourId {
  return dark ? "green" : "neutral";
}

/** Ключ в браузере — тем же именем, что и остальные настройки окна. */
const STORAGE_KEY = "grafik13.lamp";

/**
 * Имя события «цвет лампы сменился в ЭТОЙ вкладке».
 *
 * Родное `storage` для этого не годится: браузер шлёт его только ДРУГИМ
 * вкладкам, а не той, что писала. Тот же приём, которым в приложении
 * разосланы правки профиля (`storage/profile.ts`).
 */
const LAMP_EVENT = "grafik13.lamp";

function subscribe(onChange: () => void): () => void {
  window.addEventListener("storage", onChange);
  window.addEventListener(LAMP_EVENT, onChange);
  return () => {
    window.removeEventListener("storage", onChange);
    window.removeEventListener(LAMP_EVENT, onChange);
  };
}

/**
 * Выбранный цвет из браузера или `null`, если человек не выбирал.
 *
 * Именно `null`, а не умолчание: умолчание зависит от темы, а хранилище о
 * теме не знает и знать не должно. Подставить его здесь значило бы намертво
 * записать в снимок ту тему, что стояла в момент чтения.
 *
 * Возвращает СТРОКУ, а не объект: снимок внешнего источника React
 * сравнивает по ссылке, и новый объект на каждом чтении зациклил бы
 * подписку.
 */
function readColour(): LampColourId | null {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    return LAMP_COLOURS.some((colour) => colour.id === saved)
      ? (saved as LampColourId)
      : null;
  } catch {
    // Хранилище может быть недоступно: приватный режим, запрет сторонних
    // данных. Лампа от этого не гаснет — просто не помнит выбор.
    return null;
  }
}

/**
 * На сервере лампы нет.
 *
 * Страница собрана заранее и отдаётся файлом, а выбранный цвет лежит в
 * браузере — узнать его можно только после запуска. Нарисуй лампу в
 * серверной разметке — и она зажглась бы умолчанием, а через мгновение
 * сменила цвет на выбранный: подмена на глазах у человека.
 *
 * Первый кадр без лампы — это не задержка, а НАЧАЛО: лампа ещё не
 * зажглась, и зажигается она с первого же кадра, как только известно,
 * каким светом.
 */
const noColour = () => null;

/**
 * Тёмная ли сейчас тема — читается с КОРНЯ ДОКУМЕНТА, а не через
 * `useTheme`.
 *
 * Лампа стоит в разметке окна ПОСЛЕ содержимого и, стало быть, вне
 * поставщика тем: тот обёрнут вокруг страницы. Хук оттуда вернул бы ей
 * пустоту, и лампа не зажглась бы вовсе.
 *
 * Читать корень при этом не обходной путь, а прямая дорога: тему на него
 * кладёт классом сам `next-themes` (`attribute="class"` в
 * `app/providers.tsx`), то есть здесь она в том же виде, в каком её видит
 * весь остальной CSS. Заодно сюда попадает и «как в системе»: класс к
 * этому времени уже разрешён в конкретную тему.
 */
function subscribeTheme(onChange: () => void): () => void {
  const watcher = new MutationObserver(onChange);
  watcher.observe(document.documentElement, {
    attributes: true,
    attributeFilter: ["class"],
  });
  return () => watcher.disconnect();
}

function readDark(): boolean {
  return document.documentElement.classList.contains("dark");
}

/** На сервере темы нет — как нет и лампы. */
const noTheme = () => null;

/**
 * Пустить показ лампы заново.
 *
 * Метка стоит на КОРНЕ документа, а не на самой лампе: светят три слоя —
 * трубка, ореол и налёт под содержимым страницы, — они в разных местах по
 * глубине и не могут быть детьми одного элемента. Мигать при этом обязаны
 * разом.
 *
 * Перезапуск — снятием метки с принудительной перерисовкой, а не разговором
 * с анимацией напрямую: на телефоне второй способ оставляет анимации
 * отменёнными навсегда (разобрано в `ui/modal.tsx`).
 */
function playLamp(name: string): void {
  const root = document.documentElement;
  delete root.dataset.lampPlay;
  void root.offsetWidth;
  root.dataset.lampPlay = name;
}

/**
 * Со скольких попыток лампа схватится на этот раз.
 *
 * Одинаковое мигание при каждом нажатии — это уже не лампа, а заставка:
 * живое узнаётся по тому, что повторяется НЕ ТОЧНО. Доли подобраны так,
 * чтобы обычным был чистый розжиг, а осечка оставалась событием: человек,
 * переключающий цвет четыре раза подряд, увидит её примерно однажды.
 */
function lampTry(): string {
  const roll = Math.random();
  if (roll < 0.74) return "try-1";
  if (roll < 0.94) return "try-2";
  return "try-3";
}

/** Через сколько лампа подрагивает в следующий раз: от 45 секунд до двух минут. */
function waverDelay(): number {
  return 45_000 + Math.random() * 75_000;
}

function labelOf(id: LampColourId): string {
  return LAMP_COLOURS.find((colour) => colour.id === id)?.label ?? "";
}

/**
 * Длина трубки — та же, что в `globals.css` (`--lamp-width`).
 *
 * Повторена здесь числом намеренно, и это единственное место, где что-то
 * из оформления лампы продублировано. Прочитать величину из вычисленных
 * стилей было бы можно, но ради неё пришлось бы иметь ссылку на элемент и
 * замерять его при каждом пересчёте; величина же не меняется никогда,
 * кроме как вместе с самим правилом. Чтобы расхождение не прошло молча,
 * обе записи названы одинаково.
 */
const LAMP_REM = 48;
const LAMP_VW = 0.74;

/**
 * Лампа изредка подрагивает на ходу.
 *
 * --- Зачем ----------------------------------------------------------------
 *
 * Это то, чем горящая трубка отличается от нарисованной полоски: она
 * продолжает гореть, а не была нарисована один раз при загрузке.
 *
 * --- Почему редко и почему не до нуля --------------------------------------
 *
 * Раз в минуту-другую и на треть секунды. Чаще — и это уже неисправная
 * лампа, на которую невозможно смотреть; заметно глубже — и человек
 * прочитает просадку как сбой страницы и полезет проверять, всё ли цело.
 * Самая глубокая точка подрагивания — шесть десятых накала.
 *
 * --- Почему не заводится при отключённой анимации --------------------------
 *
 * Общее правило сводит длительность любой анимации к сотой доле
 * миллисекунды, так что подрагивание и без того было бы незаметно. Но
 * будильник, который ничего не делает, всё равно будильник: тот, кто
 * отключил движение в системе, просил именно этого.
 */
function useWaver(ready: boolean): void {
  useEffect(() => {
    if (!ready) return;
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

    let timer = 0;
    const later = () => {
      timer = window.setTimeout(() => {
        // Пока вкладка не на виду, дрожать не для кого; браузер к тому же
        // сам придерживает будильники в фоне, и подрагивания копились бы
        // очередью к возвращению.
        if (!document.hidden) playLamp("waver");
        later();
      }, waverDelay());
    };

    later();
    return () => window.clearTimeout(timer);
  }, [ready]);
}

/**
 * С какой стороны лампа светит на каждый блок, ловящий свет.
 *
 * --- Зачем это вообще ------------------------------------------------------
 *
 * Блик, оставленный на одной верхней кромке, верен только для того, что
 * стоит ПРЯМО ПОД лампой. Кнопки шапки стоят у правого края, дальше конца
 * трубки: до них свет доходит сверху и слева, и блик сверху читался бы
 * неправдой. Предмет, освещённый не с той стороны, глаз ловит быстрее, чем
 * успевает объяснить себе, что именно не так.
 *
 * --- Почему замером, а не классами в разметке ------------------------------
 *
 * Положение блока зависит от ширины окна, выбранного масштаба сетки и от
 * того, сколько мелких плашек поместилось в строку итога, — то есть от
 * вещей, которые решаются во время работы. Расставленные руками классы
 * «этот слева, этот справа» были бы верны на одной ширине и врали на всех
 * остальных, причём молча.
 *
 * --- Что считается ---------------------------------------------------------
 *
 * Доля от −1 до 1: насколько середина блока вынесена вбок ЗА КОНЕЦ трубки.
 * Под самой трубкой свет строго сверху, и наклона нет вовсе; за её концом
 * он заходит сбоку тем сильнее, чем дальше блок, и становится полностью
 * боковым, отойдя на половину вылета трубки.
 *
 * Половина, а не целый вылет: трубка висит по самой кромке окна, и до
 * кнопки, стоящей у правого края, свет от её ближнего конца идёт почти
 * горизонтально — двести сорок точек вбок против тридцати вниз. Считать
 * такое «почти сверху» значило бы поставить блик не с той стороны как раз
 * там, где это заметнее всего.
 *
 * --- Когда пересчитывается -------------------------------------------------
 *
 * При изменении размеров окна и при появлении новых блоков — те приходят с
 * окнами, которых в разметке до открытия нет. Оба повода сводятся к одному
 * проходу за кадр: замеров десяток, а собирать их чаще, чем рисуется кадр,
 * всё равно незачем.
 */
function useLitTilt(ready: boolean): void {
  useEffect(() => {
    if (!ready) return;

    let frame = 0;

    const aim = () => {
      frame = 0;
      const centre = window.innerWidth / 2;
      const reach =
        Math.min(
          LAMP_REM * parseFloat(getComputedStyle(document.documentElement).fontSize),
          window.innerWidth * LAMP_VW,
        ) / 2;

      // `.lit` — блок, который сам ловит свет; `.lit-aim` — тот, кто
      // только ЗАДАЁТ наклон своим детям: так помечен месяц, чьи клетки
      // светятся каждая, а мерить их все по отдельности значило бы делать
      // четыреста замеров с перерасчётом раскладки между ними.
      for (const block of document.querySelectorAll<HTMLElement>(".lit, .lit-aim")) {
        const box = block.getBoundingClientRect();
        // Скрытые блоки (окно ещё закрыто) мерить нечего: нулевая ширина
        // дала бы им наклон по левому краю экрана.
        if (box.width === 0) continue;
        const away = box.left + box.width / 2 - centre;
        const outside = Math.max(0, Math.abs(away) - reach);
        const tilt = Math.sign(away) * Math.min(1, outside / (reach / 2));
        block.style.setProperty("--lit-tilt", tilt.toFixed(2));
      }
    };

    const schedule = () => {
      if (frame === 0) frame = window.requestAnimationFrame(aim);
    };

    schedule();
    window.addEventListener("resize", schedule);
    // Блоки приходят и уходят вместе с окнами; метка «открыто» на окне
    // меняется тогда же, поэтому её и слушаем — вместе с появлением самих
    // узлов.
    const watcher = new MutationObserver(schedule);
    watcher.observe(document.body, {
      childList: true,
      subtree: true,
      attributeFilter: ["data-modal"],
    });

    return () => {
      if (frame !== 0) window.cancelAnimationFrame(frame);
      window.removeEventListener("resize", schedule);
      watcher.disconnect();
    };
  }, [ready]);
}

export function Lamp() {
  const chosen = useSyncExternalStore(subscribe, readColour, noColour);
  // Тема нужна лампе ради умолчания, и только ради него. `null` до
  // монтирования — он же и признак готовности: в серверной разметке лампы
  // нет вовсе.
  const dark = useSyncExternalStore(subscribeTheme, readDark, noTheme);
  const colour = dark === null ? null : (chosen ?? defaultColour(dark));

  // Объявлять смену цвета нужно только тому, кто её вызвал. Живая область,
  // заполненная сразу, произносила бы «зелёный» при каждом открытии
  // страницы.
  const [announce, setAnnounce] = useState(false);

  /**
   * Цвет — меткой на КОРНЕ документа, а не свойством самой лампы: из него
   * собираются и трубка, и налёт под содержимым страницы, и блики на
   * блоках, разбросанных по всему дереву.
   *
   * На светлой теме метка ставится, но всегда НЕЙТРАЛЬНАЯ. Самой лампы там
   * нет, а блики на кромках блоков остаются: свет над листом всё-таки
   * есть, только дневной — и цвета у него нет. Розовый блик на бумаге при
   * отсутствующей розовой лампе был бы светом без источника, ровно тем, от
   * чего лампу и заводили.
   */
  useEffect(() => {
    if (dark === null || colour === null) return;
    document.documentElement.dataset.lamp = dark ? colour : "neutral";
  }, [colour, dark]);

  // Розжиг — однократный, при первом появлении. Загорается только то, что
  // горит: на светлой теме зажигать нечего.
  const struck = useRef(false);
  useEffect(() => {
    if (!dark || struck.current) return;
    struck.current = true;
    playLamp("strike");
  }, [dark]);

  /**
   * Метки снимаются только при уходе со страницы — и никогда раньше.
   *
   * Уборка стояла в эффекте розжига, у которого в зависимостях цвет, и
   * потому срабатывала при КАЖДОЙ его смене: сразу после нажатия React
   * стирал `data-lamp-play`, анимация снималась на полпути, и свет
   * вспыхивал вместо того, чтобы разгораться. Заметно это было едва — та
   * же доля секунды, — но розжига, ради которого всё и заведено, не было
   * вовсе.
   */
  useEffect(
    () => () => {
      delete document.documentElement.dataset.lamp;
      delete document.documentElement.dataset.lampPlay;
    },
    [],
  );

  // Наклон бликов считается в обеих темах: блоки ловят свет и на белой
  // бумаге, просто дневной. А вот подрагивание накала — только там, где
  // есть чему подрагивать.
  useLitTilt(colour !== null);
  useWaver(dark === true);

  function switchColour() {
    if (colour === null) return;
    const index = LAMP_COLOURS.findIndex((option) => option.id === colour);
    const next = LAMP_COLOURS[(index + 1) % LAMP_COLOURS.length]!.id;

    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // Не запомнить выбор — не повод его не применить.
    }
    window.dispatchEvent(new Event(LAMP_EVENT));
    setAnnounce(true);

    /**
     * Розжиг на новом цвете — с тем числом попыток, которое выпало.
     *
     * Не украшение и не «отклик на нажатие»: цвет трубки и ореола нарисован
     * градиентами, а они не переходят один в другой плавно — новый встал бы
     * подменой, в один кадр. Лампа же так и меняет свет: гаснет и загорается
     * снова.
     */
    playLamp(lampTry());
  }

  /**
   * На светлой теме лампы не ВИДНО — но она есть.
   *
   * Свет — не краска, и на белой бумаге ему нечего делать: яркости он там
   * не добавляет (некуда), остаётся одна подкраска, а её глаз ловит куда
   * хуже. Светильник при этом висел бы на виду и обещал то, чего не
   * делает. Светлая тема — это лист при дневном свете, и лампа над ним
   * погашена.
   *
   * Но ПОГАШЕНА, а не снята: слои остаются в разметке и гасятся
   * прозрачностью (`globals.css`). Разница не косметическая. Лампа
   * закреплена у самой кромки окна, а верх окна на айфоне сафари красит
   * по странице — и снимает цвет как раз оттуда. Появляясь и исчезая,
   * лампа перестраивала там слои ровно в тот момент, когда браузер решает,
   * чем красить верх; пока лампа стояла в обеих темах (а стояла она так до
   * выпуска 2.16.0), смена темы работала.
   *
   * Уходит только выключатель цвета: менять цвет у лампы, которой не
   * видно, человеку нечем и незачем. Ничего не рисуя, он на слои не
   * влияет. Выбор цвета при этом цел — он в браузере, и при возврате на
   * тёмную лампа загорится тем же светом.
   */
  if (colour === null) return null;

  return (
    <>
      {/* Сам светильник: он перед страницей, и содержимое проезжает за
          ним, как за лампой на стене.

          Светильник — вырезка из фотографии, посаженная так, что стекло
          приходится ровно на кромку окна. Всё, что на снимке выше стекла —
          верх патронов и налёт на стене, — лежит ЗА кромкой, то есть
          обычно не видно вовсе и на вид приложения не влияет ничем. Но у
          части браузеров — телеграмного в первую очередь — адресная строка
          полупрозрачна, и страница под ней просвечивает: там светильник
          оказывается светильником целиком. Стоит это ничего: та же
          картинка, просто видная не до конца. */}
      <div aria-hidden className="lamp">
        {/* Ореол ПЕРЕД снимком: он светит из-под светильника, а не поверх
            него. */}
        <span className="lamp__halo" />
        <span className="lamp__tube" />
        <span className="lamp__glow" />
      </div>

      {/* Свет, упавший на бумагу, — НА странице, под её содержимым. Будь он
          поверх, тёплый налёт лежал бы и на тексте, съедая контраст; лежит
          он на бумаге, а блоки поверх ловят свой блик сами (`.lit`). */}
      <div aria-hidden className="lamp-wash" />

      {dark ? (
        <button
          type="button"
          className="lamp-switch"
          onClick={switchColour}
          // Название говорит и что это, и что с ним делать: у полоски света
          // под шапкой нет ни подписи, ни очертаний, по которым её можно
          // было бы узнать.
          aria-label={`Лампа, ${labelOf(colour)} свет. Нажмите, чтобы сменить цвет`}
        />
      ) : null}

      {/* Смена цвета видна глазом и ничем больше: ни разметка страницы, ни
          фокус от неё не меняются. Живая область — единственный способ
          сказать о ней тому, кто страницу не видит. */}
      <p className="sr-only" aria-live="polite">
        {announce ? `Лампа: ${labelOf(colour)} свет` : ""}
      </p>
    </>
  );
}
