/**
 * Длина трубки — та же, что в `globals.css` (`--lamp-width`).
 *
 * Повторена здесь числом намеренно, и это единственное место, где что-то
 * из оформления лампы продублировано. Прочитать величину из вычисленных
 * стилей было бы можно, но ради неё пришлось бы иметь ссылку на элемент и
 * замерять его при каждом пересчёте; величина же не меняется никогда,
 * кроме как вместе с самим правилом. Чтобы расхождение не прошло молча,
 * обе записи названы одинаково.
 */
const LAMP_REM = 48;
const LAMP_VW = 0.74;

/**
 * Лампа изредка подрагивает на ходу.
 *
 * --- Зачем ----------------------------------------------------------------
 *
 * Это то, чем горящая трубка отличается от нарисованной полоски: она
 * продолжает гореть, а не была нарисована один раз при загрузке.
 *
 * --- Почему редко и почему не до нуля --------------------------------------
 *
 * Раз в минуту-другую и на треть секунды. Чаще — и это уже неисправная
 * лампа, на которую невозможно смотреть; заметно глубже — и человек
 * прочитает просадку как сбой страницы и полезет проверять, всё ли цело.
 * Самая глубокая точка подрагивания — шесть десятых накала.
 *
 * --- Почему не заводится при отключённой анимации --------------------------
 *
 * Общее правило сводит длительность любой анимации к сотой доле
 * миллисекунды, так что подрагивание и без того было бы незаметно. Но
 * будильник, который ничего не делает, всё равно будильник: тот, кто
 * отключил движение в системе, просил именно этого.
 */
function useWaver(ready: boolean): void {
  useEffect(() => {
    if (!ready) return;
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

    let timer = 0;
    const later = () => {
      timer = window.setTimeout(() => {
        // Пока вкладка не на виду, дрожать не для кого; браузер к тому же
        // сам придерживает будильники в фоне, и подрагивания копились бы
        // очередью к возвращению.
        if (!document.hidden) playLamp("waver");
        later();
      }, waverDelay());
    };

    later();
    return () => window.clearTimeout(timer);
  }, [ready]);
}

/**
 * С какой стороны лампа светит на каждый блок, ловящий свет.
 *
 * --- Зачем это вообще ------------------------------------------------------
 *
 * Блик, оставленный на одной верхней кромке, верен только для того, что
 * стоит ПРЯМО ПОД лампой. Кнопки шапки стоят у правого края, дальше конца
 * трубки: до них свет доходит сверху и слева, и блик сверху читался бы
 * неправдой. Предмет, освещённый не с той стороны, глаз ловит быстрее, чем
 * успевает объяснить себе, что именно не так.
 *
 * --- Почему замером, а не классами в разметке ------------------------------
 *
 * Положение блока зависит от ширины окна, выбранного масштаба сетки и от
 * того, сколько мелких плашек поместилось в строку итога, — то есть от
 * вещей, которые решаются во время работы. Расставленные руками классы
 * «этот слева, этот справа» были бы верны на одной ширине и врали на всех
 * остальных, причём молча.
 *
 * --- Что считается ---------------------------------------------------------
 *
 * Доля от −1 до 1: насколько середина блока вынесена вбок ЗА КОНЕЦ трубки.
 * Под самой трубкой свет строго сверху, и наклона нет вовсе; за её концом
 * он заходит сбоку тем сильнее, чем дальше блок, и становится полностью
 * боковым, отойдя на половину вылета трубки.
 *
 * Половина, а не целый вылет: трубка висит по самой кромке окна, и до
 * кнопки, стоящей у правого края, свет от её ближнего конца идёт почти
 * горизонтально — двести сорок точек вбок против тридцати вниз. Считать
 * такое «почти сверху» значило бы поставить блик не с той стороны как раз
 * там, где это заметнее всего.
 *
 * --- Когда пересчитывается -------------------------------------------------
 *
 * При изменении размеров окна и при появлении новых блоков — те приходят с
 * окнами, которых в разметке до открытия нет. Оба повода сводятся к одному
 * проходу за кадр: замеров десяток, а собирать их чаще, чем рисуется кадр,
 * всё равно незачем.
 */
function useLitTilt(ready: boolean): void {
  useEffect(() => {
    if (!ready) return;

    let frame = 0;

    const aim = () => {
      frame = 0;
      const centre = window.innerWidth / 2;
      const reach =
        Math.min(
          LAMP_REM * parseFloat(getComputedStyle(document.documentElement).fontSize),
          window.innerWidth * LAMP_VW,
        ) / 2;

      // `.lit` — блок, который сам ловит свет; `.lit-aim` — тот, кто
      // только ЗАДАЁТ наклон своим детям: так помечен месяц, чьи клетки
      // светятся каждая, а мерить их все по отдельности значило бы делать
      // четыреста замеров с перерасчётом раскладки между ними.
      for (const block of document.querySelectorAll<HTMLElement>(".lit, .lit-aim")) {
        const box = block.getBoundingClientRect();
        // Скрытые блоки (окно ещё закрыто) мерить нечего: нулевая ширина
        // дала бы им наклон по левому краю экрана.
        if (box.width === 0) continue;
        const away = box.left + box.width / 2 - centre;
        const outside = Math.max(0, Math.abs(away) - reach);
        const tilt = Math.sign(away) * Math.min(1, outside / (reach / 2));
        block.style.setProperty("--lit-tilt", tilt.toFixed(2));
      }
    };

    const schedule = () => {
      if (frame === 0) frame = window.requestAnimationFrame(aim);
    };

    schedule();
    window.addEventListener("resize", schedule);
    // Блоки приходят и уходят вместе с окнами; метка «открыто» на окне
    // меняется тогда же, поэтому её и слушаем — вместе с появлением самих
    // узлов.
    const watcher = new MutationObserver(schedule);
    watcher.observe(document.body, {
      childList: true,
      subtree: true,
      attributeFilter: ["data-modal"],
    });

    return () => {
      if (frame !== 0) window.cancelAnimationFrame(frame);
      window.removeEventListener("resize", schedule);
      watcher.disconnect();
    };
  }, [ready]);
}

/**
 * Насколько далеко от поверхности её кромка ещё ловит курсор, в точках.
 *
 * Полтораста — это примерно ладонь на экране: из такой дали отблеск уже
 * виден на соседях, но не на половине страницы разом. Дальше свет не
 * идёт вовсе, и элемент перестаёт считаться освещённым.
 */
const REACH = 150;

/**
 * Самый яркий отблеск на подступах.
 *
 * Половина от каймы под курсором, и это не осторожность, а разница в
 * смысле: приближение показывает ОБЪЁМ — что поверхность поднята и у неё
 * есть край, — а наведение показывает выбор. Сравняй их, и наведение
 * перестало бы что-либо означать.
 */
const NEAR_MAX = 0.55;

/**
 * С какого накала за курсором следит ещё и ТОЧКА входа света.
 *
 * У еле тлеющей кромки не видно, с какой стороны на неё светят, — а каждая
 * поправка точки перерисовывает кайму целиком, и у сорока поверхностей
 * разом это и есть вся цена затеи. Поэтому слабым достаётся та точка, с
 * которой они загорелись, а следят за курсором только ближние.
 */
const AIM_FROM = 0.08;

/**
 * Кому достаётся отблеск на подступах — и почему не клеткам календаря.
 *
 * Клетка суток (`.lit-tile`) — не предмет на столе, а часть разлинованного
 * листа: объёма у неё нет, и показывать его нечем. Зажги их приближением —
 * и по сетке года поехало бы световое пятно, которое читается фонариком, а
 * не светом в комнате; заодно это и вся цена затеи, потому что клеток на
 * странице больше трёхсот, и каждая перерисовывает свою кайму.
 *
 * Поднятым поверхностям — плашкам, кнопкам, карточкам, легендам — он
 * достаётся весь: это они лежат НАД бумагой, и это у них есть край, о
 * котором свет и рассказывает. Клеткам остаётся прежнее: кайма под
 * курсором.
 */
const NEAR_LIT = ".lit, .lit-edge";

/**
 * Как быстро отблеск гаснет с расстоянием.
 *
 * Не поровну с расстоянием и не квадратом. Поровну — это луч прожектора с
 * ровным краем, который видно там, где он кончается; квадрат гаснет так
 * рано, что от приближения остаётся вспышка у самой кромки — то же
 * наведение, только раньше на палец. Степень в полтора держит середину:
 * свет заметен уже на подступах и сходит на нет без видимой границы.
 */
function nearness(away: number): number {
  const close = 1 - away / REACH;
  return NEAR_MAX * close * Math.sqrt(close);
}

/**
 * Свет от курсора: откуда светит кайма и насколько горит та, до которой
 * курсор ещё не доехал.
 *
 * --- Почему кайма загорается ЗАРАНЕЕ ----------------------------------------
 *
 * Кайма, вспыхивающая ровно на наведении, — это выключатель: было темно,
 * стало светло, промежутка нет. Настоящий свет так себя не ведёт: предмет,
 * к которому подносят лампу, светлеет постепенно, и по тому, как быстро он
 * светлеет, глаз и понимает, что предмет ПОДНЯТ над бумагой, а не нарисован
 * на ней. Поэтому отблеск проступает на подступах и усиливается по мере
 * приближения, а под курсором доходит до полной каймы.
 *
 * Горит при этом не только то, на что человек целится, а всё, что рядом, —
 * иначе вышел бы прожектор, выхватывающий один предмет из темноты.
 *
 * --- Почему один слушатель на всю страницу ----------------------------------
 *
 * Кайму получает КАЖДАЯ поднятая поверхность (`.lit`, `.lit-edge` и
 * `.lit-tile` в `globals.css`), а их на рабочем экране не десятки, а
 * сотни: плашки итога, кнопки шапки, карточки проводника, легенды — и
 * каждая клетка года, а их больше трёхсот. Вешать обработчик на каждую
 * значило бы заводить их по числу клеток и помнить про это в любом новом
 * месте — а забытый обработчик выглядел бы как поломка: блок светится, но
 * блик стоит в середине и не двигается.
 *
 * Слушатель поэтому один и живёт при самой лампе: свет — её забота.
 * Величины пишутся прямо в стиль, минуя состояние React: их читает только
 * градиент каймы, в отрисовке они не участвуют, и перерисовывать страницу
 * из-за движения мыши было бы дорого ровно настолько, насколько это
 * заметно.
 *
 * --- Чем это не стоит кадра -------------------------------------------------
 *
 * Положения поверхностей МЕРЯЮТСЯ не каждый раз, а запоминаются: от
 * движения мыши раскладка не меняется, и перемер на каждом кадре был бы
 * тремястами замеров ради того же ответа. Снимок сбрасывается там, где
 * раскладка и правда меняется: прокрутка, изменение размеров, появление и
 * исчезновение узлов, — и на всякий случай по времени, если ничего из
 * этого не случилось.
 *
 * В снимок идёт только видимое: клетки января, когда человек смотрит на
 * июль, светить всё равно некому. И пишется величина лишь тем, у кого она
 * изменилась, — иначе триста записей в стиль за кадр переоценивали бы
 * страницу целиком при каждом вздрагивании мыши.
 *
 * --- Почему на телефоне этого нет -------------------------------------------
 *
 * Приближаться там нечем: палец или касается поверхности, или его нет
 * вовсе, промежутка между этим не бывает. Остаётся прежнее — блик под
 * пальцем у той поверхности, которой он коснулся.
 */
function useCursorGlow(ready: boolean): void {
  useEffect(() => {
    if (!ready) return;

    const fine = window.matchMedia("(hover: hover) and (pointer: fine)").matches;

    let frame = 0;
    let latest: PointerEvent | null = null;
    let boxes: { node: HTMLElement; box: DOMRect }[] = [];
    let measured = 0;
    let stale = true;
    /**
     * Что каждому уже написано.
     *
     * Нужно не для памяти, а ради цены: написанная величина — это
     * пересчёт стиля и перерисовка каймы, и платить за неё, когда свет
     * изменился на сотую долю, нечем. Дальние поверхности так и не
     * переписываются вовсе, пока курсор не подойдёт ближе.
     */
    const written = new Map<HTMLElement, { near: number; x: number; y: number }>();

    const measure = () => {
      boxes = [];
      for (const node of document.querySelectorAll<HTMLElement>(NEAR_LIT)) {
        const box = node.getBoundingClientRect();
        // Спрятанное (окно ещё закрыто) и то, что лежит далеко за краем
        // экрана, светить некому.
        if (box.width === 0) continue;
        if (box.bottom < -REACH || box.top > window.innerHeight + REACH) continue;
        boxes.push({ node, box });
      }
      // Погасить то, что из снимка ушло: уехавшая за край экрана или
      // исчезнувшая поверхность иначе осталась бы светиться написанной ей
      // когда-то величиной — её никто больше не считает.
      const present = new Set(boxes.map((it) => it.node));
      for (const node of written.keys()) {
        if (present.has(node)) continue;
        node.style.removeProperty("--near");
        written.delete(node);
      }

      measured = performance.now();
      stale = false;
    };

    const darken = () => {
      for (const node of written.keys()) {
        node.style.removeProperty("--near");
      }
      written.clear();
    };

    const paint = () => {
      frame = 0;
      const event = latest;
      if (event === null) return;

      // Касание: ни приближения, ни того, к чему приближаться, — только
      // блик под пальцем, как было до всего этого.
      if (!fine) {
        const touched =
          event.target instanceof Element
            ? event.target.closest<HTMLElement>(".lit, .lit-edge, .lit-tile")
            : null;
        if (touched === null) return;
        const box = touched.getBoundingClientRect();
        touched.style.setProperty("--glow-x", `${event.clientX - box.left}px`);
        touched.style.setProperty("--glow-y", `${event.clientY - box.top}px`);
        return;
      }

      if (stale || performance.now() - measured > 400) measure();

      for (const { node, box } of boxes) {
        // Расстояние до самой поверхности, а не до её середины: у длинной
        // плашки середина может быть за экраном, когда её край — под
        // курсором. Внутри расстояние нулевое.
        const dx = Math.max(box.left - event.clientX, 0, event.clientX - box.right);
        const dy = Math.max(box.top - event.clientY, 0, event.clientY - box.bottom);
        const away = Math.hypot(dx, dy);

        if (away > REACH) {
          if (written.delete(node)) node.style.removeProperty("--near");
          continue;
        }

        // Под курсором отблеск не нужен: там кайму зажигает наведение, и
        // оно же решает, какой из вложенных поверхностей она достанется
        // (`globals.css`). Напиши её здесь — загорелись бы разом и плашка,
        // и всё, что на ней лежит.
        const near = away === 0 ? 0 : nearness(away);
        // Свет входит в ближнюю к курсору точку поверхности. Пока курсор
        // внутри, это он сам; снаружи — её край с его стороны, и оттого
        // соседи загораются обращёнными друг к другу кромками.
        const x = Math.round(Math.min(Math.max(event.clientX - box.left, 0), box.width));
        const y = Math.round(Math.min(Math.max(event.clientY - box.top, 0), box.height));

        const was = written.get(node);
        if (was === undefined) {
          node.style.setProperty("--glow-x", `${x}px`);
          node.style.setProperty("--glow-y", `${y}px`);
          node.style.setProperty("--near", near.toFixed(3));
          written.set(node, { near, x, y });
          continue;
        }
        // Доли и точки, в которых разницы не видно, не стоят перерисовки:
        // еле тлеющих поверхностей вокруг курсора десятки, и писать им
        // каждый кадр по сотой доле значило бы переоценивать стиль
        // полустраницы на каждое вздрагивание мыши.
        if (Math.abs(near - was.near) >= 0.02) {
          node.style.setProperty("--near", near.toFixed(3));
          was.near = near;
        }
        if (near >= AIM_FROM && (Math.abs(x - was.x) >= 3 || Math.abs(y - was.y) >= 3)) {
          node.style.setProperty("--glow-x", `${x}px`);
          node.style.setProperty("--glow-y", `${y}px`);
          was.x = x;
          was.y = y;
        }
      }
    };

    const follow = (event: PointerEvent) => {
      latest = event;
      if (frame === 0) frame = window.requestAnimationFrame(paint);
    };

    const forget = () => {
      stale = true;
    };

    // Курсор ушёл за край окна: он не «остановился у кромки», он пропал, и
    // оставленный им отблеск повис бы на странице до следующего движения.
    const leave = (event: PointerEvent) => {
      if (event.relatedTarget === null) {
        latest = null;
        darken();
      }
    };

    window.addEventListener("pointermove", follow, { passive: true });
    window.addEventListener("pointerout", leave, { passive: true });
    window.addEventListener("resize", forget);
    window.addEventListener("scroll", forget, { passive: true, capture: true });
    const watcher = new MutationObserver(forget);
    watcher.observe(document.body, {
      childList: true,
      subtree: true,
      attributeFilter: ["data-modal"],
    });

    return () => {
      window.removeEventListener("pointermove", follow);
      window.removeEventListener("pointerout", leave);
      window.removeEventListener("resize", forget);
      window.removeEventListener("scroll", forget, { capture: true });
      watcher.disconnect();
      if (frame !== 0) window.cancelAnimationFrame(frame);
      darken();
    };
  }, [ready]);
}

export function Lamp() {
  const chosen = useSyncExternalStore(subscribe, readColour, noColour);
  // Тема нужна лампе ради умолчания, и только ради него. `null` до
  // монтирования — он же и признак готовности: в серверной разметке лампы
  // нет вовсе.
  const dark = useSyncExternalStore(subscribeTheme, readDark, noTheme);
  const colour = dark === null ? null : (chosen ?? defaultLampColour(dark));

  // Объявлять смену цвета нужно только тому, кто её вызвал. Живая область,
  // заполненная сразу, произносила бы «зелёный» при каждом открытии
  // страницы.
  const [announce, setAnnounce] = useState(false);

  // Цвет — меткой на КОРНЕ документа, а не свойством самой лампы: из него
  // собираются и трубка, и налёт под содержимым страницы, и блики на
  // блоках, разбросанных по всему дереву.
  useEffect(() => {
    if (colour === null) return;
    document.documentElement.dataset.lamp = colour;
  }, [colour]);

  // Розжиг — однократный, при первом появлении.
  const struck = useRef(false);
  useEffect(() => {
    if (colour === null || struck.current) return;
    struck.current = true;
    playLamp("strike");
  }, [colour]);

  /**
   * Метки снимаются только при уходе со страницы — и никогда раньше.
   *
   * Уборка стояла в эффекте розжига, у которого в зависимостях цвет, и
   * потому срабатывала при КАЖДОЙ его смене: сразу после нажатия React
   * стирал `data-lamp-play`, анимация снималась на полпути, и свет
   * вспыхивал вместо того, чтобы разгораться. Заметно это было едва — та
   * же доля секунды, — но розжига, ради которого всё и заведено, не было
   * вовсе.
   */
  useEffect(
    () => () => {
      delete document.documentElement.dataset.lamp;
      delete document.documentElement.dataset.lampPlay;
    },
    [],
  );

  useLitTilt(colour !== null);
  useCursorGlow(colour !== null);
  useWaver(colour !== null);

  function switchColour() {
    if (colour === null) return;
    const index = LAMP_COLOURS.findIndex((option) => option.id === colour);
    const next = LAMP_COLOURS[(index + 1) % LAMP_COLOURS.length]!.id;

    try {
      window.localStorage.setItem(LAMP_STORAGE_KEY, next);
    } catch {
      // Не запомнить выбор — не повод его не применить.
    }
    window.dispatchEvent(new Event(LAMP_EVENT));
    setAnnounce(true);

    /**
     * Розжиг на новом цвете — с тем числом попыток, которое выпало.
     *
     * Не украшение и не «отклик на нажатие»: цвет трубки и ореола нарисован
     * градиентами, а они не переходят один в другой плавно — новый встал бы
     * подменой, в один кадр. Лампа же так и меняет свет: гаснет и загорается
     * снова.
     */
    playLamp(lampTry());
  }

  if (colour === null) return null;

  return (
    <>
      {/* Сам светильник: он перед страницей, и содержимое проезжает за
          ним, как за лампой на стене. */}
      {/* Сам светильник: он перед страницей, и содержимое проезжает за
          ним, как за лампой на стене.

          Корпус, провод и изолента лежат ВЫШЕ верхней кромки окна, то есть
          обычно не видны вовсе и на вид приложения не влияют ничем. Но у
          части браузеров — телеграмного в первую очередь — адресная строка
          полупрозрачна, и страница под ней просвечивает: там лампа
          оказывается лампой целиком, с корпусом и уходящим вверх проводом.
          Стоит это ничего: три пустых элемента, которые не рисуются, пока
          их некому показать. */}
      <div aria-hidden className="lamp">
        <span className="lamp__cord" />
        <span className="lamp__tape" />
        <span className="lamp__mount" />
        <span className="lamp__tube" />
        <span className="lamp__glow" />
      </div>

      {/* Свет, упавший на бумагу, — НА странице, под её содержимым. Будь он
          поверх, тёплый налёт лежал бы и на тексте, съедая контраст; лежит
          он на бумаге, а блоки поверх ловят свой блик сами (`.lit`). */}
      <div aria-hidden className="lamp-wash" />

      <button
        type="button"
        className="lamp-switch"
        onClick={switchColour}
        // Название говорит и что это, и что с ним делать: у полоски света
        // под шапкой нет ни подписи, ни очертаний, по которым её можно
        // было бы узнать.
        aria-label={`Лампа, ${labelOf(colour)} свет. Нажмите, чтобы сменить цвет`}
      />

      {/* Смена цвета видна глазом и ничем больше: ни разметка страницы, ни
          фокус от неё не меняются. Живая область — единственный способ
          сказать о ней тому, кто страницу не видит. */}
      <p className="sr-only" aria-live="polite">
        {announce ? `Лампа: ${labelOf(colour)} свет` : ""}
      </p>
    </>
  );
}
