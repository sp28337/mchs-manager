/**
 * Цвет лампы: сам список, память о выборе и метка на корне документа.
 *
 * --- Почему отдельным файлом ----------------------------------------------
 *
 * Всё это нужно двоим сразу. Лампе (`lamp.tsx`) — чтобы светить и помнить
 * выбор; разметке страницы (`app/layout.tsx`) — чтобы поставить метку ДО
 * первой отрисовки, крохотным вставленным сценарием.
 *
 * А `lamp.tsx` живёт в браузере (`"use client"`), и разметка страницы,
 * которая собирается на сервере, взять оттуда не может даже строковую
 * постоянную: Next подменяет такой модуль заглушкой, и любое обращение к
 * ней с сервера — ошибка. Поэтому общее вынесено сюда, в модуль без
 * стороны: его читают и там и там.
 *
 * --- Зачем метка ставится до отрисовки -------------------------------------
 *
 * Свет лампы — не украшение лампы, а вид ВСЕХ поднятых поверхностей: блик
 * по верхней кромке и тень вниз у карточек, плашек, кнопок, клеток
 * календаря (`.lit`, `.lit-tile` в `globals.css`). Все они висят на
 * `:root[data-lamp]`.
 *
 * Ставила метку сама лампа, из эффекта, — то есть после того, как в
 * браузере запустится сценарий. Замером на рабочем экране: страница
 * показывалась на 217-й миллисекунде, а метка появлялась на 597-й, и всё
 * это время человек смотрел на плоские, ничем не освещённые блоки. Хуже
 * того, ровно в этот же миг заглушка сменялась расчётом — и выходило, что
 * свет включается вместе с подстановкой, одним рывком на весь экран.
 *
 * Сценарий ниже вставляется в разметку и выполняется, пока браузер ещё
 * разбирает страницу: свет стоит на месте с первого кадра, а лампа,
 * появившись, находит метку уже поставленной и ничего не меняет.
 */

export const LAMP_COLOURS = [
  { id: "warm", label: "тёплый" },
  { id: "neutral", label: "нейтральный" },
  { id: "cool", label: "холодный" },
  { id: "green", label: "зелёный" },
  { id: "blue", label: "синий" },
  { id: "pink", label: "розовый" },
] as const;

export type LampColourId = (typeof LAMP_COLOURS)[number]["id"];

/** Ключ в браузере — тем же именем, что и остальные настройки окна. */
export const LAMP_STORAGE_KEY = "grafik13.lamp";

/**
 * Каким светит лампа, пока цвет не выбран, — по теме.
 *
 * На графите зеленоватый: тёмная тема этого приложения зелёная по всему —
 * ею отмечена отработанная смена, ею набран заголовок первого экрана, — и
 * лампа над такой комнатой светит её же тоном.
 *
 * На белой бумаге, наоборот, нейтральный. Цветной свет на белом — это уже
 * не свет, а КРАСКА: бумага становится зелёной или розовой, и лист, на
 * котором человек считает часы, перестаёт быть листом. Умолчание обязано
 * быть тем, чего никто не заметит; за цветом человек приходит сам,
 * нажатием.
 *
 * Умолчание СЛЕДИТ за темой: переключил человек тему — сменился и свет,
 * пока он не выбрал цвет сам. После выбора тема на лампу не влияет: свой
 * ответ старше любого умолчания.
 */
export function defaultLampColour(dark: boolean): LampColourId {
  return dark ? "green" : "neutral";
}

/**
 * Тот же выбор, но крохотным сценарием для разметки страницы.
 *
 * Собран из тех же постоянных, что и всё выше, и повторяет ту же тройку
 * шагов: выбранный цвет из хранилища, проверка, что такой цвет есть, иначе
 * умолчание по теме. Разойтись двум записям нельзя — они и не написаны
 * дважды: строка складывается из этих же значений.
 *
 * Тема к этому времени уже назначена: `next-themes` ставит класс своим
 * таким же сценарием, и наш стоит после него. Хранилище может быть закрыто
 * (приватный режим, запрет сторонних данных) — тогда просто умолчание, как
 * и у самой лампы.
 */
export const LAMP_MARK_SCRIPT = `(function(){try{var i=${JSON.stringify(
  LAMP_COLOURS.map((colour) => colour.id),
)},s=null;try{s=localStorage.getItem(${JSON.stringify(
  LAMP_STORAGE_KEY,
)})}catch(e){}var d=document.documentElement.classList.contains("dark");document.documentElement.setAttribute("data-lamp",i.indexOf(s)<0?(d?${JSON.stringify(
  defaultLampColour(true),
)}:${JSON.stringify(defaultLampColour(false))}):s)}catch(e){}})()`;
