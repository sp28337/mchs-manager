import Link from "next/link";
import type { ReactNode } from "react";

import { BoneText } from "@/components/ui/bone";
import { SECTION_HASH, type SectionHash } from "@/features/shift/components/section-hash";
import { cn } from "@/lib/utils/cn";

/**
 * Подвал сайта: оговорка о расчёте, навигация, документы и адрес для
 * обращений — на каждой странице.
 *
 * --- Почему на каждой ------------------------------------------------------
 *
 * Политика обязана быть доступна с любой страницы (ч. 2 ст. 18.1 152-ФЗ:
 * «опубликовать или иным образом обеспечить неограниченный доступ»), а
 * согласие и условия — то, на что человек ссылается, когда спорит. Пока
 * ссылки стояли только на посадочной, человек с рабочего экрана добирался
 * до них через главную — то есть не добирался.
 *
 * Настройки cookie здесь по той же причине: отозвать согласие должно быть
 * так же просто, как дать его (ч. 2 ст. 9 152-ФЗ — отзыв в любое время), а
 * баннер после ответа исчезает, и другого входа к этому выбору у человека
 * нет.
 *
 * Оговорка о расчёте — по той же логике: «приложение не заменяет табель»
 * должно быть сказано там, где человека застанет вопрос, а не только на
 * странице, с которой он давно ушёл.
 *
 * --- Как он устроен и почему так ---------------------------------------------
 *
 * Четыре колонки, у каждой подпись и содержимое под ней: «О расчёте»,
 * «Навигация», «Документы», «Контакты». Подписи — тем же голосом, каким
 * подписаны цифры в полосе итога: узкая гарнитура названий, прописные,
 * разрядка. Цвет — тот же, каким в шапке написано «ГРАФИК» в названии
 * сайта: подписи стоят в одном ряду с названием и читаются его родней, а
 * не бледной сноской. Это не заголовки разделов, а подписи: они говорят,
 * что лежит под ними, и не спорят с содержимым.
 *
 * Содержимое у всех колонок одно по виду: обычный шрифт, один кегль, один
 * серый. Ссылки белеют под курсором и под фокусом с клавиатуры, оговорка —
 * нет, она не нажимается. Ни плашек, ни рамок, ни знаков: прежние плитки
 * были самым заметным, что есть на странице ниже календаря, а документы
 * читают раз в жизни.
 *
 * Оговорка стоит слева и занимает место двух соседних колонок: она
 * единственная, что читается связным текстом, а не списком слов, и в одну
 * колонку этот текст встал бы столбиком в пять слов. Навигация, документы и
 * контакты — правым краем.
 *
 * Отсекающей черты над подвалом нет: страница заканчивается, а не
 * переходит в другую, и линия поперёк рамки читалась границей, за которой
 * начинается нечто иное, — тогда как это тот же экран, только ниже.
 */

/** Почта для связи. */
export const EMAIL = "grafik1-3@yandex.ru";

/**
 * Оговорка о расчёте — двумя абзацами, теми же словами, что стояли на
 * посадочной странице, пока подвал был только у неё.
 */
const ОГОВОРКА: readonly string[] = [
  "График 1 3 не заменяет табель или другие документы работодателя. " +
    "Приложение показывает, как норма и переработка получаются из " +
    "производственного календаря и вашего графика.",
  "Точность зависит от введённого: даты смены, недельной нормы и периодов " +
    "отсутствия.",
];

/**
 * Навигация: разделы рабочего экрана, в том порядке, в каком их ищут чаще —
 * сперва то, что правят и смотрят каждый день.
 *
 * С расчёта они открываются на месте (`onOpenSection` у `FooterBody`), с
 * остальных страниц — ссылкой на расчёт с адресом раздела
 * (`/calculator#settings`, см. `section-hash.ts`).
 */
const НАВИГАЦИЯ: readonly { section: SectionHash; label: string }[] = [
  { section: SECTION_HASH.settings, label: "Настройки" },
  { section: SECTION_HASH.stats, label: "Статистика" },
  { section: SECTION_HASH.events, label: "События" },
  { section: SECTION_HASH.graphs, label: "Графики" },
];

/**
 * Документы сайта. Порядок — от общего к частному: на каких условиях
 * вообще, что с данными, на что человек согласился, чем управлять.
 *
 * Названия короче заголовков самих документов: «Политика в отношении
 * обработки персональных данных» в подвале занимает строку целиком, а
 * человек ищет глазами слово «политика».
 */
const ДОКУМЕНТЫ: readonly { href: string; label: string }[] = [
  { href: "/terms", label: "Пользовательское соглашение" },
  { href: "/privacy", label: "Политика конфиденциальности" },
  { href: "/consent", label: "Согласие на обработку данных" },
  { href: "/cookies", label: "Настройки cookie" },
];

/**
 * Подпись колонки: тем же голосом, что подписи под цифрами в полосе итога
 * (`period-summary.tsx`, `CAPTION_MINOR`), но цветом названия сайта в шапке
 * (`HEADER_WORD`): чёрный на светлой бумаге, чернила темы на тёмной.
 */
const ПОДПИСЬ =
  "block font-display text-xs font-bold uppercase leading-4 tracking-wide text-black/80 dark:text-ink";

/**
 * Содержимое колонки — одно на все четыре: один кегль и интерлиньяж, один
 * серый. Задано на списке или абзаце, а не на ссылках: высота строки
 * берётся от кегля контейнера, и ссылка внутри неё не меняет.
 */
const ТЕКСТ = "mt-3 text-sm leading-5 text-ink-muted";

/** Ссылка подвала: серая, белеет под курсором и под фокусом с клавиатуры. */
const ССЫЛКА = cn(
  "rounded-xs text-ink-muted no-underline transition-colors hover:text-ink",
  "focus-visible:text-ink focus-visible:outline-2 focus-visible:outline-offset-4",
  "focus-visible:outline-ink",
);

/**
 * Подвал целиком, без внешней рамки: оговорка, навигация, документы, адрес.
 *
 * `onOpenSection` — для рабочего экрана: раздел открывается на месте, без
 * перехода (ссылка на ту же страницу с новым адресом не пересоздала бы
 * экран, а он читает адрес только при открытии). Без него пункты навигации
 * — ссылки на расчёт.
 *
 * `skeleton` рисует ту же разметку теми же классами, но костями вместо
 * слов: заглушка рабочего экрана (`workspace-skeleton.tsx`) не копирует
 * подвал, а берёт его, и высота совпадает до пикселя, а не подбирается
 * числом.
 */
export function FooterBody({
  skeleton = false,
  onOpenSection,
}: {
  skeleton?: boolean;
  onOpenSection?: (section: SectionHash) => void;
}) {
  // В заглушке ссылки — не ссылки: нажимать там нечего, а подчёркивание и
  // цвет под плашкой всё равно не видны.
  const текст = (содержимое: ReactNode) => (
    <BoneText skeleton={skeleton}>{содержимое}</BoneText>
  );

  return (
    <div
      // Колонок: одна на телефоне; две с `sm` (оговорка на обе, под ней
      // остальные); три с `lg` (оговорка на все три сверху); и с `xl` — одной
      // строкой из четырёх, по середине рамки и с ОДИНАКОВЫМ просветом между
      // каждой парой (`justify-center` и общий `gap-x`): оговорка — 26 рем,
      // ровно две колонки документов, остальные три — по ширине содержимого.
      // Раньше `xl` нет смысла: четыре колонки в 854 точки рамки на 1024 не
      // помещаются, и оговорка сжалась бы до полутораста.
      //
      // `minmax(0, 26rem)`, а не просто 26 рем: на самой узкой рамке `xl`
      // (1110 точек) четыре колонки с просветами занимают 1070, и запас в
      // сорок точек не должен ломаться от одной лишней буквы в названии.
      //
      // `items-start`: все колонки стоят от одной верхней линии. Ячейки по
      // умолчанию растягиваются на высоту самой высокой, и подписи оказались
      // бы на разной высоте.
      className={cn(
        "grid items-start gap-x-12 gap-y-8",
        "sm:grid-cols-2 lg:grid-cols-3",
        "xl:grid-cols-[minmax(0,26rem)_auto_auto_auto] xl:justify-center 2xl:gap-x-20",
      )}
    >
      <div className="sm:col-span-2 lg:col-span-3 xl:col-span-1">
        <h2 className={ПОДПИСЬ}>{текст("О расчёте")}</h2>
        {/* Ширина строки — читательская: на экране шире `lg` оговорка не
            растягивается на весь ряд, а стоит столбцом, в котором глаз не
            теряет начало следующей строки. С `xl` её ширину задаёт сама
            колонка (26 рем). */}
        <div className={cn(ТЕКСТ, "max-w-[30rem] space-y-2")}>
          {ОГОВОРКА.map((абзац) => (
            <p key={абзац}>{текст(абзац)}</p>
          ))}
        </div>
      </div>

      <nav aria-labelledby={skeleton ? undefined : "footer-navigation"}>
        <h2 id={skeleton ? undefined : "footer-navigation"} className={ПОДПИСЬ}>
          {текст("Навигация")}
        </h2>
        <ul className={cn(ТЕКСТ, "space-y-2")}>
          {НАВИГАЦИЯ.map(({ section, label }) => (
            <li key={section}>
              {skeleton ? (
                текст(label)
              ) : onOpenSection ? (
                <button
                  type="button"
                  onClick={() => onOpenSection(section)}
                  className={cn(ССЫЛКА, "cursor-pointer text-left")}
                >
                  {label}
                </button>
              ) : (
                <Link href={`/calculator#${section}`} className={ССЫЛКА}>
                  {label}
                </Link>
              )}
            </li>
          ))}
        </ul>
      </nav>

      <nav aria-labelledby={skeleton ? undefined : "footer-documents"}>
        <h2 id={skeleton ? undefined : "footer-documents"} className={ПОДПИСЬ}>
          {текст("Документы")}
        </h2>
        <ul className={cn(ТЕКСТ, "space-y-2")}>
          {ДОКУМЕНТЫ.map(({ href, label }) => (
            <li key={href}>
              {skeleton ? (
                текст(label)
              ) : (
                <Link href={href} className={ССЫЛКА}>
                  {label}
                </Link>
              )}
            </li>
          ))}
        </ul>
      </nav>

      <div>
        <h2 className={ПОДПИСЬ}>{текст("Контакты")}</h2>
        <p className={ТЕКСТ}>
          {skeleton ? (
            текст(EMAIL)
          ) : (
            <a
              href={`mailto:${EMAIL}`}
              // Адрес не переносится по дефису: разорванный на «grafik1-» и
              // «3@yandex.ru» он читается как два куска и не копируется
              // двойным нажатием.
              className={cn(ССЫЛКА, "whitespace-nowrap")}
            >
              {EMAIL}
            </a>
          )}
        </p>
      </div>
    </div>
  );
}

/**
 * Готовый подвал страницы — `FooterBody` в рамке страницы, без черты над ним.
 */
export function SiteFooter({ className }: { className?: string }) {
  return (
    <footer className={className}>
      <div className="mx-auto w-full max-w-4xl px-6 py-10 xl:max-w-6xl 2xl:max-w-7xl">
        <FooterBody />
      </div>
    </footer>
  );
}
