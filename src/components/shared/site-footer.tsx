import { Cookie, FileSignature, Handshake, ShieldCheck, type LucideIcon } from "lucide-react";
import Link from "next/link";
import type { ReactNode } from "react";

import { cn } from "@/lib/utils/cn";

/**
 * Подвал сайта: документы и адрес для обращений — на каждой странице.
 *
 * --- Почему на каждой ------------------------------------------------------
 *
 * Политика обязана быть доступна с любой страницы (ч. 2 ст. 18.1 152-ФЗ:
 * «опубликовать или иным образом обеспечить неограниченный доступ»), а
 * согласие и условия — то, на что человек ссылается, когда спорит. Пока
 * ссылки стояли только на посадочной, человек с рабочего экрана добирался
 * до них через главную — то есть не добирался.
 *
 * Настройки cookie здесь по той же причине: отозвать согласие должно быть
 * так же просто, как дать его (ч. 2 ст. 9 152-ФЗ — отзыв в любое время), а
 * баннер после ответа исчезает, и другого входа к этому выбору у человека
 * нет.
 *
 * --- Почему плитками, а не строкой ссылок ----------------------------------
 *
 * Документов четыре, и названия у них одинаковой длины и одинакового вида:
 * «Пользовательское соглашение», «Политика конфиденциальности», «Согласие
 * на обработку данных». Строкой подряд они читаются как одна длинная фраза
 * с непонятными границами, а по отдельности не отвечают на единственный
 * вопрос, который у человека есть: в каком из четырёх искать своё.
 *
 * Поэтому у каждого свой знак и своя строка о том, что внутри. Знаки
 * выбраны по смыслу документа, а не по виду файла: четыре одинаковых
 * листка бумаги различали бы документы ровно так же, как ничего, —
 * рукопожатие, щит, подпись и печенье различимы с одного взгляда и
 * называют именно свой документ.
 */

/** Почта для связи. */
export const EMAIL = "grafik1-3@yandex.ru";

/**
 * Документы сайта. Порядок — от общего к частному: на каких условиях
 * вообще, что с данными, на что человек согласился, чем управлять.
 *
 * Названия короче заголовков самих документов: «Политика в отношении
 * обработки персональных данных» в подвале занимает строку целиком, а
 * человек ищет глазами слово «политика». Строка под названием — не
 * пересказ документа, а ответ на вопрос «мне сюда?».
 *
 * И названия, и строки под ними обязаны вставать в ОДНУ строку каждое на
 * самой узкой плитке — около двухсот точек под текст (подвал страницы
 * документа на мониторе, четыре плитки в ряд, и телефон в 320 точек).
 * Знак слева стоит по середине двух строк, и третья, перенесённая,
 * сдвинула бы его вниз от названия. Отсюда и краткость: «Какие данные
 * обрабатываются», а не «…и зачем» — «зачем» уже в самом документе.
 */
const ДОКУМЕНТЫ: readonly {
  href: string;
  label: string;
  note: string;
  Icon: LucideIcon;
}[] = [
  {
    href: "/terms",
    label: "Пользовательское соглашение",
    note: "Условия работы приложения",
    Icon: Handshake,
  },
  {
    href: "/privacy",
    label: "Политика конфиденциальности",
    note: "Какие данные обрабатываются",
    Icon: ShieldCheck,
  },
  {
    href: "/consent",
    label: "Согласие на обработку данных",
    note: "Что принимается при регистрации",
    Icon: FileSignature,
  },
  {
    href: "/cookies",
    label: "Настройки cookie",
    note: "Разрешить счётчик или отказать",
    Icon: Cookie,
  },
];

/** Перечень документов — для тех подвалов, что собраны своими руками. */
export function FooterDocuments({ className }: { className?: string }) {
  return (
    <nav
      aria-label="Документы сайта"
      // Одна колонка на телефоне, две на планшете, четыре на мониторе: в
      // две колонки на узком экране название ломалось бы на четыре строки,
      // а в четыре на `max-w-4xl` — на три.
      className={cn("grid gap-2 sm:grid-cols-2 xl:grid-cols-4", className)}
    >
      {ДОКУМЕНТЫ.map(({ href, label, note, Icon }) => (
        <Link
          key={href}
          href={href}
          // `lit` — та же кайма от лампы и от курсора, что у остальных
          // плашек приложения: плитка документа ничем не особеннее кнопки
          // в проводнике.
          //
          // Цвет на самой ссылке: наследования тут не происходит — у `a`
          // свой цвет по умолчанию, синий, и он перебивает цвет родителя.
          className={cn(
            "lit group flex items-center gap-3 rounded-xl bg-paper-raised px-3 py-2.5",
            "text-ink no-underline",
            "focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-ink",
          )}
        >
          <Icon
            aria-hidden
            // Знак — лицо плитки, а не пометка при названии: он стоит по
            // середине обеих строк, а не у верхней, иначе под ним оставался
            // пустой угол. Но ниже их общего роста — 28 точек против 32, тот
            // же размер, что у знака сайта и знаков по углам окна. Знак во
            // весь рост текста спорил с названием за взгляд.
            //
            // Приглушён он по той же причине: читают в плитке название, а
            // знак лишь помогает найти нужную среди четырёх. Под курсором
            // он проявляется — плитка отвечает на наведение целиком.
            //
            // Обводка тоньше обычной: в таком размере значок из набора
            // рисуется линией в два с лишним пикселя и весит больше текста
            // рядом.
            strokeWidth={1.5}
            className={cn(
              "size-7 shrink-0 text-ink-muted opacity-55 transition-[color,opacity]",
              "group-hover:text-ink group-hover:opacity-90",
            )}
          />
          <span className="min-w-0">
            {/* Обе строки — ровно по шестнадцать точек (`leading-4`): их
                сумма и есть рост знака слева, и считать её по
                межстрочным долям двух разных кеглей было бы гаданием. */}
            <span className="block text-xs font-medium leading-4">{label}</span>
            <span className="block text-[11px] leading-4 text-ink-muted">{note}</span>
          </span>
        </Link>
      ))}
    </nav>
  );
}

/**
 * Адрес для обращений — строкой под документами.
 *
 * По середине, а не у края: под плитками документов, выстроенными в
 * ряд, прижатая вправо строка читалась как подпись к последней из них.
 * Середина не принадлежит ни одной плитке, и строка снова читается сама
 * по себе.
 */
export function FooterEmail({ className }: { className?: string }) {
  return (
    // Отступ от плиток — свой, шестнадцать единиц, и он перекрывает
    // просвет родителя (поля соседей схлопываются, берётся больший).
    // Строка вплотную под плитками читалась пятой из них, только без
    // плашки; на расстоянии она — отдельная вещь, подпись всего подвала.
    <p className={cn("mt-16 text-center text-xs text-ink-muted", className)}>
      Вопросы и обращения:{" "}
      <a
        href={`mailto:${EMAIL}`}
        // Адрес не переносится по дефису: разорванный на «grafik1-» и
        // «3@yandex.ru» он читается как два куска и не копируется
        // двойным нажатием.
        className="whitespace-nowrap text-ink-muted hover:underline"
      >
        {EMAIL}
      </a>
    </p>
  );
}

/**
 * Готовый подвал: перечень документов, почта и то, что страница допишет
 * сама (`children`) — оговорки посадочной, время правки на рабочем экране.
 */
export function SiteFooter({
  children,
  className,
}: {
  children?: ReactNode;
  className?: string;
}) {
  return (
    <footer className={cn("border-t border-rule", className)}>
      <div className="mx-auto w-full max-w-4xl space-y-6 px-6 py-8 xl:max-w-6xl 2xl:max-w-7xl">
        {children}
        <FooterDocuments />
        <FooterEmail />
      </div>
    </footer>
  );
}
