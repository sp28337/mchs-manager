/**
 * «Как работает» — четыре шага, каждый со своим показом.
 *
 * --- Что было и почему это переделано -------------------------------------
 *
 * Раздел был сеткой из шести плиток: серый значок, заголовок, строчка
 * текста. Плитка честно НАЗЫВАЛА возможность, но человек, не открывавший
 * приложение, из неё не знал ни что нажимать, ни что он увидит в ответ.
 * Шесть одинаковых серых значков подряд при этом не показывали ничего:
 * такой ряд читается как оформление, а не как содержание.
 *
 * Теперь шагов четыре, и у каждого свой маленький показ — теми же
 * клетками и теми же цветами, что человек встретит внутри. Показ отвечает
 * на «как это выглядит», текст рядом — на «зачем это».
 *
 * --- Почему четыре, а не шесть --------------------------------------------
 *
 * Плитки перечисляли возможности, а шаги рассказывают порядок работы, и в
 * этом порядке некоторые пары неразделимы. «Автоматический график» и
 * «норма периода» — это один ответ: график человек задаёт, норма из
 * производственного календаря следует, и разносить их по разным плиткам
 * значило бы разорвать причину и следствие. Так же «отпуска» и «работа
 * помимо графика»: они стоят рядом именно потому, что действуют
 * ПО-РАЗНОМУ — одно уменьшает норму, другое прибавляет к отработанному, — и
 * разница видна, только когда они названы вместе.
 *
 * --- Почему без плашек ----------------------------------------------------
 *
 * Плашка отделяет содержимое от страницы, и шести карточкам это было
 * нужно: без неё они рассыпались бы. Показу плашка мешает: он и сам
 * предмет, у него своя рамка внутри, и вторая рамка вокруг превращает шаг
 * в скриншот в рамочке. Шаги теперь разделяет воздух, а не заливка.
 *
 * --- Кегль -----------------------------------------------------------------
 *
 * Раздел идёт сразу за первым экраном, а там заголовок в восемь ступеней и
 * подпись от руки в пять. Мелкий текст после такого читается как сноска —
 * будто главное уже сказано, а дальше подробности для дотошных. Поэтому
 * здесь свои ступени: заголовок раздела вровень с прочими на странице,
 * заголовок шага — крупный и НЕ прописными (прописные на таком кегле
 * превращаются в вывеску), текст шага на ступень крупнее обычного абзаца.
 *
 * --- Раскладка ------------------------------------------------------------
 *
 * На узком экране колонка одна и порядок такой: заголовок, показ, текст.
 * Показ стоит между ними намеренно — заголовок называет шаг, показ
 * отвечает, а текст объясняет уже увиденное.
 *
 * На широком шаги идут змейкой: у первого текст слева и показ справа, у
 * второго наоборот, и так дальше. Ряд одинаково собранных шагов глаз
 * пролистывает как таблицу; змейка заставляет его переходить со строки на
 * строку, и каждый шаг читается отдельно.
 *
 * Порядок в разметке при этом ОДИН для всех — заголовок, показ, текст, —
 * а местами их меняет сетка (`grid-template-areas`). Это важнее, чем
 * кажется: программа чтения и поисковый робот идут по разметке, и там шаг
 * обязан читаться сверху вниз, в каком бы порядке он ни стоял на экране.
 */

export interface HowStep {
  title: string;
  text: string;
  demo: ReactNode;
}

