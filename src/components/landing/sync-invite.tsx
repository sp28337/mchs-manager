import Link from "next/link";

/**
 * Приглашение к учётной записи — на посадочной странице, одной плашкой.
 *
 * --- Почему не раздел во весь экран ---------------------------------------
 *
 * Разделы на этой странице отвечают на вопросы, с которыми человек пришёл:
 * что это, как считает, по каким нормам. Синхронизация не из их числа —
 * пришёл он считать часы, а не заводить учётную запись. Поэтому не раздел
 * с заголовком в шесть ступеней, а плашка в один абзац: кому нужно — тот
 * увидит, остальным она не мешает читать дальше.
 *
 * --- Почему вообще нужна ---------------------------------------------------
 *
 * Без неё возможность не существует. Строка в подвале рабочего экрана
 * видна тому, кто уже внутри и долистал до низа; человек, открывший сайт с
 * телефона и думающий, не придётся ли вводить всё заново на компьютере,
 * ответа не находит нигде.
 *
 * --- Почему тут сказано про ключ ------------------------------------------
 *
 * «Копия на сервере» у человека, пришедшего из приложения, которое обещало
 * считать в браузере, вызывает ровно один вопрос — «а кто это прочтёт».
 * Ответ должен стоять в том же абзаце, что и предложение, иначе предложение
 * выглядит отказом от прежнего обещания.
 *
 * Рисуется только в сборке с включённой синхронизацией — решает это
 * страница (`app/page.tsx`): в сборке без неё заводить учётную запись
 * негде, и приглашение было бы обманом.
 */
export function SyncInvite() {
  return (
    <section
      aria-labelledby="sync"
      // `lit` — та же лампа, что у карточек и вопросов ниже: отдельного
      // света у этой плашки нет, она часть той же комнаты.
      className="lit my-16 rounded-xl bg-paper-raised px-5 py-5 md:my-20 md:px-6 md:py-6"
    >
      <h2 id="sync" className="text-md font-medium md:text-lg">
        Нужно на телефоне и на компьютере
      </h2>
      <p className="max-w-prose pt-2 text-sm leading-6 text-ink-muted md:text-md">
        Можно завести учётную запись — тогда правка, сделанная на телефоне,
        окажется на компьютере сама. На сервер при этом уезжает{" "}
        <strong className="font-medium text-ink">зашифрованная</strong> копия:
        ключ выводится из вашего пароля в браузере и на сервер не попадает,
        поэтому прочитать её не может никто — ни владелец сервиса, ни тот, кто
        получит доступ к серверу. Без учётной записи приложение работает
        полностью, как и раньше.
      </p>
      <p className="flex flex-wrap gap-x-4 gap-y-1 pt-3 text-sm">
        <Link href="/account" className="text-ink underline hover:no-underline">
          Учётная запись
        </Link>
        <Link href="/privacy" className="text-ink-muted hover:underline">
          Что именно уходит на сервер
        </Link>
      </p>
    </section>
  );
}
