import { LogIn, MonitorSmartphone, ShieldCheck, UserPlus, WifiOff } from "lucide-react";
import Link from "next/link";

import { Button } from "@/components/ui/button";

/**
 * Учётная запись на посадочной — своим разделом.
 *
 * --- Почему раздел, а не плашка в один абзац -------------------------------
 *
 * Плашка здесь и была: абзац текста и две ссылки под ним. Читалась она
 * ровно как то, чем была по виду, — примечанием к приложению, которое
 * хранит данные в браузере. Между тем вопрос «а на компьютере мне всё
 * вводить заново?» человек задаёт себе на первом же экране, и ответ на
 * него — не примечание.
 *
 * Поэтому раздел: заголовок, три коротких ответа на три настоящих вопроса
 * («оно и там и там?», «кто это прочтёт?», «а без сети?») и две кнопки —
 * создать запись и войти. Столько же, сколько у любого другого раздела
 * этой страницы, и ни ступенью больше: пришёл человек считать часы, а не
 * заводить учётную запись.
 *
 * --- Почему две кнопки, а не одна ------------------------------------------
 *
 * Потому что людей здесь двое. Первый видит предложение впервые — ему
 * «Создать учётную запись». Второй уже заводил её на телефоне и открыл
 * сайт на компьютере именно затем, чтобы войти, — и искать вход в шапке
 * мелким значком ему незачем, когда речь о нём идёт прямо здесь.
 *
 * Ведут они на одну страницу, но в разные её положения: `#register`
 * открывает её на регистрации (`auth-screen.tsx`). Кнопка, после которой
 * надо ещё переключить закладку, обещает не то, что делает.
 *
 * Рисуется только в сборке с включённой синхронизацией — решает это
 * страница (`app/page.tsx`): в сборке без неё заводить учётную запись
 * негде, и приглашение было бы обманом.
 */

const ДОВОДЫ = [
  {
    icon: MonitorSmartphone,
    title: "Телефон и компьютер",
    text: "Правка, сделанная по дороге с работы, окажется на компьютере сама — переносить файл не нужно.",
  },
  {
    icon: ShieldCheck,
    title: "Копия зашифрована",
    text: "Ключ выводится из вашего пароля в браузере и на сервер не уезжает: прочитать копию не может никто, включая владельца сервиса.",
  },
  {
    icon: WifiOff,
    title: "Без сети — как раньше",
    text: "Расчёт и правки живут в браузере. Сервер — это копия, а не источник: пропала связь, правки уедут позже сами.",
  },
];

export function SyncInvite() {
  return (
    <section aria-labelledby="sync" className="border-b border-rule py-16 md:py-20">
      <div className="space-y-4">
        <h2 id="sync" className="text-3xl md:text-5xl lg:text-6xl">
          График на всех ваших устройствах
        </h2>
        <p className="max-w-[52ch] text-md leading-7 text-ink-muted text-pretty md:text-lg md:leading-8">
          Учётная запись нужна для одного — чтобы не переносить профиль файлом
          с телефона на компьютер. Без неё приложение работает полностью, как и
          раньше.
        </p>
      </div>

      <ul className="grid gap-3 pt-8 sm:grid-cols-3">
        {ДОВОДЫ.map((довод) => (
          <li
            key={довод.title}
            // `lit` — та же лампа, что у карточек с нормами ниже: отдельного
            // света у этого раздела нет, он часть той же комнаты.
            className="lit flex h-full flex-col gap-1.5 rounded-xl bg-paper-raised p-5"
          >
            <довод.icon aria-hidden className="size-5 shrink-0 text-ink-muted" />
            <span className="pt-1 font-medium text-ink">{довод.title}</span>
            <span className="text-sm leading-6 text-ink-muted">{довод.text}</span>
          </li>
        ))}
      </ul>

      {/* Кнопки во всю долю своего места: кнопка в приложении растянута по
          ширине (`ui/button.tsx`), и доли здесь заданы сеткой, а не
          растяжением строки. */}
      <div className="grid gap-2 pt-6 sm:grid-cols-[repeat(2,minmax(0,15rem))]">
        <Button asChild>
          <Link href="/account#register">
            <UserPlus aria-hidden /> Создать учётную запись
          </Link>
        </Button>
        <Button asChild variant="outline">
          <Link href="/account">
            <LogIn aria-hidden /> Войти
          </Link>
        </Button>
      </div>

      <p className="pt-4 text-sm text-ink-faint">
        <Link href="/privacy" className="hover:underline">
          Что именно уходит на сервер
        </Link>
      </p>
    </section>
  );
}
