import { ArrowRight } from "lucide-react";
import Link from "next/link";
import type { ReactNode } from "react";

import { SHIFTS_ON, ShiftsIcon } from "@/features/shift/components/grid-icons";
import { cn } from "@/lib/utils/cn";

/**
 * Кнопка в расчёт. Одна деталь на обе: в шапке она меньше, на первом
 * экране крупнее, но разъехаться формой или цветом им нельзя — это одна
 * и та же дверь.
 *
 * Лежит отдельным файлом, а не в самой странице, потому что надпись на
 * ней решает `HeroCta` — а он читает хранилище и потому работает в
 * браузере. Кнопка при этом остаётся обычной: ни состояния, ни эффектов у
 * неё нет, и в шапку она попадает прямо из серверной разметки.
 */
export function ToCalculator({
  children,
  size = "md",
}: {
  children: ReactNode;
  size?: "sm" | "md";
}) {
  return (
    <Link href="/calculator" className={ctaClass(size)}>
      <CtaBody size={size}>{children}</CtaBody>
    </Link>
  );
}

/**
 * Вид кнопки первого экрана — отдельно от неё самой.
 *
 * У кнопки два поведения: у того, кто уже завёл график, она ссылка в
 * расчёт; у того, кто здесь впервые, — кнопка, открывающая окно на месте.
 * Это разные элементы разметки (`a` и `button`), и разъехаться видом им
 * нельзя: человек нажимает одно и то же место, и одинаковость здесь —
 * обещание, что за ней одно и то же.
 *
 * --- Почему плашка, а не залитая чернилами кнопка ----------------------------
 *
 * Чёрная (на тёмной теме — белая) таблетка с «календариком» — кнопка из
 * любого конструктора сайтов: она ничем не говорит, что за ней приложение
 * со своим языком. Здесь она сделана из того, чем это приложение говорит
 * везде:
 *
 * * поднятая бумага с лампой (`lit`), как окна, меню и карточки внутри:
 *   кайма горит от лампы и разгорается под курсором;
 * * знак слева — тот же, что у «График» в левом столбце знаков на расчёте:
 *   знак сайта, у которого залитая клетка зелёная (та же зелёная, какой в
 *   календаре стоят смены и набрана первая строка заголовка над кнопкой). Сам
 *   знак, без плитки, рамки и заливки под ним;
 * * надпись узкой гарнитурой названий, прописными, с разрядкой — голосом
 *   слов «МЕНЮ» и «ВХОД» в шапке и подписей под числами итога;
 * * стрелка справа, тусклая в покое и проступающая под указателем: она
 *   говорит «дальше», не крича об этом.
 *
 * Нажатие — лёгкое сжатие, как у плиток внутри. Размеры `sm` и `md` — по
 * высоте плашки (44 и 56 точек); 44 — меньше, чем место под палец не бывает.
 */
export function ctaClass(size: "sm" | "md" = "md"): string {
  return cn(
    "group lit relative inline-flex shrink-0 cursor-pointer items-center bg-paper-raised text-ink no-underline",
    "transition-transform duration-200 active:scale-[0.98]",
    "focus-visible:outline-2 focus-visible:outline-offset-4 focus-visible:outline-ink",
    // Справа поля нет: правый зазор стрелки до края плашки задаёт сама стрелка
    // (`CtaBody`), чтобы он был равен зазору до надписи.
    size === "sm" ? "h-11 gap-2.5 rounded-xl pl-1.5" : "h-14 gap-3.5 rounded-2xl pl-2",
  );
}

/**
 * Самая длинная из надписей, которые кнопка может показать: под неё отводится
 * место (см. `CtaBody`).
 */
const LONGEST_LABEL = "Построить график";

/**
 * Содержимое плашки: знак, надпись, стрелка.
 *
 * Надпись приходит снаружи — она бывает «Построить график», «Открыть график»
 * и «Заполнить график». Знак и стрелка — `aria-hidden`: они повторяют слова
 * рядом, и без этого программа чтения произносила бы кнопку дважды.
 *
 * Знак — тот же, что у графика в переключателе сеток (`ShiftsIcon` с
 * цветом `SHIFTS_ON`): кнопка ведёт к сетке месяцев, и называет её тем же
 * рисунком, что стоит у самой сетки внутри. Совпадение не украшение:
 * человек, попавший внутрь, узнаёт кнопку, которой пришёл.
 *
 * Под знаком ничего нет — ни плитки, ни рамки, ни заливки: он стоит прямо на
 * бумаге плашки, как стоит в левом столбце. Коробка вокруг него без вида, и нужна
 * она только затем, чтобы знак встал туда, где раньше стояла плитка: от этого
 * места посчитаны поля плашки (`ctaClass`).
 *
 * --- Почему место под самую длинную надпись ---------------------------------
 *
 * Надпись на кнопке первого экрана решает `HeroCta`, а решает он её по
 * хранилищу — то есть уже в браузере. В разметку уходит «Построить график»,
 * и тому, у кого график есть, она через мгновение меняется на «Открыть
 * график».
 *
 * Мгновение это приходится ровно на появление первого экрана, и замер
 * показывал вот что: на 112 мс кнопка шириной 218 точек, на 290 мс — 204,
 * и всё это под ещё не сошедшим размытием. Четырнадцать точек, отскочившие
 * посреди плавного появления, глаз ловит безошибочно — и читает как рывок
 * анимации, хотя анимация ни при чём.
 *
 * Поэтому под надпись отводится место по самой длинной из возможных. Обе
 * лежат в одной клетке сетки, невидимая — только ради ширины. Подмена после
 * этого не двигает ничего. Программе чтения невидимая не достаётся:
 * `aria-hidden` снимает её, иначе кнопка называлась бы двумя надписями.
 *
 * --- Почему стрелка стоит посередине свободного места -------------------------
 *
 * Место под самую длинную надпись у короткой оставляет запас — у «Открыть
 * график» это около двадцати точек. Прижми стрелку к правому краю — и между
 * текстом и ней зазор шире, чем между ней и краем плашки; прижми к тексту — и
 * ширина поедет вместе с надписью, то есть вернётся тот самый рывок.
 *
 * Поэтому стрелка лежит в той же клетке, что и надпись, и стоит по середине
 * ОСТАВШЕГОСЯ места — от конца видимого текста до края плашки. Зазоры слева и
 * справа от неё равны при любой надписи: у самой длинной это ровно поле плашки
 * (24 точки; 16 у малой), у короткой — оно же и половина запаса. Ширина при
 * этом постоянна.
 *
 * Невидимая надпись несёт с собой пустое место под стрелку такой же ширины,
 * что и видимая зона (два поля и сама стрелка): иначе ширина плашки зависела бы
 * от того, что в зоне лежит.
 *
 * --- Как отъезжает стрелка ------------------------------------------------------
 *
 * Под указателем и под фокусом с клавиатуры стрелка плавно сдвигается вправо на
 * шесть точек и так же плавно возвращается. Переход назван по СВОЙСТВУ
 * `translate`: в Tailwind 4 `translate-x-*` пишет именно его, а не `transform`, и
 * переход, назначенный на `transform`, сдвига не видел — стрелка прыгала.
 */
export function CtaBody({
  children,
  size = "md",
}: {
  children: ReactNode;
  size?: "sm" | "md";
}) {
  const small = size === "sm";
  return (
    <>
      <span
        aria-hidden
        className={cn(
          "grid shrink-0 place-items-center",
          small ? "size-8" : "size-10",
          SHIFTS_ON,
        )}
      >
        {/* `scale-100`: поправка размера знака сайта (`grid-icons.tsx`) нужна
            в ряду знаков, чтобы выровнять его с часами и календарём, а здесь
            ряда нет. Крупнее, чем в плитке: плитки нет, и мелкий знак
            терялся бы на пустом месте. */}
        <ShiftsIcon className={cn("scale-100", small ? "size-5.5" : "size-7")} />
      </span>

      <span
        className={cn(
          "grid font-display font-bold uppercase leading-none tracking-wide",
          small ? "text-base" : "text-xl",
        )}
      >
        {/* Невидимая: ширина под самую длинную надпись и под зону стрелки. */}
        <span
          aria-hidden
          className="invisible col-start-1 row-start-1 flex items-center whitespace-nowrap"
        >
          {LONGEST_LABEL}
          <span className={small ? "w-12" : "w-17"} />
        </span>

        <span className="col-start-1 row-start-1 flex items-center whitespace-nowrap">
          <span>{children}</span>
          {/* Зона от конца текста до края плашки; стрелка по её середине. */}
          <span aria-hidden className="flex min-w-0 flex-1 justify-center">
            <ArrowRight
              className={cn(
                "shrink-0 text-ink/30 transition-[translate,color] duration-300 ease-out",
                "group-hover:translate-x-1.5 group-hover:text-ink",
                "group-focus-visible:translate-x-1.5 group-focus-visible:text-ink",
                small ? "size-4" : "size-5",
              )}
            />
          </span>
        </span>
      </span>
    </>
  );
}
