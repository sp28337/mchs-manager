/* ==========================================================================
   Время: когда палец что делает.

   История — это цепочка шагов, и у каждого шага один и тот же ритм. Рука
   подъезжает к суткам, на мгновение замирает и нажимает; через долю секунды
   запись ложится на месяц (сутки — друг за другом, чтобы было видно, что это
   период, а не одна клетка); когда последние сутки сели, пересчитываются
   числа; после короткой паузы рука едет к следующему месяцу.

   Убирает она так же, но короче: нажала — записи нет — числа вернулись.

   Сроки считаются, а не записаны числами: поменяется длительность отметки или
   дорога руки — расписание сдвинется само.
   ========================================================================== */

/**
 * Сколько идёт появление отметки на клетке.
 *
 * Столько же стоит и в самой анимации: значение уходит в CSS переменной
 * `--mark-ms`, чтобы второго источника этой длительности не было.
 */
export const HERO_MARK_MS = 520;

/** Дорога руки между двумя местами. Столько же — в переходе `HeroPointer`. */
export const HERO_MOVE_MS = 760;

/** Рука доехала и стоит перед нажатием. */
const SETTLE_MS = 140;

/** От нажатия до первой отметки на сетке. */
const PRESS_TO_MARK_MS = 160;

/** Пауза после пересчёта чисел, прежде чем рука поедет дальше. */
const HOLD_MS = 560;

/** Пауза после удаления, прежде чем рука поедет дальше. */
const HOLD_REMOVE_MS = 260;

/** Сколько отметка гаснет при удалении. */
const REMOVE_MS = 280;

/** Рука убрана, и до нового круга — тишина: пусть календарь постоит пустым. */
const LOOP_GAP_MS = 1400;

/**
 * Доля хода отметки, на которой она перестаёт расти и начинает садиться.
 *
 * Отметка появляется с подскоком: сперва вырастает крупнее клетки, потом
 * оседает в её размер. Пик приходится на 60 процентов хода — эта же цифра
 * стоит ключевым кадром в `@keyframes cal-absence-in` (`globals.css`), и
 * связать их одним значением нельзя: доля ключевого кадра переменной не
 * задаётся. Меняешь там — меняй и здесь.
 */
const MARK_SETTLES_AT = 0.6;

/**
 * Через сколько ложатся следующие сутки той же записи.
 *
 * Запись ложится днями подряд за ограниченное время, как бы длинна ни была:
 * отпуск на тридцать одни сутки не должен идти в тридцать раз дольше
 * больничного на семь. Верх — чтобы неделя не растягивалась в замедленное
 * кино.
 */
export function heroStagger(days: number): number {
  return Math.min(70, Math.round(640 / Math.max(1, days - 1)));
}

/** Сколько от нажатия по первым суткам записи до пика последних. */
function cascadeMs(event: HeroEvent): number {
  return (event.days.length - 1) * heroStagger(event.days.length) + HERO_MARK_MS * MARK_SETTLES_AT;
}

/** Нажатое сейчас и что на нём написано. */
export interface HeroChip {
  events: readonly number[];
  /** Нажатие убирает, а не ставит. */
  remove: boolean;
}

/** Что меняется в какой-то миг истории. */
export interface HeroPatch {
  stage?: number;
  /** Состояние записей по имени: `on` — легла, `off` — убрана. */
  events?: Readonly<Record<string, "on" | "off">>;
  pointer?: {
    visible?: boolean;
    /** Сутки, к которым едет рука, ISO. */
    day?: string;
    /** Нажатие: счётчик растёт, и круг от руки расходится заново. */
    press?: true;
    chip?: HeroChip | null;
  };
}

export interface HeroAction {
  /** Миг от начала круга, мс. */
  at: number;
  patch: HeroPatch;
}

const pad = (value: number) => String(value).padStart(2, "0");

/** Первые сутки записи — ISO. Туда и едет рука. */
export function heroEventDay(event: HeroEvent): string {
  return `${HERO_YEAR}-${pad(event.month)}-${pad(event.days[0]!)}`;
}

/**
 * Один круг истории, разложенный по мигам.
 *
 * Считается один раз на раскладку и не зависит от окна: часы идут от начала
 * круга, а не от кадров. Хронометраж записан не в тексте, а здесь — и тест
 * следит, чтобы круг был упорядочен и кончался тем же, с чего начался.
 */
export function buildTimeline(script: HeroScript): { actions: HeroAction[]; period: number } {
  const actions: HeroAction[] = [];
  const act = (at: number, patch: HeroPatch) => actions.push({ at: Math.round(at), patch });

  let t = 0;
  for (const step of script.steps) {
    if (step.kind === "add") {
      const event = script.events[step.event]!;
      act(t, { pointer: { visible: true, day: heroEventDay(event), chip: null } });
      const press = t + HERO_MOVE_MS + SETTLE_MS;
      act(press, {
        pointer: { press: true, chip: { events: [step.event], remove: false } },
      });
      const placed = press + PRESS_TO_MARK_MS;
      act(placed, { events: { [event.id]: "on" } });
      const done = placed + cascadeMs(event);
      act(done, { stage: step.event + 1 });
      t = done + HOLD_MS;
    } else {
      const first = script.events[step.events[0]!]!;
      act(t, { pointer: { visible: true, day: heroEventDay(first), chip: null } });
      const press = t + HERO_MOVE_MS + SETTLE_MS;
      act(press, { pointer: { press: true, chip: { events: step.events, remove: true } } });
      const gone = press + PRESS_TO_MARK_MS;
      act(gone, {
        events: Object.fromEntries(step.events.map((index) => [script.events[index]!.id, "off"])),
      });
      const done = gone + REMOVE_MS;
      act(done, { stage: Math.min(...step.events) });
      t = done + HOLD_REMOVE_MS;
    }
  }

  // Рука уходит, когда всё убрано, и круг ждёт, пока календарь постоит чистым.
  act(t, { pointer: { visible: false, chip: null } });
  return { actions, period: t + LOOP_GAP_MS };
}

/**
 * Когда история может начаться: сетка собрана, числа над ней встали.
 *
 * Все слагаемые — из `globals.css` (кроме волны: её длину задают номер
 * последней клетки и шаг, оба известны здесь и в `hero-wave.ts`):
 *
 *    360  разлиновка проступает           `--cal-grid-ms`
 *  +  60  вдох перед волной               `--cal-lead` минус разлиновка
 *  + волна доходит до ближнего угла       номер последней клетки × шаг
 *  + 260  пауза перед числами             задержка `.hero-cal__figures`
 *  + 900  числа встают                    длительность там же
 *  + 400  пауза: пусть глаз осмотрит собранное, прежде чем появится рука
 *
 * Тронешь любое из этих значений в `globals.css` — пересчитай и это.
 */
export function heroStartAt(layout: HeroLayout): number {
  const script = HERO_SCRIPTS[layout];
  return 360 + 60 + heroLastWave(layout) * script.waveStepMs + 260 + 900 + 400;
}
