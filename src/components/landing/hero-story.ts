/**
 * Что человек ставит на сутки: освобождение от смены, вызов или смену там, где
 * её по графику нет («Поставить смену» в перечне видов у дня).
 */
export type HeroEventKind = AbsenceKind | "callout" | "shift";

/** Одно действие пальца: запись на месяце. */
export interface HeroEvent {
  /** Имя записи — по нему клетки находят свою отметку. */
  id: string;
  kind: HeroEventKind;
  /** Номер месяца в году (7 — июль). */
  month: number;
  /**
   * Сутки, закрашенные на сетке: все, что запись накрывает, и хвост её смены.
   * У смены — заступление и продолжение: два дня подряд.
   */
  days: readonly number[];
  /** Границы записи для расчёта, включительно. */
  from: number;
  to: number;
  /** Часы вызова в сутки. Только у вызова. */
  hours?: number;
}

/** Итоги: норма, факт и две стороны их разницы. */
export interface HeroTotals {
  /** Норма к отработке. */
  norm: number;
  /** Фактически отработано. */
  actual: number;
  /** Переработка сверх нормы. Ноль, если ушли под норму. */
  overtime: number;
  /** Недоработка. Ноль, если норма перекрыта. */
  undertime: number;
}

export interface HeroStage extends HeroTotals {
  /** Итоги месяцев над сеткой — в порядке `HERO_MONTHS[layout]`. */
  months: readonly HeroTotals[];
}

/** Шаг истории: поставить запись или убрать записи. */
export type HeroStep =
  | { kind: "add"; event: number }
  /** Убирает записи одним нажатием; после него остаются те, что стояли до первой из них. */
  | { kind: "remove"; events: readonly number[] };

export interface HeroScript {
  layout: HeroLayout;
  events: readonly HeroEvent[];
  /**
   * Состояния расчёта: `stages[k]` — когда стоят первые `k` записей.
   * Переработка и недоработка лежат порознь, как и в домене: там это два
   * неотрицательных числа, из которых одно всегда ноль.
   */
  stages: readonly HeroStage[];
  steps: readonly HeroStep[];
  /** Шаг волны сборки, мс: у узкой раскладки клеток меньше, и шаг больше. */
  waveStepMs: number;
}

const span = (from: number, to: number): number[] =>
  Array.from({ length: to - from + 1 }, (_, index) => from + index);

/** Итог по двум числам: разницу домен считает так же, вычитанием. */
const totals = (norm: number, actual: number): HeroTotals => ({
  norm,
  actual,
  overtime: Math.max(0, actual - norm),
  undertime: Math.max(0, norm - actual),
});

const stage = (period: HeroTotals, months: readonly HeroTotals[]): HeroStage => ({
  ...period,
  months,
});

