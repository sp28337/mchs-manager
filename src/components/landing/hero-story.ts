/**
 * Что показывает первый экран: палец ставит события на месяцы графика, числа
 * пересчитываются после каждого, а в конце палец всё убирает — и так по кругу.
 *
 * --- Почему числа лежат здесь, а не считаются на месте --------------------
 *
 * Считать их в самой странице значило бы утянуть в её выдачу весь домен
 * расчёта: производственный календарь, десятичную арифметику, разбор смен.
 * Посадочная страница отдаётся статикой и должна оставаться лёгкой.
 *
 * Но и выдумывать их нельзя: приложение существует ради того, чтобы числа
 * не врали, и первый экран — не исключение. Поэтому числа настоящие, а
 * сходятся они с доменом ПРОВЕРКОЙ: `hero-story.test.ts` прогоняет тот же
 * расчёт для каждого этапа истории и сверяет и итог периода, и итог каждого
 * месяца над сеткой. Изменится правило — упадёт тест, а не доверие.
 *
 * --- Почему июль — октябрь ---------------------------------------------------
 *
 * Месяцы выбраны ЧИСТЫЕ: ни праздников, ни предпраздничных дней, ни
 * перенесённых выходных. Тогда каждое число выводится из того, что видно на
 * сетке, — рабочие дни на восемь часов и смены по двадцать четыре:
 *
 *   июль     норма 168 = 21 день × 8      факт 192 = 8 смен × 24
 *   август   норма 184 = 23 дня × 8       факт 192 = 8 смен × 24
 *   сентябрь норма 168 = 21 день × 8      факт 168 = 7 смен × 24
 *   октябрь  норма 176 = 22 дня × 8       факт 192 = 8 смен × 24
 *
 * График — «сутки через трое», с первого июля. Смена в двадцать четыре часа
 * делится полуночью на 16 и 8, и ни одна не переходит границу месяца: итог
 * месяца — сумма его суток, и перенос на соседний тут ничего бы не сдвинул.
 *
 * --- Что происходит на широком экране --------------------------------------
 *
 * Четыре месяца, и на каждом своё действие, разное по смыслу:
 *
 *   июль     ОТПУСК на весь месяц — норма и факт падают в ноль;
 *   август   БОЛЬНИЧНЫЙ с первого числа на неделю;
 *   сентябрь ДОПОЛНИТЕЛЬНЫЙ ОТПУСК на неделю;
 *   октябрь  ВЫЗОВ на четыре часа в свободные сутки — они идут в
 *            отработанное и норму не трогают; потом СМЕНА, поставленная
 *            самим человеком на свободные сутки, — переработка растёт; и
 *            наконец ОТГУЛ за неё на одну из смен графика — отработанное
 *            падает, норма на месте.
 *
 * Отсутствия уменьшают и факт, и норму, вызов и лишняя смена прибавляют к
 * факту, отгул отнимает от него: четыре разных ответа на «что стало с
 * числами» — и человек видит их все, не прочитав ни одного слова. Лишняя
 * смена перед отгулом — потому что отгул берут за переработку: сначала она
 * набегает, потом тратится.
 *
 * --- Что происходит на узком --------------------------------------------------
 *
 * Там четыре месяца не умещаются — клетка вышла бы в полтора десятка точек, —
 * и остаётся один, июль. Те же действия, но без дополнительного отпуска, а
 * отпуск и больничный — на первую и вторую недели месяца: так весь рассказ
 * уходит в один месяц и остаётся читаемым. Лишняя смена здесь — двадцать
 * седьмого июля.
 *
 * --- Почему границы записей стоят именно там -----------------------------------
 *
 * Смена длится сутки и лежит в двух днях: заступление и продолжение. Если
 * запись начинается или кончается посреди смены, на сетке появляются клетки,
 * которых нет ни в одном из правил «в полный голос — только заступление»: хвост
 * чужой смены под отпуском остаётся с часами, хвост смены, начатой в последний
 * день записи, помечается тоже. Чтобы показывать только то, что ясно с первого
 * взгляда, границы поставлены на свободные сутки и на хвост собственной смены
 * записи, — тест это проверяет.
 */

