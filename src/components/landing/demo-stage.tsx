"use client";

import { useEffect, useRef, useState, type ReactNode } from "react";

import { cn } from "@/lib/utils/cn";

/**
 * Сцена показа: анимация внутри играет, когда до неё дошли.
 *
 * --- Зачем вообще ---------------------------------------------------------
 *
 * Первый экран показывает историю один раз, при загрузке, и этого хватает:
 * он и есть то, на что человек смотрит в эту секунду. Разделу «Как
 * работает» так нельзя — он лежит экраном ниже. Отыграй он на загрузке, и
 * человек, прокрутивший до него через десять секунд, увидел бы четыре
 * готовых картинки и ни одного движения. Показ, который никто не видел,
 * это не показ.
 *
 * --- Почему `data-play`, а не класс на элементах ---------------------------
 *
 * Анимации целиком описаны в `globals.css` и назначены только под этим
 * признаком. Снять признак — значит снять `animation-name`, а снятое и
 * заново назначенное имя анимация начинает С НАЧАЛА. Поэтому повтор при
 * возврате в поле зрения получается сам, без перемонтирования разметки и
 * без счётчиков в состоянии.
 *
 * `animation-play-state` для этого не годится: пауза замирает на текущем
 * кадре и продолжает с него же, то есть вернувшийся человек застаёт
 * историю с середины.
 *
 * --- Почему в разметке стоит «играет» -------------------------------------
 *
 * Страница отдаётся статикой, и без сценария в браузере признак не
 * появится вовсе: анимации остались бы в своём НАЧАЛЬНОМ кадре, то есть на
 * пустом месте. Поэтому разметка приходит с «играет», а сценарий, увидев,
 * что до сцены ещё не долистали, гасит показ — до того, как он кому-то
 * попался на глаза. С отключённым сценарием всё отыграет на загрузке и
 * замрёт в конечном виде: он и есть то, что нужно понять.
 */

export function DemoStage({
  children,
  className,
}: {
  children: ReactNode;
  className?: string;
}) {
  const host = useRef<HTMLDivElement>(null);
  const [playing, setPlaying] = useState(true);

  useEffect(() => {
    const node = host.current;
    if (node === null) return;

    // Порог в четверть: сцена начинает играть, когда видна настолько,
    // чтобы за ней можно было следить, а не когда показался её край.
    const watcher = new IntersectionObserver(
      ([entry]) => setPlaying(entry?.isIntersecting ?? false),
      { threshold: 0.25 },
    );
    watcher.observe(node);
    return () => watcher.disconnect();
  }, []);

  return (
    <div
      ref={host}
      // Это показ, а не сведения: всё, что здесь нарисовано, рядом сказано
      // словами. Диктовка клеток и стрелок не добавила бы к ним ничего.
      aria-hidden
      data-play={playing ? "on" : "off"}
      className={cn("demo select-none", className)}
    >
      {children}
    </div>
  );
}
