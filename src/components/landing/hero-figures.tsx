"use client";

import type { CSSProperties } from "react";

import { BalanceCaption } from "@/components/ui/balance-caption";
import { Figure } from "@/components/ui/summary-figure";
import { cn } from "@/lib/utils/cn";

import { useHeroStage } from "./hero-stage";

/**
 * Три числа первого экрана — той же полосой, что в расчёте, но крупно.
 *
 * --- Почему не «похожее», а то же -----------------------------------------
 *
 * Первый экран обещает то, что человек увидит внутри, и показывать он
 * обязан тот самый блок. Здесь стояла своя плашка: подпись сбоку от числа,
 * рамка с заливкой и светом, кегль крупнее у нормы. В расчёте давно всё
 * иначе — числа лежат прямо на бумаге, столбиком над подписями, равными
 * колонками, и главные отличаются весом, а не рамкой. Страница, которая
 * рисует одно, а продаёт другое, ловится на первом же переходе в
 * приложение.
 *
 * Поэтому разметка — та же: `MainPlate` из расчёта отличается от этой
 * только тем, что считает числа из домена, а здесь они приходят из
 * сценария. Само число (`Figure`) общее, а не повторённое: правка вида
 * полосы в расчёте меняет и это место.
 *
 * Группа ширины по содержимому и по середине, а не три колонки на всю
 * плоскость: растянутые, числа стоят островками с пустыми полями между
 * ними — так было и в расчёте, пока он не перешёл на группу.
 *
 * --- Почему крупнее, чем в расчёте -----------------------------------------
 *
 * В расчёте полоса — одна строка под шапкой, и числа в ней в 24 точки. Здесь
 * они стоят над четырьмя месяцами, занимающими половину экрана, и числа того
 * же роста терялись на таком листе мелким незаметным блоком. Построение то же
 * — число жирным над подписью, единица блёклая, — но кегль вдвое крупнее
 * (`size="hero"` у `Figure`): так они видны на фоне календаря и читаются
 * первыми, как и должны, — ведь это итог всего, что под ними.
 *
 * Числа — за ВЕСЬ показанный отрезок, четыре месяца. Над каждым месяцем стоит
 * его собственный итог (`HeroMonthMeta`), и они сходятся: нормы и факты
 * месяцев складываются в норму и факт отрезка, а разницы — нет: недобор
 * одного месяца гасится переработкой другого, как и в расчёте.
 *
 * --- Почему числа перещёлкиваются ----------------------------------------
 *
 * Это и есть предмет разговора. Человек отмечает на сетке отпуск во втором
 * месяце и отгул за переработку в четвёртом, — и числа отвечают по-разному:
 * отпуск уменьшает И отработанное, И норму (сорок часов нормы, сорок восемь
 * отработанных), а отгул — только отработанное: норма после него та же.
 *
 * Что норма считается по производственному календарю, а отпуск вычитает из
 * неё свои рабочие дни, можно объяснить абзацем текста, а можно показать: два
 * числа меняются по-разному. Счётчик нужен именно для этого — чтобы глаз
 * увидел, КАКОЕ из чисел двинулось и на сколько.
 *
 * Сам счётчик здесь не свой: это `CountedNumber`, тот же, что крутит числа
 * в полосе итога при правке календаря. Первый экран обещает поведение,
 * которое человек встретит внутри, и расходиться им нельзя.
 *
 * --- Уважение к `prefers-reduced-motion` ---------------------------------
 *
 * Человеку с отключённой анимацией показывается СРАЗУ последнее
 * состояние: и отсутствия, и числа при них. Это честнее, чем оставить его
 * с первым кадром истории, которую он не увидит.
 */
export function HeroFigures({
  className,
  style,
}: {
  className?: string;
  style?: CSSProperties;
}) {
  const stage = useHeroStage();
  const under = stage.undertime > 0;
  const balance = under ? stage.undertime : stage.overtime;

  return (
    // Обёртка держит группу по середине плоскости, а анимацию появления и
    // отступ от месяца несёт на себе: у самой группы они были бы смещены
    // её собственной шириной.
    <div className={cn("flex justify-center", className)} style={style}>
      <dl className="grid min-w-0 grid-cols-3 items-center gap-x-3 min-[360px]:gap-x-5 md:gap-x-7 xl:gap-x-10">
        <Figure
          size="hero"
          parts={[{ value: String(stage.norm), unit: "ч" }]}
          caption="Норма периода"
        />
        <Figure
          size="hero"
          parts={[{ value: String(stage.actual), unit: "ч" }]}
          caption="Отработано"
        />
        {/* Третье число — разница, и имя у неё меняется вместе со знаком.
            Та же деталь, что в расчёте: приставка уезжает, число меняет
            цвет. Ноль цвета не имеет — как и там. */}
        <Figure
          size="hero"
          parts={[{ value: String(balance), unit: "ч" }]}
          caption={<BalanceCaption under={under} />}
          tone={under ? "signal" : balance > 0 ? "verify" : undefined}
        />
      </dl>
    </div>
  );
}
