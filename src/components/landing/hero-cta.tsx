"use client";

import { useSyncExternalStore } from "react";

import {
  hasStoredProfile,
  subscribeToStoredProfile,
} from "@/features/shift/storage/profile";

import { ToCalculator } from "./to-calculator";

/**
 * Кнопка первого экрана: «Построить график» или «Открыть график».
 *
 * --- Почему две надписи ---------------------------------------------------
 *
 * За кнопкой одна и та же дверь, но за ней человека ждёт разное. У того,
 * кто здесь впервые, никакого графика нет — «Открыть график» обещает ему
 * то, чего не существует, и открывается анкетой. У того, кто возвращается,
 * график есть, и «Построить» звучит так, будто прежний придётся заводить
 * заново.
 *
 * --- Почему это решается в браузере ---------------------------------------
 *
 * Профиль лежит в `localStorage`, сервера у приложения нет, и страница
 * отдаётся статикой — одна на всех. Значит, надпись выбирается уже на
 * устройстве.
 *
 * В саму разметку уходит «Построить график»: посадочную страницу открывают
 * в основном те, кто пришёл из поиска и ничего ещё не заводил. Кому есть
 * что открывать, надпись меняется первым же кадром после загрузки.
 *
 * `useSyncExternalStore` взят ради этого честно: он сам отдаёт разметке
 * серверное значение, а браузеру — своё, и подмена не считается
 * расхождением при гидратации.
 */
export function HeroCta() {
  const built = useSyncExternalStore(subscribeToStoredProfile, hasStoredProfile, () => false);

  return <ToCalculator>{built ? "Открыть график" : "Построить график"}</ToCalculator>;
}
