/**
 * Что показывает первый экран: месяц, отсутствия и три числа при них.
 *
 * --- Почему числа лежат здесь, а не считаются на месте --------------------
 *
 * Считать их в самой странице значило бы утянуть в её выдачу весь домен
 * расчёта: производственный календарь, десятичную арифметику, разбор смен.
 * Посадочная страница отдаётся статикой и должна оставаться лёгкой.
 *
 * Но и выдумывать их нельзя: приложение существует ради того, чтобы числа
 * не врали, и первый экран — не исключение. Поэтому числа настоящие, а
 * сходятся они с доменом ПРОВЕРКОЙ: `hero-scenario.test.ts` прогоняет тот
 * же расчёт и сверяет каждое. Изменится правило — упадёт тест, а не
 * доверие.
 *
 * --- Что здесь за история -------------------------------------------------
 *
 * Май 2026-го, 1-й караул, сорокачасовая неделя. Восемь смен по двадцать
 * четыре часа: норма 151, отработано 192, переработка 41.
 *
 * Сначала ОТПУСК — с первой смены месяца, на неделю. Две смены уходят из
 * отработанного, и норма при этом уменьшается: часы, которые не нужно
 * было отрабатывать по уважительной причине, из неё исключаются (письмо
 * Роструда № 550-6-1). Норма 119, факт 144, переработка 25.
 *
 * Потом ОТГУЛ за переработку, тринадцатого. Ещё одна смена уходит из
 * отработанного, а норму он не уменьшает: этот отгул ею уже оплачен.
 * Норма та же 119, факт 120, переработка 1 — от сорока одного часа сверх
 * нормы не осталось почти ничего.
 *
 * Порядок именно такой: сперва то, что двигает ОБА числа, потом то, что
 * двигает одно. Так разница между ними видна на одном экране, без слов.
 *
 * --- Почему отпуск занимает две смены, а не одну -------------------------
 *
 * Одну смену он занимать не может, и это не вёрстка, а арифметика. Отпуск
 * и отгул уносят по двадцать четыре часа, вместе — сорок восемь. Если
 * отпуск накрывает одну смену, из нормы исключается в лучшем случае
 * шестнадцать часов, и переработки (сорок один час) на оба отсутствия не
 * хватает: расчёт уходит в НЕДОРАБОТКУ. Проверено по всем месяцам года и
 * всем четырём караулам — случая, где хватило бы, нет.
 *
 * В мае к этому добавляется первое число: это праздник, и смена на нём
 * норму не уменьшает вовсе — отпуск на одной такой смене выглядел бы
 * ровно как отгул, и показывать было бы нечего.
 *
 * Ровно об этом различии всё приложение — и первый экран показывает его
 * не словами, а на числах.
 */

export const HERO_YEAR = 2026;

/** Май: начинается с пятницы, и у месяца есть уступ в первой неделе. */
export const HERO_MONTH = 5;

/** Смена 1-го караула, от которой отсчитывается цикл «сутки через трое». */
export const HERO_KNOWN_SHIFT = `${HERO_YEAR}-03-02`;

/**
 * Отпуск с первого числа по седьмое: смены 1-го и 5-го со своими хвостами.
 *
 * Начинается он с ПЕРВОЙ смены месяца: в конце месяца на телефоне нижние
 * строки уходят в растворение, и до отпуска история не доживала.
 */
export const HERO_LEAVE_DAYS = [1, 2, 5, 6];

/** Сутки отгула за переработку: заступление и его продолжение. */
export const HERO_REST_DAYS = [13, 14];

export interface HeroStage {
  /** Норма к отработке. */
  norm: number;
  /** Фактически отработано. */
  actual: number;
  /** Переработка сверх нормы. */
  overtime: number;
}

/**
 * Три состояния расчёта: как есть, после отпуска, после отгула.
 *
 * Проверены `hero-scenario.test.ts` — там они считаются доменом заново.
 */
export const HERO_STAGES: readonly HeroStage[] = [
  { norm: 151, actual: 192, overtime: 41 },
  { norm: 119, actual: 144, overtime: 25 },
  { norm: 119, actual: 120, overtime: 1 },
];

/**
 * Когда наступает каждое из состояний, в миллисекундах от загрузки.
 *
 * Отсчёт начинается сразу, как месяц собрался и над ним встали числа
 * (около двух секунд). Дальше отметки идут вплотную: между ними ровно
 * столько, сколько занимает перещёлкивание чисел, плюс полсекунды на то,
 * чтобы увидеть, что изменилось.
 *
 * Значения отсюда получает и разметка, и CSS: `HeroCalendar` кладёт их в
 * переменные, а правила берут задержку из них. Двух источников времени
 * быть не должно — иначе клетка помечается раньше, чем меняются числа.
 */
export const HERO_STAGE_AT = [0, 2200, 3600];

/** Сколько идёт перещёлкивание чисел. */
export const HERO_COUNT_MS = 900;
