/**
 * Что показывает первый экран: месяц, отсутствия и три числа при них.
 *
 * --- Почему числа лежат здесь, а не считаются на месте --------------------
 *
 * Считать их в самой странице значило бы утянуть в её выдачу весь домен
 * расчёта: производственный календарь, десятичную арифметику, разбор смен.
 * Посадочная страница отдаётся статикой и должна оставаться лёгкой.
 *
 * Но и выдумывать их нельзя: приложение существует ради того, чтобы числа
 * не врали, и первый экран — не исключение. Поэтому числа настоящие, а
 * сходятся они с доменом ПРОВЕРКОЙ: `hero-scenario.test.ts` прогоняет тот
 * же расчёт и сверяет каждое. Изменится правило — упадёт тест, а не
 * доверие.
 *
 * --- Что здесь за история -------------------------------------------------
 *
 * Май 2026-го, 1-й караул, сорокачасовая неделя. Восемь смен по двадцать
 * четыре часа: норма 151, отработано 192, переработка 41.
 *
 * Тринадцатого человек берёт ОТГУЛ за переработку. Смена уходит из
 * отработанного, но норму не уменьшает: этот отгул ею уже оплачен. Было
 * 192 и 41 — стало 168 и 17.
 *
 * С двадцать пятого и до конца месяца — ОТПУСК. Две смены уходят из
 * отработанного, а вот норма на этот раз уменьшается: часы, которые не
 * нужно было отрабатывать по уважительной причине, из неё исключаются
 * (письмо Роструда № 550-6-1). Норма 111, факт 120, переработка 9.
 *
 * Ровно об этом различии всё приложение — и первый экран показывает его
 * не словами, а на числах.
 */

export const HERO_YEAR = 2026;

/** Май: начинается с пятницы, и у месяца есть уступ в первой неделе. */
export const HERO_MONTH = 5;

/** Смена 1-го караула, от которой отсчитывается цикл «сутки через трое». */
export const HERO_KNOWN_SHIFT = `${HERO_YEAR}-03-02`;

/** Сутки отгула за переработку: заступление и его продолжение. */
export const HERO_REST_DAYS = [13, 14];

/** Отпуск с 25-го до конца месяца: смены 25-го и 29-го со своими хвостами. */
export const HERO_LEAVE_DAYS = [25, 26, 29, 30];

export interface HeroStage {
  /** Норма к отработке. */
  norm: number;
  /** Фактически отработано. */
  actual: number;
  /** Переработка сверх нормы. */
  overtime: number;
}

/**
 * Три состояния расчёта: как есть, после отгула, после отпуска.
 *
 * Проверены `hero-scenario.test.ts` — там они считаются доменом заново.
 */
export const HERO_STAGES: readonly HeroStage[] = [
  { norm: 151, actual: 192, overtime: 41 },
  { norm: 151, actual: 168, overtime: 17 },
  { norm: 111, actual: 120, overtime: 9 },
];

/**
 * Когда наступает каждое из состояний, в миллисекундах от загрузки.
 *
 * Отсчёт начинается после того, как месяц собрался и над ним встали числа
 * (около двух секунд). Дальше — пауза, отгул, пауза, отпуск: человеку
 * нужно время увидеть, что изменилось, прежде чем меняется следующее.
 *
 * Значения отсюда получает и разметка, и CSS: `HeroCalendar` кладёт их в
 * переменные, а правила берут задержку из них. Двух источников времени
 * быть не должно — иначе клетка помечается раньше, чем меняются числа.
 */
export const HERO_STAGE_AT = [0, 2800, 5000];

/** Сколько идёт перещёлкивание чисел. */
export const HERO_COUNT_MS = 900;
