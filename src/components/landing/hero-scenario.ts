/**
 * Что показывает первый экран: четыре месяца графика, отпуск и отгул в них и
 * числа, которые от этого меняются.
 *
 * --- Почему числа лежат здесь, а не считаются на месте --------------------
 *
 * Считать их в самой странице значило бы утянуть в её выдачу весь домен
 * расчёта: производственный календарь, десятичную арифметику, разбор смен.
 * Посадочная страница отдаётся статикой и должна оставаться лёгкой.
 *
 * Но и выдумывать их нельзя: приложение существует ради того, чтобы числа
 * не врали, и первый экран — не исключение. Поэтому числа настоящие, а
 * сходятся они с доменом ПРОВЕРКОЙ: `hero-scenario.test.ts` прогоняет тот
 * же расчёт и сверяет каждое — и итог периода, и итог каждого месяца над
 * сеткой. Изменится правило — упадёт тест, а не доверие.
 *
 * --- Почему четыре месяца, а не один ----------------------------------------
 *
 * Один месяц крупно был красив, но показывал не то, что человек увидит
 * внутри: там сетка из месяцев с итогом над каждым, а не одна страница
 * календаря. Чтобы первый экран обещал то, что есть, он собран так же: те
 * же месяцы, те же шапки с нормой, фактом и разницей, те же клетки.
 *
 * --- Почему июль — октябрь -----------------------------------------------------
 *
 * Месяцы выбраны ЧИСТЫЕ: ни праздников, ни предпраздничных дней, ни
 * перенесённых выходных. Тогда каждое число выводится из того, что видно на
 * сетке, — рабочие дни на восемь часов и смены по двадцать четыре, — и
 * пересчитать его можно глазами:
 *
 *   июль     норма 168 = 21 день × 8      факт 192 = 8 смен × 24
 *   август   норма 184 = 23 дня × 8       факт 192 = 8 смен × 24
 *   сентябрь норма 168 = 21 день × 8      факт 168 = 7 смен × 24
 *   октябрь  норма 176 = 22 дня × 8       факт 192 = 8 смен × 24
 *
 * График — «сутки через трое», с первого июля. Смена в двадцать четыре
 * часа делится полуночью на 16 и 8, и ни одна не переходит границу месяца:
 * итог месяца — это сумма его суток, и перенос на соседний тут ничего бы
 * не сдвинул.
 *
 * --- Что здесь за история -------------------------------------------------
 *
 * Во втором месяце ОТПУСК с четырнадцатого по двадцатое. Он накрывает две
 * смены (14-го и 18-го) и пять рабочих дней, и числа отвечают двояко: из
 * отработанного уходит 48 часов, а из нормы — 40. Отпуск уменьшает и то и
 * другое.
 *
 * В четвёртом месяце ОТГУЛ за переработку тринадцатого. Одна смена уходит из
 * отработанного, а норму он не трогает: этот отгул ею уже оплачен. Месяц
 * из плюса уходит в минус, а период в целом остаётся в плюсе — разница
 * месяцев и разница периода не складываются, и это тоже видно на экране.
 *
 * Различие между двумя отметками — то, о чём всё приложение: норма считается
 * по производственному календарю и отпуск её уменьшает, а отгул — нет.
 */

