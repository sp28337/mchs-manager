/** Итоги: норма, факт и две стороны их разницы. */
export interface HeroTotals {
  /** Норма к отработке. */
  norm: number;
  /** Фактически отработано. */
  actual: number;
  /** Переработка сверх нормы. Ноль, если ушли под норму. */
  overtime: number;
  /** Недоработка. Ноль, если норма перекрыта. */
  undertime: number;
}

export interface HeroStage extends HeroTotals {
  /** Итоги месяцев над сеткой — в порядке `HERO_MONTHS`. */
  months: readonly HeroTotals[];
}

