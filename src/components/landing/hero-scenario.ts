/**
 * Что показывает первый экран: месяц, отсутствия и три числа при них.
 *
 * --- Почему числа лежат здесь, а не считаются на месте --------------------
 *
 * Считать их в самой странице значило бы утянуть в её выдачу весь домен
 * расчёта: производственный календарь, десятичную арифметику, разбор смен.
 * Посадочная страница отдаётся статикой и должна оставаться лёгкой.
 *
 * Но и выдумывать их нельзя: приложение существует ради того, чтобы числа
 * не врали, и первый экран — не исключение. Поэтому числа настоящие, а
 * сходятся они с доменом ПРОВЕРКОЙ: `hero-scenario.test.ts` прогоняет тот
 * же расчёт и сверяет каждое. Изменится правило — упадёт тест, а не
 * доверие.
 *
 * --- Почему месяц без праздников -----------------------------------------
 *
 * Раньше здесь стоял май, и первое же число вызывало вопрос: откуда норма
 * 151, если в месяце двадцать один рабочий день? Ответ — праздники и
 * предпраздничный день — на экране не написан, и написать его негде.
 * Человек видит числа, которые не сходятся ни с чем, что он может
 * пересчитать глазами.
 *
 * Поэтому месяц выбран ЧИСТЫЙ: ни праздников, ни предпраздничных дней, ни
 * перенесённых выходных. Тогда каждое число выводится прямо из того, что
 * видно на сетке:
 *
 *   норма 160 = 20 рабочих дней × 8 часов
 *   факт  192 = 8 смен × 24 часа
 *   переработка 32 = 192 − 160
 *
 * Месяц при этом на экране не подписан — ни года, ни названия, — так что
 * от него нужна только форма и арифметика, а не близость к сегодняшнему
 * дню.
 *
 * --- Что здесь за история -------------------------------------------------
 *
 * Апрель 2028-го, сорокачасовая неделя. Восемь смен по двадцать четыре
 * часа: норма 160, отработано 192, переработка 32.
 *
 * Сначала ОТПУСК на первую смену месяца — первого и второго. Из
 * отработанного уходят двадцать четыре часа, а норма НЕ МЕНЯЕТСЯ: первое
 * апреля 2028-го суббота, второе воскресенье, рабочих дней внутри отпуска
 * нет ни одного, и исключать из нормы нечего. Норма те же 160, факт 168,
 * переработка 8.
 *
 * Это и есть главное, что показывает первый экран, и показывает без слов:
 * норма считается по производственному календарю, а не по графику смен.
 * Смены не было — а отрабатывать всё равно те же 160.
 *
 * Потом ОТГУЛ за переработку, тринадцатого. Ещё одна смена уходит из
 * отработанного, норму он тоже не трогает: этот отгул ею уже оплачен.
 * Норма 160, факт 144 — и восьми часов переработки на суточный отгул не
 * хватило: получилась недоработка в шестнадцать часов.
 *
 * --- Почему история кончается недоработкой --------------------------------
 *
 * Не выбором, а арифметикой: отгул берут сменой в двадцать четыре часа, а
 * переработки к тому моменту восемь. Разница уходит в минус, и это
 * настоящий случай, с которым человек столкнётся сам.
 *
 * Заодно на первом экране показано то, чего иначе не увидеть, пока не
 * уйдёшь в минус: разница меняет не только цвет, но и имя — приставка
 * «пере» уезжает вниз, на её место встаёт «недо». Числу на плашке от
 * этого не тесно: оно так и остаётся третьим и последним.
 */

export const HERO_YEAR = 2028;

/**
 * Апрель: тридцать дней, начинается с субботы.
 *
 * От этого у месяца уступ в первой строке — тот самый скошенный угол,
 * который делает плашку похожей на страницу календаря, а не на
 * прямоугольник. Двадцать рабочих дней, ни одного праздника.
 */
export const HERO_MONTH = 4;

/**
 * Смена, от которой отсчитывается цикл «сутки через трое».
 *
 * Первое число месяца: тогда все восемь смен помещаются в месяц целиком,
 * вместе с хвостами, и факт выходит ровно восемью сутками.
 */
export const HERO_KNOWN_SHIFT = `${HERO_YEAR}-04-01`;

/**
 * Отпуск первого и второго: ПЕРВАЯ смена месяца и её продолжение.
 *
 * Ровно те сутки, что помечены на сетке, — и ни одних сверх. Раньше
 * отпуск шёл по четвёртое, а помечены были всё те же двое суток
 * (отсутствие ложится на смену по дате её начала), и норма от этого
 * уменьшалась на шестнадцать часов: третье и четвёртое — будни. На экране
 * это выглядело как обман: помечены выходные, а норма почему-то упала.
 *
 * Теперь отпуск целиком лежит на субботе и воскресенье, норма не меняется,
 * и каждое число на плашке выводится из того, что видно на сетке.
 *
 * Начинается отпуск с первой смены месяца намеренно: в конце месяца на
 * телефоне нижние строки уходят в растворение, и до отметок история бы не
 * дожила.
 */
export const HERO_LEAVE_DAYS = [1, 2];

/** Сутки отгула за переработку: начало смены и её продолжение. */
export const HERO_REST_DAYS = [13, 14];

export interface HeroStage {
  /** Норма к отработке. */
  norm: number;
  /** Фактически отработано. */
  actual: number;
  /** Переработка сверх нормы. Ноль, если ушли под норму. */
  overtime: number;
  /** Недоработка. Ноль, если норма перекрыта. */
  undertime: number;
}

/**
 * Три состояния расчёта: как есть, после отпуска, после отгула.
 *
 * Переработка и недоработка лежат порознь, как и в домене: там это два
 * неотрицательных числа, из которых одно всегда ноль. Свести их в одно
 * со знаком значило бы завести своё представление величины и сверять с
 * доменом уже не его, а свой пересчёт.
 *
 * Проверены `hero-scenario.test.ts` — там они считаются доменом заново.
 */
export const HERO_STAGES: readonly HeroStage[] = [
  { norm: 160, actual: 192, overtime: 32, undertime: 0 },
  { norm: 160, actual: 168, overtime: 8, undertime: 0 },
  { norm: 160, actual: 144, overtime: 0, undertime: 16 },
];

/**
 * Расписание истории, в миллисекундах от загрузки.
 *
 * --- Почему по очереди, а не разом ----------------------------------------
 *
 * Отметка и числа рассказывают одно и то же, но с разных сторон: на сетке
 * видно, ЧТО случилось, в числах — что из этого вышло. Стартуя вместе,
 * они спорят за взгляд, и оба остаются непрочитанными: глаз не успевает
 * ни поймать, какая клетка загорелась, ни увидеть, какое из чисел
 * двинулось.
 *
 * Поэтому строго по очереди — сперва ВСЁ, что человек отметил, потом
 * ответ расчёта:
 *
 *   2400  отпуск проявляется на клетках 1 и 2
 *   3220  отгул проявляется на клетках 13 и 14
 *   4040  числа идут к 160 / 144 / недоработка 16
 *
 * --- Почему обе отметки раньше чисел --------------------------------------
 *
 * Порядок был другим: отметка — числа — отметка — числа, по паре на
 * каждое отсутствие. Пара «причина и следствие» так читается лучше всего,
 * но история из четырёх ходов длинна, а на первом экране человек не
 * досматривает: он листает дальше, и вторая половина остаётся никому не
 * показанной.
 *
 * Теперь ходов три, и они отвечают на два разных вопроса, а не на один
 * дважды: сперва «что вносит человек» — отпуск и отгул, оба руками, — и
 * только потом «что из этого выходит». Проигрыш здесь один: промежуточный
 * итог (после отпуска, до отгула) на экран не попадает. Он не пропал —
 * лежит здесь третьим состоянием и проверен `hero-scenario.test.ts`
 * наравне с остальными, — но показывать его больше некому и незачем.
 *
 * Главное, ради чего экран заведён, при этом цело: норма как стояла 160,
 * так и стоит, а отработанное падает со 192 до 144. Двух смен нет, а
 * отрабатывать всё равно те же 160 — норма считается по производственному
 * календарю, а не по графику смен.
 *
 * --- Почему всё считается, а не записано числами -------------------------
 *
 * Каждый срок здесь — сумма предыдущего и того, что успело произойти.
 * Поменяется длительность отметки или счётчика — расписание сдвинется
 * само; записанные руками числа пришлось бы пересчитывать в уме, и
 * однажды они разошлись бы с тем, что на экране.
 */

/**
 * Сколько идёт появление отметки на клетке.
 *
 * Столько же стоит и в самой анимации: значение уходит в CSS переменной
 * `--mark-ms`, чтобы второго источника этой длительности не было.
 */
export const HERO_MARK_MS = 520;

/**
 * Когда появляется первая отметка.
 *
 * К этому времени волна собрала месяц и над ним встали числа. Раньше —
 * отметка легла бы на ещё не собравшуюся сетку.
 *
 * Число сходится с той стороной, что живёт в `globals.css`, вручную, и вот
 * из чего оно складывается (все слагаемые — оттуда):
 *
 *    360  разлиновка проступает           `--cal-grid-ms`
 *  +  60  вдох перед волной               `--cal-lead` минус разлиновка
 *  + 736  волна доходит до ближнего угла  16 клеток × `--cal-step` 46 мс
 *  + 260  пауза перед числами             задержка `.hero-cal__figures`
 *  + 900  числа встают                    длительность там же
 *   ----
 *   2316  всё показанное закончило движение
 *  +  84  запас
 *   ----
 *   2400
 *
 * Шестнадцать — место последней клетки в волне; его считает
 * `HeroCalendar` (`lastWave`) по числу строк в месяце. Тронешь любое из
 * этих значений — пересчитай и это.
 */
const FIRST_MARK_AT = 2400;

/**
 * Пауза между двумя событиями истории.
 *
 * Ровно столько, чтобы увидеть, что случилось, и не столько, чтобы решить,
 * что история кончилась.
 */
/**
 * Доля хода отметки, на которой она перестаёт расти и начинает садиться.
 *
 * Отметка появляется с подскоком: сперва вырастает крупнее клетки, потом
 * оседает в её размер. Пик приходится на 60 процентов хода — эта же цифра
 * стоит ключевым кадром в `@keyframes cal-absence-in` (`globals.css`), и
 * связать их одним значением нельзя: доля ключевого кадра переменной не
 * задаётся. Меняешь там — меняй и здесь.
 *
 * От неё считается следующий шаг истории. Раньше между шагами стояла пауза
 * («вдох») и следующий начинался ПОСЛЕ того, как предыдущий полностью
 * закончился, — история от этого шла четыре секунды, и последнюю треть
 * человек досматривал уже вхолостую. Теперь шаги заходят друг на друга:
 * следующий трогается ровно тогда, когда предыдущий прошёл свой пик и
 * стало ясно, что случилось. Хронометраж от этого короче на секунду, а
 * порядок событий читается тот же.
 */
const MARK_SETTLES_AT = 0.6;

/** Сколько от начала отметки до её пика. */
const STEP_MS = HERO_MARK_MS * MARK_SETTLES_AT;

/** Когда проявляется отметка каждого этапа. У первого её нет. */
export const HERO_MARK_AT: readonly number[] = [
  0,
  FIRST_MARK_AT,
  FIRST_MARK_AT + STEP_MS,
];

/**
 * Что показывают числа и когда.
 *
 * Состояний расчёта три, а показанных два: промежуточное — «после отпуска,
 * до отгула» — на экран не выносится, потому что к моменту, когда числа
 * трогаются, обе отметки уже стоят, и показывать состояние, которому на
 * сетке ничего не соответствует, значило бы сбивать с толку.
 *
 * Список назван явно, парами «состояние — срок», а не выведен из
 * `HERO_STAGES` по порядку: связь «этап расчёта → кадр истории» перестала
 * быть один к одному, и молчаливое совпадение индексов однажды подсунуло
 * бы на экран не тот итог.
 *
 * Сроки отсюда получает разметка, а из неё — CSS: `HeroCalendar` кладёт их
 * в переменные, `HeroFigures` заводит по ним таймеры. Двух источников
 * времени быть не должно.
 */
export const HERO_FIGURE_STEPS: readonly { stage: number; at: number }[] = [
  { stage: 0, at: 0 },
  {
    stage: HERO_STAGES.length - 1,
    at: (HERO_MARK_AT[2] ?? 0) + STEP_MS,
  },
];
