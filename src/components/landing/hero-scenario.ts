/**
 * Что показывает первый экран: месяц, отсутствия и три числа при них.
 *
 * --- Почему числа лежат здесь, а не считаются на месте --------------------
 *
 * Считать их в самой странице значило бы утянуть в её выдачу весь домен
 * расчёта: производственный календарь, десятичную арифметику, разбор смен.
 * Посадочная страница отдаётся статикой и должна оставаться лёгкой.
 *
 * Но и выдумывать их нельзя: приложение существует ради того, чтобы числа
 * не врали, и первый экран — не исключение. Поэтому числа настоящие, а
 * сходятся они с доменом ПРОВЕРКОЙ: `hero-scenario.test.ts` прогоняет тот
 * же расчёт и сверяет каждое. Изменится правило — упадёт тест, а не
 * доверие.
 *
 * --- Почему месяц без праздников -----------------------------------------
 *
 * Раньше здесь стоял май, и первое же число вызывало вопрос: откуда норма
 * 151, если в месяце двадцать один рабочий день? Ответ — праздники и
 * предпраздничный день — на экране не написан, и написать его негде.
 * Человек видит числа, которые не сходятся ни с чем, что он может
 * пересчитать глазами.
 *
 * Поэтому месяц выбран ЧИСТЫЙ: ни праздников, ни предпраздничных дней, ни
 * перенесённых выходных. Тогда каждое число выводится прямо из того, что
 * видно на сетке:
 *
 *   норма 160 = 20 рабочих дней × 8 часов
 *   факт  192 = 8 смен × 24 часа
 *   переработка 32 = 192 − 160
 *
 * Месяц при этом на экране не подписан — ни года, ни названия, — так что
 * от него нужна только форма и арифметика, а не близость к сегодняшнему
 * дню.
 *
 * --- Что здесь за история -------------------------------------------------
 *
 * Апрель 2028-го, сорокачасовая неделя. Восемь смен по двадцать четыре
 * часа: норма 160, отработано 192, переработка 32.
 *
 * Сначала ОТПУСК — с первого по четвёртое. Из отработанного уходит одна
 * смена, ПЕРВАЯ в месяце, и норма при этом тоже уменьшается: часы, которые
 * не нужно было отрабатывать по уважительной причине, из неё исключаются
 * (письмо Роструда № 550-6-1). Норма 144, факт 168, переработка 24.
 *
 * Потом ОТГУЛ за переработку, тринадцатого. Ещё одна смена уходит из
 * отработанного, а норму он не уменьшает: этот отгул ею уже оплачен.
 * Норма та же 144, факт 144, переработка 0 — переработка ушла в отгул
 * ровно, без остатка.
 *
 * Порядок именно такой: сперва то, что двигает ОБА числа, потом то, что
 * двигает одно. Так разница между ними видна на одном экране, без слов.
 *
 * --- Почему история кончается нулём ---------------------------------------
 *
 * Не выбором, а арифметикой. В месяце без праздников переработки набегает
 * самое большее тридцать два часа (восемь смен против двадцати рабочих
 * дней), а отпуск и отгул уносят из отработанного по двадцать четыре —
 * сорок восемь. Вернуть в норму отпуск может не больше того, сколько
 * рабочих дней он накрыл: с первого по четвёртое их два, шестнадцать
 * часов. Тридцать два минус сорок восемь плюс шестнадцать — ровно ноль.
 *
 * Проверено по всем чистым месяцам с 2026-го по 2032-й и всем четырём
 * сдвигам цикла: положительного остатка при отпуске на ОДНОЙ смене не
 * даёт ни один. Ноль здесь — не бедный конец, а точное попадание в норму, и месяц
 * подобран так, чтобы недоработки не возникло тоже: иначе на плашке
 * появилось бы четвёртое число, которого в этой истории быть не должно.
 */

import { COUNT_MS } from "@/lib/motion";

export const HERO_YEAR = 2028;

/**
 * Апрель: тридцать дней, начинается с субботы.
 *
 * От этого у месяца уступ в первой строке — тот самый скошенный угол,
 * который делает плашку похожей на страницу календаря, а не на
 * прямоугольник. Двадцать рабочих дней, ни одного праздника.
 */
export const HERO_MONTH = 4;

/**
 * Смена, от которой отсчитывается цикл «сутки через трое».
 *
 * Первое число месяца: тогда все восемь смен помещаются в месяц целиком,
 * вместе с хвостами, и факт выходит ровно восемью сутками.
 */
export const HERO_KNOWN_SHIFT = `${HERO_YEAR}-04-01`;

/**
 * Отпуск с первого по четвёртое: ПЕРВАЯ смена месяца и её продолжение.
 *
 * Помечены двое суток, а не четверо: отсутствие ложится на смену по дате
 * её начала, и в промежуток попадает только одно — первое число. Третьего
 * и четвёртого смены и так нет, но норму эти дни уменьшают: из неё
 * исключаются рабочие дни внутри отпуска, а не смены.
 *
 * Начинается отпуск с первой смены месяца намеренно: в конце месяца на
 * телефоне нижние строки уходят в растворение, и до отметок история бы не
 * дожила.
 */
export const HERO_LEAVE_DAYS = [1, 2];

/** Сутки отгула за переработку: начало смены и её продолжение. */
export const HERO_REST_DAYS = [13, 14];

export interface HeroStage {
  /** Норма к отработке. */
  norm: number;
  /** Фактически отработано. */
  actual: number;
  /** Переработка сверх нормы. */
  overtime: number;
}

/**
 * Три состояния расчёта: как есть, после отпуска, после отгула.
 *
 * Проверены `hero-scenario.test.ts` — там они считаются доменом заново.
 */
export const HERO_STAGES: readonly HeroStage[] = [
  { norm: 160, actual: 192, overtime: 32 },
  { norm: 144, actual: 168, overtime: 24 },
  { norm: 144, actual: 144, overtime: 0 },
];

/**
 * Расписание истории, в миллисекундах от загрузки.
 *
 * --- Почему по очереди, а не разом ----------------------------------------
 *
 * Отметка и числа рассказывают одно и то же, но с разных сторон: на сетке
 * видно, ЧТО случилось, в числах — что из этого вышло. Стартуя вместе,
 * они спорят за взгляд, и оба остаются непрочитанными: глаз не успевает
 * ни поймать, какая клетка загорелась, ни увидеть, какое из чисел
 * двинулось.
 *
 * Поэтому строго по очереди: сперва проявляется отметка и ДОИГРЫВАЕТ до
 * конца, следом трогаются числа, и только когда они дошли — появляется
 * следующая отметка.
 *
 *   2200  отпуск проявляется на клетках 1 и 2
 *   2720  числа идут к 144 / 168 / 24
 *   3920  отгул проявляется на клетках 13 и 14
 *   4440  числа идут к 144 / 144 / 0
 *
 * --- Почему всё считается, а не записано числами -------------------------
 *
 * Каждый срок здесь — сумма предыдущего и того, что успело произойти.
 * Поменяется длительность отметки или счётчика — расписание сдвинется
 * само; записанные руками числа пришлось бы пересчитывать в уме, и
 * однажды они разошлись бы с тем, что на экране.
 */

/**
 * Сколько идёт появление отметки на клетке.
 *
 * Столько же стоит и в самой анимации: значение уходит в CSS переменной
 * `--mark-ms`, чтобы второго источника этой длительности не было.
 */
export const HERO_MARK_MS = 520;

/**
 * Когда появляется первая отметка.
 *
 * К этому времени волна собрала месяц и над ним встали числа. Раньше —
 * отметка легла бы на ещё не собравшуюся сетку.
 */
const FIRST_MARK_AT = 2200;

/**
 * Пауза между «числа досчитали» и «появляется следующая отметка».
 *
 * Ровно столько, чтобы увидеть новый итог, и не столько, чтобы решить,
 * что история кончилась.
 */
const BREATH_MS = 300;

/** Когда проявляется отметка каждого этапа. У первого её нет. */
export const HERO_MARK_AT: readonly number[] = [
  0,
  FIRST_MARK_AT,
  FIRST_MARK_AT + HERO_MARK_MS + COUNT_MS + BREATH_MS,
];

/**
 * Когда трогаются числа каждого этапа: как только отметка доиграла.
 *
 * Значения отсюда получает разметка, а из неё — CSS: `HeroCalendar` кладёт
 * сроки в переменные, `HeroFigures` заводит по ним таймеры. Двух
 * источников времени быть не должно.
 */
export const HERO_FIGURES_AT: readonly number[] = HERO_MARK_AT.map((at, stage) =>
  stage === 0 ? 0 : at + HERO_MARK_MS,
);
