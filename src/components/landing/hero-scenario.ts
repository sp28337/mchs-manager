/**
 * Расписание истории, в миллисекундах от загрузки.
 *
 * --- Почему по очереди, а не разом ----------------------------------------
 *
 * Отметка и числа рассказывают одно и то же, но с разных сторон: на сетке
 * видно, ЧТО случилось, в числах — что из этого вышло. Стартуя вместе,
 * они спорят за взгляд, и оба остаются непрочитанными: глаз не успевает
 * ни поймать, какая клетка загорелась, ни увидеть, какое из чисел
 * двинулось.
 *
 * Поэтому строго по очереди, причина и следствие, дважды:
 *
 *   отпуск ложится на август  →  числа августа и периода идут к новым
 *   отгул ложится на октябрь  →  числа октября и периода идут к новым
 *
 * Во втором случае ждём, пока первый счёт почти дойдёт, — но не до конца:
 * он закончится уже под второй отметкой, и пауза «ничего не происходит» не
 * успеет сказать, что история кончилась.
 *
 * --- Почему всё считается, а не записано числами -------------------------
 *
 * Каждый срок здесь — сумма предыдущего и того, что успело произойти.
 * Поменяется длительность отметки или счётчика — расписание сдвинется
 * само; записанные руками числа пришлось бы пересчитывать в уме, и
 * однажды они разошлись бы с тем, что на экране.
 */

/**
 * Сколько идёт появление отметки на клетке.
 *
 * Столько же стоит и в самой анимации: значение уходит в CSS переменной
 * `--mark-ms`, чтобы второго источника этой длительности не было.
 */
export const HERO_MARK_MS = 520;

/**
 * Через сколько после предыдущих суток ложатся следующие сутки той же
 * отметки.
 *
 * Отпуск — это период, и на сетке он ложится днями подряд, а не одним
 * щелчком: так видно, что он протяжённый и в какую сторону растёт. Шаг мал —
 * неделя из семи суток укладывается в треть секунды сверх самой отметки.
 */
export const HERO_MARK_STAGGER_MS = 50;

/**
 * Шаг волны сборки. Задан здесь, а не в `globals.css`: от него зависит
 * срок начала истории, и разойтись им нельзя. Уходит в CSS переменной
 * `--cal-step` с самого корня первого экрана.
 *
 * Шаг мельче прежнего (тогда он был 46 мс): месяцев четыре, и клеток в
 * волне втрое больше, — чтобы сборка заняла те же три четверти секунды, а не
 * две.
 */
export const HERO_WAVE_STEP_MS = 17;

/**
 * Когда появляется первая отметка.
 *
 * К этому времени волна собрала месяцы и над ними встали числа. Раньше —
 * отметка легла бы на ещё не собравшуюся сетку.
 *
 * Все слагаемые — из `globals.css` (кроме волны: её длину задают номер
 * последней клетки и шаг, оба лежат здесь и в `hero-wave.ts`):
 *
 *    360  разлиновка проступает           `--cal-grid-ms`
 *  +  60  вдох перед волной               `--cal-lead` минус разлиновка
 *  + волна доходит до ближнего угла       номер последней клетки × шаг
 *  + 260  пауза перед числами             задержка `.hero-cal__figures`
 *  + 900  числа встают                    длительность там же
 *  +  84  запас
 *
 * Тронешь любое из этих значений в `globals.css` — пересчитай и это.
 */
const FIRST_MARK_AT = 360 + 60 + HERO_LAST_WAVE * HERO_WAVE_STEP_MS + 260 + 900 + 84;

/**
 * Доля хода отметки, на которой она перестаёт расти и начинает садиться.
 *
 * Отметка появляется с подскоком: сперва вырастает крупнее клетки, потом
 * оседает в её размер. Пик приходится на 60 процентов хода — эта же цифра
 * стоит ключевым кадром в `@keyframes cal-absence-in` (`globals.css`), и
 * связать их одним значением нельзя: доля ключевого кадра переменной не
 * задаётся. Меняешь там — меняй и здесь.
 *
 * От неё считается следующий шаг истории: он трогается ровно тогда, когда
 * предыдущий прошёл свой пик и стало ясно, что случилось, а не после того,
 * как тот полностью закончился.
 */
const MARK_SETTLES_AT = 0.6;

/** Сколько от начала отметки до её пика. */
const STEP_MS = HERO_MARK_MS * MARK_SETTLES_AT;

/** Сколько длится счёт чисел (`COUNT_MS` в `lib/motion.ts`). */
const COUNT_MS = 900;

/** Когда пик последних суток отметки из `days` суток, начатой в `from`. */
const settledAt = (from: number, days: number) =>
  from + (days - 1) * HERO_MARK_STAGGER_MS + STEP_MS;

/** Первые сутки отпуска ложатся здесь. */
const LEAVE_AT = FIRST_MARK_AT;

/** Числа отвечают на отпуск. */
const LEAVE_FIGURES_AT = settledAt(LEAVE_AT, HERO_LEAVE.days.length);

/**
 * Отгул ложится, когда первый счёт отошёл на две трети: на разных концах
 * плоскости глаз успевает перейти, а пауза в конце не вылезает.
 */
const REST_AT = LEAVE_FIGURES_AT + Math.round((COUNT_MS * 2) / 3);

/** Числа отвечают на отгул. */
const REST_FIGURES_AT = settledAt(REST_AT, HERO_REST.days.length);

/** Когда проявляются первые сутки отметки каждого этапа. У первого её нет. */
export const HERO_MARK_AT: readonly number[] = [0, LEAVE_AT, REST_AT];

/**
 * Что показывают числа и когда.
 *
 * Список назван явно, парами «состояние — срок», а не выведен из
 * `HERO_STAGES` по порядку: связь «этап расчёта → кадр истории» и
 * молчаливое совпадение индексов однажды подсунули бы на экран не тот итог.
 *
 * Сроки отсюда получают числа над сеткой и итоги месяцев: все они заводят
 * по ним таймеры. Двух источников времени быть не должно.
 */
export const HERO_FIGURE_STEPS: readonly { stage: number; at: number }[] = [
  { stage: 0, at: 0 },
  { stage: 1, at: LEAVE_FIGURES_AT },
  { stage: 2, at: REST_FIGURES_AT },
];
