import type { ReactNode } from "react";

import { cn } from "@/lib/utils/cn";

import { HeroCalendar } from "./hero-calendar";

/**
 * Первый экран: слово слева, месяц справа.
 *
 * --- Почему это отдельная деталь, а не часть посадочной страницы --------
 *
 * Их два: посадочная страница и калькулятор, открытый без профиля. Во
 * втором случае за окном «Создать профиль» должна стоять ГЛАВНАЯ — то, с
 * чего человек только что пришёл, — а не отдельная страница-анкета с
 * собственным заголовком. Человек нажал кнопку и получил окно поверх
 * того же экрана; закрыл окно — остался там же.
 *
 * Разница между двумя случаями ровно в одной кнопке, и она передаётся
 * сюда (`cta`): на посадочной это ссылка в расчёт, в расчёте без профиля
 * — кнопка, открывающая окно снова.
 *
 * --- Что здесь решено раскладкой ----------------------------------------
 *
 * Две колонки, а не текст поверх фона: месяц справа — не подложка, а
 * вторая половина разговора. Слева сказано, о чём речь, справа показано,
 * как это выглядит.
 *
 * Две колонки начинаются с 768 точек. Раньше они появлялись только с
 * 1024, и на планшете первый экран выглядел растянутым телефоном: месяц
 * прижат влево, треть полосы пустует, а наклон и растворение у него не
 * те, что на мониторе. Одна раскладка от планшета и выше — один предмет
 * на всех широких экранах.
 *
 * Ниже 768 колонка одна: сверху сборка календаря, под ней текст с
 * кнопкой. Первым в разметке текст остаётся намеренно — он же первым
 * читается программой чтения и первым попадает в выдачу, а порядок на
 * экране меняет `order`.
 */

export function LandingHero({ cta }: { cta: ReactNode }) {
  return (
    // `hero-band` (в `globals.css`) выводит экран за колонку `main` —
    // ровно настолько, насколько это не съедает поле у края окна.
    // Поле сверху больше высоты шапки: она закреплена и ничего под собой
    // не отодвигает, а первым в одноколоночной раскладке идёт ряд чисел —
    // без этого поля он уезжал под неё. На широком экране первый экран
    // высотой в окно и содержимое в нём отцентровано, там хватает и
    // меньшего.
    <section className="hero-band grid gap-10 pt-18 sm:items-center md:min-h-[84lvh] md:grid-cols-2 md:gap-8 md:pt-15 md:pb-0 lg:gap-12">
      {/* Текст поверх плоскости: дальний край месяца уходит под него, и
          порядок слоёв должен быть назван явно. */}
      <div className="relative z-10 space-y-6 max-md:order-2 flex flex-col justify-center">
        {/* Переносы расставлены руками, а не отданы автоматике: при
            свободном переносе на широком экране последней строкой
            остаётся одно слово, и заголовок разваливается. Неразрывные
            пробелы держат предлог при своём слове.

            Чем крупнее кегль, тем плотнее строки: интерлиньяж 0,92 и
            чуть отрицательный трекинг. Отрицательный «чуть» — PT Sans
            Narrow и без того узкий, сильное сжатие слепит буквы.

            Пробел ПОСЛЕ переноса обязателен. `<br>` спрятан классом
            только на узком экране, но текст рядом с ним остаётся: без
            пробела «для учёта» и «рабочего времени» слипались в
            «учётарабочего» — одно слово в двадцать знаков, которое
            переносить негде, и заголовок вылезал за экран.

            Ступень кегля на 400 точках — оттуда же: «инструмент» с
            «Удобный» в одной строке при 36 пунктах не помещается в
            триста двадцать. */}
        <h1 className="rise text-[2rem] leading-[0.92] tracking-[-0.01em] text-balance xxs:text-4xl sm:text-5xl md:text-4xl lg:text-5xl xl:text-6xl">
          <span className="block text-verify">Удобный инструмент</span>
          для&nbsp;учёта{" "}
          <br className="hidden lg:inline" />
          рабочего&nbsp;времени
        </h1>

        <p className="rise rise-2 max-w-prose leading-snug text-ink-muted text-pretty max-md:text-lg">
          Бесплатно и без регистрации
        </p>

        <div className="rise rise-3">{cta}</div>
      </div>

      {/* Месяц заходит левым краем под текстовую колонку: там он уже
          растворён маской, и наезжать ему не на что. Отрицательное поле
          заодно делает плоскость шире своей колонки — клетка получается
          размером с клетку настенного календаря. */}
      <HeroCalendar
        className={cn(
          "max-md:order-1",
          // В одну колонку месяц заходит нижним краем под заголовок: там
          // он уже растворён маской, и слова читаются поверх пустоты, а не
          // поверх клеток. Отрицательное поле съедает зазор колонки
          // целиком и ещё пару десятков точек сверх него — от этого
          // наплыва и берётся объём.
          "max-md:-mb-24",
          "md:-ml-[26%] md:max-w-[118%] lg:-ml-[30%] lg:max-w-[114%]",
        )}
      />
    </section>
  );
}
