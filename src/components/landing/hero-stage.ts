"use client";

import { useEffect, useState } from "react";

import { HERO_FIGURE_STEPS, HERO_STAGES, type HeroStage } from "./hero-scenario";

/**
 * Состояние расчёта на текущий момент истории.
 *
 * Возвращает СОСТОЯНИЕ целиком, а не числа по дороге к нему: дорогу до
 * нового значения каждое число проходит само (`CountedNumber`). Первая
 * отрисовка отдаёт первое состояние — она же уходит в статическую
 * разметку, и расходиться ей с браузером нельзя.
 *
 * --- Почему хук, а не одно состояние на весь экран -------------------------
 *
 * Состояние нужно двум разным местам: числам над сеткой и итогам над каждым
 * месяцем, а те стоят внутри разметки, собранной на сервере. Общий предок
 * у них — вся плоскость, и делать её клиентской целиком ради четырёх
 * чисел значило бы утянуть в бандл месяцы с клетками. Поэтому у каждого
 * места свои часы, а расходиться им нечем: все они заводятся в один и тот
 * же миг, по одним и тем же срокам (`HERO_FIGURE_STEPS`), и отличаются на
 * доли миллисекунды.
 *
 * --- Уважение к `prefers-reduced-motion` ---------------------------------
 *
 * Человеку с отключённой анимацией показывается СРАЗУ последнее
 * состояние: и отсутствия, и числа при них. Это честнее, чем оставить его
 * с первым кадром истории, которую он не увидит.
 */
export function useHeroStage(): HeroStage {
  const [index, setIndex] = useState(HERO_FIGURE_STEPS[0]?.stage ?? 0);

  useEffect(() => {
    // Правило запрещает синхронный `setState` в эффекте — обычно верно,
    // это лишний прогон отрисовки. Здесь он неизбежен и однократен:
    // системную настройку на сервере не прочесть, а отдать в разметку
    // сразу итог нельзя — она общая для всех, и у большинства история
    // всё-таки играется с начала.
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      // eslint-disable-next-line react-hooks/set-state-in-effect
      setIndex(HERO_STAGES.length - 1);
      return;
    }

    // Первый кадр уже стоит в разметке — его срок нулевой, и заводить под
    // него будильник незачем.
    const timers = HERO_FIGURE_STEPS.slice(1).map((step) =>
      window.setTimeout(() => setIndex(step.stage), step.at),
    );

    return () => timers.forEach((timer) => window.clearTimeout(timer));
  }, []);

  return HERO_STAGES[index] ?? HERO_STAGES[0]!;
}
