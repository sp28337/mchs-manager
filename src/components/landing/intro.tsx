/**
 * Слово о приложении — между первым экраном и «Как работает».
 *
 * --- Зачем оно здесь -------------------------------------------------------
 *
 * Первый экран показывает, как это выглядит, а «Как работает» — по шагам, как
 * этим пользоваться. Между ними нужна фраза, которая отвечает на вопрос, с
 * которого начинается любой выбор: что приложение берёт на себя, а что остаётся
 * человеку. Без неё человек, дочитавший до шагов, знает, КАК нажимать, но не
 * знает, ЧТО ему за это получится.
 *
 * --- Почему рукописью и этим цветом ----------------------------------------
 *
 * Шрифт и цвет — те же, что у имени графика над расчётом (`font-hand`,
 * чернила на 20 %): это голос самого человека на странице, а не системы. Печатным
 * шрифтом абзац читался бы ещё одним куском описания среди двух десятков
 * похожих; рукописью он стоит отдельно и связывает посадочную страницу с
 * приложением — там то же начертание над цифрами.
 *
 * Цвет задан на тексте, а не прозрачностью всего элемента: прозрачность
 * слоя накладывалась бы на всё, что окажется внутри.
 *
 * --- Что происходит под указателем ----------------------------------------
 *
 * Абзац светлеет — с 20 до 60 % чернил, за треть секунды. В покое он стоит
 * тенью: вступление не должно спорить с заголовком и шагами под ним. Но
 * тень читается плохо (контраст 1,8:1 на тёмной теме и 1,5:1 на светлой), и
 * человек, который повёл по ней указателем, делает это затем, чтобы прочесть:
 * в ответ текст становится читаемым (5,7:1 и 4,7:1). У имени графика всё наоборот
 * — оно тускнеет, потому что под указателем оно кнопка, и отзывается уходом в
 * тень; а здесь нажимать нечего, и отзыв — свет.
 *
 * На телефоне указателя нет, и абзац остаётся тенью: цвет не меняется от
 * касания, чтобы страница не мигала при прокрутке пальцем.
 *
 * --- Раскладка -------------------------------------------------------------
 *
 * Один абзац по середине, без заголовка и рамки: это не раздел со своим
 * названием, а вступление к следующему. Ширина ограничена — рукописная строка
 * длиннее шести десятков знаков теряет начало следующей.
 *
 * Воздуха вокруг много, и поровну с обеих сторон: абзац стоит тенью и без
 * рамки, и вплотную к первому экрану или к заголовку раздела он читался бы
 * подписью к ним, а не самостоятельной фразой. Сверху — 144 точки от низа
 * первого экрана; снизу то же самое до заголовка «Как работает»: 64 здесь и
 * 80 верхнего поля самого раздела (на телефоне — 96 и 144 с меньшими полями).
 *
 * --- Что в тексте --------------------------------------------------------
 *
 * Три фразы, и каждая отвечает на один вопрос: что приложение берёт на себя;
 * что для этого делает человек (отмечает события) и что видит в ответ (норму,
 * отработанные часы, разницу); что делать дальше, когда графиков стало
 * несколько (создавать, группировать, смотреть статистику). Перечня событий и
 * названия сайта нет намеренно: то и другое сказано рядом, в «Как работает» и
 * в шапке, и здесь они удлиняли бы абзац, не отвечая ни на один из вопросов.
 */
const TEXT =
  "Приложение берёт расчёты рабочего времени на себя. Отмечайте события в календаре и " +
  "наглядно отслеживайте норму рабочего времени, фактически отработанные часы и переработку " +
  "или недоработку. Создавайте и группируйте графики, чтобы вести учёт и следить за " +
  "статистикой в одном месте.";

export function LandingIntro() {
  return (
    <section aria-label="О приложении" className="pt-24 pb-8 md:pt-36 md:pb-16">
      <p className="mx-auto max-w-4xl text-center font-hand text-2xl leading-snug text-ink/20 text-pretty transition-colors duration-300 hover:text-ink/60 sm:text-3xl lg:text-4xl">
        {TEXT}
      </p>
    </section>
  );
}
