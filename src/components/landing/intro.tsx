/**
 * Слово о приложении — между первым экраном и «Как работает».
 *
 * --- Зачем оно здесь -------------------------------------------------------
 *
 * Первый экран показывает, как это выглядит, а «Как работает» — по шагам, как
 * этим пользоваться. Между ними нужна фраза, которая отвечает на вопрос, с
 * которого начинается любой выбор: что приложение берёт на себя, а что остаётся
 * человеку. Без неё человек, дочитавший до шагов, знает, КАК нажимать, но не
 * знает, ЧТО ему за это получится.
 *
 * --- Почему рукописью и этим цветом ----------------------------------------
 *
 * Шрифт и цвет — те же, что у имени графика над расчётом (`font-hand`,
 * чернила на 20 %): это голос самого человека на странице, а не системы. Печатным
 * шрифтом абзац читался бы ещё одним куском описания среди двух десятков
 * похожих; рукописью он стоит отдельно и связывает посадочную страницу с
 * приложением — там то же начертание над цифрами.
 *
 * Цвет задан на тексте, а не прозрачностью всего элемента: прозрачность
 * слоя накладывалась бы на всё, что окажется внутри.
 *
 * --- Раскладка -------------------------------------------------------------
 *
 * Один абзац по середине, без заголовка и рамки: это не раздел со своим
 * названием, а вступление к следующему. Ширина ограничена — рукописная строка
 * длиннее шести десятков знаков теряет начало следующей. Отступ снизу не
 * задан: его даёт верхнее поле «Как работает», и двойной просвет разорвал бы
 * вступление с тем, к чему оно ведёт.
 *
 * Название сайта в тексте — с неразрывными пробелами: «График 1 3» не
 * рвётся на конце строки на «График» и «1 3».
 */
const TEXT =
  "Приложение берёт расчёты рабочего времени на себя. Вам достаточно указать свой график и " +
  "отмечать события в календаре — отпуска, командировки, больничные, отгулы, замены и " +
  "дополнительные выходы. График 1 3 автоматически пересчитает показатели и покажет " +
  "норму рабочего времени, фактически отработанные часы и переработку или недоработку. " +
  "Создавайте несколько графиков, объединяйте их по папкам и следите за статистикой.";

export function LandingIntro() {
  return (
    <section aria-label="О приложении" className="pt-16 md:pt-24">
      <p className="mx-auto max-w-4xl text-center font-hand text-2xl leading-snug text-ink/20 text-pretty sm:text-3xl lg:text-4xl">
        {TEXT}
      </p>
    </section>
  );
}
