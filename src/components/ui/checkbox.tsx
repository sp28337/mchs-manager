"use client";

import { Check } from "lucide-react";
import type { ReactNode } from "react";

import { cn } from "@/lib/utils/cn";

/**
 * Флажок: отметить или снять отметку.
 *
 * --- Чем он отличается от тумблера ----------------------------------------
 *
 * Тумблер отвечает на вопрос «включить ли режим»: положение кружка — это
 * состояние чего-то, что работает и меняет экран под ним. Флажок отвечает
 * на другой вопрос — «отметить ли», — и вопрос этот про СПИСОК: перед
 * человеком перечень, из которого он выбирает.
 *
 * Ровно так устроено окно дня: двенадцать видов суток подряд, и человек
 * отмечает те, что были. Двенадцать тумблеров в столбец читались как
 * двенадцать независимых механизмов, у каждого из которых своя жизнь, — а
 * это один список с отметками.
 *
 * --- Почему квадрат, а не круг --------------------------------------------
 *
 * Круглая отметка означает «одно из» (радиокнопка), квадратная — «сколько
 * угодно из». В сутках может стоять и отпуск, и вызов, и то и другое сразу,
 * поэтому квадрат.
 *
 * Скругление у него то же, что у клетки вида суток рядом (`rounded-sm`), и
 * это не совпадение: в строке стоят две квадратные метки, и разная форма
 * углов у них читалась бы как разная природа.
 *
 * --- Почему `role="checkbox"`, а не `input` -------------------------------
 *
 * Строка целиком — нажимаемая: попасть пальцем в квадратик в четыре
 * миллиметра на телефоне нельзя. Значит, нажатие ловит кнопка во всю
 * строку, а внутри неё настоящему `input` места нет — вложенный
 * управляющий элемент внутри кнопки недопустим. `role="checkbox"` вместе с
 * `aria-checked` даёт программе чтения то же самое: «флажок, отмечен».
 */
export function Checkbox({
  checked,
  onChange,
  label,
  className,
}: {
  checked: boolean;
  onChange: (checked: boolean) => void;
  /**
   * Что отмечает этот флажок. Не только строка: в окне дня подпись — это
   * клетка вида суток и название рядом с ней.
   */
  label: ReactNode;
  className?: string;
}) {
  return (
    <button
      type="button"
      role="checkbox"
      aria-checked={checked}
      onClick={() => onChange(!checked)}
      className={cn(
        "group inline-flex w-full cursor-pointer items-center justify-between gap-2 rounded-xl",
        "text-sm text-ink transition-colors",
        "focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-trace",
        className,
      )}
    >
      {label}
      <span
        aria-hidden
        className={cn(
          "inline-flex size-5 shrink-0 items-center justify-center rounded-sm border",
          "transition-colors",
          // Отмеченный — тем же зелёным, каким на сетке отмечены смены.
          //
          // Пустой — утопленная бумага в тонком контуре. Заливка утопленная
          // по тому же доводу, что у дорожки тумблера: флажки стоят на
          // поднятой карточке, и цвет поднятой пропал бы на ней вовсе.
          // Контур при этом не линейка (`rule-strong`), а приглушённые
          // чернила: линейкой пустой квадрат на тёмной теме превращался в
          // чёрное пятно без краёв — заливка #161612 в обводке #444a53
          // читалась дырой, а не местом, куда нажимают.
          checked
            ? "border-verify bg-verify text-paper"
            : "border-ink-faint/70 bg-paper text-transparent group-hover:border-ink-muted",
        )}
      >
        {/* Галочка стоит всегда, но у пустого флажка она цвета пустоты:
            так квадрат не меняет размера в момент отметки — меняется
            только цвет, и строка под пальцем не дёргается. */}
        <Check className="size-3.5" strokeWidth={3} />
      </span>
    </button>
  );
}
