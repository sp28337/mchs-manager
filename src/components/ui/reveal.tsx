import type { ReactNode } from "react";

import { cn } from "@/lib/utils/cn";

/**
 * Блок, который плавно раскрывается по высоте, а содержимое проступает.
 *
 * --- Зачем -------------------------------------------------------------------
 *
 * Лист входа при переходе на «Регистрацию» получает две отметки с текстом, и
 * без хода он вырастал на сотню точек рывком, а отметки возникали из пустоты.
 * Теперь высота раскрывается плавно (лист тянется вслед за блоком, потому что
 * высоты у него нет — он растёт от содержимого), а содержимое проступает из
 * размытия снизу тем же ходом, каким в названии сайта приходят цифры нового
 * графика (`.mark-kindle` в `globals.css`): 380 мс, та же кривая, то же
 * размытие и тот же подъём на треть высоты строки. Гаснет оно тем же
 * движением вспять, но быстрее и без задержки: уходящее не должно
 * мешать приходящему.
 *
 * --- Как это устроено ------------------------------------------------------
 *
 * Высота `auto` не анимируется, а строка грида — анимируется:
 * `grid-template-rows` ходит между `0fr` и `1fr`, и внутренний блок
 * (`min-h-0 overflow-hidden`) сжимается вместе со строкой. Содержимое
 * всегда в разметке: иначе нечему было бы сжиматься, а закрытому блоку
 * при удалении из разметки пришлось бы исчезать рывком.
 *
 * Закрытый блок — `inert`: до его полей не добраться ни клавишей, ни
 * мышью, а программа чтения его не видит. Прозрачного, но живого блока —
 * с отметками, на которые можно попасть табуляцией, — быть не должно.
 *
 * Уважение к `prefers-reduced-motion` обеспечено общим правилом
 * (`globals.css`): длительность любого хода сводится к нулю.
 */
export function Reveal({
  show,
  children,
  className,
}: {
  show: boolean;
  children: ReactNode;
  className?: string;
}) {
  return (
    <div
      inert={!show}
      className={cn(
        "grid transition-[grid-template-rows] ease-[cubic-bezier(0.22,1,0.36,1)]",
        show ? "grid-rows-[1fr] duration-[380ms]" : "grid-rows-[0fr] delay-75 duration-[380ms]",
        className,
      )}
    >
      <div className="min-h-0 overflow-hidden">
        <div
          className={cn(
            "transition-[opacity,filter,translate] ease-[cubic-bezier(0.22,1,0.36,1)]",
            show
              ? "translate-y-0 opacity-100 blur-none delay-100 duration-[380ms]"
              : "translate-y-1.5 opacity-0 blur-[2px] duration-200",
          )}
        >
          {children}
        </div>
      </div>
    </div>
  );
}
