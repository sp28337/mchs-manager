import type { ReactNode } from "react";

import { HEADER_WORD } from "@/components/shared/header-action";
import { cn } from "@/lib/utils/cn";

/**
 * Знак нижнего ряда: значок без плашки, а на широком экране — с подписью,
 * которая выезжает при наведении.
 *
 * --- Почему без плашки и без подписи ---------------------------------------
 *
 * Ряд стоит поверх сетки, у самой нижней кромки окна, и плашки с
 * подписями под ним читались бы отдельной панелью, положенной на
 * страницу. Знаки без подложки — как легенда и тема, стоявшие в углах
 * раньше всех, — лежат на бумаге и не спорят с сеткой.
 *
 * --- Почему подпись выезжает, а не всплывает ------------------------------
 *
 * Всплывающая подсказка ложится поверх соседа и закрывает его. Подпись,
 * которая раздвигает ряд, не закрывает ничего: соседи справа отъезжают
 * ровно на её ширину и возвращаются, когда курсор уходит. И читается она
 * тем же голосом, что «ГРАФИК» в знаке сайта (`HEADER_WORD`): это имя
 * органа управления, а не пояснение к нему.
 *
 * С `md` знаки стоят колонкой у левого края (`grid-dock.tsx`), и
 * раздвигать в ней некого: подпись выезжает вбок, поверх сетки, а не
 * толкает соседей. Поэтому у неё подложка цвета бумаги — слово поверх чисел
 * клеток не читалось бы.
 *
 * Ширина анимируется через колонку сетки (`0fr` → `1fr`): у `width: auto`
 * перехода нет, а подобранная на глаз ширина обрезала бы длинные слова.
 * Ход — мягкий на обоих концах: подпись трогается плавно и так же плавно
 * встаёт.
 *
 * Только с `md` и только у устройств с наведением (`hover:` в Tailwind 4
 * само ограничено `(hover: hover)`): на телефоне наводить нечем, а ряд там
 * и так занимает всю ширину. С клавиатуры подпись выезжает по фокусу —
 * иначе человек без мыши никогда бы её не увидел.
 */

/**
 * Гнездо знака: держит наведение (`group/knob`) — и на самом знаке, и на
 * раскрытом из него окошке, чтобы подпись не убегала, пока в окошке
 * выбирают.
 *
 * `pointer-events-auto` — ряд лежит поверх страницы прозрачной полосой во
 * всю ширину и сам нажатий не ловит; ловят только знаки.
 */
export const KNOB_NEST = "group/knob pointer-events-auto relative flex shrink-0";

/**
 * Сама кнопка. Место под палец — 44 точки (`KNOB_ICON`), значок в нём —
 * 28, как знак сайта: ряд читается одним набором с шапкой.
 */
export const KNOB = cn(
  "group/press flex h-11 cursor-pointer items-center rounded-xl",
  "focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ink",
);

/** Клетка значка: 44 точки, значок в 28 посередине. */
export const KNOB_ICON = "grid size-11 shrink-0 place-items-center [&_svg]:size-7";

/** Мягкий ход на обоих концах — трогается и встаёт без рывка. */
const ХОД = "duration-[420ms] ease-[cubic-bezier(0.65,0,0.35,1)]";

/**
 * Подпись знака: выезжает при наведении или фокусе с клавиатуры.
 *
 * В сторону от знака туда, где есть место (`side`): у знаков левой группы
 * вправо, у знака темы, прижатого к правому краю, — влево. Справа от него
 * кромка окна, и подпись, выехавшая туда, ушла бы за экран.
 *
 * В разметке подпись левой стороны стоит ПЕРЕД клеткой значка: ряд
 * прижимает знак к правому краю, колонка подписи растёт от него влево, и
 * сам значок не сдвигается ни на точку. Слово при этом выровнено к знаку
 * (`justify-end`): колонка открывает его, а не тащит за собой, — так же,
 * как у правой подписи, только зеркально.
 */
export function KnobLabel({
  children,
  side = "right",
}: {
  children: ReactNode;
  side?: "right" | "left";
}) {
  const left = side === "left";
  return (
    // Для программы чтения подпись лишняя: имя у кнопки своё
    // (`aria-label`), и подпись повторила бы его второй раз.
    <span
      aria-hidden
      className={cn(
        "grid grid-cols-[0fr] transition-[grid-template-columns]",
        // Дорожка прижата к знаку: у подписи слева — к правому краю грида.
        // Ширина грида у подписи своя (по содержимому) и растёт быстрее, чем
        // сама колонка с `fr`; а колонка по умолчанию стоит у ЛЕВОГО края
        // грида. У подписи справа это незаметно — её левый край у знака и так
        // не двигается. У подписи слева стоял бы не у знака: правый край
        // колонки, а с ним и слово, сначала уезжал влево, а потом возвращался
        // вправо, к знаку, пока колонка дотягивалась до ширины грида.
        left && "justify-end",
        ХОД,
        "md:group-hover/knob:grid-cols-[1fr] md:group-focus-visible/press:grid-cols-[1fr]",
        // Пока из знака раскрыто окошко, подпись скрыта: с `md` окошко
        // стоит справа от знака, там же, куда выезжает подпись, и слово
        // выглядывало бы из-под него. Скрыта, а не убрана (`invisible`):
        // место она держит, и окошко не дёргается.
        "md:group-has-[[role=group]]/knob:invisible",
      )}
    >
      <span className={cn("min-w-0 overflow-hidden", left && "flex justify-end")}>
        <span
          className={cn(
            HEADER_WORD,
            // Поле у знака — тот же просвет, что между знаком сайта и
            // «ГРАФИК» в шапке (`gap-2.5`): клетка значка уже даёт 8 точек
            // от рисунка, ещё две — здесь. С другой стороны — поле до
            // соседа.
            //
            // Сдвиг в начале хода — к знаку: подпись выходит из-под него.
            left ? "block shrink-0 pl-3 pr-0.5 translate-x-2" : "block pl-0.5 pr-3 -translate-x-2",
            // С `md` знаки стоят в полях страницы, а подпись выезжает на
            // сетку, и слово поверх чисел клеток не читалось бы. Подложка
            // цвета бумаги закрывает клетки под самой подписью; пока
            // подпись прозрачна, прозрачна и она.
            "md:rounded-xl md:bg-paper/90 md:py-1.5",
            "opacity-0 transition-[translate,opacity]",
            ХОД,
            "md:group-hover/knob:translate-x-0 md:group-hover/knob:opacity-100",
            "md:group-focus-visible/press:translate-x-0 md:group-focus-visible/press:opacity-100",
          )}
        >
          {children}
        </span>
      </span>
    </span>
  );
}

/**
 * Окошко, раскрытое из знака нижнего ряда, — вверх, потому что ряд стоит у
 * нижней кромки окна.
 *
 * Та же кайма и тень, что у окон приложения (`lit modal-lift`): кайма
 * горит от лампы вполсилы, а под курсором разгорается, и блик на ней
 * стоит там, где указатель. Без `lit` она оставалась бы ровной, как
 * нарисованная: наведение и отблеск лампа пишет только поверхностям со
 * светом (`shared/lamp.tsx`). Так же устроены все окошки — меню шапки,
 * выбор периода, имя профиля, тема и перечень видов у дня.
 *
 * С `md` знаки стоят колонкой у левого края (`grid-dock.tsx`), и вверх
 * окошко раскрывать нельзя: оно легло бы на знаки, что стоят над тем, из
 * которого оно вышло. Там оно раскрывается вправо от знака и выровнено по
 * его нижнему краю — растёт вверх, как и раньше, но уже рядом, а не поверх.
 *
 * Отступ слева — 3,25 рем (44 точки клетки значка и 8 просвета), а не
 * `left-full`: у гнезда с наведением ширина растёт на подпись, и окошко,
 * привязанное к его правому краю, уезжало бы вправо вместе с ней и
 * возвращалось, когда курсор уходит, — по сетке на глазах.
 */
export const KNOB_POPOVER = cn(
  "lit modal-lift absolute bottom-full mb-2 max-w-[calc(100vw-3rem)]",
  "md:bottom-0 md:left-13 md:mb-0 md:max-w-[calc(100vw-7rem)]",
  // Выезжает из знака: на телефоне — снизу вверх, с `md` — вправо.
  "pop-in [--pop-origin:50%_100%] [--pop-y:6px] md:[--pop-origin:0%_100%] md:[--pop-x:-6px] md:[--pop-y:0px]",
  "overflow-y-auto rounded-xl bg-paper-raised",
);

/** Строка выбора в окошке: значок, слово, галочка у выбранного. */
export function knobOption(active: boolean): string {
  return cn(
    "flex w-full cursor-pointer items-center gap-2.5 rounded-lg px-2.5 py-2",
    "text-left text-sm transition-colors hover:bg-paper-sunken",
    "focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-ink",
    // Значки — в девять десятых рема, как на кнопках шапки: доли кольца
    // периода в шестнадцати точках уже не различить.
    "[&_svg]:size-4.5 [&_svg]:shrink-0",
    active ? "bg-paper-sunken font-medium text-ink" : "text-ink-muted",
  );
}
