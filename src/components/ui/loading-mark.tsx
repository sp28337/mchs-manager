import type { CSSProperties } from "react";

import { cn } from "@/lib/utils/cn";

/**
 * Загрузка: знак сайта, клетки которого по очереди окрашиваются цветами
 * событий.
 *
 * --- Почему знак, а не заглушка ---------------------------------------------
 *
 * Заглушка рабочего экрана повторяла его раскладку костями, и каждая правка
 * экрана тянула за собой правку заглушки: положение и высота блоков должны
 * были совпадать до точки, иначе страница дёргалась в миг подстановки. Знак
 * по центру ничего не обещает о том, что окажется на месте, и подстановки,
 * которая могла бы сдвинуться, у него нет.
 *
 * --- Что в нём происходит ---------------------------------------------------
 *
 * Четыре клетки — те же, что в знаке сайта (`Logo`), и свет обходит их по
 * часовой стрелке. Клетка загорается видом суток из словаря событий —
 * отпуск, командировка, отгул, учёба, — сначала разгорается, потом долго
 * гаснет. Загорается и следующая, пока предыдущая ещё не погасла: так свет
 * переливается из клетки в клетку, а не прыгает.
 *
 * Круг за кругом цвета сдвигаются: первую клетку в первом круге красит
 * отпуск, во втором — командировка, и так далее. Один и тот же цвет
 * возвращается в ту же клетку лишь через четыре круга, и за это время
 * движение не успевает стать заметной механикой.
 *
 * Цвета берутся из тех же переменных, что у клеток на сетке (`--fps-*`), а
 * значит следуют за темой и за цветами, которые человек выбрал в
 * оформлении, — в загрузке они те же, что на графике.
 *
 * --- Как это сделано --------------------------------------------------------
 *
 * Под каждой клеткой лежат четыре одинаковых по форме слоя — по слою на цвет.
 * Слой весь круг прозрачен и раз в круг зажигается на секунду с небольшим:
 * задержка слоя — его место в очереди (`--rank`), длина круга у всех общая.
 * Анимируется одна прозрачность, поэтому ни раскладки, ни перерисовки
 * страницы движение не стоит.
 *
 * Тем, кто просил поменьше движения, общее правило (`globals.css`) сводит
 * анимацию к одному кадру, где все слои прозрачны: остаётся неподвижный знак
 * из четырёх пустых клеток.
 */
const CELLS = [
  [1.25, 1.25],
  [13.25, 1.25],
  [13.25, 13.25],
  [1.25, 13.25],
] as const;

/** Виды суток, чьими цветами горят клетки, — по кругу, в этом порядке. */
const EVENTS = ["leave", "trip", "rest", "study"] as const;

export function LoadingMark({ className }: { className?: string }) {
  return (
    <svg
      viewBox="0 0 24 24"
      aria-hidden
      fill="none"
      className={cn("loading-mark size-12 shrink-0", className)}
    >
      {CELLS.map(([x, y], cell) => (
        <g key={cell}>
          {/* Пустая клетка — как у знака на экране входа: тот же серый
              контур, что у знаков по углам окна. */}
          <rect
            x={x}
            y={y}
            width="9.5"
            height="9.5"
            rx="2"
            strokeWidth="1.5"
            className="fill-transparent stroke-ink/25"
          />
          {EVENTS.map((event, round) => (
            <rect
              key={event}
              x={x}
              y={y}
              width="9.5"
              height="9.5"
              rx="2"
              strokeWidth="1.5"
              data-event={event}
              className="loading-mark__lit"
              style={{ "--rank": round * CELLS.length + cell } as CSSProperties}
            />
          ))}
        </g>
      ))}
    </svg>
  );
}

/**
 * Экран, на котором больше нечего показывать, кроме ожидания: знак по центру
 * окна и слово для программы чтения. Страница под ним не прокручивается.
 *
 * Слово — единственное, что здесь сообщает о происходящем: рисунок для
 * диктора пуст (`aria-hidden`), а картинка без подписи оставила бы его молча
 * перед пустой страницей.
 */
export function LoadingScreen({ label }: { label: string }) {
  return (
    // `fixed`, а не высота в `svh`: у `body` внизу поле под нижнюю дымку, и
    // экран в высоту окна плюс это поле прокручивался бы на его величину —
    // с полосой прокрутки, которая сдвигала бы знак с оси, и с пустым хвостом.
    // Закреплённый слой места в потоке не занимает, а центр у него — центр
    // видимого окна, в том числе на телефоне с уезжающей адресной строкой.
    <main className="fixed inset-0 grid place-items-center">
      <LoadingMark />
      <p className="sr-only" role="status">
        {label}
      </p>
    </main>
  );
}
