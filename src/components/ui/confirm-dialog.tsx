"use client";

import type { ReactNode } from "react";

import { Button } from "./button";
import { Modal } from "./modal";

/**
 * Вопрос «точно?» — отдельным окном поверх всего.
 *
 * --- Почему окном, а не разворотом на месте кнопки ------------------------
 *
 * Раньше подтверждение разворачивалось прямо под кнопкой: текст, «Да» и
 * «Отмена» вставали в поток и раздвигали то, что под ними. На телефоне,
 * где настройки открыты листом во весь экран, это означало, что вопрос
 * появляется где-то внизу длинной формы — иногда за краем экрана, и
 * человек, нажавший «Сбросить», не видел вообще никакой реакции.
 *
 * Окно решает ровно это: вопрос встаёт по центру, поверх всего, и увидеть
 * его нельзя не заметив. Заодно оно закрывает собой то, что стоит за ним,
 * — а именно этого от подтверждения и ждут: сначала ответь, потом
 * продолжай.
 *
 * --- Почему второе окно поверх первого допустимо --------------------------
 *
 * Довод против был: два крестика на экране, и один закрывает не то.
 * Но `dialog`, открытый через `showModal()`, уходит в верхний слой, и
 * верхний слой — стопка: последний открытый перехватывает и фокус, и Esc.
 * Нижнее окно на это время недоступно ни мыши, ни клавиатуре, ни программе
 * чтения. Двух равных крестиков не получается: работает ровно один.
 *
 * --- Почему подтверждение вообще есть -------------------------------------
 *
 * Оба действия, которые сюда ходят, необратимы и стирают внесённое руками:
 * сброс календаря — год отметок, удаление профиля — вообще всё. Отмены у
 * них нет и быть не может: данные лежат в браузере, истории правок никто
 * не ведёт.
 *
 * Поэтому вопрос обязан называть ПОСЛЕДСТВИЯ, а не спрашивать «вы
 * уверены?». Что именно исчезнет и что при этом уцелеет — это и есть
 * содержимое окна; без второй половины человек честно испугается нажать.
 */
export function ConfirmDialog({
  open,
  onClose,
  onConfirm,
  title,
  confirm,
  icon,
  destructive,
  children,
}: {
  open: boolean;
  onClose: () => void;
  onConfirm: () => void;
  title: string;
  /** Надпись на кнопке согласия: она называет действие, а не «Да». */
  confirm: string;
  /** Знак действия — тот же, что на кнопке, которой окно открыли. */
  icon?: ReactNode;
  /**
   * Действие стирает данные безвозвратно.
   *
   * Сигнальный цвет в этом интерфейсе означает «требует решения человека»
   * и кнопку «Сохранить» не красит никогда. Здесь он на месте: удаление
   * профиля — само по себе вмешательство.
   */
  destructive?: boolean;
  children: ReactNode;
}) {
  return (
    <Modal
      open={open}
      onClose={onClose}
      title={title}
      // Окно вопроса узкое намеренно: в нём три строки текста, и растянутые
      // на сорок четыре рема они читались бы как страница, а не как вопрос.
      className="w-[min(26rem,calc(100vw-2rem))]"
    >
      <div className="space-y-4">
        <div className="space-y-2 text-sm">{children}</div>

        <div className="flex flex-wrap items-center gap-2">
          <Button
            type="button"
            variant={destructive ? "signal" : "default"}
            size="sm"
            onClick={() => {
              onConfirm();
              onClose();
            }}
          >
            {icon}
            {confirm}
          </Button>
          <Button type="button" variant="ghost" size="sm" onClick={onClose}>
            Отмена
          </Button>
        </div>
      </div>
    </Modal>
  );
}
