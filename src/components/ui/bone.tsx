import type { ReactNode } from "react";

import { cn } from "@/lib/utils/cn";

/**
 * Кости заглушки: место будущего содержимого.
 *
 * --- Почему текст остаётся в разметке ------------------------------------
 *
 * Заглушка обязана занимать РОВНО то место, которое займёт содержимое, —
 * иначе страница дёрнется в момент подстановки. Прямоугольник с высотой,
 * подобранной на глаз, этого не гарантирует: строка занимает столько,
 * сколько ей отмерили кегль, интерлиньяж и гарнитура, а не столько,
 * сколько показалось верным.
 *
 * Поэтому в заглушке лежит НАСТОЯЩАЯ строка — те же слова, тем же кеглем,
 * — просто прозрачная и на плашке. Высота строки тогда не подбирается, а
 * получается сама и совпадает с точностью до пикселя. Отсюда же требование
 * к вызывающему: подставлять образец той же длины, что и настоящая
 * подпись, а не «примерно такой».
 *
 * --- Почему та же деталь рисует и настоящий текст -------------------------
 *
 * `skeleton` выключен — и `BoneText` отдаёт содержимое как есть. Так один
 * и тот же компонент показывает и заглушку, и расчёт, и разойтись им
 * негде: разметка одна на оба случая (`ShiftLegend`).
 */
export function BoneText({
  skeleton,
  className,
  children,
}: {
  skeleton?: boolean;
  className?: string;
  children: ReactNode;
}) {
  if (!skeleton) return <>{children}</>;

  return (
    <span
      className={cn(
        "skeleton-bone rounded-xs bg-paper-raised text-transparent",
        // Внутренние ссылки и подчёркивания в заглушке не нужны: под
        // плашкой их всё равно не видно, а линия подчёркивания вылезала бы
        // из-под неё.
        "[&_*]:text-transparent [&_*]:no-underline",
        className,
      )}
    >
      {children}
    </span>
  );
}

/**
 * Плашка на месте блока — там, где размер задан разметкой, а не строкой:
 * кнопка, поле, клетка календаря.
 */
export function Bone({ className }: { className?: string }) {
  return <div className={cn("skeleton-bone bg-paper-raised", className)} />;
}
