import { cn } from "@/lib/utils/cn";

/**
 * Знак приложения: цикл «сутки через трое».
 *
 * --- Почему именно четыре квадрата --------------------------------------
 *
 * Каску, огонь и часы рисуют все, и ни одно из этих изображений не
 * говорит, чем занят этот сайт. А четыре клетки, из которых закрашена
 * одна, — это буквально график, который человек сюда пришёл проверить:
 * сутки дежурства и трое суток отдыха. Тот, кто так работает, узнаёт свой
 * график мгновенно; тот, кто нет, всё равно видит календарную сетку.
 *
 * Знак нарисован той же геометрией, что и клетки календаря на экране, —
 * скруглённые квадраты в сетке. Знак, не похожий на содержимое страницы,
 * выглядит наклейкой поверх неё.
 *
 * --- Почему у него есть одноцветный вид (`mono`) --------------------------
 *
 * Кнопка «График» в панели управления сеткой показывает знак сайта, а не
 * значок из набора: сетка смен — это и есть то, что нарисовано на знаке, и
 * ни один календарик из набора не скажет этого точнее.
 *
 * Но в ряду органов управления знак обязан вести себя как значок: гореть
 * тем же цветом, что подпись под ним, и гаснуть вместе с ней, когда сетка
 * не выбрана. Сигнальный красный там означал бы «внимание» — он занят
 * ровно этим, — а серый по-прежнему называет цикл: залито одно из четырёх.
 *
 * Поэтому у одноцветного вида от знака остаётся всё, кроме цвета: те же
 * квадраты, та же геометрия, та же залитая клетка. Обводки при этом чуть
 * плотнее (0,55 против 0,45): в шапке знак вдвое крупнее, чем в ряду
 * управления, и на мелком прежняя доля растворялась до неразличимой.
 *
 * Размер в ряду знак берёт не отсюда: квадраты занимают клетку рисунка
 * почти целиком, и рядом со значками из набора он выходит крупнее.
 * Поправка стоит там, где знаки собраны вместе (`shift/components/
 * grid-icons.tsx`), — вместе с замером, из которого она получена.
 */
export function Logo({ className, mono }: { className?: string; mono?: boolean }) {
  const outline = mono ? "currentColor" : "#8a8578";
  return (
    <svg
      viewBox="0 0 24 24"
      aria-hidden
      className={cn("size-6 shrink-0", className)}
      fill="none"
    >
      {/* Дежурные сутки — залитые. Цвет берётся от текста, чтобы знак
          работал и на светлой теме, и на тёмной, и в один цвет на печати. */}
      <rect x="1" y="1" width="10" height="10" rx="2" fill="currentColor" />
      <rect
        x="13.75"
        y="1.75"
        width="8.5"
        height="8.5"
        rx="1.75"
        stroke={outline}
        strokeWidth="1.5"
        opacity={mono ? "0.55" : "0.45"}
      />
      <rect
        x="1.75"
        y="13.75"
        width="8.5"
        height="8.5"
        rx="1.75"
        stroke={outline}
        strokeWidth="1.5"
        opacity={mono ? "0.55" : "0.45"}
      />
      <rect
        x="13.75"
        y="13.75"
        width="8.5"
        height="8.5"
        rx="1.75"
        stroke={outline}
        strokeWidth="1.5"
        opacity={mono ? "0.55" : "0.45"}
      />
    </svg>
  );
}
