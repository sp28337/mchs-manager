"use client";

import type { ReactNode } from "react";

import { MARK_EMPTY_TEXT } from "@/components/shared/header-action";
import { BALANCE_SWAP_MS } from "@/components/ui/balance-caption";
import { CountedNumber } from "@/components/ui/counted-number";
import { cn } from "@/lib/utils/cn";

/**
 * Число полосы итога: цифры над подписью. Одно на расчёт и на первый экран.
 *
 * --- Почему это отдельный модуль -------------------------------------------
 *
 * Первый экран показывает ту же полосу, что человек увидит внутри:
 * норма, факт, разница. Пока у лендинга было своё число — подпись сбоку,
 * плашка вокруг, другой кегль, — оно расходилось с расчётом при каждой
 * правке полосы, и это вскрывалось только глазами. Теперь число одно, и
 * правка вида в одном месте меняет оба.
 *
 * Модуль лёгкий намеренно: лендинг не должен тянуть домен расчёта
 * (`decimal`, `calculation`) ради двух констант и одной разметки, поэтому
 * здесь нет ничего, кроме отрисовки.
 */

/**
 * Величина числом с единицей — и, если нужно, не одним.
 *
 * Пар бывает две: переработка сменами это «8 смен 20 ч», и остаток от
 * смены такое же число, как сами смены. Оформлять его иначе значило бы
 * сказать, что он менее настоящий.
 *
 * --- Почему число доходит до нового значения, а не подменяется -----------
 *
 * Полоса итога затем и закреплена под шапкой, что человек правит календарь
 * и смотрит на неё. Правка меняет разом несколько чисел из семи, а
 * подменённые мгновенно они не говорят, КАКОЕ из них двинулось: разницу в
 * час на одном и том же месте глаз не замечает вовсе.
 *
 * Отсчёт (`CountedNumber`) отвечает на это движением — тот же самый, что
 * крутит числа на первом экране. Эталон, по которому меряется ширина
 * полосы, при этом стоит неподвижно (`still`): считать место по числу в
 * пути значило бы менять раскладку, пока оно идёт.
 */
export interface FigurePart {
  value: string;
  /** Единица при числе; у счёта смен её нет. */
  unit?: string;
}

/**
 * Подпись под числом: гарнитура для названий, прописные, с разрядкой (тем
 * же голосом, что названия в шапке, `HEADER_WORD`), но мелко: подпись
 * называет число, а не спорит с ним. И у главных чисел она жирная, и у мелких
 * итогов, но у мелких на ступень мельче.
 *
 * Кегль главных ступенями: 11 точек на самом узком телефоне, 12 — с 340, 14
 * — с 680 (42,5 рема). Три подписи в равных колонках на 320 точках иначе не
 * помещаются («НОРМА ПЕРИОДА» в 12 точек — 82, колонка там — 85). У мелких
 * итогов те же 11 и 12, но на широком экране они остаются на 12
 * (`min-[42.5rem]:text-xs`): справка не должна подрастать вместе с главным.
 *
 * Ступень на 680, а не на `sm` (640), не случайно: подписи и числа при
 * ступени растут, и боковые итоги, помещавшиеся на 640 в малом кегле, в
 * большой уже не лезли — на 34 точках (640–673) они пропадали и снова
 * появлялись. С ростом на 680 первая пара помещается и до, и после ступени,
 * и мигать ей нечем. Тот же порог у чисел и у единиц рядом (`Figure`).
 *
 * Высота задана и одинакова у главных и мелких, а не взята из строки: у
 * «Переработки» внутри коробка приставки выше строки на несколько точек, и
 * без заданной высоты эта подпись стояла бы ниже соседних; а подписи
 * разного кегля с высотой «по строке» сдвигали бы друг относительно друга
 * и числа над ними. Классы написаны целиком, а не собраны из переменной:
 * Tailwind находит их в исходнике как строки.
 */
const CAPTION_BASE = cn(
  "flex h-[1.125rem] items-center justify-center whitespace-nowrap",
  "font-display uppercase leading-tight tracking-wide",
  MARK_EMPTY_TEXT,
  "text-[11px] min-[340px]:text-xs",
);
const CAPTION = cn(CAPTION_BASE, "font-bold min-[42.5rem]:text-sm");
const CAPTION_MINOR = cn(CAPTION_BASE, "font-bold min-[42.5rem]:text-xs");

/**
 * Крупная подпись — для первого экрана посадочной (`size="hero"`).
 *
 * Те же гарнитура, регистр, разрядка и цвет, что у обычной: отличается один
 * кегль. Там числа стоят на фоне календаря в полэкрана, и числа и подписи
 * обычного размера терялись на нём, как мелкая плашка на большом листе.
 * Ступени — по ширине окна: 10 точек на самом узком телефоне (три подписи в
 * колонках по 79 точек иначе не помещаются, и «НОРМА ПЕРИОДА» обрезается по
 * краю плоскости), 12 с 340, 14 с `md`, 16 с `xl`.
 */
const CAPTION_HERO = cn(
  "flex h-6 items-center justify-center whitespace-nowrap",
  "font-display font-bold uppercase leading-tight tracking-wide",
  MARK_EMPTY_TEXT,
  "text-[10px] min-[340px]:text-xs md:text-sm xl:text-base",
);

export function Figure({
  parts,
  caption,
  tone,
  still,
  minor,
  size,
  hint,
  className,
}: {
  /** Ширина и место числа в чужой раскладке — например, равные колонки второго ряда. */
  className?: string;
  parts: readonly FigurePart[];
  caption: ReactNode;
  tone?: "signal" | "verify";
  /** Эталон: считать по нему ширину, пока число в пути, нельзя. */
  still?: boolean;
  /** Мелкий итог: число на ступень меньше. */
  minor?: boolean;
  /**
   * `hero` — число крупнее обычного, для первого экрана. Построение то же:
   * число над подписью, жирное, единица блёклая; крупнее только кегль.
   */
  size?: "hero";
  /**
   * Что это за число — строкой подсказок внизу окна (`info-bar.tsx`) и
   * всплывающей подсказкой там, где строки нет. Первый экран подсказок не
   * даёт: числа там — картинка, а не величины человека.
   */
  hint?: string;
}) {
  const hero = size === "hero";
  return (
    // Число над подписью, оба по середине колонки и по середине высоты.
    <div
      title={hint}
      className={cn(
        "flex min-w-0 flex-col items-center justify-center gap-1",
        still && "shrink-0",
        className,
      )}
    >
      {/* Число и его единица не разрываются переносом: «1796,00» на одной
          строке и «ч» на следующей читается как другое число. Все главные —
          одного роста и жирные: разный рост нужен там, где одно число —
          заголовок над остальными, а здесь они равны. У мелких итогов число
          тоже жирное, но мельче (`text-sm`): от главных их отличает размер,
          а не вес — обычный вес на таком кегле терялся рядом с подписью. */}
      <dd
        className={cn(
          // Строка числа одной высоты у главных и мелких, число — к её
          // низу: подписи под ними встают на одну линию, а базовые линии
          // чисел разного роста совпадают. Без этого блоки разной высоты,
          // выровненные по середине, сдвигали подписи мелких итогов на пару
          // точек относительно главных.
          "flex items-end justify-center whitespace-nowrap font-mono leading-none text-center",
          // Крупное — своя лесенка: на первом экране число стоит на фоне
          // месяцев, а не в строке под шапкой, и растёт с шириной окна.
          hero
            ? "h-9 text-3xl font-bold md:h-11 md:text-4xl xl:h-14 xl:text-5xl"
            : cn(
                "h-5 min-[42.5rem]:h-6",
                minor
                  ? "text-sm font-bold"
                  : "text-xl font-bold min-[42.5rem]:text-2xl",
              ),
          // Сами цифры — обычными чернилами темы (от страницы), а тон
          // разницы — зелёный и красный — говорит о переработке и
          // недоработке. Цвет бургера (`MARK_EMPTY_TEXT`) — у БУКВ полосы:
          // у подписей и у единицы при числе, но не у цифр: цифры — то, ради
          // чего полоса существует, и им гаснуть не за чем.
          //
          // Цвет меняется столько же, сколько едет приставка в подписи:
          // это одно событие, показанное с двух сторон, и разъезжаться им
          // нельзя. Поэтому длительность приходит оттуда же, откуда её
          // берёт сама приставка, а не повторяется здесь числом.
          "transition-colors",
          tone === "signal" && "text-signal",
          tone === "verify" && "text-verify",
        )}
        style={{ transitionDuration: `${BALANCE_SWAP_MS}ms` }}
      >
        {parts.map((part, index) => (
          <span key={`${index}:${part.unit ?? ""}`} className={index > 0 ? "ml-2" : undefined}>
            {still ? part.value : <CountedNumber value={part.value} />}
            {/* Единица тише числа: ни жирности, ни полного роста. Это
                буква, а не цифра, и цвет у неё как у подписей — цвет
                бургера; у числа с тоном тоже: «ч» при зелёном числе серое,
                как везде. */}
            {part.unit ? (
              <span
                className={cn(
                  "ml-1 font-normal",
                  hero ? "text-base md:text-xl xl:text-2xl" : "text-xs min-[42.5rem]:text-sm",
                  MARK_EMPTY_TEXT,
                )}
              >
                {part.unit}
              </span>
            ) : null}
          </span>
        ))}
      </dd>
      <dt className={hero ? CAPTION_HERO : minor ? CAPTION_MINOR : CAPTION}>{caption}</dt>
    </div>
  );
}
