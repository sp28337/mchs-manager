"use client";

import { useEffect, useLayoutEffect, useRef } from "react";

import { cn } from "@/lib/utils/cn";

/**
 * Подпись разницы часов: «Переработка» или «Недоработка».
 *
 * --- Почему это одно число, а не два -------------------------------------
 *
 * Раньше недоработка была ОТДЕЛЬНЫМ числом и появлялась справа от
 * переработки, когда возникала. Числа на плашке становилось четыре, ряд
 * менял ширину на ровном месте, и главное — рядом стояли «Переработка 0 ч»
 * и «Недоработка 16 ч», то есть одна и та же величина, показанная дважды.
 *
 * Величина действительно одна: разница между отработанным и нормой.
 * Меняется у неё только знак, и правильный способ показать знак — не
 * второе число, а другое имя и другой цвет у того же самого.
 *
 * --- Почему приставка едет, а не подменяется ------------------------------
 *
 * «Пере» и «недо» отличаются четырьмя буквами в начале слова — ровно тем
 * местом, куда человек не смотрит: он смотрит на число. Мгновенная
 * подмена букв проходит незамеченной, и число меняет цвет как будто само
 * по себе.
 *
 * Поэтому приставка СДВИГАЕТСЯ: «недо» приходит сверху и выталкивает
 * «пере» вниз, освобождая себе место. Движение в подписи ловится боковым
 * зрением — тем же, которым замечают, что число покраснело.
 *
 * Хвост слова при этом стоит на месте: едет только то, что меняется.
 * Ширину коробки держит самая широкая из двух приставок, поэтому
 * «работка» не дёргается ни в одну сторону.
 *
 * --- Почему приставка смазывается на ходу ---------------------------------
 *
 * Четыре буквы, проезжающие свою собственную высоту, глаз читать не
 * успевает и не должен: пока они едут, это не слово, а движение. Резкий
 * текст в пути читается как подмена кадра — мелькнуло что-то другое, —
 * а смазанный честно говорит «здесь сейчас происходит», и в конце
 * останавливается уже словом.
 *
 * Размытие сходит к нулю раньше, чем кончается ход: последняя треть
 * движения — доводка на место, и она обязана быть чёткой.
 *
 * --- Почему движение считается кодом, а не переходом CSS ------------------
 *
 * Переход умеет вести значение из А в Б, но не умеет пройти через
 * ТРЕТЬЕ по дороге: у размытия начало и конец одинаковые — ноль, — а
 * весь смысл в том, что посередине оно есть. Это уже раскадровка, и
 * задать её можно либо ключевыми кадрами, либо здесь.
 *
 * Выбран второй способ: ключевые кадры пришлось бы запускать сменой
 * класса, а класс меняется в той же отрисовке, что и положение приставки,
 * — и один кадр она успевала бы показать себя уже на месте. Здесь
 * анимация назначается ДО того, как браузер нарисовал новое положение
 * (`useLayoutEffect`), и рывка не бывает.
 *
 * Первая отрисовка ничего не играет: приставка просто стоит там, где
 * стоит. Проигрывать при загрузке страницы движение, которого не было, —
 * значит соврать о том, что что-то изменилось.
 */

/** Сколько идёт смена приставки и перекраска числа рядом с ней. */
export const BALANCE_SWAP_MS = 420;

/** Насколько смазывается приставка на ходу. */
const BLUR_PX = 3.2;

/**
 * Где стоит приставка при этом знаке разницы.
 *
 * `«недо»` сверху, `«пере»` снизу — и та из них, что сейчас не при деле,
 * уезжает за край коробки на свою собственную высоту.
 */
function restOf(prefix: "over" | "under", under: boolean): string {
  if (prefix === "under") return under ? "0%" : "-100%";
  return under ? "100%" : "0%";
}

export function BalanceCaption({ under }: { under: boolean }) {
  const overRef = useRef<HTMLSpanElement>(null);
  const underRef = useRef<HTMLSpanElement>(null);
  const previous = useRef(under);

  useSwapEffect(() => {
    const was = previous.current;
    previous.current = under;
    if (was === under) return;
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

    for (const [element, prefix] of [
      [underRef.current, "under"],
      [overRef.current, "over"],
    ] as const) {
      element?.animate(
        [
          { transform: `translateY(${restOf(prefix, was)})`, filter: `blur(${BLUR_PX}px)` },
          { filter: `blur(${BLUR_PX * 0.35}px)`, offset: 0.45 },
          { transform: `translateY(${restOf(prefix, under)})`, filter: "blur(0px)" },
        ],
        { duration: BALANCE_SWAP_MS, easing: "cubic-bezier(0.22, 1, 0.36, 1)" },
      );
    }
  }, [under]);

  return (
    // Приставка и «работка» — ОДНА строка текста, а не два бокса рядом.
    // ----------------------------------------------------------------
    // Раньше это был `inline-flex items-center`: приставка лежала в боксе
    // высотой 1,45 em, хвост — в строке в 1,25 em, и браузер центрировал их
    // по вертикали дробной арифметикой (на 14 точках — 1,15 точки). Каждый
    // движок округляет такой сдвиг по-своему, и на одних экранах приставка
    // стояла вровень с хвостом, а на других — на точку ниже: замером на
    // дробных масштабах и при нечётной высоте окна, и на снимке с
    // создания графика. Центрирование и было причиной: сам сдвиг не
    // нужен, если обе части встают на одну базовую линию.
    //
    // Теперь приставка — `inline-grid` в потоке строки, и базовую линию
    // выравнивает сам браузер: арифметики нет, и округлять нечего. Бокс без
    // `overflow` — у него базовая линия берётся из текста, а не со дна
    // коробки (потому прежний вариант и не мог встать по базовой линии).
    // Обрезка ходом приставки — `clip-path`: он ничего не двигает и
    // слоёв не создаёт.
    <span>
      {/* Обе приставки лежат в ОДНОЙ ячейке грида: она и задаёт коробке
          ширину по самой широкой из них, и держит их друг над другом.
          Высоту коробке даёт строка, и обрезка идёт ровно по ней: подпись
          набрана прописными (`uppercase` у `CAPTION*`), а у них ни выносных
          вверх, ни вниз за строку нет. */}
      <span className="inline-grid [clip-path:inset(0)]">
        <Prefix ref={underRef} at={restOf("under", under)} hidden={!under}>
          Недо
        </Prefix>
        <Prefix ref={overRef} at={restOf("over", under)} hidden={under}>
          Пере
        </Prefix>
      </span>
      работка
    </span>
  );
}

/** Одна приставка на своём месте: на виду или за краем коробки. */
function Prefix({
  ref,
  at,
  hidden,
  children,
}: {
  ref: React.RefObject<HTMLSpanElement | null>;
  /** Сдвиг от места на виду. */
  at: string;
  /** Уехала за край: читалке её произносить нечего. */
  hidden: boolean;
  children: string;
}) {
  return (
    <span
      ref={ref}
      aria-hidden={hidden}
      // К правому краю коробки, а не по середине: коробку держит самая
      // широкая приставка («НЕДО» в прописных), и узкая «ПЕРЕ» по середине
      // оставляла бы просвет между собой и хвостом слова — «ПЕРЕ РАБОТКА».
      // У края она стоит вплотную к хвосту, а лишнее место уходит влево, где
      // читается сдвигом подписи, а не разрывом слова.
      className={cn("col-start-1 row-start-1 flex justify-end")}
      // На месте — БЕЗ `transform`, даже единичного. Приставка, у которой он
      // стоит, рисуется отдельным слоем: её смещение остаётся дробным, а «работка»
      // рядом, без него, прижата к целой точке. Окно по середине экрана ставит
      // подпись на дробную высоту (`m-auto` у окна), и при нечётной высоте окна
      // «ПЕРЕ» оказывалось на точку ниже «РАБОТКА» и светлее её: замер на
      // создании графика — верх букв 10 и 9, яркость 30 и 23. Сдвиг нужен
      // только уехавшей приставке (за краем она не видна) и ходу самой смены,
      // а тот задаёт `animate` выше.
      style={at === "0%" ? undefined : { transform: `translateY(${at})` }}
    >
      {children}
    </span>
  );
}

/**
 * Тот же эффект, что до отрисовки, но безопасный на сервере.
 *
 * Разметка отдаётся статикой, а `useLayoutEffect` на сервере ругается в
 * консоль. Выбор между ним и обычным эффектом делается один раз при
 * загрузке модуля и потому не нарушает порядок вызовов.
 */
const useSwapEffect = typeof window === "undefined" ? useEffect : useLayoutEffect;
