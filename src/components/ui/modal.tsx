import { cn } from "@/lib/utils/cn";

/**
 * Модальное окно со справкой.
 *
 * --- Почему родной `dialog` ----------------------------------------------
 *
 * Всё, что модальное окно обязано делать, кроме показа текста, браузер
 * умеет сам, если открыть его через `showModal()`: увести фокус внутрь и
 * не выпускать его по Tab, закрыться по Esc, вернуть фокус на кнопку, с
 * которой его открыли, объявить себя диалогом и сделать остальную
 * страницу недоступной для экранного диктора. Своя реализация на `div` с
 * `position: fixed` не делает ничего из этого, пока не написать это всё
 * руками, — а написать это всё руками означает завести пять новых
 * способов запереть человека в окне без выхода.
 *
 * --- Ловушка с `display` -------------------------------------------------
 *
 * Закрытый `dialog` скрыт правилом `display: none` из таблицы браузера.
 * Любая утилита раскладки — `flex`, `grid`, `block` — это правило
 * перебивает, и окно остаётся на экране навсегда. Поэтому раскладка
 * задана вариантом `open:`: она применяется только к открытому окну.
 *
 * --- Прокрутка страницы под окном ----------------------------------------
 *
 * Браузер не запрещает прокручивать страницу за модальным окном, и на
 * телефоне это выглядит так, будто закрылось не то. Прокрутка снимается
 * на время показа и возвращается ровно та, что была: чужое значение
 * `overflow` тут перетирать нельзя — его мог поставить кто-то ещё.
 *
 * Снятая прокрутка убирает полосу, а вместе с ней — её ширину, и страница
 * на фоне разъезжается вправо. Место под полосу держит
 * `scrollbar-gutter: stable` у корня документа; где этого свойства нет,
 * ширина добирается полем справа. Подробности — у самого эффекта.
 *
 * Само место под полосу окно НЕ ТРОГАЕТ, и это выяснено дорого. Лист во
 * весь экран лез под него — оно закрашивается поверх верхнего слоя, и вдоль
 * правого края листа оставалась непрокрашенная кромка. Место убирали на
 * время показа; от этого страница под окном перевёрстывалась вдвое: на
 * открытии и на закрытии, — и на закрытии прокрутка съезжала (замером: на
 * девятнадцать точек). Человек видел рывок в тот самый миг, когда окно
 * гасло. Теперь место остаётся на месте всегда, а лист просто не лезет
 * под него (`w-full` вместо `100vw`).
 *
 * --- Ловушка с `flex: 1 1 0%` --------------------------------------------
 *
 * Высота окна не задана: её определяет содержимое, а `max-height` только
 * ставит потолок. В таком столбце тело окна обязано занимать место по
 * СОДЕРЖИМОМУ (`flex: 1 1 auto`), а не по нулевой основе (`flex-1`, то
 * есть `flex: 1 1 0%`).
 *
 * Разница не косметическая. С нулевой основой высоту окна приходится
 * выводить из максимального содержимого тела, и WebKit этого не делает:
 * тело получает нулевой вклад, и окно схлопывается до одной шапки — на
 * телефоне это выглядит как пустая полоска с заголовком и крестиком.
 * Chromium и Gecko считают правильно, поэтому на настольном браузере
 * поломки не видно вовсе.
 *
 * `min-height: 0` при этом обязателен по-прежнему: без него тело не даёт
 * себя сжать ниже содержимого, и вместо прокрутки ВНУТРИ окна получается
 * окно выше экрана.
 *
 * --- Лист во весь экран (`sheet`) ----------------------------------------
 *
 * На телефоне окно шириной в экран минус два поля и высотой в 85 процентов
 * — это не окно, а страница с полями. Полей этих хватает ровно на то,
 * чтобы показать полоску чужого содержимого по краям и отнять у формы
 * четыре строки.
 *
 * Поэтому у окна есть второй вид: ниже `sm` оно занимает экран целиком, без
 * скруглений и рамки. Всё остальное — перехват фокуса, Esc, возврат фокуса,
 * снятая прокрутка — остаётся тем же, потому что это тот же `dialog`.
 * Заводить ради полноэкранного вида отдельную деталь значило бы завести
 * второй такой же список подводных камней.
 *
 * Лист не появляется рывком, а плавно проступает целиком, тем же переходом,
 * что и обычное окно, — хореография в `globals.css`, здесь только имя
 * (`sheet`), за которое она цепляется.
 *
 * Шапку лист рисует сам, а не показывает страничную: `dialog` живёт в
 * верхнем слое, и до шапки страницы изнутри него не дотянуться никаким
 * селектором. Кто открывает лист, тот и решает, чем заполнить его шапку —
 * например, тем же знаком сайта, что и на странице (`header-tools.tsx`).
 *
 * --- Появление и уход ------------------------------------------------------
 *
 * Окно и его затемнение не возникают и не пропадают рывком: они проступают
 * и гаснут. Сами переходы записаны в `globals.css` по имени `modal`, а
 * ведёт их отсюда метка `data-modal`: «closed» — кадр, из которого окно
 * приходит и в который уходит, «open» — то, каким оно стоит.
 *
 * --- Почему уход ведёт скрипт, а не одни правила ---------------------------
 *
 * Закрытый `dialog` скрыт правилом `display: none`, и уход из него браузер
 * сам по себе не показывает: в тот же кадр, когда окно закрылось, оно
 * пропадает. Обойти это одними правилами МОЖНО — `@starting-style` даёт
 * кадр, с которого окно проступает, `transition-behavior: allow-discrete`
 * держит его показанным, а `overlay` — в верхнем слое, пока идёт уход, — и
 * именно так здесь и было сделано.
 *
 * Не сработало. Все три вещи молодые, и на телефоне их нет: в Safari
 * `overlay` не поддержан вовсе, а без него окно вылетает из верхнего слоя
 * в тот же кадр, и никакой уход показать нельзя в принципе. На настольном
 * Chromium всё выглядело гладко, на iPhone окно исчезало рывком — трижды
 * подряд, потому что искали причину не там.
 *
 * Поэтому закрытие теперь ждёт скрипт: `close()` вызывается не сразу, а
 * через `EXIT_MS` — ровно столько, сколько идёт переход. Всё это время
 * окно ОТКРЫТО по-настоящему: оно в верхнем слое, с затемнением, с
 * перехваченным фокусом, — и гаснет обычным переходом, который умеет любой
 * браузер с `dialog`.
 *
 * Второго источника правды при этом не заводится. Правда одна — довод
 * `open`; отставание родного состояния окна от него это не другое мнение,
 * а длительность ухода, и живёт оно ровно в одном месте — в отложенном
 * вызове. Повторное открытие этот вызов отменяет, и окно остаётся тем же
 * самым, не мигнув.
 *
 * Esc идёт тем же путём: браузер закрыл бы окно немедленно, поэтому его
 * `cancel` перехватывается, а закрытие идёт через то же состояние снаружи —
 * иначе клавиша уходила бы мимо анимации.
 */
/**
 * Снятая прокрутка страницы, пока открыто хоть одно окно.
 *
 * --- Почему счётчик, а не «запомнить и вернуть» ----------------------------
 *
 * Сперва каждое окно запоминало прежнее значение при открытии и возвращало
 * его при закрытии. На одном окне это работает, на вложенных — ломается, и
 * ломается молча.
 *
 * Так это и вылезло. Из настроек открывается день: сами настройки при этом
 * закрываются, окно дня остаётся. Порядок получался такой — настройки
 * взяли себе прежнее «прокрутка есть», день открылся ПОВЕРХ них и взял
 * себе прежнее «прокрутки нет», настройки закрылись и честно вернули
 * «есть», а следом закрылся день и вернул «нет». Страница оставалась без
 * прокрутки до перезагрузки, и починить это человек не мог ничем.
 *
 * Считается поэтому не значение, а ЧИСЛО открытых окон. Прежнее состояние
 * запоминается один раз — когда первое окно снимает прокрутку, — и
 * возвращается один раз, когда закрывается последнее. Сколько окон
 * открывалось и в каком порядке они закрылись, значения больше не имеет.
 */
let openModals = 0;
let scrollBefore: { overflow: string; paddingRight: string } | null = null;
let unlocking: number | null = null;

function lockScroll(): void {
  if (unlocking !== null) {
    window.clearTimeout(unlocking);
    unlocking = null;
  }
  openModals += 1;
  if (openModals > 1) return;

  // Прежнее состояние берётся ОДИН раз — пока его не вернули.
  //
  // Здесь и сидела вторая половина той же поломки. Возврат отложен на время
  // ухода окна, и в промежутке `overflow` ещё «hidden». Из настроек день
  // открывается ровно в этот промежуток: настройки закрылись и отложили
  // возврат, день открылся и, будучи первым, записал себе в «прежнее» то
  // самое «hidden», которое поставили настройки. Дальше он его честно
  // возвращал, и страница оставалась без прокрутки навсегда.
  //
  // Пока запись цела, она и есть прежнее состояние: её поставил тот, кто
  // снял прокрутку первым, и переписывать её некому.
  scrollBefore ??= {
    overflow: document.body.style.overflow,
    paddingRight: document.body.style.paddingRight,
  };

  // Место под исчезающую полосу прокрутки.
  //
  // Обычно его держит `scrollbar-gutter: stable` у корня документа
  // (`globals.css`): полоса пропадает, а ширина колонки не меняется. Там,
  // где свойства нет (Safari до 18.2), приходится добирать шириной поля —
  // иначе страница на фоне разъезжается вправо в тот момент, когда человек
  // только нажал кнопку.
  //
  // Одно И другое одновременно было бы двойной компенсацией и сдвигом в
  // обратную сторону, поэтому поле добавляется только при отсутствии
  // поддержки.
  const gutter = CSS.supports("scrollbar-gutter: stable");
  const bar = window.innerWidth - document.documentElement.clientWidth;

  document.body.style.overflow = "hidden";
  if (!gutter && bar > 0) document.body.style.paddingRight = `${bar}px`;
}

function unlockScroll(): void {
  openModals = Math.max(0, openModals - 1);
  if (openModals > 0) return;

  // Возврат прокрутки — ПОСЛЕ того, как окно догорит, а не в первый кадр
  // закрытия.
  //
  // Возвращать её сразу значит менять страницу под ещё видимым окном, и на
  // телефоне это видно: снятая прокрутка держит адресную строку раскрытой,
  // возвращённая — отпускает её, высота окна браузера меняется, а вместе с
  // ней и `dvh`, которым лист меряет себя. Окно подпрыгивало на долю
  // секунды прямо перед тем, как исчезнуть.
  //
  // Пока окно на экране, прокручивать всё равно нечего: оно закрывает собой
  // страницу целиком. Поэтому возврат просто ждёт конца ухода — а если за
  // это время открылось следующее окно, `lockScroll` его отменит.
  unlocking = window.setTimeout(() => {
    if (openModals === 0 && scrollBefore) {
      document.body.style.overflow = scrollBefore.overflow;
      document.body.style.paddingRight = scrollBefore.paddingRight;
      scrollBefore = null;
    }
    unlocking = null;
  }, EXIT_MS);
}

export function Modal({
  open,
  onClose,
  title,
  sheet,
  children,
  className,
  headerClassName,
  bodyClassName,
}: {
  open: boolean;
  onClose: () => void;
  /** Заголовок окна: он же его имя для экранного диктора. */
  title: ReactNode;
  /** Ниже `sm` — во весь экран, без скруглений и рамки. */
  sheet?: boolean;
  children: ReactNode;
  className?: string;
  /** Шапка окна: за неё цепляется переход из шапки сайта. */
  headerClassName?: string;
  /** Тело окна: за него цепляется появление содержимого. */
  bodyClassName?: string;
}) {
  const ref = useRef<HTMLDialogElement>(null);
  // Опознаватель заголовка выдаётся, а не пишется руками: окон на
  // странице бывает несколько сразу — настройки, выбор периода и правка
  // суток живут рядом, — и одинаковый `id` у двух заголовков это и
  // недопустимая разметка, и `aria-labelledby`, указывающий не туда.
  const titleId = useId();

  // Уход окна доигрывается ДО того, как окно закроется по-настоящему:
  // отложенное закрытие живёт здесь, чтобы повторное открытие могло его
  // отменить. Подробности — в шапке файла.
  const leaving = useRef<number | null>(null);

  useEffect(() => {
    const dialog = ref.current;
    if (!dialog) return;

    if (open) {
      // Открылись, не дождавшись конца ухода, — уход отменяется, и окно
      // остаётся тем же самым.
      if (leaving.current !== null) {
        window.clearTimeout(leaving.current);
        leaving.current = null;
      }
      if (!dialog.open) dialog.showModal();

      // Кадр «закрыто», перевёрстка, кадр «открыто» — иначе переходить
      // не с чего: браузер склеит два состояния в одно и покажет окно
      // сразу готовым.
      dialog.dataset.modal = "closed";
      void dialog.offsetWidth;
      dialog.dataset.modal = "open";
      return;
    }

    if (!dialog.open || leaving.current !== null) return;

    dialog.dataset.modal = "closed";
    leaving.current = window.setTimeout(() => {
      leaving.current = null;
      if (dialog.open) dialog.close();
    }, EXIT_MS);
  }, [open]);

  useEffect(() => {
    if (!open) return;
    lockScroll();
    return unlockScroll;
  }, [open]);

  return (
    <dialog
      ref={ref}
      // `close` срабатывает и на Esc, и на кнопку, и на вызов `close()`.
      // Слушать нужно именно его: иначе состояние снаружи останется
      // «открыто», и повторное нажатие не откроет окно снова.
      //
      // Проверка отправителя — не перестраховка, а лечение конкретной
      // поломки. Родное событие `close` НЕ всплывает, но React разносит
      // его по своему дереву так же, как всплывающие, и обработчик
      // предка получает чужое закрытие. Окна у нас теперь вложены:
      // подтверждение сброса живёт внутри настроек, и без этой строки
      // «Отмена» в подтверждении закрывала заодно и настройки.
      onClose={(event) => {
        if (event.target !== ref.current) return;
        onClose();
      }}
      // Esc. Браузер закрыл бы окно немедленно, минуя уход, поэтому его
      // решение отменяется, а закрытие идёт обычной дорогой — через
      // состояние снаружи. Проверка отправителя нужна по той же причине,
      // что и у `close`: React разносит и это событие по своему дереву.
      onCancel={(event) => {
        if (event.target !== ref.current) return;
        event.preventDefault();
        onClose();
      }}
      // Клик мимо окна. У модального `dialog` подложка — часть самого
      // элемента, поэтому щелчок по ней приходит с `target` равным
      // диалогу. Отступов у него нет намеренно: с ними в эту же ветку
      // попадали бы клики по полям внутри окна.
      onClick={(event) => {
        if (event.target === ref.current) onClose();
      }}
      aria-labelledby={titleId}
      className={cn(
        // Имя для появления и ухода: сама хореография — в `globals.css`,
        // потому что закрытию нужны `@starting-style` и `allow-discrete`,
        // а их утилитами Tailwind не выразить.
        "modal",
        // `overflow-hidden` на самой коробке — не мелочь, а починка.
        // Прокручиваться в окне должно ТЕЛО, у него для этого и стоит
        // `overflow-y-auto`. Но коробка тоже расползалась под содержимым и
        // заводила вторую полосу: замер при открытых настройках показывал
        // две прокручиваемые области сразу — коробка 991 точка содержимого
        // на 680 высоты и тело 995 на 623. Человек видел две полосы рядом и
        // не знал, какую тянуть.
        //
        // Высота поднята с 85 до 92 сотых экрана: полоса остаётся (все
        // настройки в высоту экрана телефона не поместятся никак), но
        // прокручивать приходится меньше.
        "m-auto w-[min(44rem,calc(100vw-2rem))] max-h-[min(92dvh,52rem)] overflow-hidden",
        // Заливка НЕПРОЗРАЧНАЯ, и это не вкусовщина.
        // -------------------------------------------------------------
        // Окно было прозрачным, а страница под ним размывалась
        // (`backdrop-filter` у затемнения). На тёмной теме это ещё
        // читалось, а на светлой — нет: сквозь окно просвечивала сетка на
        // год, поля формы стояли на клетках календаря, и глазу не за что
        // было зацепиться, где кончается страница и начинается вопрос.
        //
        // Теперь окно устроено так же, как лист на телефоне, — тот, что
        // занимает экран целиком: своя бумага, своя шапка, прокрутка
        // внутри тела. Разница между ними только в размере, а не в том, из
        // чего они сделаны.
        //
        // И оно ЛОВИТ СВЕТ, как всякая поднятая поверхность приложения:
        // блик по верхней кромке, тень вниз (`lit`). Не ловило только оно
        // — самая поднятая вещь на экране стояла плоским серым щитом среди
        // карточек, у которых свет есть. Тень при этом своя, крупнее
        // обычной: у окна и подъём другой (`modal-lift` в `globals.css`).
        "lit modal-lift rounded-xl bg-paper p-0 text-ink",
        // Цвета у родного затемнения нет: оно рисуется в верхнем слое
        // браузера, выше любого `z-index`, и утянуло бы за собой лампу.
        // Гасит страницу отдельный слой (`.scrim` в `globals.css`), а
        // `::backdrop` остаётся тем, чем и был, — ловушкой нажатий мимо
        // окна.
        // Вариантом `open:` задан ТОЛЬКО показ — и только он и должен быть
        // им задан. Направление столбца стоит без условия, и это не
        // косметика: закрытие теперь идёт переходом, и всё это время окно
        // ещё показано (`display` держится `allow-discrete`), а вот класс
        // `open:flex-col` в первый же кадр закрытия отваливается. Шапка и
        // тело вставали в РЯД и разъезжались по горизонтали — окно
        // перекашивало ровно в тот миг, когда оно должно тихо гаснуть.
        "flex-col open:flex",
        sheet && [
          "sheet",
          "max-sm:m-0 max-sm:h-dvh max-sm:max-h-none",
          // Ширина В ДОЛЮ ОТ ОКНА, а не `100vw`: `vw` считает и место,
          // оставленное под полосу прокрутки, а рисовать в этом месте лист
          // всё равно не может — оно закрашивается поверх верхнего слоя. За
          // `100vw` лист лез под полосу и получал вдоль правого края
          // непрокрашенную кромку.
          "max-sm:w-full max-sm:max-w-none",
          "max-sm:rounded-none max-sm:border-0",
          // Затемнения под листом нет — он и так закрывает экран целиком, —
          // и решает это правило `.scrim` в `globals.css`: класс `sheet`
          // здесь и есть та примета, по которой оно лист узнаёт.
        ],
        className,
      )}
    >
      <header
        className={cn(
          // Линии под шапкой нет. Линовка в этом приложении живёт ВНУТРИ
          // карточек, разделяя строки одного списка, а не обводит блоки
          // снаружи; полоса поперёк окна читалась как рамка чужой
          // программы. Шапку от тела отделяет поле, и этого довольно:
          // заголовок набран другим шрифтом и стоит один в строке.
          "flex shrink-0 items-start gap-4 px-5 pt-4 pb-2",
          // Шапка листа встаёт ровно на место шапки страницы: та же высота
          // содержимого (`4rem`), те же поля (`px-6`), та же вертикальная
          // середина.
          //
          // Высота с добавкой в точку — не придирка. У шапки страницы линии
          // снизу нет, у шапки листа есть, а размеры здесь считаются по
          // внешнему краю (`border-box`): при ровных четырёх ремах линия
          // съедала бы точку у содержимого.
          sheet && "max-sm:h-[calc(4rem+1px)] max-sm:items-center max-sm:px-6 max-sm:py-0",
          headerClassName,
        )}
      >
        {/* Заголовок — голосом сайта: тот же наборный шрифт, прописные и
            разрядка, что у знака в шапке, у названий месяцев и у подписей
            в карточках. Раньше он был набран обычным текстом на два
            кегля крупнее — единственная строка во всём приложении,
            набранная так. */}
        <h2
          id={titleId}
          className="min-w-0 flex-1 font-display text-base font-bold uppercase leading-6 tracking-wide"
        >
          {title}
        </h2>
        <button
          type="button"
          onClick={onClose}
          aria-label="Закрыть"
          className={cn(
            // Имя класса — зацепка для перехода: у листа крестик проступает
            // вместе с заголовком, а не стоит готовым над ещё видимой
            // страницей.
            "modal-close",
            "-mr-1.5 shrink-0 cursor-pointer rounded-lg p-1.5 text-ink-faint",
            // В обычном окне шапка выровнена по верху, и крестик поднят к
            // первой строке заголовка. У листа шапка выровнена по середине,
            // и подъём увёл бы крестик выше неё.
            sheet && "max-sm:mt-0",
            "border border-transparent transition-colors hover:border-ink-muted hover:text-ink",
            "focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-trace",
          )}
        >
          <X className="size-4" />
        </button>
      </header>

      {/* `flex-auto` и `min-h-0` — вместе, и оба обязательны: почему именно
          так, написано у самого окна. `overscroll-contain` не пускает
          прокрутку дальше края тела: докрутив список до низа, человек на
          телефоне утаскивал за собой страницу под окном. */}
      <div
        // Метка для содержимого, которому нужно знать, сколько его СЕЙЧАС
        // видно: тело окна и есть та коробка, за край которой уходит
        // прокрутка. Ищут её снизу вверх (`settings-tabs.tsx`).
        data-modal-body
        className={cn(
          // Поля тела и шапки совпадают по горизонтали: заголовок стоит
          // ровно над содержимым, а не с уступом в четыре точки.
          "min-h-0 flex-auto overflow-y-auto overscroll-contain bg-paper px-5 pt-2 pb-5",
          sheet && "max-sm:px-4",
          bodyClassName,
        )}
      >
        {children}
      </div>
    </dialog>
  );
}

