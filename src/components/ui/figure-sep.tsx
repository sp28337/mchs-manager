import { cn } from "@/lib/utils/cn";

/**
 * Иглы между тремя главными числами полосы итога.
 *
 * Отдельным модулем и без `"use client"` намеренно: заглушка рабочего экрана
 * собирается на сервере, и константа, вынесенная из клиентского модуля
 * (`summary-figure.tsx`), пришла бы туда не строкой, а ссылкой на клиентский
 * код — класс из неё не прочесть. Здесь ни состояния, ни эффектов, только
 * разметка, и она одинакова на сервере и в браузере.
 */

/**
 * Строка из трёх главных чисел с иглами в просветах.
 *
 * Дорожек пять: число, нулевая дорожка под иглу, число, игла, число. Нулевая
 * дорожка не занимает места сама, но по обе стороны от неё — по зазору, и два
 * зазора по половине дают прежний просвет между числами: сетка по ширине
 * осталась ровно той, какой была до игл, а игла стоит точно посередине просвета.
 * Поэтому зазор в каждой из строк (`gap-x-*`) написан ПОЛОВИНОЙ прежнего:
 * `gap-x-5` стал `gap-x-2.5`. Просвет, который читался как «20 точек», теперь
 * «10 + игла + 10».
 *
 * Классы написаны целиком, а не собраны из переменной: Tailwind находит их в
 * исходнике как строки. Три строки — расчёт, его эталон для замера и заглушка
 * рабочего экрана, плюс первый экран, — берут отсюда одну и ту же раскладку, и
 * разойтись по числу дорожек им нельзя.
 */
export const FIGURE_TRIO =
  "grid grid-cols-[minmax(0,1fr)_0_minmax(0,1fr)_0_minmax(0,1fr)] items-center";

/**
 * Игла между главными числами — та же, что делит цифры над месяцем
 * (`MetaSep` в `month-grid.tsx`) и стоит в названии сайта (`.mark-needle`):
 * сходится в точку к обоим концам, одна точка в ширину, цвет подписи вполсилы.
 *
 * Выше, чем над месяцем: там она стоит между строками мелкого шрифта, а здесь
 * между колонками «число над подписью», и игла в десять точек между блоками
 * вдвое выше потерялась бы. Но короче самих блоков — она делит, а не огораживает.
 * На первом экране числа крупнее вдвое, и игла растёт вместе с ними и в
 * полторы точки, как в названии сайта.
 *
 * Скрыта от программы чтения целиком: «вертикальная черта» между числами вслух
 * ничего не значит. Элемент в списке определений допустим — это `div`.
 */
export function FigureSep({ size }: { size?: "hero" }) {
  return (
    <div
      aria-hidden
      className={cn(
        "mark-needle justify-self-center bg-current text-ink-muted opacity-50",
        size === "hero" ? "h-10 w-[1.5px] md:h-12 xl:h-14" : "h-8 w-px",
      )}
    />
  );
}
