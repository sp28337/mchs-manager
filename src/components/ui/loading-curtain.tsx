"use client";

import { useEffect, useRef, useState } from "react";

import { cn } from "@/lib/utils/cn";

import { LoadingMark } from "./loading-mark";

/**
 * Плёнка загрузки: знак на листе цвета страницы поверх неё — и её плавный уход,
 * когда страница готова.
 *
 * --- Зачем она уходит, а не исчезает -----------------------------------------
 *
 * Знак стоял на экране, пока что-то не готово, а потом пропадал вместе со своим
 * листом в один кадр, и под ним оказывалась готовая страница. Рывок выходил тем
 * заметнее, чем дольше человек смотрел на спокойный знак: страница возникала,
 * как щелчок выключателя.
 *
 * Теперь готовая страница рисуется ПОД плёнкой, а плёнка растворяется за
 * `CURTAIN_EXIT_MS` с замедлением к концу. Страница проступает сквозь неё, а не
 * подменяет её; знак тает вместе с листом, потому что лежит на нём.
 *
 * Пользуются два места, и вид у них один: экран расчёта, пока читается профиль
 * (`calculator-screen.tsx`), и переход между страницами, затянувшийся дольше
 * ожидания (`navigation-loading.tsx`). Различаются они только появлением —
 * `variant`. Лист у обоих цвета самой страницы (`body`), поэтому, когда одна
 * плёнка передаёт место другой — переход открыл экран расчёта, — тон не
 * меняется, а меняется только то, что под листом.
 *
 * --- Как она растворяется ------------------------------------------------------
 *
 * Не классом с переходом и не ключевыми кадрами, а Web Animations из кода, и вот
 * почему. К этому мигу плёнка могла быть где угодно на пути своего появления
 * (`.nav-loading` проступает 200 мс), а знак — не успеть даже начать: у него
 * задержка на тот случай, когда профиль читается мгновенно. Ключевые кадры «от
 * единицы до нуля» стартовали бы с единицы: плёнка, не дойдя до плотности,
 * скакнула бы к ней и только потом пошла вниз, а знак, которого ещё не было
 * видно, мелькнул бы призраком посреди ухода.
 *
 * Поэтому в миг ухода текущая прозрачность читается как есть, анимации
 * появления снимаются, знак замирает на том, что был, — и от этого значения
 * плёнка идёт к нулю. Невидимый знак остаётся невидимым. Вспышки клеток внутри
 * знака не трогаются: они бегут, пока плёнка тает.
 *
 * Тем, кто просил поменьше движения (`prefers-reduced-motion`), плёнка уходит
 * сразу: общее правило `globals.css` на Web Animations не распространяется,
 * поэтому условие проверяется здесь. Там, где Web Animations нет (старые
 * браузеры, `jsdom`), плёнка просто снимается через то же время.
 *
 * --- Когда она уходит ---------------------------------------------------------------
 *
 * Не в тот миг, когда страница поставлена в разметку, а когда она затихла
 * (`whenSettled`). Замер в Chromium показал: в этот миг React впервые рисует
 * весь график, и основной поток занят — в сборке для сайта четверть секунды, в
 * режиме разработки около трёх четвертей, на слабом телефоне секунды. Растворение,
 * начатое посреди этой работы, стоит на месте, а потом идёт рывками между долгими
 * задачами: сама прозрачность считается отдельно от потока, но стартует она с
 * первым кадром после работы, а числа и клетки знака, которые рисует основной
 * поток, дёргаются. Знак при этом остаётся на экране и ничего не обещает: он
 * лучше пустой паузы и рывков.
 *
 * --- Что остаётся человеку ---------------------------------------------------------
 *
 * С момента «готово» плёнка не ловит нажатий (`pointer-events-none`) и скрыта от
 * программы чтения (`aria-hidden`): страница под ней готова, и пользоваться ею
 * можно, как только она показалась. Признак — `data-leaving`.
 */

/** Сколько плёнка растворяется. Где анимаций нет, столько же она остаётся в разметке. */
export const CURTAIN_EXIT_MS = 400;

/** Признак на корне страницы, пока плёнка растворяется (его читает `globals.css`). */
const FADING = "data-curtain-fading";

/** Как часто проверять, что страница затихла. */
const SETTLE_TICK_MS = 16;
/** Опоздание проверки, за которым главный поток считается занятым. */
const SETTLE_LATE_MS = 12;
/** Сколько проверок подряд должны прийти вовремя, чтобы страница считалась затихшей. */
const SETTLE_CALM_TICKS = 4;

/** Меньше этого плёнка после «готово» не ждёт: столько идут подряд спокойные проверки. */
export const CURTAIN_SETTLE_MIN_MS = SETTLE_TICK_MS * SETTLE_CALM_TICKS;
/** Дольше этого плёнка не ждёт никогда: слабое устройство не должно держать её вечно. */
export const CURTAIN_SETTLE_MAX_MS = 1500;

/**
 * Дождаться, пока страница под плёнкой затихнет; вернуть то, что ожидание
 * отменяет.
 *
 * «Готово» у страницы — это момент, когда React поставил её в разметку. Но на
 * этом работа не кончается: браузер считает стили и раскладку сотен клеток,
 * срабатывают эффекты, замеры и отсчёт чисел. Всё это занимает главный поток на
 * 200–700 мс, и растворение, начатое в этот миг, стояло бы на месте, а потом шло
 * рывками между долгими задачами. Поэтому плёнка со знаком остаётся на экране,
 * пока всё не уляжется, и растворяется уже по затихшей странице.
 *
 * Затихло — это несколько проверок подряд, пришедших вовремя. Проверка — обычный
 * таймер: долгая задача откладывает его на свою длину, и опоздание показывает,
 * что поток занят. Считать кадры (`requestAnimationFrame`) тут не нужно: нужно
 * знать только, свободен ли поток, а не доходит ли до экрана кадр, — и таймер
 * при этом одинаково работает и в браузере, и под тестовыми часами.
 *
 * Кроме потока — шрифты: пока они грузятся, текст на странице меняет вид, и
 * подмена под растворяющейся плёнкой была бы видна.
 *
 * Ждать вечно нельзя, поэтому есть потолок (`CURTAIN_SETTLE_MAX_MS`): по его
 * истечении плёнка растворяется как есть. На вкладке в фоне таймеры замедлены до
 * секунды, и она тоже уходит по потолку.
 */
function whenSettled(done: () => void): () => void {
  let calm = 0;
  let last = Date.now();
  let tick = 0;

  const finish = () => {
    window.clearTimeout(cap);
    window.clearTimeout(tick);
    done();
  };

  const step = () => {
    const now = Date.now();
    const late = now - last - SETTLE_TICK_MS;
    last = now;

    calm = late <= SETTLE_LATE_MS ? calm + 1 : 0;
    const fontsLoading = document.fonts?.status === "loading";

    if (calm >= SETTLE_CALM_TICKS && !fontsLoading) finish();
    else tick = window.setTimeout(step, SETTLE_TICK_MS);
  };

  const cap = window.setTimeout(finish, CURTAIN_SETTLE_MAX_MS);
  tick = window.setTimeout(step, SETTLE_TICK_MS);

  return () => {
    window.clearTimeout(cap);
    window.clearTimeout(tick);
  };
}

function exitDuration(): number {
  if (typeof window.matchMedia !== "function") return CURTAIN_EXIT_MS;
  return window.matchMedia("(prefers-reduced-motion: reduce)").matches ? 0 : CURTAIN_EXIT_MS;
}

/**
 * Начать растворение; вернуть то, что его отменяет. Когда плёнка растворилась,
 * вызывается `done`.
 *
 * Конец определяет сама анимация, а не таймер на `CURTAIN_EXIT_MS`. Таймер идёт
 * по часам с момента вызова, а анимация стартует с первым кадром после него, и
 * если страница под плёнкой только что рисовалась тяжело (так и бывает: на экране
 * расчёта это сотни клеток), кадр приходит с опозданием. Таймер снял бы плёнку
 * на середине растворения — тем самым рывком, ради отказа от которого она и
 * уходит плавно. Таймер остаётся только там, где анимации нет.
 *
 * Прозрачность плёнки и знака читается до того, как с них снимутся анимации
 * появления: после снятия браузер вернул бы им обычную единицу.
 */
function dissolve(film: HTMLElement, ms: number, done: () => void): () => void {
  if (ms === 0 || typeof film.animate !== "function" || typeof film.getAnimations !== "function") {
    const timer = window.setTimeout(done, ms);
    return () => window.clearTimeout(timer);
  }

  const mark = film.querySelector<SVGElement>(".loading-mark");
  if (mark !== null) {
    const opacity = getComputedStyle(mark).opacity;
    mark.getAnimations().forEach((animation) => animation.cancel());
    mark.style.opacity = opacity;
  }

  const from = getComputedStyle(film).opacity;
  film.getAnimations().forEach((animation) => animation.cancel());
  const fade = film.animate([{ opacity: from }, { opacity: 0 }], {
    duration: ms,
    easing: "ease-out",
    fill: "forwards",
  });

  // Пока плёнка прозрачна не до конца, браузер пересчитывает размытие дымки
  // (`backdrop-filter` у `.veil`) каждый кадр: на экране расчёта это 36 кадров в
  // секунду против 52 без него. На время растворения оно выключено, а потом
  // возвращается плавно (`globals.css`, `data-curtain-fading`).
  const root = document.documentElement;
  root.setAttribute(FADING, "");

  fade.onfinish = () => {
    root.removeAttribute(FADING);
    done();
  };

  return () => {
    fade.onfinish = null;
    fade.cancel();
    root.removeAttribute(FADING);
    if (mark !== null) mark.style.opacity = "";
  };
}

export function LoadingCurtain({
  show,
  label,
  variant = "page",
}: {
  /** Страница не готова: плёнка на месте. Стала готова — плёнка уходит. */
  show: boolean;
  /**
   * Слово для программы чтения: рисунок ей пуст (`aria-hidden`), и без слова
   * человек остался бы молча перед пустой страницей.
   */
  label: string;
  /**
   * `page` — экран, на котором, кроме ожидания, ничего нет: лист плотный с
   * первого кадра, а знак проступает не сразу (быстрое чтение профиля не
   * должно начинаться со вспышки того, что тут же растворится).
   * `navigation` — поверх покидаемой страницы: лист проступает за 200 мс, а у
   * знака задержки нет (`.nav-loading` в `globals.css`).
   */
  variant?: "page" | "navigation";
}) {
  const film = useRef<HTMLDivElement>(null);
  // Плёнка остаётся в разметке и после `show = false`: пока она уходит.
  const [mounted, setMounted] = useState(show);
  // Показали снова — в разметку снова. Состояние, выведенное из свойства,
  // выставляется при отрисовке, а не в эффекте: иначе лишний кадр плёнка не
  // рисовалась бы вовсе.
  if (show && !mounted) setMounted(true);

  useEffect(() => {
    if (show) return;
    const element = film.current;
    if (element === null) return;

    // Страница готова — но плёнка уходит не сразу, а когда страница затихла
    // (`whenSettled`): растворение по занятому потоку рывками хуже, чем
    // небольшая задержка перед ним.
    let undo: () => void = () => undefined;
    const stop = whenSettled(() => {
      undo = dissolve(element, exitDuration(), () => setMounted(false));
    });

    return () => {
      stop();
      undo();
    };
  }, [show]);

  if (!show && !mounted) return null;

  return (
    // `fixed`, а не высота в `svh`: у `body` внизу поле под нижнюю дымку, и лист
    // в высоту окна плюс это поле прокручивался бы на его величину — с полосой
    // прокрутки, которая сдвигала бы знак с оси, и с пустым хвостом.
    // Закреплённый слой места в потоке не занимает, а центр у него — центр
    // видимого окна, в том числе на телефоне с уезжающей адресной строкой.
    //
    // Выше шапки и боковых знаков (z-100), выше перечня у дня (z-115) — под
    // плёнкой страница, которую показывать рано или уже нечего. Ниже лампы
    // (z-120): она общая у всех страниц, и гаснуть на время загрузки ей
    // незачем.
    <div
      ref={film}
      data-curtain={variant}
      data-leaving={show ? undefined : ""}
      aria-hidden={show ? undefined : true}
      className={cn(
        "fixed inset-0 z-[118] grid place-items-center bg-paper-sunken",
        variant === "navigation" && "nav-loading",
        !show && "pointer-events-none",
      )}
    >
      <LoadingMark />
      <p className="sr-only" role="status">
        {label}
      </p>
    </div>
  );
}
