/**
 * Подсветка строки меню под курсором — одна на все меню и окошки выбора.
 *
 * Плавно и коротко: заливка и входит, и уходит за две десятых секунды.
 * Стандартный переход Tailwind (150 мс, `cubic-bezier(0.4, 0, 0.2, 1)`)
 * стартует почти рывком — за первые 50 мс заливка уже на половине, и на
 * глаз это скачок, а не появление. (`ease-in-out` в Tailwind 4 — та же самая
 * кривая, поэтому кривая здесь задана числами.) Симметричная кривая
 * разгоняется мягко и так же мягко садится, и две соседние строки, пока
 * курсор идёт по списку, перетекают друг в друга: одна гаснет, другая
 * разгорается.
 *
 * Дольше нельзя: на длинном списке подсветка начинала бы отставать от
 * руки. `hover:` в Tailwind 4 сам ограничен устройствами с наведением, так
 * что на телефоне строка не залипает в подсвеченном виде после касания.
 */
export const MENU_ROW_HOVER =
  "transition-colors duration-200 ease-[cubic-bezier(0.45,0,0.55,1)] hover:bg-paper-sunken";

/**
 * Просвет между строками меню и окошек выбора.
 *
 * Без него подсветка соседних строк сливалась в одну плашку: наведённая
 * строка и выбранная под ней, обе на `paper-sunken`, стояли вплотную и
 * читались одним куском с двумя скруглёнными углами посередине. Четыре
 * точки — столько же, сколько отступ окошка от края строки (`p-1.5` минус
 * скругление), так что поле вокруг строк и между ними на глаз одно.
 *
 * Сеткой, а не `flex-col`: в окошке с прокруткой (`max-h-[60svh]`) строки
 * flex-колонки при нехватке места сжимаются, а строки сетки — нет.
 */
export const MENU_LIST = "grid gap-1";
