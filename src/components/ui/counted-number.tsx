"use client";

import {
  useEffect,
  useLayoutEffect,
  useRef,
  useState,
  type CSSProperties,
} from "react";

import { COUNT_MS } from "@/lib/motion";

/**
 * Число, которое не подменяется, а доходит до нового значения.
 *
 * --- Зачем ---------------------------------------------------------------
 *
 * Человек правит календарь и смотрит на полосу итога: что стало с нормой,
 * что с переработкой. Числа там меняются все разом, и подменённые
 * мгновенно они не отвечают на главный вопрос — КАКОЕ из них двинулось.
 * Особенно когда разница в один час: «144» и «143» на одном месте глаз не
 * различает вовсе, если между ними ничего не происходило.
 *
 * Отсчёт до нового значения отвечает на это движением. Он же стоит на
 * первом экране, где показывает разницу между отпуском и отгулом, — и
 * деталь тут одна на оба места намеренно: числа приложения обязаны себя
 * вести одинаково, где бы они ни стояли.
 *
 * --- Почему на строке, а не на числе ---------------------------------------
 *
 * Величины приходят сюда уже готовыми строками: «1972», «15,5», «8».
 * Формат у них общий (`formatHoursTrim`), но берётся он в разных местах, и
 * протаскивать сюда ещё и правило записи значило бы завести второй
 * источник формата. Поэтому строка разбирается на месте: сколько знаков
 * после запятой у ЦЕЛИ, столько же будет у промежуточных значений, а
 * последним кадром ставится ровно та строка, которую передали, — без
 * пересчёта и без риска разойтись с ней на последнюю цифру.
 *
 * Что разобрать не удалось — «8 суток», «—», пустое место — меняется
 * подстановкой. Отсчитывать нечего.
 *
 * --- Почему место под число не сжимается ----------------------------------
 *
 * Пока число идёт от «32» к «8», оно теряет знак — а с ним и ширину. В
 * полосе итога число стоит в строку с подписью, и строка при этом
 * дёргается влево-вправо: подпись отъезжает, потому что соседнее число
 * стало короче. Дрожь эта чужая — двигалось одно число, а поехала вся
 * плашка.
 *
 * Поэтому число живёт в коробке, которая НЕ УМЕНЬШАЕТСЯ: её ширина —
 * самая длинная запись, какую это число показывало. Растёт коробка сразу,
 * а сужаться ей незачем: место под число уже занято, и второй раз его
 * никто не просит.
 *
 * Ширина считается в `ch` и работает потому, что цифры здесь моноширинные
 * (`tabular-nums`): один знак — одна и та же ширина, что «1», что «8».
 * Прижато содержимое вправо, к своей единице измерения: запас тогда
 * достаётся промежутку с подписью, где он и так есть.
 *
 * --- Уважение к `prefers-reduced-motion` ----------------------------------
 *
 * Отсчёта нет вовсе: новое значение встаёт сразу. Числа при этом не
 * страдают — движение здесь помогает заметить перемену, но не является
 * самой переменой.
 */

export function CountedNumber({ value }: { value: string }) {
  const { shown, reserve, roll, up } = useCountedNumber(value);
  return (
    <span
      className="inline-block text-right tabular-nums"
      style={{ minWidth: `${reserve}ch` }}
    >
      {[...shown].map((char, index) => (
        <span
          // Ключ считается от ПРАВОГО края: барабан у единиц один и тот
          // же, сколько бы знаков ни было в числе. Смена знака в ключе
          // означает новый элемент — с него и начинается оборот.
          key={`${shown.length - 1 - index}:${char}`}
          className={roll > 0 ? "digit-roll" : undefined}
          style={
            roll > 0
              ? ({ "--roll": roll, "--dir": up ? 1 : -1 } as CSSProperties)
              : undefined
          }
        >
          {char}
        </span>
      ))}
    </span>
  );
}

/**
 * Строка, которую надо показать сейчас: цель или значение по дороге к ней.
 *
 * Первая отрисовка отдаёт цель как есть — и на сервере, и в браузере.
 * Отсчёт начинается только со ВТОРОГО значения: иначе экран, едва
 * открывшись, принимался бы крутить все свои числа от нуля, хотя ничего
 * ещё не менялось.
 */
export function useCountedNumber(target: string): {
  shown: string;
  /** Сколько знаков держать под число: столько же, сколько было в самой
   *  длинной его записи за жизнь этого экрана. */
  reserve: number;
  /** Скорость барабана: 1 в начале хода, 0 в конце и в покое. */
  roll: number;
  /** Куда идёт счёт: вверх или вниз. */
  up: boolean;
} {
  const [tween, setTween] = useState<Tween | null>(null);
  const [reserved, setReserved] = useState(target.length);
  const shown = tween?.text ?? target;

  // Что стоит на экране прямо сейчас. Отсчёт начинается отсюда, а не от
  // прежней цели: если человек правит календарь быстрее, чем идёт
  // перещёлкивание, новое значение подхватывается с полдороги, а не
  // прыгает назад к тому, от чего шли.
  const displayed = useRef(shown);
  const frame = useRef(0);

  useCountEffect(() => {
    const from = parse(displayed.current);
    const to = parse(target);

    if (from === null || to === null || from === to || reducedMotion()) {
      displayed.current = target;
      setTween(null);
      return;
    }

    const up = to > from;

    // Первым кадром — то, что уже стоит на экране, а не новая цель.
    //
    // Без этой строки браузер успевал нарисовать итог ДО того, как к нему
    // пошёл отсчёт: число мигало конечным значением, отскакивало назад и
    // только потом шло. Один кадр, но именно он и выдавал ответ раньше
    // движения, ради которого весь отсчёт и заведён.
    //
    // Лишняя отрисовка здесь неизбежна: сравнить старое значение с новым
    // можно только после того, как новое пришло, а исправить картинку
    // нужно до того, как её увидят.
    setTween({ text: displayed.current, roll: 1, up });

    const digits = decimalsOf(target);
    const startedAt = performance.now();

    const step = (now: number) => {
      const passed = Math.min(1, (now - startedAt) / COUNT_MS);
      if (passed < 1) {
        // Замедление к концу: число подходит к своему значению, а не
        // останавливается на нём с разбегу.
        const eased = 1 - Math.pow(1 - passed, 3);
        const text = format(from + (to - from) * eased, digits);
        displayed.current = text;
        // Скорость барабана — производная того же замедления, приведённая
        // к единице: полный ход в начале, полная остановка в конце. Из неё
        // берутся и размытие, и подскок цифры, поэтому «быстро» и «резко»
        // не расходятся между собой ни на кадр.
        setTween({ text, roll: Math.pow(1 - passed, 2), up });
        // Запас считается по дороге, а не заранее: длина промежуточных
        // значений известна только здесь. Обновление идёт из кадра
        // анимации, вместе с самим числом, и лишней отрисовки не даёт.
        setReserved((current) => Math.max(current, text.length));
        frame.current = requestAnimationFrame(step);
        return;
      }
      // Последним кадром — переданная строка, а не пересчитанная: только
      // так итог гарантированно совпадает с тем, что показывает расчёт.
      displayed.current = target;
      setTween(null);
    };

    frame.current = requestAnimationFrame(step);
    return () => cancelAnimationFrame(frame.current);
  }, [target]);

  return {
    shown,
    reserve: Math.max(reserved, shown.length),
    roll: tween?.roll ?? 0,
    up: tween?.up ?? true,
  };
}

/** Кадр отсчёта: что показать и с какой скоростью крутится барабан. */
interface Tween {
  text: string;
  roll: number;
  up: boolean;
}

/** Число из записи вида «1972» или «15,5». Всё прочее — не число. */
function parse(text: string): number | null {
  if (!/^-?\d+(,\d+)?$/.test(text)) return null;
  return Number(text.replace(",", "."));
}

/** Сколько знаков после запятой у цели: столько же будет по дороге к ней. */
function decimalsOf(text: string): number {
  const comma = text.indexOf(",");
  return comma === -1 ? 0 : text.length - comma - 1;
}

function format(value: number, digits: number): string {
  return value.toFixed(digits).replace(".", ",");
}

function reducedMotion(): boolean {
  return window.matchMedia("(prefers-reduced-motion: reduce)").matches;
}

/**
 * Эффект ДО отрисовки — и безопасный на сервере.
 *
 * Отсчёт правит то, что уже посчитано к отрисовке, поэтому обычный
 * эффект здесь опаздывает на кадр. На сервере же `useLayoutEffect`
 * ругается в консоль и всё равно не выполняется. Выбор делается один раз
 * при загрузке модуля и потому не нарушает порядок вызовов.
 */
const useCountEffect = typeof window === "undefined" ? useEffect : useLayoutEffect;
