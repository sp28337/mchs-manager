/**
 * Как вид суток выглядит в клетке: буква и цвет.
 *
 * Отдельным словарём, потому что мест, где это нужно, три: сетка графика
 * вместе с легендой, кольцо видов вокруг клетки (`day-ring.tsx`), где вид
 * суток и ВЫБИРАЮТ такой же клеткой, и перечень внесённых правок.
 * Разъедься они хоть буквой, хоть оттенком — и человек, нажавший в кольце
 * на знакомый значок, не узнал бы его потом на сетке.
 */
import type { AbsenceKind } from "../domain/value-objects";

/**
 * Код работы помимо графика в клетке — один на все её виды.
 *
 * --- Почему один -----------------------------------------------------------
 *
 * Видов вызова в данных шесть (вызов, соревнования, сбор, резерв, праздник,
 * выборы), и у каждого был свой двухбуквенный код: «СР», «СБ», «РЗ».
 * Человеку это стоило шести строк легенды и шести кодов, которые надо
 * помнить, а расчёту не давало ничего: все шесть считаются одинаково —
 * работа сверх графика по тем же правилам.
 *
 * Поэтому в клетке теперь один код. Отмечают тоже один вид — «Вызов»; в
 * старых профилях остальные пять сохранены как есть (схема их принимает и
 * будет принимать), и различает их подпись клетки и перечень внесённых
 * изменений, где для названия есть место целой строкой. Так же и старые
 * коды: в клетках их больше нет, но записи, ими помеченные, целы — им
 * просто досталась общая буква.
 *
 * --- Почему «Р» -------------------------------------------------------------
 *
 * Потому что это рабочий день — единственное, что человеку про эти сутки и
 * нужно знать: он в них работал, хотя по графику не должен был. «ВЗ» —
 * сокращение от «вызов», и сокращение это ведомственное: оно объясняет,
 * КАК человека позвали, а не что в сутках произошло.
 *
 * Та же буква стоит в производственном календаре у рабочего дня по закону
 * (`DAY_TYPE_MARK`), и это не путаница, а то же самое слово: там «по закону
 * рабочий», здесь «отработан сверх графика». Сетки эти показываются по
 * очереди, одна вместо другой, и рядом эти две буквы не встречаются.
 */
export const CALLOUT_MARK = "Р";

/**
 * Буква вместо прочерка в клетке пропущенной смены.
 *
 * Раньше все семь видов отсутствия выглядели одинаково: «—» на сигнальном
 * фоне. Но человек, глядя на год, ищет не «отсутствие вообще» — он ищет
 * конкретный случай, из-за которого спорит: где стоял больничный, где
 * отпуск, где отгул. Прочерк на этот вопрос не отвечал, и приходилось
 * наводить курсор на каждую клетку.
 *
 * Обозначения взяты из табеля Т-13, а не выдуманы: их узнает и тот, кто
 * заполняет табель по ту сторону спора.
 */
export const ABSENCE_MARK: Record<AbsenceKind, string> = {
  annual_leave: "О",
  // «Д» из того же табеля Т-13: дополнительный отпуск там обозначается
  // именно так, и двум знакам в клетке место есть — коды вызовов тоже
  // двухбуквенные.
  extra_leave: "Д",
  sick_leave: "Б",
  time_off_in_lieu: "В",
  study_leave: "У",
};

/**
 * Цвет клетки по виду отсутствия.
 *
 * Свой цвет у каждого вида, кроме отпуска: он остаётся сигнальным, каким
 * был. Тона разведены не на глаз — между насыщенными цветами интерфейса
 * не меньше 26° по кругу, значения и расчёт в `globals.css`.
 *
 * Пунктирная рамка общая у всех: она означает «смена по графику была, но
 * не состоялась», и это свойство у семи видов одно на всех. Цвет отвечает
 * на следующий вопрос — почему именно не состоялась.
 */
