import { describe, expect, it } from "vitest";

import { fileNameOf } from "./save-to-file";

/**
 * Имя файла собирается из имени профиля, а его человек пишет свободной
 * строкой. Значит, туда попадает всё: косые черты, кавычки, перевод
 * строки из буфера обмена, одни пробелы. Ни один из этих случаев не имеет
 * права ни сорвать сохранение, ни создать файл не там, где ждали.
 */
describe("имя файла выгрузки", () => {
  it("обычное имя остаётся как есть", () => {
    expect(fileNameOf("Основной график")).toBe("Основной график");
  });

  it("разделители путей не уводят файл в другую папку", () => {
    expect(fileNameOf("график 1/3")).toBe("график 1-3");
    expect(fileNameOf("C:\\смены")).toBe("C--смены");
  });

  it("управляющие символы выбрасываются", () => {
    expect(fileNameOf("график\nна год")).toBe("график на год");
  });

  it("точки и пробелы по краям снимаются — иначе файл скрытый", () => {
    expect(fileNameOf("  .график.  ")).toBe("график");
  });

  it("пустое имя не даёт файла без имени", () => {
    expect(fileNameOf("   ")).toBe("график");
    expect(fileNameOf("///")).toBe("график");
  });

  it("длинное имя обрезается: у файловых систем есть предел", () => {
    expect(fileNameOf("а".repeat(300))).toHaveLength(100);
  });
});
