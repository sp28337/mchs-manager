import type { IsoDate } from "../domain/plain-date";

/**
 * Сколько месяцев показано на сетке: от месяца начала отрезка до месяца
 * его конца включительно, и частичный крайний месяц считается целым — как
 * его рисует сетка (`ShiftStrip`): первое число после начала отсчёта,
 * середина месяца при «Онлайн», всё равно одна сетка на месяц.
 *
 * Конец отрезка — первый день ПОСЛЕ него (`periodEnd` расчёта): для года
 * это 1 января следующего, и месяц, в который он падает, не считается.
 */
export function monthsInPeriod(start: IsoDate, end: IsoDate): number {
  const index = (iso: string) => Number(iso.slice(0, 4)) * 12 + Number(iso.slice(5, 7)) - 1;
  const partial = Number(end.slice(8, 10)) > 1 ? 1 : 0;
  return Math.max(0, index(end) + partial - index(start));
}

/**
 * Колонок в «компактной» раскладке: столько, чтобы ряды вышли ровными.
 *
 * В ряду помещается `perRow` месяцев (это масштаб), но заполнять его до
 * краю необязательно: шесть месяцев при пяти в ряду — это пять и один
 * одинокий, а три и три смотрятся как одно целое. Поэтому сперва считается,
 * сколько рядов понадобится при предельной ширине, а потом месяцы
 * раскладываются по ним поровну.
 *
 * Если всё влезает в один ряд — столько колонок, сколько месяцев: квартал
 * не растягивается до ширины года. Неровный остаток возможен только там,
 * где поровну не разделить (три месяца в два ряда, семь в два): последний
 * ряд короче, и сетка по середине всё равно ставит его симметрично.
 */
export function balancedColumns(count: number, perRow: number): number {
  if (count <= 0) return Math.max(1, perRow);
  if (count <= perRow) return count;
  const rows = Math.ceil(count / perRow);
  return Math.ceil(count / rows);
}
