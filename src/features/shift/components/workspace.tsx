/**
 * Рабочий экран: период, расчёт, график и отсутствия.
 *
 * Всё на одной странице намеренно. Человек смотрит на месяц и правит его
 * тут же, и разносить норму, график и правки по вкладкам значило бы
 * заставить его держать числа в голове, переходя между ними, — ровно в
 * тот момент, когда важна точность.
 *
 * --- Что стоит в боковой колонке и почему именно это --------------------
 *
 * Слева — ВВОД, справа — ВЫВОД. Слева человек говорит приложению, что он
 * знает: какой период смотрим, какая у него норма, когда он был в отпуске
 * и когда выходил помимо графика. Справа приложение отвечает: вот норма,
 * вот график, вот производственный календарь.
 *
 * Раньше и то и другое стояло одной лентой сверху вниз, и это стоило
 * человеку прокрутки на каждом шаге: чтобы посмотреть тот же график за
 * соседний месяц, приходилось листать двенадцать календарных сеток вверх,
 * переключать и листать обратно; чтобы внести отпуск и увидеть, как
 * изменилась норма, — то же самое в другую сторону.
 *
 * Колонка закреплена, поэтому ввод и его последствие видны одновременно:
 * внесённый отпуск сразу меняет норму справа, и человеку не нужно
 * запоминать, сколько было до.
 *
 * --- Чем колонка заменена на телефоне ------------------------------------
 *
 * Ничем на самой странице: там её нет вовсе. Значки блоков переехали в
 * шапку (`aside-panels`, `PanelDock`), и нажатие открывает ОДИН блок в
 * окне — тот, который значок называет.
 *
 * Колонка на трёхсотвосьмидесяти точках была бы лентой закрытых крышек над
 * расчётом: до первого числа пять нажатий. Плавающая полоска у правого
 * края, которая была здесь до шапки, эту ленту убрала, но висела поверх
 * содержимого и отнимала у календаря полосу справа. В шапке строка всё
 * равно есть, и справа в ней пусто — название сайта там скрыто.
 *
 * --- Почему все блоки колонки сворачиваются ------------------------------
 *
 * Их пять, и развёрнутыми они не помещаются ни в один экран. Открытым
 * держится только то, что нужно всегда: период и сумма. Остальное человек
 * открывает, когда вносит, — а свёрнутая крышка при этом отвечает на свой
 * вопрос без раскрытия («внесено периодов: 3», «расхождений нет»).
 *
 * --- Почему колонку можно убрать целиком ---------------------------------
 *
 * График на год и двенадцать календарных сеток — самое широкое, что есть
 * на экране, и девятнадцать рем слева им мешают. Но убрать колонку совсем
 * значило бы спрятать вход в неё: человек, свернувший её ради календаря,
 * должен видеть, куда нажать, чтобы вернуться к отпускам.
 *
 * Поэтому она сворачивается не в ничто, а в полоску значков. Значок в
 * полоске — тот же, что в заголовке блока, и нажатие на него делает сразу
 * два дела: возвращает колонку и открывает именно этот блок. Иначе
 * человек, нажавший на сирену, получил бы развёрнутую колонку и всё тот же
 * закрытый блок вызовов.
 *
 * Свёрнутость — состояние экрана, а не данных, и в профиль не пишется:
 * человек сворачивает колонку на время, пока смотрит календарь.
 *
 * --- Почему нет состояний загрузки --------------------------------------
 *
 * Считать больше нечего ждать: расчёт идёт здесь же, за доли миллисекунды,
 * и ошибок сети у него не бывает. Экран, который раньше умел показывать
 * «Считаем…» и «Сервер недоступен», теперь просто всегда показывает
 * результат — и это самое заметное следствие переноса расчёта в браузер.
 */

export interface WorkspaceProps {
  profile: StoredProfile;
  onChange: (change: (previous: StoredProfile) => StoredProfile) => void;
  onForget: () => void;
}

export function Workspace({ profile, onChange, onForget }: WorkspaceProps) {
  const periods = accountingPeriodsOf();

  // Умолчание — учётный период целиком: именно по его итогу определяется
  // переработка (ст. 104 ТК РФ), и открывать экран на месяце значило бы
  // показывать первым то число, которое ничего не решает.
  const widest = periods.at(-1) ?? "year";
  const [statutory, setStatutory] = useState<StatutoryChoice>({
    kind: widest,
    index: 0,
  });
  // Месяц хранится отдельно от периода, а не вместо него: это уточнение
  // поверх выбранного периода, и `null` значит «весь период». Раньше это
  // было одно поле с двумя режимами, и выбор месяца стирал выбранный
  // период — вернуться к нему можно было, только вспомнив, какой он был.
  const [month, setMonth] = useState<number | null>(null);

  // Выбранный отрезок — и сразу обрезанный началом отсчёта: до него
  // человек в этом графике не работал, и часы за те дни не его. Обрезка
  // стоит здесь, выше обоих расчётов, потому что отрезок у них общий: один
  // считает числа наверху, другой рисует сетку, и разойтись им нельзя.
  const chosen = countedBounds(
    month === null
      ? statutoryBounds(profile.accountingYear, statutory.kind, statutory.index)
      : monthBounds(profile.accountingYear, month),
    profile.countFrom,
  );

  // Режим «веду учёт» обрезает выбранный отрезок живым временем: по
  // сегодняшний день включительно. Сегодняшний день берётся один раз за
  // отрисовку — переживать полночь странице не приходится, её открывают
  // и закрывают в тот же день.
  const { periodStart, periodEnd } = profile.liveMode
    ? liveBounds(chosen, todayIso())
    : chosen;

  const calculation = useMemo(
    () => calculateFor(profile, periodStart, periodEnd),
    [profile, periodStart, periodEnd],
  );

  /**
   * Второй расчёт — на ВЕСЬ выбранный отрезок, для сетки.
   *
   * Числа наверху обрезаны сегодняшним днём, и это правильно: столько
   * переработки набежало на сегодня. Но сетка, обрезанная вместе с ними,
   * теряла остаток периода целиком — человек включал «Онлайн» и половина
   * квартала пропадала с экрана. Своих смен на будущее он при этом не
   * видел вовсе, хотя они известны: цикл четырёхдневный и достраивается
   * куда угодно.
   *
   * Поэтому расчётов два. Этот знает весь отрезок и нужен только для
   * показа; сутки после сегодняшних сетка гасит и в свои итоги не берёт.
   * Когда режим выключен, второго расчёта нет вовсе — отрезки совпадают.
   */
  const shown = useMemo(
    () =>
      profile.liveMode ? calculateFor(profile, chosen.periodStart, chosen.periodEnd) : null,
    [profile, chosen.periodStart, chosen.periodEnd],
  );

  // Первые сутки, которые ещё не наступили. Граница расчёта исключающая,
  // то есть это ровно она: «по сегодня» кончается завтрашним днём.
  const upcoming = profile.liveMode ? periodEnd : null;

  /**
   * Настройки на телефоне — не окно, а другое содержимое ЭТОЙ страницы.
   *
   * --- Почему состояние живёт здесь --------------------------------------
   *
   * Открытие меняет разом три места: шапку (знак называет «Настройки»),
   * полосу цифр (она становится закладками) и то, что стоит под ней
   * (анкета вместо графика). Три разных места экрана нельзя привязать к
   * состоянию одной кнопки в шапке — держать его пришлось бы здесь, откуда
   * видно всех троих.
   *
   * --- Почему это работает, только пока `isMobile` ------------------------
   *
   * На столе у настроек по-прежнему обычное плавающее окно
   * (`header-tools.tsx`): колонки и панели там никуда не убираются, и
   * подменять содержимое страницы ради него незачем. `showSettings`
   * поэтому требует оба условия разом — и если ширина экрана изменится,
   * пока настройки открыты, страница молча вернётся к обычному виду.
   */
  const isMobile = useMediaQuery("(width < 40rem)");
  const [mobileSettingsOpen, setMobileSettingsOpen] = useState(false);
  const [settingsTab, setSettingsTab] = useState<SettingsTab>("profile");
  const showSettings = isMobile && mobileSettingsOpen;

  /**
   * Открыть настройки — БЕЗ единого движения прокруткой.
   *
   * Прокрутку сюда просилась вернуть к нулю — «человек ведь смотрел на
   * какой-то месяц, а не на анкету». Расчёт был неверным: полоса цифр
   * закреплена (`position: sticky`), и прокрутка на неё не влияет вовсе —
   * она либо стоит на своём месте в потоке (прокрутка мала), либо уже
   * прилипла к кромке (прокрутка велика), и это ровно то же самое место
   * на экране что до открытия настроек, что после.
   *
   * Свой откат ломал именно это: даже пять точек прокрутки заставляли его
   * отдёргивать страницу к нулю, и полоса, только что стоявшая прилипшей,
   * дважды прыгала — сперва вслед за отдёрнутой прокруткой, потом обратно
   * в поток под короткой анкетой. Без отката браузер поджимает прокрутку
   * сам, если новая, более короткая, страница не может показать прежнюю
   * глубину, — и делает это тем же кадром, без анимации, которую можно
   * было бы заметить.
   */
  function toggleMobileSettings() {
    setMobileSettingsOpen((open) => !open);
  }

  // Что показано на сетке года. Живёт здесь, а не в самой сетке, потому
  // что от этого зависят заголовок и подпись раздела вокруг неё.
  const [yearView, setYearView] = useState<YearViewKind>("shifts");

  // День, по которому нажали в сетке. Правка идёт от дня, а не от формы
  // со списком: человек уже нашёл в календаре те сутки, из-за которых
  // спорит, и переносить их дату в отдельную форму глазами — лишний шаг,
  // в котором и ошибаются.
  const [pickedDay, setPickedDay] = useState<IsoDate | null>(null);

  return (
    <>
      {/* Шапка рисуется отсюда, а не с экрана вокруг: в ней стоят
          настройки и выгрузка профиля, а им нужен профиль вместе с
          выбранным периодом — он живёт здесь. Тянуть его наверх значило бы
          поднять туда и выбор периода, то есть половину этого экрана. */}
      <SiteHeader
        // Знак называет «Настройки» вместо «График 1|3», пока на телефоне
        // показаны они, а не сам расчёт: страница та же, читает она о себе
        // другое.
        brandLabel={showSettings ? "Настройки" : undefined}
        tools={
          <HeaderTools
            profile={profile}
            onChange={onChange}
            onForget={onForget}
            isMobile={isMobile}
            mobileSettingsOpen={mobileSettingsOpen}
            onToggleMobileSettings={toggleMobileSettings}
            // Перечень изменений в настройках ведёт в сутки, а сутки
            // открывает тот же самый выбор, что и нажатие по клетке.
            // Сетку он тоже называет: правка вида дня живёт на
            // производственном календаре, остальное — на графике.
            onOpenDay={(day, grid) => {
              setYearView(grid === "calendar" ? "calendar" : "shifts");
              setPickedDay(day);
            }}
          />
        }
      />

      {/* Поле снизу — под нижнюю панель телефона (`grid-deck.tsx`). Она
          закреплена у кромки окна и места в потоке не занимает, поэтому
          подвал уезжал бы под неё, и последняя строка страницы была бы
          нечитаемой. С `md` панели нет, и поля тоже. */}
      <main className={cn("mx-auto w-full px-6 pt-26 2xl:max-w-[2000px]", WORKSPACE_PAD)}>
      {/* Поле под именем — не про воздух: полоса с числами закрывает над
          собой двенадцать точек бумаги (щиток в `PeriodSummary`, он гасит
          просвет под шапкой), и без этого зазора щиток лёг бы прямо на
          имя. */}
      <header className="pb-12">
        <ProfileName profile={profile} onChange={onChange} />
      </header>

      {/* Итог — закреплённой полосой, календарь — во всю ширину под ней.
          Числа и сетка нужны одновременно: человек отмечает день и тут же
          смотрит, что стало с нормой. Колонкой слева это стоило календарю
          четырёхсот точек ширины, а лентой сверху — прокрутки назад через
          двенадцать сеток.

          На телефоне та же полоса умеет становиться закладками настроек
          (`settings`, ниже) — тем же способом, каким шапка выше умеет
          называть себя «Настройки»: одно место экрана, разное содержимое. */}
      <PeriodSummary
        calculation={calculation}
        accountingYear={profile.accountingYear}
        overtimeInDays={profile.overtimeInDays}
        shiftDurationHours={profile.shiftDurationHours}
        settings={{ open: showSettings, tab: settingsTab, onTab: setSettingsTab }}
      />

      <div className="space-y-10">
      {showSettings ? (
        // Настройки на месте графика — не поверх страницы, а вместо той
        // его части, что сейчас не нужна: панель управления сеткой
        // (`GridDeck`, ниже) при этом тоже скрыта — управлять ей больше
        // нечем.
        <FadeIn key={`settings-${settingsTab}`}>
          <section aria-labelledby="settings-heading" className="space-y-4">
            <h2 id="settings-heading" className="sr-only">
              {SETTINGS_TAB_LABEL[settingsTab]}
            </h2>
            {settingsTab === "profile" ? (
              <div className="space-y-4">
                <SettingsPanel profile={profile} onChange={onChange} />
                <DangerActions onForget={onForget} onChange={onChange} showReset={false} />
              </div>
            ) : (
              <ChangesList
                profile={profile}
                onChange={onChange}
                // Строка перечня ведёт в сутки, а значит и обратно на
                // страницу — раз сутки уже открыты, показывать позади них
                // ещё и анкету незачем.
                onOpenDay={(day, grid) => {
                  setMobileSettingsOpen(false);
                  setYearView(grid === "calendar" ? "calendar" : "shifts");
                  setPickedDay(day);
                }}
                onOpenProfile={() => setSettingsTab("profile")}
              />
            )}
          </section>
        </FadeIn>
      ) : (
        // Календарь не сворачивается. Крышка над ним была наследством от
        // времён, когда на странице стояло пять разделов и двенадцать
        // сеток отодвигали всё остальное вниз. Теперь ниже только подвал,
        // а сетка — то, ради чего экран открыт: закрывать её значит
        // закрывать страницу.
        <FadeIn key="calendar">
          <section aria-labelledby="calendar-heading" className="space-y-4 -translate-y-2">
            <h2 id="calendar-heading" className="flex items-center gap-2 text-xl sr-only">
              Календарь
              {yearView === "calendar" ? (
                <Hint label="Про производственный календарь">
                  <CalendarNote profile={profile} />
                </Hint>
              ) : null}
            </h2>
            <YearView
              profile={profile}
              calculation={shown ?? calculation}
              upcoming={upcoming}
              view={yearView}
              onViewChange={setYearView}
              onChange={onChange}
              statutory={statutory}
              onStatutory={setStatutory}
              month={month}
              onMonth={setMonth}
              onPickDay={setPickedDay}
              // Перенос смены — одно событие, и в профиль он попадает одной
              // правкой: снять здесь, назначить там (`withShiftMoved`).
              onMoveShift={(from, to) =>
                onChange((previous) => withShiftMoved(previous, from, to))
              }
            />
          </section>
        </FadeIn>
      )}

      <ProfileFooter profile={profile} />
      </div>

      {/* О чём спросить в открытых сутках, решает сетка, с которой по ним
          нажали: на производственном календаре — вид дня, на графике смен
          — отпуск, больничный или вызов. Состояние это уже есть здесь
          (`yearView`), и второго источника правды заводить не нужно. */}
      <DayEditor
        day={pickedDay}
        kind={yearView === "calendar" ? "calendar" : "shifts"}
        profile={profile}
        onChange={onChange}
        onClose={() => setPickedDay(null)}
      />

      {/* Нижняя панель телефона — здесь, а не внутри `YearView`, где
          стоят те же органы управления строкой над сеткой.
          -----------------------------------------------------------------
          Причина не в порядке разметки, а в том, как работает закрепление.
          Элемент `position: fixed` считает своё место от окна ТОЛЬКО пока
          над ним нет предка со сдвигом: любой `transform` заводит новую
          систему отсчёта, и закреплённый потомок начинает ездить вместе со
          страницей. Раздел с сеткой поднят на восемь точек
          (`-translate-y-2`) — и панель, стоявшая внутри него, оказывалась
          не у нижней кромки экрана, а в трёх с половиной тысячах точек от
          верха страницы, то есть за краем.

          Здесь, в самом низу разметки, панель ещё и встречается последней —
          и обходу клавишей, и чтению вслух. Управление, названное до
          двенадцати сеток, человек с клавиатурой встречал бы дважды.

          Пока показаны настройки, панели тоже нет: управлять ей нечем —
          сетки на экране в этот момент нет вовсе. */}
      {showSettings ? null : (
        <GridDeck
          profile={profile}
          onChange={onChange}
          view={yearView}
          onViewChange={setYearView}
          statutory={statutory}
          onStatutory={setStatutory}
          month={month}
          onMonth={setMonth}
        />
      )}
      </main>
    </>
  );
}

/**
 * Появление содержимого — плавным проступанием, а не рывком.
 *
 * Настройки и календарь занимают одно и то же место на экране по очереди,
 * а не разом: у них слишком разная высота, чтобы стоять друг под другом
 * слоем, — свободного места под коротким перечнем правок было бы на весь
 * рост несостоявшегося календаря. Поэтому смена — не перекрёстное
 * растворение одного в другое, а простое появление того, что встало на
 * освободившееся место.
 *
 * `key` снаружи (`workspace.tsx`) заставляет пересоздать обёртку при
 * каждой смене раздела — календарь, анкета профиля, перечень правок, — и
 * проступание играет заново.
 */
function FadeIn({ children }: { children: ReactNode }) {
  // Отключённая анимация — не рывок, а готовый вид сразу: читается тем же
  // умолчанием, что и у самой настройки (`window.matchMedia`), а не вторым
  // прогоном отрисовки следом за первым.
  const [shown, setShown] = useState(
    () => window.matchMedia("(prefers-reduced-motion: reduce)").matches,
  );

  useEffect(() => {
    if (shown) return;
    // Первый кадр обязан прийти с нулевой прозрачностью — иначе браузер
    // склеит появление и его исчезновение в один кадр, и переход не
    // сыграет.
    const frame = requestAnimationFrame(() => setShown(true));
    return () => cancelAnimationFrame(frame);
  }, [shown]);

  return (
    <div
      className={cn(
        // Расфокусировка, оседающая в резкость вместе с прозрачностью, —
        // тот же приём, что у слова рядом со знаком сайта и у имён закладок
        // (`Materialize`). Здесь не сам компонент: тот рассчитан на строку
        // текста (`inline-block`), а тут — блок в колонку страницы, и
        // сжимать его в строчный элемент значило бы сломать его ширину.
        "transition-[opacity,filter] duration-300 ease-out",
        shown ? "opacity-100 blur-none" : "opacity-0 blur-[6px]",
      )}
    >
      {children}
    </div>
  );
}
