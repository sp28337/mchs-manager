        // сайт: прежде он читал «НАСТРОЙКИ», оставаясь ссылкой домой, и
        // нажатие по слову уводило с расчёта на посадочную страницу.
        section={раздел}
        // Имя профиля — в строке шапки, сразу за знаком сайта, там, где
