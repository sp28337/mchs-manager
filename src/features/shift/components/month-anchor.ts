/**
 * Нынешний месяц под полосой с числами — и у расчёта, и у заглушки.
 *
 * --- Зачем это отдельным файлом -------------------------------------------
 *
 * Год на телефоне — двенадцать экранов подряд, и страница открывается на
 * нынешнем месяце, а не на январе (довод — в `year-view.tsx`). Ставит его
 * туда прокрутка, и делать её приходится ДВАЖДЫ: сперва для заглушки,
 * потом для расчёта, вставшего на её место.
 *
 * Разойдись эти две прокрутки хоть на строку — и человек, обновивший
 * страницу, увидел бы, как содержимое переезжает под ним в тот самый миг,
 * ради которого заглушка и заведена. Поэтому прокрутка здесь ровно одна, и
 * обе стороны зовут её же.
 *
 * --- Почему сценарий строкой ----------------------------------------------
 *
 * Заглушка отдаётся статикой, и браузер рисует её задолго до того, как
 * выполнится хоть строчка сценариев страницы. Прокрутка, сделанная после
 * загрузки, застала бы уже нарисованный январь: человек увидел бы сперва
 * начало года, потом рывок к сентябрю — то есть ровно то, что здесь и
 * лечится.
 *
 * Поэтому та же самая функция уезжает в разметку заглушки строкой и
 * выполняется, пока браузер разбирает страницу, — тем же приёмом, каким
 * ставится метка лампы (`shared/lamp-colour.ts`). Строка получается из
 * самой функции (`toString`), а не пишется рядом второй раз: две записи
 * одного и того же однажды разошлись бы, и разошлись бы молча.
 *
 * Отсюда требование к функции: она обязана быть САМОДОСТАТОЧНОЙ — никаких
 * ссылок наружу, ни на импорт, ни на соседнюю константу. В разметке вокруг
 * неё нет ничего.
 */
export function anchorCurrentMonth(): void {
  try {
    // Только телефон: порог тот же, что у нижней панели (`grid-deck.tsx`).
    // На широком экране год виден почти весь, и прыжок при открытии
    // читался бы как сбой.
    if (!window.matchMedia("(max-width: 767px)").matches) return;

    // Местный календарь, а не UTC: за Уралом «сегодня» наступает раньше, и
    // остальная арифметика приложения считает так же (`plain-date.ts`).
    const now = new Date();
    const year = now.getFullYear();

    // Учётный год из сохранённого профиля. Заглушка размечена нынешним
    // годом, а человек мог оставить экран на позапрошлом — и тогда месяца,
    // на который она встанет, в расчёте не окажется вовсе: страница
    // прокрутилась бы и тут же вернулась к началу.
    //
    // Читается он ВЫРАЖЕНИЕМ, а не разбором всего профиля: сценарий
    // выполняется до первой отрисовки, а в профиле лежит год отпусков,
    // вызовов и правок календаря — разбирать их здесь незачем, нужно одно
    // число. Не нашлось — считаем, что год нынешний: у только что
    // созданного профиля так и есть.
    // Профиля нет вовсе — двигать нечего: расчёта не будет, экран уводит
    // человека на главную. Прокрученная перед этим страница успела бы
    // мигнуть серединой года.
    const stored = localStorage.getItem("shift-schedule.profile");
    if (stored === null) return;
    const found = /"accountingYear"\s*:\s*(\d{4})/.exec(stored);
    if (found !== null && Number(found[1]) !== year) return;

    const key = `${year}-${String(now.getMonth() + 1).padStart(2, "0")}`;
    const month = document.querySelector(`[data-month="${key}"]`);
    // Нынешнего месяца в показанном отрезке может не быть вовсе — человек
    // смотрит позапрошлый год. Тогда не двигаемся никуда.
    if (month === null) return;

    // В два приёма: полоса с числами закреплена наверху, и её нижняя кромка
    // становится известна только после первой прокрутки. Восемь точек —
    // просвет, чтобы название месяца не касалось кромки полосы.
    month.scrollIntoView({ block: "start" });
    const bar = document.querySelector("[data-summary]");
    const under = bar === null ? 0 : bar.getBoundingClientRect().bottom;
    window.scrollBy(0, month.getBoundingClientRect().top - under - 8);
  } catch {
    // Прокрутка — удобство, а не расчёт: сломайся она, человек всего лишь
    // начнёт год с января. Ронять из-за этого страницу нельзя, тем более
    // что сценарий выполняется до всего остального на ней.
  }
}

/** Та же функция строкой — для разметки заглушки. */
export const MONTH_ANCHOR_SCRIPT = `(${anchorCurrentMonth.toString()})()`;
