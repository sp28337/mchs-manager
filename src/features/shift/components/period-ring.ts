import type { AccountingPeriodKind } from "../domain/value-objects";

/**
 * Кольцо знака периода: какая доля года выбрана.
 *
 * --- Что оно показывает -----------------------------------------------------
 *
 * Год — кольцо целиком, без разрывов. Полугодие — две половины, квартал —
 * четыре четверти; выбранная нарисована полностью, остальные — тусклее.
 * Знак на кнопке периода отвечает на тот же вопрос, что и подпись рядом,
 * только глазу быстрее: «какой кусок года я смотрю».
 *
 * --- Куда идёт год ----------------------------------------------------------
 *
 * Первое полугодие — левая половина, второе — правая: год читается слева
 * направо, как строка. Кварталы идут по часовой стрелке от нижней левой
 * четверти — туда же, куда идут стрелки на самом знаке: первый слева внизу,
 * второй слева вверху, третий справа вверху, четвёртый справа внизу. Тогда
 * два первых квартала вместе по-прежнему и есть первое полугодие, а два
 * последних — второе, и знаки полугодия и квартала не спорят между собой.
 *
 * Раньше кварталы шли против часовой от верха — первый слева вверху, второй
 * слева внизу, третий справа внизу, четвёртый справа вверху, — и ход года
 * шёл против хода стрелок рядом. В каждой паре соседей их поменяли местами.
 *
 * --- Просветы ---------------------------------------------------------------
 *
 * Те же, что были между отрезками у прежнего знака — часов с тающим
 * следом (`ClockFading` из lucide): там концы соседних дуг разнесены на
 * 22–24°. Здесь ровно 22,5° — восьмая часть прямого угла, и просветы
 * встают точно на 12, 3, 6 и 9 часов.
 */

/** Угол между концами соседних отрезков, в градусах. */
export const RING_GAP = 22.5;

/** Отрезок кольца: углы по часовой стрелке от 12 часов, в градусах. */
export interface RingSegment {
  from: number;
  to: number;
  /** Выбранный — рисуется полностью, остальные тусклее. */
  on: boolean;
}

/**
 * Какое по счёту место кольца (от верха против часовой) занимает доля года.
 *
 * У полугодий место совпадает с номером. У кварталов в каждой паре соседей
 * они поменяны: первый квартал — на месте второго, второй — на месте
 * первого, третий — на месте четвёртого, четвёртый — на месте третьего. Это
 * `index ^ 1`: младший бит номера переворачивается, а пара остаётся в своём
 * полугодии.
 */
function placeOf(kind: AccountingPeriodKind, index: number): number {
  return kind === "quarter" ? index ^ 1 : index;
}

/**
 * Отрезки кольца для выбранной доли года.
 *
 * У года отрезок один и во весь круг — без просвета: целый год не делится.
 */
export function ringSegments(kind: AccountingPeriodKind, index: number): RingSegment[] {
  if (kind === "year") return [{ from: 0, to: 360, on: true }];

  const count = kind === "half_year" ? 2 : 4;
  const span = 360 / count;

  // Места отрезков — против часовой стрелки от верха: у первого места конец
  // на 12 часах. Какое место у какой доли года, решает `placeOf`.
  const lit = placeOf(kind, index);
  return Array.from({ length: count }, (_, part) => {
    const end = 360 - span * part;
    return {
      from: end - span + RING_GAP / 2,
      to: end - RING_GAP / 2,
      on: part === lit,
    };
  });
}

/** Число для пути SVG: три знака после запятой, без хвоста нулей. */
function n(value: number): string {
  const text = value.toFixed(3).replace(/\.?0+$/, "");
  return text === "-0" ? "0" : text;
}

/**
 * Дуга окружности путём SVG — от угла `from` до угла `to` по часовой
 * стрелке. Окружность та же, что у часов lucide: центр 12,12, радиус 10.
 */
export function arcPath(from: number, to: number, radius = 10, centre = 12): string {
  const at = (degrees: number) => {
    const angle = (degrees * Math.PI) / 180;
    return `${n(centre + radius * Math.sin(angle))} ${n(centre - radius * Math.cos(angle))}`;
  };
  const large = to - from > 180 ? 1 : 0;
  return `M${at(from)}A${radius} ${radius} 0 ${large} 1 ${at(to)}`;
}
