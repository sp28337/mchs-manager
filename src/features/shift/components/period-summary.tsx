/**
 * Мелкие итоги — плашками по обе стороны от главной, если для них есть
 * место.
 *
 * --- Почему главная плашка посередине -------------------------------------
 *
 * Она стояла у левого края, а мелкие итоги тянулись за ней лентой до
 * правого. Глаз, пришедший за нормой и переработкой, находил их в углу, а
 * середину полосы — самое заметное место под шапкой — занимали «Ночные
 * часы». Теперь главное в середине, а мелкое расходится от него в обе
 * стороны.
 *
 * Стороны разведены по смыслу, а не по очереди: слева счёт смен — по
 * графику и отработано, — справа часы особого рода — ночные и
 * праздничные. Слева направо строка читается одной фразой: сколько смен
 * положено и сколько вышло, сколько это часами против нормы, и сколько из
 * этих часов ночных и праздничных.
 *
 * --- Как они появляются ----------------------------------------------------
 *
 * Парами, по одной с каждой стороны, — иначе главная плашка съехала бы с
 * середины. Сначала ближайшие по смыслу к главной: «Смен по графику» и
 * «Ночные часы»; потом, когда места хватает на всё, «Отработано смен» и
 * «Праздничные часы». Порядок слева направо при этом не меняется: план
 * смен всегда левее факта.
 *
 * Пропущенных смен в полосе больше нет. Это разница двух соседних чисел
 * («по графику» минус «отработано»), и третья плашка с ней повторяла то,
 * что видно и так, — а место у полосы самое дорогое на экране. В
 * статистике года пропуски остаются: там их считают по месяцам.
 *
 * --- Почему плашки одной ширины ------------------------------------------
 *
 * Содержание у них разной длины: «92» против «734», «Ночные часы» против
 * «Праздничные часы». Плашки по содержимому давали разные прямоугольники с
 * рваными краями — то самое, из-за чего ряд выглядел случайным. Одинаковые
 * складываются в ленту, а лента читается одной вещью. Стороны к тому же
 * равны между собой: только так главная плашка стоит ровно посередине, а
 * не там, где её оставила более длинная подпись.
 *
 * --- Что растёт, когда места больше ---------------------------------------
 *
 * Сначала стороны: главной плашке хватает её собственной ширины, а
 * мелкие итоги на узком экране стоят впритык. Но только до 168 точек на
 * плашку (10,5 рем): дальше мелкий итог, растянутый вширь, — это
 * пустое поле вокруг двузначного числа, а главная плашка рядом зажата в
 * своих 370 точках. Поэтому, как только мелкие плашки достигли предела, они
 * замирают, и весь прирост ширины уходит главной: норма, факт и разница
 * расходятся по ней свободнее.
 *
 * Предел наступает при ширине окна около 1124 точек. Задан он не порогом
 * экрана, а пределом самих колонок (`minmax(0, предел)` по бокам и
 * `minmax(auto, 1fr)` в середине): так переход идёт без скачка — плашка,
 * доросшая до предела, просто перестаёт расти, — и не зависит ни от
 * полосы прокрутки, ни от длины чисел в главной плашке.
 *
 * С одной парой по сторонам предела нет: она стоит лишь на средних
 * экранах, где до 168 точек плашкам ещё расти и расти.
 *
 * --- Почему число над подписью, а не рядом -------------------------------
 *
 * Так же, как в главной плашке. Число и подпись, стоящие в строку, при
 * растянутой плашке разъезжаются по её краям, и между ними появляется
 * пустота, которую глаз читает как границу: «92» отдельно, «смен по
 * графику» отдельно. Столбиком они остаются одним целым при любой ширине.
 *
 * И главное: подписи всех чисел — и крупных, и мелких — встают на одну
 * линию. Ряд держится этой линией, а не рамками плашек.
 *
 * --- Почему по замеру, а не по ширине экрана ------------------------------
 *
 * Строка главных чисел не одной ширины: разница бывает и «212,0 ч», и
 * «8 смен 20 ч», а норма — и «160», и «1972,5». Любой порог вроде
 * «показывать с 1280» на одном профиле оставил бы пустоту, а на другом
 * полез бы за край.
 *
 * Замер идёт по невидимому эталону — тем же плашкам, сжатым по
 * содержимому. Круга здесь нет именно поэтому: эталон не зависит от того,
 * что показано. Мерить видимый ряд было бы нельзя — спрятав его, мы
 * получили бы «теперь помещается» и показали снова.
 */
/**
 * Запас, с которым главная плашка переходит на строчную запись: сверх
 * ширины самой строки — по 24 точки на каждый из шести полупросветов
 * вокруг трёх чисел. Впритык строка читалась бы сжатой, а столбик в
 * той же плашке ещё выглядит уместно.
 */
const INLINE_ROOM = 144;

function FiguresRow({
  calculation,
  inShifts,
  shiftHours,
}: {
  calculation: PeriodCalculation;
  inShifts: boolean;
  shiftHours: string;
}) {
  const row = useRef<HTMLDivElement>(null);
  const probe = useRef<HTMLDivElement>(null);
  const plate = useRef<HTMLDListElement>(null);
  /** Сколько пар мелких итогов помещается: ни одной, одна или обе. */
  const [pairs, setPairs] = useState<0 | 1 | 2>(0);
  /** Подписи главных чисел — в строку с ними, а не под ними. */
  const [inline, setInline] = useState(false);

  // Замер ДО первой отрисовки, а не после неё.
  //
  // Раньше первое значение ставил `ResizeObserver`: он вызывает обработчик
  // сразу при подписке, и казалось, что отдельный замер не нужен. Но
  // подписка шла из обычного эффекта, а тот работает уже ПОСЛЕ отрисовки —
  // и обработчик приходил только следующим кадром. Между этими двумя
  // моментами человек успевал увидеть кадр, нарисованный по умолчанию
  // «не помещается»: плашка во всю ширину экрана и без мелких итогов.
  // Замерено при обновлении страницы — два кадра, полторы десятых доли
  // секунды, плашка 1862 точки вместо 370.
  //
  // Теперь замер идёт из layout-эффекта и сразу: React успевает
  // перерисовать полосу до того, как кадр попадёт на экран. Наблюдатель
  // остаётся, но отвечает уже только за ПОСЛЕДУЮЩИЕ изменения — смену
  // ширины окна и длины самих чисел.
  useLayoutEffect(() => {
    const room = row.current;
    const content = probe.current;
    if (!room || !content) return;

    const measure = () => {
      // Эталон — главная плашка, четыре мелких в порядке `sideItems`
      // (сначала левая сторона, потом правая) и последней та же главная
      // плашка в строчной записи.
      const [main = 0, planned = 0, worked = 0, night = 0, holiday = 0, mainInline = 0] = [
        ...content.children,
      ].map((child) => child.getBoundingClientRect().width);
      const width = room.clientWidth - 48;
      // Запас на плашку: итог, помещающийся впритык, читается как
      // переполненный, даже когда формально влез.
      const slack = 8;
      // Между колонками и между плашками внутри стороны — `gap-2`.
      const gap = 8;

      // Стороны равны (`1fr auto 1fr`), поэтому мерить надо по более
      // широкой из них. С двумя парами плашки одной ширины на всех
      // четырёх местах — и мерить нужно по самой широкой.
      const one = main + 2 * gap + 2 * (Math.max(planned, night) + slack);
      const widest = Math.max(planned, worked, night, holiday) + slack;
      const two = main + 2 * gap + 2 * (2 * widest + gap);

      setPairs(two <= width ? 2 : one <= width ? 1 : 0);

      // Строчная запись — когда главной плашке достаётся заметно больше,
      // чем ей нужно в строку. Мерится настоящая плашка, а не расчёт её
      // ширины: та зависит от числа пар, и после их смены наблюдатель
      // приходит сюда ещё раз — уже с новой шириной.
      //
      // Порог один, без запаса в обратную сторону, и дрожать здесь нечему:
      // ширину плашки задаёт сетка полосы, а не её содержимое. Строка
      // включается, только когда плашка шире строки с запасом, — то есть
      // её нижняя граница по содержимому до ширины плашки не дотягивает.
      const plateWidth = plate.current?.getBoundingClientRect().width ?? 0;
      setInline(plateWidth >= mainInline + INLINE_ROOM);
    };

    measure();

    const observer = new ResizeObserver(measure);
    observer.observe(room);
    observer.observe(content);
    if (plate.current) observer.observe(plate.current);
    return () => observer.disconnect();
  }, []);

  const { left, right } = sideItems(calculation);
  const shown = (side: readonly MinorItem[]) => side.slice(0, pairs);

  return (
    // Полоса залита бумагой, хотя плашки в ней и свои: без заливки между
    // ними просвечивает календарь — он проезжает под закреплённой полосой,
    // и в зазорах видно, как едут клетки.
    <div
      ref={row}
      className={cn(
        "relative items-stretch gap-2 px-6 pb-3",
        pairs === 0 && "flex",
        pairs === 1 && "grid grid-cols-[1fr_auto_1fr]",
        // Две плашки по 10,5 рем и просвет между ними в полрема: 21,5 рем.
        pairs === 2 && "grid grid-cols-[minmax(0,21.5rem)_minmax(auto,1fr)_minmax(0,21.5rem)]",
      )}
    >
      {/* Главная плашка — первой в разметке, хотя на экране она в
          середине: программа чтения начинает с нормы и переработки, ради
          которых полоса и существует, а не с числа смен. */}
      <MainPlate
        plateRef={plate}
        calculation={calculation}
        inShifts={inShifts}
        shiftHours={shiftHours}
        grow={pairs === 0}
        inline={inline}
        className={pairs === 0 ? undefined : "col-start-2 row-start-1"}
      />

      {pairs > 0 ? (
        <>
          <dl className="col-start-1 row-start-1 flex h-14 min-w-0 gap-2">
            {shown(left).map((item) => (
              <MinorPlate key={item.caption} {...item} />
            ))}
          </dl>
          <dl className="col-start-3 row-start-1 flex h-14 min-w-0 gap-2">
            {shown(right).map((item) => (
              <MinorPlate key={item.caption} {...item} />
            ))}
          </dl>
        </>
      ) : null}

      {/* Эталон: каждая плашка отдельно, сжатая по содержимому и вынесенная
          из потока. `inert` — чтобы знак вопроса в нём не ловил ни курсор,
          ни клавиатуру. */}
      <div
        ref={probe}
        inert
        aria-hidden
        className="pointer-events-none invisible absolute bottom-0 left-6 flex h-14 gap-2 whitespace-nowrap"
      >
        <MainPlate
          calculation={calculation}
          inShifts={inShifts}
          shiftHours={shiftHours}
          tight
        />
        {[...left, ...right].map((item) => (
          <MinorPlate key={item.caption} {...item} tight />
        ))}
        <MainPlate
          calculation={calculation}
          inShifts={inShifts}
          shiftHours={shiftHours}
          tight
          inline
        />
      </div>
    </div>
  );
}

interface MinorItem {
  value: string;
  unit?: string;
  caption: string;
}

/**
 * Мелкие итоги по сторонам от главной плашки.
 *
 * Каждая сторона — в порядке ПОЯВЛЕНИЯ: первая плашка показывается уже
 * при одной паре, вторая — только при двух. На экране левая сторона при
 * этом читается в том же порядке («Смен по графику», потом «Отработано
 * смен»), а правая — от главной наружу («Ночные часы», потом
 * «Праздничные часы»).
 */
function sideItems(calculation: PeriodCalculation): {
  left: readonly MinorItem[];
  right: readonly MinorItem[];
} {
  return {
    left: [
      { value: String(calculation.scheduledShifts), caption: "Смен по графику" },
      { value: String(calculation.workedShifts), caption: "Отработано смен" },
    ],
    right: [
      { value: hoursTrim(calculation.nightHours), unit: "ч", caption: "Ночные часы" },
      { value: hoursTrim(calculation.holidayHours), unit: "ч", caption: "Праздничные часы" },
    ],
  };
}

/**
 * Мелкий итог: то же построение, что у главного числа, но вполголоса и на
 * своей плашке.
 *
 * Единица измерения остаётся при числе, хотя подпись под ним и повторяет
 * её словом. Без «ч» ряд из «92», «92», «734», «96» выглядит четырьмя
 * числами одной природы, тогда как левые два — это смены, а правые два —
 * часы. Нулевого хвоста при этом нет ни у тех, ни у других: ноль после
 * запятой ничего не уточняет, а показывать его только в двух плашках из
 * четырёх значило бы делать вид, что там точность выше.
 */
function MinorPlate({
  value,
  unit,
  caption,
  tight,
}: MinorItem & {
  /** Плашка эталона: по содержимому, а не в общую долю ширины. */
  tight?: boolean;
}) {
  return (
    <div
      className={cn(
        "flex min-w-0 flex-col items-center justify-end rounded-xl bg-paper-raised px-3 pb-2",
        // Свет лампы: блик по верху, тень вниз. У эталона его нет — тот
        // невидим, и лишняя тень в нём только сбила бы замер ширины.
        tight ? "shrink-0" : "lit flex-1",
      )}
    >
      <dd className="whitespace-nowrap font-mono text-base leading-none text-ink">
        {tight ? value : <CountedNumber value={value} />}
        {unit ? <span className="ml-1 text-[11px] text-ink-muted">{unit}</span> : null}
      </dd>
      <dt className="mt-1.5 flex h-3.5 items-center gap-1 whitespace-nowrap text-[11px] leading-tight text-ink-muted">
        {caption}
      </dt>
    </div>
  );
}

/**
 * Главная плашка: норма, факт и разница между ними.
 *
 * Чисел ровно три, всегда. Разница бывает в обе стороны, но она ОДНА
 * величина: переработка и недоработка — это её знак, а не два разных
 * итога. Показывает знак сама разница — именем и цветом
 * (`BalanceCaption`), а не второе число рядом.
 *
 * Плашка одна на все три, а не по одной на число: норму, факт и разницу
 * сравнивают между собой, и рамка вокруг каждого разрезала бы то, что
 * читается вместе. Мелкие итоги — наоборот, четыре независимых факта, и
 * плашка у каждого своя.
 *
 * На телефоне плашка занимает всю ширину: мелких итогов там нет, и делить
 * строку не с кем.
 */
function MainPlate({
  plateRef,
  calculation,
  inShifts,
  shiftHours,
  grow,
  tight,
  inline = false,
  className,
}: {
  /** Сама плашка — для замера её ширины в `FiguresRow`. */
  plateRef?: Ref<HTMLDListElement>;
  calculation: PeriodCalculation;
  /** Переработку — сменами и часами, а не часами. */
  inShifts: boolean;
  /** Продолжительность смены: на неё делится переработка. */
  shiftHours: string;
  /** Мелких итогов рядом нет — занять всю строку и развести числа. */
  grow?: boolean;
  /** Плашка эталона: по содержимому. */
  tight?: boolean;
  /**
   * Подписи в строку с числами, а все три числа — ростом нормы. Решает
   * `FiguresRow` по замеру: так плашка стоит, когда места в ней заметно
   * больше, чем нужно строке.
   */
  inline?: boolean;
  /** Место в сетке полосы: посередине, когда по сторонам есть итоги. */
  className?: string;
}) {
  const under = calculation.undertimeHours.greaterThan(0);
  const balance = under ? calculation.undertimeHours : calculation.overtimeHours;
  // Столбиком или в строку — решает замер (`FiguresRow`), а не порог
  // ширины окна. Прежде строчная запись была привязана к средним экранам и
  // растянутой плашке, и при мелких итогах рядом её не бывало вовсе: на
  // широком мониторе главная плашка вырастала до тысячи точек, а три
  // числа столбиком стояли в ней островками с пустыми полями между ними.

  return (
    <dl
      ref={plateRef}
      className={cn(
        // Поля и просветы ужаты на самом узком телефоне: три числа с
        // подписями требуют 267 точек, а на 320-точечном экране полосе
        // достаётся 272 — впритык, и «Переработка» упиралась в край.
        "flex h-14 items-center rounded-xl bg-paper-raised px-2 min-[360px]:px-4 py-2 lg:min-w-92.5 justify-around",
        // Свет лампы — на видимой плашке, но не на эталоне: тот невидим и
        // служит линейкой, а лишняя тень сбила бы замер ширины.
        !tight && "lit",
        // Пока мелких итогов нет, плашка занимает строку целиком, а числа
        // расходятся по ней: три числа, сжатые в левый угол полосы во всю
        // ширину экрана, читаются как незаконченная вёрстка.
        grow && !tight
          ? "min-w-0 flex-1 justify-around gap-x-1.5 min-[360px]:gap-x-3"
          : "shrink-0 gap-x-5 sm:gap-x-6",
        className,
      )}
    >
      <Figure
        parts={[{ value: hoursTrim(calculation.normHours), unit: "ч" }]}
        caption="Норма периода"
        emphatic
        still={tight}
        inline={inline}
      />
      <Figure
        parts={[{ value: hoursTrim(calculation.actualHours), unit: "ч" }]}
        caption="Отработано"
        still={tight}
        inline={inline}
      />
      <Figure
        parts={overtimeParts(balance, inShifts, shiftHours)}
        caption={<BalanceCaption under={under} />}
        // Ноль — это попадание в норму, и цвета у него нет: ни зелёного,
        // ни красного. Сигнальным становится только то, что требует
        // разговора с работодателем.
        tone={under ? "signal" : balance.greaterThan(0) ? "verify" : undefined}
        still={tight}
        inline={inline}
      />
    </dl>
  );
}

/**
 * Переработка — часами или сменами, по выбору человека.
 *
 * --- Почему выбор, а не оба сразу ----------------------------------------
 *
 * Оба и стояли: «212,0 ч Переработка ≈ 8,8 смены В сменах» — четыре числа
 * и знак приблизительности ради одной величины, и половина строки на то,
 * чтобы сказать её дважды. При этом «8,8 смены» само требовало пересчёта:
 * десятая доля суточной смены это два часа с четвертью, а отгул берут
 * сменами и часами.
 *
 * Теперь величина одна, и мера у неё та, в которой человек привык считать:
 * либо «212,0 ч», либо «8 смен 20 ч».
 *
 * --- Почему «смены», а не «сутки» ----------------------------------------
 *
 * У суточного графика тут стояло «8 суток» — по привычке речи. Но
 * названо этим числом не время, а количество отработанного сверх нормы,
 * и у графика «два через два» то же самое число пришлось бы называть
 * сменами. Одна величина не может зваться двумя словами в зависимости от
 * графика: человек, сменивший график, читал бы разные меры на одном и
 * том же месте экрана.
 *
 * --- Почему недоработка в той же мере ------------------------------------
 *
 * Она такая же разница часов, только с другим знаком, и показывать её в
 * другой мере значило бы предложить сравнивать несравнимое.
 */
function overtimeParts(
  value: Decimal,
  inShifts: boolean,
  shiftHours: string,
): FigurePart[] {
  if (!inShifts) return [{ value: hoursTrim(value), unit: "ч" }];

  // Мера — своя смена: у графика «два через два» она двенадцатичасовая, и
  // делить её переработку на двадцать четыре значило бы назвать вдвое
  // меньше смен, чем человек отработал.
  const perShift = shiftMinutes(shiftHours) / 60;
  const { shifts: whole, hours: rest } = splitIntoShifts(value, perShift);
  const parts: FigurePart[] = [];
  if (whole > 0) {
    parts.push({ value: String(whole), unit: shiftsWord(whole) });
  }
  // Ровные смены не тянут за собой «0 ч», но и пустой строки не бывает:
  // меньше смены — значит просто часы.
  if (!rest.isZero() || whole === 0) {
    parts.push({ value: hoursTrim(rest), unit: "ч" });
  }
  return parts;
}

/**
 * Названная цена непроставленного переноса.
 *
 * Единственное, что осталось карточкой в потоке страницы: это не
 * пояснение, а недоделанное дело, и оно требует действия в календаре
 * ниже. В полосе ему не место — полоса это числа.
 */
function PendingNotice({ accountingYear }: { accountingYear: number }) {
  const pending = pendingTransfers(accountingYear).length;
  if (pending === 0) return null;

  return (
    // Не «календарь не опубликован» — эта формулировка досталась от
    // серверной версии и человеку ничего не говорила. Названа конкретная
    // недостача и её цена в часах.
    <p className="mt-6 max-w-prose rounded-xl bg-signal-soft px-4 py-3 text-sm">
      Норма может быть завышена на {pending * 8} часов: переносы новогодних
      выходных на {accountingYear} год ещё не проставлены. Откройте календарь
      года ниже и отметьте их по своему производственному календарю.
    </p>
  );
}

/**
 * Величина числом с единицей — и, если нужно, не одним.
 *
 * Пар бывает две: переработка сменами это «8 смен 20 ч», и остаток от
 * смены такое же число, как сами смены. Оформлять его иначе значило бы
 * сказать, что он менее настоящий.
 *
 * --- Почему число доходит до нового значения, а не подменяется -----------
 *
 * Полоса итога затем и закреплена под шапкой, что человек правит календарь
 * и смотрит на неё. Правка меняет разом несколько чисел из семи, а
 * подменённые мгновенно они не говорят, КАКОЕ из них двинулось: разницу в
 * час на одном и том же месте глаз не замечает вовсе.
 *
 * Отсчёт (`CountedNumber`) отвечает на это движением — тот же самый, что
 * крутит числа на первом экране. Эталон, по которому меряется ширина
 * полосы, при этом стоит неподвижно (`still`): считать место по числу в
 * пути значило бы менять раскладку, пока оно идёт.
 */
export interface FigurePart {
  value: string;
  unit: string;
}

function Figure({
  parts,
  caption,
  emphatic,
  tone,
  still,
  inline,
}: {
  parts: readonly FigurePart[];
  caption: ReactNode;
  emphatic?: boolean;
  tone?: "signal" | "verify";
  /** Плашка эталона: считать по ней ширину, пока число в пути, нельзя. */
  still?: boolean;
  /**
   * Строчная запись: «Норма периода: 1972 ч» — подпись слева, по оси
   * числа, и число ростом нормы, как бы оно ни было выделено столбиком.
   * Три числа одного роста в строку читаются одной фразой; разный рост
   * нужен столбиком, где норма — заголовок над остальными.
   */
  inline?: boolean;
}) {
  return (
    <div className={cn("min-w-0", inline && "flex flex-row-reverse items-center gap-2.5")}>
      {/* Число и его единица не разрываются переносом: «1796,00» на одной
          строке и «ч» на следующей читается как другое число. */}
      <dd
        className={cn(
          "whitespace-nowrap font-mono leading-none text-center",
          emphatic || inline ? "text-xl sm:text-2xl" : "text-lg sm:text-xl",
          // Цвет меняется столько же, сколько едет приставка в подписи:
          // это одно событие, показанное с двух сторон, и разъезжаться им
          // нельзя. Поэтому длительность приходит оттуда же, откуда её
          // берёт сама приставка, а не повторяется здесь числом.
          "transition-colors",
          tone === "signal" && "text-signal",
          tone === "verify" && "text-verify font-medium",
        )}
        style={{ transitionDuration: `${BALANCE_SWAP_MS}ms` }}
      >
        {parts.map((part, index) => (
          <span key={part.unit} className={index > 0 ? "ml-2" : undefined}>
            {still ? part.value : <CountedNumber value={part.value} />}
            <span className="ml-1 text-xs text-ink-muted sm:text-sm">{part.unit}</span>
          </span>
        ))}
      </dd>
      {/* Подписи шире самих чисел — «Норма периода» занимает больше, чем
          «1972 ч», — и на 320 точках место экономится именно на них. */}
      <dt
        className={cn(
          "flex items-center justify-center gap-1 whitespace-nowrap leading-tight text-ink-muted",
          // В строку подпись крупнее: рядом с числом в полтора рема
          // одиннадцать точек читались бы сноской.
          inline ? "text-sm" : "h-3.5 text-[10px] min-[360px]:text-[11px]",
        )}
      >
        {/* Двоеточие принадлежит строчной записи «Норма периода: 1972 ч».
            Под числом подписи не к чему прицепиться — двоеточия там нет. */}
        <span className={inline ? "after:content-[':']" : undefined}>{caption}</span>
      </dt>
    </div>
  );
}
