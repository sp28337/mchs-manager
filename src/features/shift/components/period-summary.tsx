/**
 * Мелкие итоги — по обе стороны от главных чисел, если для них есть место.
 *
 * --- Почему главные числа посередине --------------------------------------
 *
 * Они стояли у левого края, а мелкие итоги тянулись за ними лентой до
 * правого. Глаз, пришедший за нормой и переработкой, находил их в углу, а
 * середину полосы — самое заметное место под шапкой — занимали «Ночные
 * часы». Теперь главное в середине, а мелкое расходится от него в обе
 * стороны.
 *
 * Стороны разведены по смыслу, а не по очереди: слева счёт смен — по
 * графику и отработано, — справа часы особого рода — ночные и
 * праздничные. Слева направо строка читается одной фразой: сколько смен
 * положено и сколько вышло, сколько это часами против нормы, и сколько из
 * этих часов ночных и праздничных.
 *
 * --- Как они появляются ----------------------------------------------------
 *
 * Парами, по одной с каждой стороны, — иначе главные числа съехали бы с
 * середины. Сначала ближайшие по смыслу к главным: «По графику» и
 * «Ночные»; потом, когда места хватает на всё, «Отработано» и
 * «Праздничные». Порядок слева направо при этом не меняется: план
 * смен всегда левее факта.
 *
 * Пропущенных смен в полосе больше нет. Это разница двух соседних чисел
 * («по графику» минус «отработано»), и третье число с ней повторяло то,
 * что видно и так, — а место у полосы самое дорогое на экране. В
 * статистике года пропуски остаются: там их считают по месяцам.
 *
 * --- Почему в том же стиле, что главные ------------------------------------
 *
 * Мелкие итоги тоже лежат прямо на бумаге: число над подписью, подпись
 * прописными гарнитурой названий. Плашки с заливкой и светом у них были,
 * пока на плашке стояли и главные числа. Когда главные её потеряли, рамка
 * осталась бы только у справочных цифр, и справка читалась бы важнее
 * главного. Различает их теперь вес: у главных число и подпись жирные, у
 * мелких обычные, и подпись мельче (12 точек на любой ширине), а число на
 * ступень меньше.
 *
 * --- Почему кучно, а не по всей ширине полосы ---------------------------
 *
 * У числа без плашки нет рамки, которая держала бы его на месте, и
 * растянутые вширь они разъезжались островками с пустыми полями между
 * ними. Поэтому каждая группа — три главных числа, пара слева, пара
 * справа — занимает ровно свою ширину, а стороны прижаты к главным: вся
 * строка читается одной сгруппированной фразой по оси экрана, а лишнее
 * место остаётся пустым по краям.
 *
 * Колонки внутри группы одной ширины — по самой широкой подписи: числа
 * стоят на равном расстоянии друг от друга, а не там, где их оставила
 * подпись подлиннее. Стороны равны между собой (`1fr auto 1fr`) — только
 * так главные числа стоят ровно посередине.
 *
 * --- Почему число над подписью, а не рядом -------------------------------
 *
 * Число и подпись, стоящие в строку, разъезжаются по краям колонки, и
 * между ними появляется пустота, которую глаз читает как границу: «92»
 * отдельно, «смен по графику» отдельно. Столбиком они остаются одним целым
 * при любой ширине.
 *
 * --- Почему по замеру, а не по ширине экрана ------------------------------
 *
 * Строка не одной ширины: разница бывает и «212,0 ч», и «8 смен 20 ч», а
 * норма — и «160», и «1972,5». Любой порог вроде «показывать с 1280» на
 * одном профиле оставил бы пустоту, а на другом полез бы за край.
 *
 * Замер идёт по невидимому эталону — тем же числам, сжатым по содержимому.
 * Круга здесь нет именно поэтому: эталон не зависит от того, что показано.
 * Мерить видимый ряд было бы нельзя — спрятав его, мы получили бы «теперь
 * помещается» и показали снова.
 */
function FiguresRow({
  calculation,
  inShifts,
  shiftHours,
}: {
  calculation: PeriodCalculation;
  inShifts: boolean;
  shiftHours: string;
}) {
  const row = useRef<HTMLDivElement>(null);
  const probe = useRef<HTMLDivElement>(null);
  /** Сколько пар мелких итогов помещается: ни одной, одна или обе. */
  const [pairs, setPairs] = useState<0 | 1 | 2>(0);

  // Замер ДО первой отрисовки, а не после неё.
  //
  // Раньше первое значение ставил `ResizeObserver`: он вызывает обработчик
  // сразу при подписке, и казалось, что отдельный замер не нужен. Но
  // подписка шла из обычного эффекта, а тот работает уже ПОСЛЕ отрисовки —
  // и обработчик приходил только следующим кадром. Между этими двумя
  // моментами человек успевал увидеть кадр, нарисованный по умолчанию
  // «не помещается»: без мелких итогов. Замерено при обновлении страницы —
  // два кадра, полторы десятых доли секунды.
  //
  // Теперь замер идёт из layout-эффекта и сразу: React успевает
  // перерисовать полосу до того, как кадр попадёт на экран. Наблюдатель
  // остаётся, но отвечает уже только за ПОСЛЕДУЮЩИЕ изменения — смену
  // ширины окна и длины самих чисел.
  useLayoutEffect(() => {
    const room = row.current;
    const content = probe.current;
    if (!room || !content) return;

    const measure = () => {
      // Эталон — главные числа и четыре мелких в порядке `sideItems`
      // (сначала левая сторона, потом правая).
      const [main = 0, planned = 0, worked = 0, night = 0, holiday = 0] = [
        ...content.children,
      ].map((child) => child.getBoundingClientRect().width);
      const width = room.clientWidth - 48;
      // Запас на сторону: итог, помещающийся впритык, читается как
      // переполненный, даже когда формально влез.
      const slack = 8;
      // Между группами — `gap-x-8`, между колонками внутри группы —
      // `gap-x-5`: группы должны читаться группами, а не одной лентой из
      // семи чисел.
      const between = 32;
      const inner = 20;

      // Стороны равны (`1fr auto 1fr`), поэтому мерить надо по более
      // широкой из них. Колонки внутри стороны одной ширины — по самой
      // широкой из двух.
      const one = main + 2 * between + 2 * (Math.max(planned, night) + slack);
      const pair = (first: number, second: number) => 2 * Math.max(first, second) + inner;
      const two =
        main +
        2 * between +
        2 * (Math.max(pair(planned, worked), pair(night, holiday)) + slack);

      setPairs(two <= width ? 2 : one <= width ? 1 : 0);
    };

    measure();

    const observer = new ResizeObserver(measure);
    observer.observe(room);
    observer.observe(content);
    return () => observer.disconnect();
  }, []);

  const { left, right } = sideItems(calculation);
  const shown = (side: readonly MinorItem[]) => side.slice(0, pairs);

  return (
    // Самой полосе заливки нет: календарь, проезжающий под ней, растворяет
    // дымка (`.veil` в `globals.css`), а не бумага полосы. Плашек нет ни у
    // главных чисел, ни у мелких.
    <div
      ref={row}
      className={cn(
        "relative items-center px-6 pb-3",
        // Без мелких итогов главные числа — одной группой по середине, а не
        // растянутыми на всю строку.
        pairs === 0 ? "flex justify-center" : "grid grid-cols-[1fr_auto_1fr] gap-x-8",
      )}
    >
      {/* Главные числа — первыми в разметке, хотя на экране они в
          середине: программа чтения начинает с нормы и переработки, ради
          которых полоса и существует, а не с числа смен. */}
      <MainPlate
        calculation={calculation}
        inShifts={inShifts}
        shiftHours={shiftHours}
        alone={pairs === 0}
        className={pairs === 0 ? undefined : "col-start-2 row-start-1"}
      />

      {pairs > 0 ? (
        <>
          {/* Слева — к главным, то есть вправо; справа — влево. */}
          <dl className={cn(SIDE, "col-start-1 row-start-1 justify-self-end")}>
            {shown(left).map((item) => (
              <MinorFigure key={item.caption} {...item} />
            ))}
          </dl>
          <dl className={cn(SIDE, "col-start-3 row-start-1 justify-self-start")}>
            {shown(right).map((item) => (
              <MinorFigure key={item.caption} {...item} />
            ))}
          </dl>
        </>
      ) : null}

      {/* Эталон: каждое число отдельно, сжатое по содержимому и вынесенное
          из потока. `inert` — чтобы он не ловил ни курсор, ни клавиатуру. */}
      <div
        ref={probe}
        inert
        aria-hidden
        className="pointer-events-none invisible absolute bottom-0 left-6 flex h-14 gap-2 whitespace-nowrap"
      >
        <MainPlate
          calculation={calculation}
          inShifts={inShifts}
          shiftHours={shiftHours}
          tight
        />
        {[...left, ...right].map((item) => (
          <MinorFigure key={item.caption} {...item} tight />
        ))}
      </div>
    </div>
  );
}

/**
 * Сторона: колонки поровну по самой широкой, вплотную к главным числам.
 * Просвет между колонками — тот же `gap-x-5`, что у главных; между
 * группами он шире (`gap-x-8` у строки), чтобы группы читались группами.
 */
const SIDE = "grid h-14 min-w-0 grid-flow-col auto-cols-fr items-center gap-x-5";

interface MinorItem {
  value: string;
  unit?: string;
  caption: string;
}

/**
 * Мелкие итоги по сторонам от главных чисел.
 *
 * Каждая сторона — в порядке ПОЯВЛЕНИЯ: первое число показывается уже
 * при одной паре, второе — только при двух. На экране левая сторона при
 * этом читается в том же порядке («По графику», потом «Отработано»), а
 * правая — от главных наружу («Ночные», потом «Праздничные»).
 */
function sideItems(calculation: PeriodCalculation): {
  left: readonly MinorItem[];
  right: readonly MinorItem[];
} {
  return {
    left: [
      // «см» — единица при числе, как «ч» у часов справа: сокращение от
      // «смен». Сокращение не склоняется, поэтому «91 см» и «90 см» без
      // подбора окончания, и ширина колонки не зависит от числа.
      {
        value: String(calculation.scheduledShifts),
        unit: "см",
        caption: "По графику",
      },
      {
        value: String(calculation.workedShifts),
        unit: "см",
        caption: "Отработано",
      },
    ],
    right: [
      // Слово «часы» в подписи не нужно: единица «ч» стоит при числе.
      { value: hoursTrim(calculation.nightHours), unit: "ч", caption: "Ночные" },
      { value: hoursTrim(calculation.holidayHours), unit: "ч", caption: "Праздничные" },
    ],
  };
}

/**
 * Мелкий итог: то же построение, что у главного числа, на ступень мельче.
 *
 * Единица измерения стоит при числе у всех четырёх: у левых — «см»
 * (смены), у правых — «ч» (часы). Без неё ряд
 * из «92», «92», «734», «96» выглядел бы четырьмя числами одной природы,
 * тогда как левые два — это смены, а правые два — часы; а подписи под ними
 * («По графику», «Отработано», «Ночные», «Праздничные») называют, ЧТО
 * это за смены и за часы, а не чего их. Нулевого хвоста при этом нет ни у
 * тех, ни у других: ноль после запятой ничего не уточняет, а показывать
 * его только в двух числах из четырёх значило бы делать вид, что там
 * точность выше.
 */
function MinorFigure({
  value,
  unit,
  caption,
  tight,
}: MinorItem & {
  /** Эталон: по содержимому, без отсчёта числа в пути. */
  tight?: boolean;
}) {
  return (
    <Figure parts={[{ value, unit }]} caption={caption} still={tight} minor />
  );
}

/**
 * Главные числа: норма, факт и разница между ними.
 *
 * Чисел ровно три, всегда. Разница бывает в обе стороны, но она ОДНА
 * величина: переработка и недоработка — это её знак, а не два разных
 * итога. Показывает знак сама разница — именем и цветом
 * (`BalanceCaption`), а не второе число рядом.
 *
 * --- Почему без плашки ----------------------------------------------------
 *
 * Плашка стояла вокруг всех трёх, и в ней числа читались как карточка
 * среди карточек. Но главные числа — не одни из многих, а то, ради чего
 * полоса существует, и рамка с заливкой и светом только сравнивала их с
 * остальными. Теперь они лежат прямо на бумаге — как и мелкие итоги по
 * сторонам: все плашки ушли разом, а главные отличаются размером.
 *
 * Цена названа: без заливки под числами проезжает календарь, и читаемость
 * держит дымка (`.veil` в `globals.css`) — она растворяет сетку там, где
 * стоят числа.
 *
 * --- Почему три колонки одной ширины, и всегда столбиком ------------------
 *
 * Число над подписью, а не рядом: рядом они разъезжались при любой ширине
 * строки. Колонки равны — по самой широкой подписи, — и числа стоят на
 * равном расстоянии друг от друга, как бы ни различались длиной
 * «Отработано» и «Переработка».
 *
 * --- Почему группой, а не на всю строку -----------------------------------
 *
 * Когда мелких итогов рядом нет, главные числа встают в одну группу по
 * середине строки, а не делят её поровну: растянутые на планшете в три
 * колонки по двести точек, они стояли островками с пустыми полями. Группа
 * сжимается, только когда строка уже её (самый узкий телефон), — тогда
 * колонки делят строку поровну.
 */
function MainPlate({
  calculation,
  inShifts,
  shiftHours,
  alone,
  tight,
  className,
}: {
  calculation: PeriodCalculation;
  /** Переработку — сменами и часами, а не часами. */
  inShifts: boolean;
  /** Продолжительность смены: на неё делится переработка. */
  shiftHours: string;
  /** Мелких итогов рядом нет — встать одной группой по середине строки. */
  alone?: boolean;
  /** Эталон для замера ширины: по содержимому. */
  tight?: boolean;
  /** Место в сетке полосы: посередине, когда по сторонам есть итоги. */
  className?: string;
}) {
  const under = calculation.undertimeHours.greaterThan(0);
  const balance = under ? calculation.undertimeHours : calculation.overtimeHours;

  return (
    <dl
      className={cn(
        // Три колонки поровну, а числа с подписями — по середине каждой и
        // по середине высоты: `items-center` у сетки, `justify-center` у
        // каждого блока. Высота та же, что у сторон рядом, — полоса не
        // растёт.
        "grid h-14 grid-cols-3 items-center",
        // Одна по середине строки: ширина — по содержимому, а на самом
        // узком телефоне группа сжимается (`min-w-0`), и просвет уже.
        //
        // Рядом со сторонами — `min-w-max`, и это не по привычке: средняя
        // колонка полосы (`1fr auto 1fr`) берёт нижней границей наименьшую
        // ширину группы, а у сетки из `minmax(0, 1fr)` она нулевая.
        // Наименьшая ширина — по содержимому: тогда стороны делят остаток,
        // а не главные числа, и подписи не налезают друг на друга.
        alone && !tight
          ? "min-w-0 gap-x-2 min-[360px]:gap-x-5"
          : "min-w-max shrink-0 gap-x-5",
        className,
      )}
    >
      <Figure
        parts={[{ value: hoursTrim(calculation.normHours), unit: "ч" }]}
        caption="Норма периода"
        still={tight}
      />
      <Figure
        parts={[{ value: hoursTrim(calculation.actualHours), unit: "ч" }]}
        caption="Отработано"
        still={tight}
      />
      <Figure
        parts={overtimeParts(balance, inShifts, shiftHours)}
        caption={<BalanceCaption under={under} />}
        // Ноль — это попадание в норму, и цвета у него нет: ни зелёного,
        // ни красного. Сигнальным становится только то, что требует
        // разговора с работодателем.
        tone={under ? "signal" : balance.greaterThan(0) ? "verify" : undefined}
        still={tight}
      />
    </dl>
  );
}

/**
 * Переработка — часами или сменами, по выбору человека.
 *
 * --- Почему выбор, а не оба сразу ----------------------------------------
 *
 * Оба и стояли: «212,0 ч Переработка ≈ 8,8 смены В сменах» — четыре числа
 * и знак приблизительности ради одной величины, и половина строки на то,
 * чтобы сказать её дважды. При этом «8,8 смены» само требовало пересчёта:
 * десятая доля суточной смены это два часа с четвертью, а отгул берут
 * сменами и часами.
 *
 * Теперь величина одна, и мера у неё та, в которой человек привык считать:
 * либо «212,0 ч», либо «8 смен 20 ч».
 *
 * --- Почему «смены», а не «сутки» ----------------------------------------
 *
 * У суточного графика тут стояло «8 суток» — по привычке речи. Но
 * названо этим числом не время, а количество отработанного сверх нормы,
 * и у графика «два через два» то же самое число пришлось бы называть
 * сменами. Одна величина не может зваться двумя словами в зависимости от
 * графика: человек, сменивший график, читал бы разные меры на одном и
 * том же месте экрана.
 *
 * --- Почему недоработка в той же мере ------------------------------------
 *
 * Она такая же разница часов, только с другим знаком, и показывать её в
 * другой мере значило бы предложить сравнивать несравнимое.
 */
function overtimeParts(
  value: Decimal,
  inShifts: boolean,
  shiftHours: string,
): FigurePart[] {
  if (!inShifts) return [{ value: hoursTrim(value), unit: "ч" }];

  // Мера — своя смена: у графика «два через два» она двенадцатичасовая, и
  // делить её переработку на двадцать четыре значило бы назвать вдвое
  // меньше смен, чем человек отработал.
  const perShift = shiftMinutes(shiftHours) / 60;
  const { shifts: whole, hours: rest } = splitIntoShifts(value, perShift);
  const parts: FigurePart[] = [];
  if (whole > 0) {
    parts.push({ value: String(whole), unit: shiftsWord(whole) });
  }
  // Ровные смены не тянут за собой «0 ч», но и пустой строки не бывает:
  // меньше смены — значит просто часы.
  if (!rest.isZero() || whole === 0) {
    parts.push({ value: hoursTrim(rest), unit: "ч" });
  }
  return parts;
}

/**
 * Названная цена непроставленного переноса.
 *
 * Единственное, что осталось карточкой в потоке страницы: это не
 * пояснение, а недоделанное дело, и оно требует действия в календаре
 * ниже. В полосе ему не место — полоса это числа.
 */
function PendingNotice({ accountingYear }: { accountingYear: number }) {
  const pending = pendingTransfers(accountingYear).length;
  if (pending === 0) return null;

  return (
    // Не «календарь не опубликован» — эта формулировка досталась от
    // серверной версии и человеку ничего не говорила. Названа конкретная
    // недостача и её цена в часах.
    <p className="mt-6 max-w-prose rounded-xl bg-signal-soft px-4 py-3 text-sm">
      Норма может быть завышена на {pending * 8} часов: переносы новогодних
      выходных на {accountingYear} год ещё не проставлены. Откройте календарь
      года ниже и отметьте их по своему производственному календарю.
    </p>
  );
}

/**
 * Величина числом с единицей — и, если нужно, не одним.
 *
 * Пар бывает две: переработка сменами это «8 смен 20 ч», и остаток от
 * смены такое же число, как сами смены. Оформлять его иначе значило бы
 * сказать, что он менее настоящий.
 *
 * --- Почему число доходит до нового значения, а не подменяется -----------
 *
 * Полоса итога затем и закреплена под шапкой, что человек правит календарь
 * и смотрит на неё. Правка меняет разом несколько чисел из семи, а
 * подменённые мгновенно они не говорят, КАКОЕ из них двинулось: разницу в
 * час на одном и том же месте глаз не замечает вовсе.
 *
 * Отсчёт (`CountedNumber`) отвечает на это движением — тот же самый, что
 * крутит числа на первом экране. Эталон, по которому меряется ширина
 * полосы, при этом стоит неподвижно (`still`): считать место по числу в
 * пути значило бы менять раскладку, пока оно идёт.
 */
export interface FigurePart {
  value: string;
  /** Единица при числе; у счёта смен её нет. */
  unit?: string;
}

/**
 * Подпись под числом: гарнитура для названий, прописные, с разрядкой (тем
 * же голосом, что названия в шапке, `HEADER_WORD`), но мелко: подпись
 * называет число, а не спорит с ним. У главных чисел она жирная, у мелких
 * итогов — обычная и на ступень мельче.
 *
 * Кегль главных ступенями: 11 точек на самом узком телефоне, 12 — с 340, 14
 * — с 680 (42,5 рема). Три подписи в равных колонках на 320 точках иначе не
 * помещаются («НОРМА ПЕРИОДА» в 12 точек — 82, колонка там — 85). У мелких
 * итогов те же 11 и 12, но на широком экране они остаются на 12
 * (`min-[42.5rem]:text-xs`): справка не должна подрастать вместе с главным.
 *
 * Ступень на 680, а не на `sm` (640), не случайно: подписи и числа при
 * ступени растут, и боковые итоги, помещавшиеся на 640 в малом кегле, в
 * большой уже не лезли — на 34 точках (640–673) они пропадали и снова
 * появлялись. С ростом на 680 первая пара помещается и до, и после ступени,
 * и мигать ей нечем. Тот же порог у чисел и у единиц рядом (`Figure`).
 *
 * Высота задана и одинакова у главных и мелких, а не взята из строки: у
 * «Переработки» внутри коробка приставки выше строки на несколько точек, и
 * без заданной высоты эта подпись стояла бы ниже соседних; а подписи
 * разного кегля с высотой «по строке» сдвигали бы друг относительно друга
 * и числа над ними. Классы написаны целиком, а не собраны из переменной:
 * Tailwind находит их в исходнике как строки.
 */
const CAPTION_BASE = cn(
  "flex h-[1.125rem] items-center justify-center whitespace-nowrap",
  "font-display uppercase leading-tight tracking-wide",
  MARK_EMPTY_TEXT,
  "text-[11px] min-[340px]:text-xs",
);
const CAPTION = cn(CAPTION_BASE, "font-bold min-[42.5rem]:text-sm");
const CAPTION_MINOR = cn(CAPTION_BASE, "min-[42.5rem]:text-xs");

function Figure({
  parts,
  caption,
  tone,
  still,
  minor,
}: {
  parts: readonly FigurePart[];
  caption: ReactNode;
  tone?: "signal" | "verify";
  /** Эталон: считать по нему ширину, пока число в пути, нельзя. */
  still?: boolean;
  /** Мелкий итог: число на ступень меньше. */
  minor?: boolean;
}) {
  return (
    // Число над подписью, оба по середине колонки и по середине высоты.
    <div
      className={cn(
        "flex min-w-0 flex-col items-center justify-center gap-1",
        still && "shrink-0",
      )}
    >
      {/* Число и его единица не разрываются переносом: «1796,00» на одной
          строке и «ч» на следующей читается как другое число. Все главные —
          одного роста и жирные: разный рост нужен там, где одно число —
          заголовок над остальными, а здесь они равны. У мелких итогов число
          обычное: вес — то, что отличает главное от справки. */}
      <dd
        className={cn(
          // Строка числа одной высоты у главных и мелких, число — к её
          // низу: подписи под ними встают на одну линию, а базовые линии
          // чисел разного роста совпадают. Без этого блоки разной высоты,
          // выровненные по середине, сдвигали подписи мелких итогов на пару
          // точек относительно главных.
          "flex h-5 items-end justify-center whitespace-nowrap font-mono leading-none text-center min-[42.5rem]:h-6",
          minor
            ? "text-lg min-[42.5rem]:text-xl"
            : "text-xl font-bold min-[42.5rem]:text-2xl",
          // Сами цифры — обычными чернилами темы (от страницы), а тон
          // разницы — зелёный и красный — говорит о переработке и
          // недоработке. Цвет бургера (`MARK_EMPTY_TEXT`) — у БУКВ полосы:
          // у подписей и у единицы при числе, но не у цифр: цифры — то, ради
          // чего полоса существует, и им гаснуть не за чем.
          //
          // Цвет меняется столько же, сколько едет приставка в подписи:
          // это одно событие, показанное с двух сторон, и разъезжаться им
          // нельзя. Поэтому длительность приходит оттуда же, откуда её
          // берёт сама приставка, а не повторяется здесь числом.
          "transition-colors",
          tone === "signal" && "text-signal",
          tone === "verify" && "text-verify",
        )}
        style={{ transitionDuration: `${BALANCE_SWAP_MS}ms` }}
      >
        {parts.map((part, index) => (
          <span key={`${index}:${part.unit ?? ""}`} className={index > 0 ? "ml-2" : undefined}>
            {still ? part.value : <CountedNumber value={part.value} />}
            {/* Единица тише числа: ни жирности, ни полного роста. Это
                буква, а не цифра, и цвет у неё как у подписей — цвет
                бургера; у числа с тоном тоже: «ч» при зелёном числе серое,
                как везде. */}
            {part.unit ? (
              <span className={cn("ml-1 text-xs font-normal min-[42.5rem]:text-sm", MARK_EMPTY_TEXT)}>
                {part.unit}
              </span>
            ) : null}
          </span>
        ))}
      </dd>
      <dt className={minor ? CAPTION_MINOR : CAPTION}>{caption}</dt>
    </div>
  );
}
