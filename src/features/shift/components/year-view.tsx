/**
 * Год на сетке: график смен и производственный календарь на одном месте.
 *
 * --- Почему это один блок, а не два --------------------------------------
 *
 * Обе сетки показывают одно и то же — месяцы года клетками по дням недели,
 * — и человек смотрит их по очереди, сверяя одно с другим: «у меня тут
 * смена, а день-то рабочий или праздничный?». Двумя разделами подряд это
 * означало прокрутку между ними: пока долистаешь до календаря, клетка
 * графика, из-за которой пошёл, уже за экраном.
 *
 * --- Почему выбор периода тоже здесь -------------------------------------
 *
 * Он жил в боковой колонке и управлял тем, что нарисовано в этой сетке, —
 * то есть человек менял период в одном углу экрана, а смотрел на
 * последствия в другом. Теперь орган управления стоит вплотную к тому,
 * чем управляет: год, полугодие, квартал и месяц выбираются над самой
 * сеткой.
 *
 * --- Почему период одной кнопкой -----------------------------------------
 *
 * Сначала здесь стояли сегменты «3 месяца / 6 месяцев / Год» и отдельный
 * список «который из них», потом один список на семь отрезков и второй —
 * на месяцы внутри. И то и другое было двумя органами управления ради
 * одного выбора. Теперь это одна кнопка, называющая выбранный отрезок, и
 * окно со всеми девятнадцатью (`PeriodPicker`).
 *
 * --- Зачем масштаб --------------------------------------------------------
 *
 * Двенадцать месяцев по три в ряд — компромисс, который никому не подходит
 * целиком. Тому, кто ищет одну спорную смену, нужны крупные клетки с
 * читаемым кодом вызова; тому, кто смотрит, «как лёг год», нужны все
 * двенадцать месяцев разом, без прокрутки. Это разные задачи, и выбирать
 * между ними должен человек, а не вёрстка.
 *
 * Масштаб общий у обеих сеток: они читаются вперемежку, и разный масштаб
 * означал бы скачок размера при каждом переключении.
 *
 * --- Куда делась кисть календаря -----------------------------------------
 *
 * Была: выбрать, чем помечать, потом щёлкнуть по числу. Два действия и
 * скрытое состояние — щёлкнув по дню, человек получал то, что выбрал
 * когда-то раньше, и не всегда помнил, что именно.
 *
 * Теперь у календаря та же механика, что у графика: нажатие по дню
 * открывает окно этих суток, и вид дня выбирается ТАМ, вместе с заметкой.
 * Ни кисти, ни формы диапазона под сеткой — одна дорога вместо трёх.
 */

/**
 * Масштаб — ЧИСЛО МЕСЯЦЕВ В РЯДУ.
 *
 * --- Почему число, а не ширина --------------------------------------------
 *
 * Масштаб сперва задавал ширину месяца: жмёшь — месяц растёт понемногу, а
 * сколько их встанет в ряд, решает `auto-fill`. Плавно выходило, но в ряду
 * оставалось непотраченное место — до ста сорока точек, — и сетка стояла с
 * откушенным правым краем.
 *
 * Одновременно плавным и во всю ширину масштаб быть не может, и это не
 * недоделка, а арифметика: пока месяцы делят ширину ПОРОВНУ, размер месяца
 * — это ширина, делённая на их число. Число целое, значит и размеров
 * ровно столько, сколько бывает делителей: на тысяче точек это 146, 180,
 * 231, 316, 486 — пять величин, и никакого «между».
 *
 * Из двух свойств выбрано второе: сетка во всю ширину. Ступеней от этого не
 * убавилось — их и было пять-шесть заметных, только между ними тянулись
 * доли, на которых не менялось ничего. Теперь каждое нажатие — это другая
 * раскладка.
 *
 * --- Пределы --------------------------------------------------------------
 *
 * Два месяца в ряд снизу: один на всю колонку — это уже не сетка года, а
 * одна страница календаря, и смотреть на неё незачем. Восемь сверху — но
 * реально предел ставит не это число, а ширина колонки: месяц уже девяти
 * рем даёт клетку в два десятка точек, где число ещё читается, а код
 * вызова уже нет. Сколько влезает, считается замером (`monthsThatFit`), и
 * кнопка «мельче» гаснет ровно там: нажатий впустую нет.
 *
 * --- Кегль ----------------------------------------------------------------
 *
 * Клетка квадратная и растёт вместе с шириной месяца, а число внутри без
 * этого осталось бы прежним — получались бы пустые квадраты с мелкой
 * цифрой посередине. Но и пропорционально кегль расти не должен: у мелкого
 * масштаба есть порог читаемости, ниже которого цифру не разобрать вовсе.
 *
 * Отсюда наклонная, а не доля: прямая проведена по прежним ступеням — на
 * них было 11 точек при самом мелком масштабе и 14 при самом крупном, — и
 * в промежуточных точках сходится с ними: 11,7 против 12 на четырёх
 * месяцах в ряд, 12,5 против 12 на трёх. Само правило — в `globals.css`,
 * там же, где сетка; сюда приходит только ширина месяца, посчитанная по
 * замеру колонки.
 */
const MONTHS_MIN = 2;
const MONTHS_CAP = 8;

/**
 * Сколько месяцев в ряду при первом открытии широкого экрана — четыре.
 *
 * Столько же было и раньше: прежнее умолчание задавалось теми же словами,
 * «четыре в ряд», и на 1440 давало месяц около 231 точки. Экран, открытый
 * впервые, выглядит ровно так же, как выглядел.
 *
 * Ниже `lg` число задаёт `globals.css`: там оно зависит от ширины экрана,
 * кнопок масштаба нет, и менять его некому.
 */
const DEFAULT_MONTHS = 4;

/**
 * Зазор между месяцами — тот же, что стоит классом на сетке (`gap-x-6`).
 *
 * Повторён здесь числом: из него считаются и предел «сколько влезает», и
 * ширина месяца для кегля. Прочитать его из вычисленных стилей было бы
 * можно, но ради полутора рем пришлось бы держать ссылку на саму сетку —
 * а её на пустом периоде нет вовсе.
 */
const GAP_REM = 1.5;

/** Уже этого месяц не читается: клетка выходит в два десятка точек. */
const MONTH_FLOOR_REM = 9;

function rootFontSize(): number {
  return Number.parseFloat(getComputedStyle(document.documentElement).fontSize);
}

/** Сколько месяцев влезает в колонку такой ширины, не мельчая до нечитаемого. */
function monthsThatFit(width: number): number {
  const rem = rootFontSize();
  return Math.floor(
    (width + GAP_REM * rem) / ((MONTH_FLOOR_REM + GAP_REM) * rem),
  );
}

/**
 * «Месяц» или «месяца» — для программы чтения.
 *
 * Она произносит итог нажатия вслух, и «4 месяц в ряду» там слышно так же
 * отчётливо, как читалось бы на экране. Форм нужно две: пределы масштаба —
 * от двух до восьми, и «один месяц» в этот отрезок не попадает.
 */
function monthsWord(count: number): string {
  return count >= 5 ? "месяцев" : "месяца";
}

/**
 * Раскладка сетки месяцев — одна на обе, и вся в `globals.css`.
 *
 * Классов здесь больше не собирается: ширину колонки и кегль задаёт одно
 * правило по ширине месяца, а та приходит переменной. Осталось только
 * место в строке (`flex-1`) — оно к масштабу отношения не имеет.
 */
const GRID = "year-grid gap-x-6 gap-y-5 flex-1";

export type YearViewKind = "shifts" | "calendar";

export function YearView({
  profile,
  calculation,
  upcoming,
  view,
  onViewChange,
  onChange,
  statutory,
  onStatutory,
  month,
  onMonth,
  onPickDay,
  onMoveShift,
}: {
  profile: StoredProfile;
  /**
   * Расчёт на ВЕСЬ показанный отрезок — в режиме «Онлайн» он шире того,
   * по которому посчитаны числа наверху.
   */
  calculation: PeriodCalculation;
  /**
   * Первые сутки, которые ещё не наступили, или `null`, если режима
   * «Онлайн» нет. Обе сетки гасят всё с этого дня и дальше.
   */
  upcoming: IsoDate | null;
  view: YearViewKind;
  onViewChange: (view: YearViewKind) => void;
  onChange: (change: (previous: StoredProfile) => StoredProfile) => void;
  statutory: StatutoryChoice;
  onStatutory: (choice: StatutoryChoice) => void;
  /** Месяц внутри периода или `null` — «весь период». */
  month: number | null;
  onMonth: (month: number | null) => void;
  onPickDay: (day: IsoDate) => void;
  /** Перенос смены перетаскиванием по сетке графика. */
  onMoveShift: (from: IsoDate, to: IsoDate) => void;
}) {
  // Кнопки масштаба появляются с `lg`: на телефоне месяц и так шире
  // экрана и занимает его целиком, растить его некуда, а мельчить —
  // значит получить клетку, в которую не попасть пальцем.
  const zoomable = useMediaQuery("(min-width: 1024px)");

  const room = useRef<HTMLDivElement>(null);
  const [asked, setAsked] = useState(DEFAULT_MONTHS);
  const [roomWidth, setRoomWidth] = useState(0);

  /**
   * Ширина колонки под сетку — замером, а не догадкой.
   *
   * Из неё следует, сколько месяцев в ряд ВООБЩЕ поместится: ниже девяти
   * рем клетка перестаёт читаться.
   *
   * Мерить нужно САМУ СЕТКУ, а не эту обёртку. С `xl` рядом с сеткой
   * встаёт легенда и забирает у неё около трёхсот точек: на окне 1280
   * обёртка 1232 точки, а сетка 836, и по обёртке масштаб разрешал семь
   * месяцев в ряду там, где помещается пять. Клетка выходила в четырнадцать
   * точек — с числом, которое в неё не влезает.
   *
   * Пока период пуст, сетки нет вовсе; тогда берётся обёртка — показывать
   * всё равно нечего, а ноль сломал бы расчёт кегля.
   *
   * Наблюдатель, а не разовый замер: колонку меняет и ширина окна, и
   * появление полосы прокрутки, и переход через порог, на котором легенда
   * встаёт сбоку.
   */
  useLayoutEffect(() => {
    const box = room.current;
    if (box === null) return;
    const measure = () => {
      const grid = box.querySelector(".year-grid");
      setRoomWidth(grid instanceof HTMLElement ? grid.clientWidth : box.clientWidth);
    };
    measure();
    const watcher = new ResizeObserver(measure);
    watcher.observe(box);
    return () => watcher.disconnect();
  }, []);

  /**
   * Телефон открывается на нынешнем месяце, а не на январе.
   *
   * --- Зачем ----------------------------------------------------------------
   *
   * На широком экране год виден почти весь: четыре месяца в ряду, три ряда.
   * На телефоне месяц занимает экран целиком, и год — это двенадцать
   * экранов подряд. Человек, открывший расчёт в сентябре, начинал с января
   * и листал восемь экранов до того места, ради которого пришёл. Каждый раз.
   *
   * --- Почему в середину, а не к верхней кромке -----------------------------
   *
   * Наверху стоит закреплённая полоса с числами, и месяц, поставленный
   * ровно под верхний край окна, наполовину уходил бы под неё. Середина
   * вдобавок показывает соседние месяцы краями — видно, что год
   * продолжается в обе стороны, а не начинается здесь.
   *
   * --- Почему один раз и только на телефоне ---------------------------------
   *
   * Один раз — потому что это ответ на ОТКРЫТИЕ страницы. Переключил
   * человек сетку или период, будучи в октябре, — он остаётся там же, где
   * смотрел; прокрутка под ним в этот момент означала бы, что приложение
   * отняло у него место, которое он выбрал сам.
   *
   * Только на телефоне — потому что там прокрутка и есть цена вопроса. На
   * широком экране сентябрь и так виден, и прыжок страницы при открытии
   * читался бы как сбой.
   *
   * Порог тот же, что у нижней панели (`grid-deck.tsx`): ниже `md` экран
   * считается телефонным во всём приложении.
   *
   * Кадр ожидания обязателен: сетка в это мгновение только что встала на
   * место заглушки, и до перерисовки её месяцы стоят не там, где встанут.
   */
  const centred = useRef(false);
  useEffect(() => {
    if (centred.current) return;
    centred.current = true;
    if (!window.matchMedia("(max-width: 767px)").matches) return;
    const key = todayIso().slice(0, 7);
    const frame = requestAnimationFrame(() => {
      // Нынешнего месяца в показанном отрезке может не быть вовсе —
      // человек смотрит позапрошлый год. Тогда не двигаемся никуда.
      document
        .querySelector(`[data-month="${key}"]`)
        ?.scrollIntoView({ block: "center" });
    });
    return () => cancelAnimationFrame(frame);
  }, []);

  const fits = roomWidth === 0 ? MONTHS_CAP : monthsThatFit(roomWidth);
  // Мельчить дальше некуда: предел — это столько месяцев, сколько влезает
  // в эту колонку, и на нём кнопка гаснет.
  const most = Math.max(MONTHS_MIN, Math.min(MONTHS_CAP, fits));
  const months = Math.min(asked, most);

  return (
    <div
      ref={room}
      className="year-room space-y-4"
      // Скрипт назначает ОДНО число — сколько месяцев в ряду. Ширину месяца
      // и кегль в клетке считает из него сама таблица стилей, запросом к
      // мерной коробке (`globals.css`), — потому и заглушка рабочего экрана,
      // где скрипта нет вовсе, совпадает с расчётом до точки.
      //
      // Ниже `lg` число задаёт тоже `globals.css`: там оно зависит от ширины
      // экрана, а кнопок масштаба нет и менять его некому.
      style={zoomable ? ({ "--months": months } as CSSProperties) : undefined}
    >
      {/* Одна панель на всё управление сеткой: что показать, за какой
          период и каким размером. Разнеси это по углам — и человек будет
          искать, где переключается год.

          Подложки у панели нет. Плашка цвета бумаги над сеткой, которая
          сама теперь плашка, читалась как второй слой поверх первого —
          два блока, спорящих за передний план. Управление держится
          линейками, а не фоном. */}
      <div className="space-y-3">
        {/* До `md` этой строки нет: те же органы управления стоят внизу
            экрана, всегда под большим пальцем (`grid-deck.tsx`). Скрыто
            правилом, а не замером ширины: замер означал бы, что до его
            выполнения не показано ни то ни другое. */}
        <div className="hidden flex-wrap items-center gap-2 md:flex">
          <div className="flex-wrap flex lg:min-w-92.5 gap-2 justify-between">
            <Segmented label="Что показывать на сетке">
              <SegmentedItem
                active={view === "shifts"}
                onClick={() => onViewChange("shifts")}
              >
                <ShiftsIcon />
                {/* «График смен» на телефоне съедает всю строку, а рядом
                    стоит «Календарь» — второго графика тут нет, и слово
                    «смен» ничего не различает. */}
                <span className="inline">График</span>
              </SegmentedItem>
              <SegmentedItem
                active={view === "calendar"}
                onClick={() => onViewChange("calendar")}
              >
                <CalendarIcon />
                <span className="inline">Календарь</span>
              </SegmentedItem>
            </Segmented>

            {/* Период стоит в одной строке с видом сетки: и то и другое
                отвечает на вопрос «что я сейчас вижу». */}
            {/* Учётный год записывается прямо в профиль, а не хранится
                состоянием экрана: человек, вернувшийся к прошлогоднему
                расчёту через день, должен найти его там же, где оставил.
                Отдельного свойства у `YearView` для этого не нужно —
                обновление профиля здесь уже есть. */}
            <PeriodPicker
              accountingYear={profile.accountingYear}
              onAccountingYear={(accountingYear) =>
                onChange((previous) => ({ ...previous, accountingYear }))
              }
              statutory={statutory}
              onStatutory={onStatutory}
              month={month}
              onMonth={onMonth}
            />
          </div>

          {/* Тумблер здесь, а не только в настройках: он меняет то, что
              нарисовано в сетке, — значит, стоит там, где на это смотрят. */}
          <LiveModeSwitch profile={profile} onChange={onChange} />

          {/* Масштаб — двумя кнопками.
              -------------------------------------------------------------
              Был ползунок: одна вещь вместо двух, и по нему сразу видно,
              где предел. Но масштаб здесь — не плавная величина, а
              ступени: от двух месяцев в ряду до восьми, и всего их шесть.
              Ползунок на шести ступенях ловит бегунком то, что нажатием
              делается вернее, а на телефоне не появляется вовсе.

              Кнопки к тому же родня всему, что стоит в этой строке:
              переключателю сеток, кнопке периода, кнопкам шапки — та же
              высота, то же скругление, тот же свет лампы по верхней
              кромке. Ползунок среди них был единственной деталью своего
              рода. */}
          {zoomable ? (
            <div className="ml-auto flex items-center gap-1">
              <span className="mr-1 font-display text-[11px] font-bold uppercase tracking-wide text-ink-muted">
                Масштаб
              </span>
              <ZoomButton
                label="Крупнее: меньше месяцев в ряду"
                disabled={months <= MONTHS_MIN}
                onClick={() => setAsked(Math.max(MONTHS_MIN, months - 1))}
              >
                <ZoomIn aria-hidden />
              </ZoomButton>
              <ZoomButton
                label="Мельче: больше месяцев в ряду"
                disabled={months >= most}
                onClick={() => setAsked(Math.min(most, months + 1))}
              >
                <ZoomOut aria-hidden />
              </ZoomButton>
              {/* Итог нажатия — вслух. У ползунка это делал
                  `aria-valuetext`; у пары кнопок сказать о том, что
                  изменилось, больше некому, а изменение это и есть весь
                  смысл нажатия. */}
              <span aria-live="polite" className="sr-only">
                {months} {monthsWord(months)} в ряду
              </span>
            </div>
          ) : null}
        </div>

      </div>

      {/* Сетка стоит здесь, и над ней — только панель управления,
          одинаковая у обоих видов. Поэтому при переключении клетка
          остаётся ровно на своём месте: проверено замером, положение
          первой клетки и прокрутка страницы не меняются ни на пиксель. */}
      {calculation.periodStart >= calculation.periodEnd ? (
        <EmptyPeriod countFrom={profile.countFrom} />
      ) : view === "shifts" ? (
        <ShiftStrip
          calculation={calculation}
          upcoming={upcoming}
          gridClassName={GRID}
          dayNotes={profile.dayNotes}
          onPickDay={onPickDay}
          onMoveShift={onMoveShift}
        />
      ) : (
        <YearCalendarEditor
          profile={profile}
          onChange={onChange}
          // Календарь показывает тот же отрезок, что и график: человек
          // переключается между ними, сверяя смену с видом дня, и разные
          // отрезки означали бы, что сверять нечего.
          periodStart={calculation.periodStart}
          periodEnd={calculation.periodEnd}
          upcoming={upcoming}
          gridClassName={GRID}
          dayNotes={profile.dayNotes}
          onPickDay={onPickDay}
        />
      )}
    </div>
  );
}

/**
 * Отрезок, целиком лежащий до начала отсчёта.
 *
 * Такое бывает ровно в одном случае: человек указал, что работает здесь с
 * августа, и выбрал март. Сетка тогда пуста, и полоса итога над ней тоже —
 * ноль смен, ноль часов, ноль нормы.
 *
 * Молча показать пустое место нельзя: ноль на экране расчёта читается как
 * «приложение не посчитало» или «данные потерялись», а не как «этих суток
 * у вас не было». Поэтому вместо сетки стоит строка, называющая причину и
 * место, где её менять.
 *
 * Месяцы до начала отсчёта при этом остаются в выборе периода, а не
 * пропадают из него. Пропав, они молча объявили бы, что до августа года не
 * существует, — а человек, поставивший дату по ошибке, не нашёл бы, где
 * ошибся: список выглядел бы нормальным.
 */
function EmptyPeriod({ countFrom }: { countFrom: IsoDate | null }) {
  return (
    <p className="max-w-prose rounded-xl bg-paper-raised px-4 py-3 text-sm text-ink-muted">
      Выбранный период целиком раньше начала отсчёта
      {countFrom ? ` (${formatDateRu(countFrom)})` : ""} — показывать нечего.
      Выберите период позже или поправьте начало отсчёта в настройках.
    </p>
  );
}

/**
 * Кнопка масштаба.
 *
 * --- Почему своя, а не общая `Button` -------------------------------------
 *
 * Общая кнопка растянута во всю ширину строки по замыслу — она стоит в
 * окнах, где кнопка и есть строка, — и `size="icon"` её не сжимает: `w-full`
 * дописывается после класса вызывающего. Здесь кнопок две подряд, и каждая
 * должна быть квадратом в девять десятых рема.
 *
 * --- Почему она поднята, а не прозрачна -----------------------------------
 *
 * Свет лампы ловят ПОВЕРХНОСТИ, а не всё подряд: блик по верхней кромке
 * имеет смысл только у того, что приподнято над бумагой. Прежние кнопки
 * масштаба были прозрачными и света не ловили — единственные во всей
 * строке, где и переключатель сеток, и кнопка периода стоят на поднятой
 * бумаге. Теперь они той же породы: та же заливка, то же скругление, тот же
 * `lit`, что у кнопок в шапке.
 */
function ZoomButton({
  label,
  disabled,
  onClick,
  children,
}: {
  /** Имя действия: на кнопке один значок, и назвать её больше нечем. */
  label: string;
  disabled: boolean;
  onClick: () => void;
  children: ReactNode;
}) {
  return (
    <button
      type="button"
      aria-label={label}
      title={label}
      disabled={disabled}
      onClick={onClick}
      className={cn(
        "lit grid size-9 shrink-0 place-items-center rounded-xl",
        "bg-paper-raised text-ink-muted transition-colors",
        "hover:text-ink",
        // Упёршись в предел, кнопка не исчезает и не гаснет наполовину:
        // она остаётся на месте бледной. Пропавшая кнопка сдвинула бы
        // соседнюю под самым пальцем, а человеку нужно видеть, что
        // мельче уже некуда.
        "disabled:pointer-events-none disabled:opacity-40",
        "cursor-pointer focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-trace",
        "[&_svg]:size-4.5 [&_svg]:shrink-0",
      )}
    >
      {children}
    </button>
  );
}
