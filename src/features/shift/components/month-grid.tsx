import type { CSSProperties, ReactNode } from "react";

import { cn } from "@/lib/utils/cn";

import { weekday, type IsoDate } from "../domain/plain-date";

/**
 * Месяц как в настенном календаре: строка — неделя, столбец — день недели.
 *
 * --- Почему это отдельная деталь ----------------------------------------
 *
 * Так показываются и график смен, и производственный календарь, и это не
 * совпадение: человек сверяет одно с другим глазами, перескакивая между
 * ними, и любое расхождение в раскладке пришлось бы держать в голове.
 * Одна раскладка на оба экрана — единственный способ, чтобы «то же число»
 * оказывалось на том же месте.
 *
 * --- Что здесь считается ------------------------------------------------
 *
 * Ровно одно: сколько пустых клеток поставить перед первым числом, чтобы
 * столбцы совпали с днями недели. Всё остальное — содержимое клетки —
 * решает вызывающий: у графика в клетке часы, у календаря тип дня.
 *
 * --- Месяц как одна плашка (`joined`) ------------------------------------
 *
 * Клетки стояли врозь, каждая в своей рамке. Сорок бордюров на месяц и
 * четыреста восемьдесят на год — это сетка, которая громче того, что в
 * ней написано: глаз читает решётку, а не смены.
 *
 * В сомкнутом виде месяц выглядит одной плашкой: щелей между клетками
 * нет, рамок у обычных дней нет тоже, а форму блоку задаёт его СОБСТВЕННЫЙ
 * внешний контур — со скруглениями по углам, включая уступ там, где месяц
 * начинается не с понедельника. Рамка остаётся только у дней, которые
 * что-то означают, и потому наконец что-то означает.
 *
 * Скругления углов клетки считаются по соседям: угол скругляется, если по
 * обе стороны от него клеток нет. Так получают форму все ВЫПУКЛЫЕ углы
 * блока, включая углы уступа.
 *
 * --- Уступ: скос, а не выемка --------------------------------------------
 *
 * У блока есть ещё вогнутый угол — там, где месяц начинается не с
 * понедельника и первая строка короче второй. Скруглить его самой клеткой
 * нельзя: скругление режет клетку, и вместо плавного перехода получается
 * маленький вырезанный квадрат внутри блока.
 *
 * Поэтому уступ заполняется СКОСОМ в пустой клетке рядом (`Fillet`): в её
 * углу лежит квадратик цвета обычного дня, а поверх — квадратик цвета
 * страницы со скруглением. Второй съедает у первого всё, кроме дужки, и
 * контур входит в уступ по касательной, без перелома.
 *
 * Цвет скоса — цвет обычного дня, а не соседней клетки: к вогнутому углу
 * сходятся три разных дня, и «правильного» цвета у него нет. Спокойная
 * подложка блока здесь единственный ответ, который не соврёт ни одному из
 * трёх.
 *
 * --- Щели между клетками (`bleed`) ---------------------------------------
 *
 * Семь столбцов делят ширину, которая на семь не делится: клетка выходит
 * шириной 27,281 пикселя. Границы клеток попадают между пикселями, и
 * браузер округляет их КАЖДУЮ ОТДЕЛЬНО — там, где округления соседей
 * разошлись, между ними остаётся столбец, который не закрасил никто.
 * Сквозь него видно страницу: по плашке месяца идёт белая нить. Замерено:
 * на ширине окна 1280 и 1728 точек в стыке стоит чистый белый пиксель,
 * при том что клетки по обе стороны — цвета подложки.
 *
 * Клетки при этом трогать НЕЛЬЗЯ. Растянуть их на полпикселя — сдвинуть
 * контур месяца и его скругления; подложить фон под всю сетку — залить
 * им же и уступ, которого в плашке нет.
 *
 * Поэтому подложка кладётся тенью на ОБЁРТКУ клетки — на элемент сетки,
 * внутри которого лежит сама клетка. Тень ничего не занимает в раскладке,
 * а рисуется в ранней очереди фонов — раньше всех клеток, потому что
 * обёртка не спозиционирована, а клетки да. Значит, ни одна клетка не
 * будет ею перекрыта и ни один цветной день не станет уже.
 *
 * Смещение — только вправо и вниз, и только туда, где сосед ЕСТЬ. Каждый
 * внутренний стык закрывается ровно одной из двух клеток, а внешний
 * контур месяца не сдвигается никуда: ни углы, ни скос уступа от этого не
 * меняются.
 */

export const WEEKDAY_LABELS = ["пн", "вт", "ср", "чт", "пт", "сб", "вс"];

export interface MonthGridProps {
  /**
   * Заголовок месяца. Необязателен: во всплывающем календаре месяц уже
   * назван в его собственной шапке со стрелками, и вторая подпись под ней
   * была бы повтором.
   */
  title?: ReactNode;
  /** Итог месяца справа от названия: смены, часы, число правок. */
  meta?: ReactNode;
  /** Подряд идущие дни ОДНОГО месяца. */
  days: readonly IsoDate[];
  /**
   * `corners` — классы скругления для этой клетки: у сомкнутого месяца
   * форму держат сами клетки, и знать её может только сетка.
   */
  renderDay: (day: IsoDate, corners: string) => ReactNode;
  /** Месяц одной плашкой: без щелей между клетками, с общим контуром. */
  joined?: boolean;
  /**
   * Добавка к клетке с буквами дня недели — по её месту в неделе.
   *
   * Нужна ровно одному вызывающему: на посадочной странице месяц
   * СОБИРАЕТСЯ, и шапка недели обязана появляться вместе с клетками, а не
   * стоять на месте с первого кадра. Задержку знает только он, а классы
   * раскладки — только эта сетка, поэтому добавка приходит снаружи, а
   * оформление остаётся здесь.
   */
  weekdayProps?: (index: number) => { className?: string; style?: CSSProperties };
  /**
   * Добавка к ПУСТОЙ клетке — по её месту в сетке.
   *
   * Нужна тому же вызывающему, что и `weekdayProps`, и по той же причине.
   * Пустая клетка обычно ничем себя не выдаёт, но в одной из них лежит
   * скос уступа (`Fillet`) — видимый кусок контура месяца. Без этой
   * добавки он оставался единственным, что стоит на месте с первого
   * кадра, пока весь остальной месяц ещё собирается.
   */
  padProps?: (slot: number) => { className?: string; style?: CSSProperties };
  /**
   * Добавка к ОБЁРТКЕ клетки суток — по её месту в сетке.
   *
   * Обёртка это не сама клетка: клетку рисует вызывающий (`renderDay`), а
   * обёртка — элемент сетки вокруг неё, и на ней висит подложка, которая
   * закрывает щели между клетками (`bleed` ниже). Подложка рисуется
   * раньше клеток и потому не гаснет вместе с ними; чтобы она приходила
   * волной, а не стояла готовой решёткой, место клетки в волне нужно
   * знать ЗДЕСЬ.
   *
   * Нужна тому же вызывающему, что `weekdayProps` и `padProps`.
   */
  dayProps?: (slot: number) => { className?: string; style?: CSSProperties };
  /**
   * Месяц СОБИРАЕТСЯ при появлении: клетки приходят волной наискось, а не
   * встают все разом.
   *
   * Зачем: сетка на год — это пятьсот клеток, и появляются они мгновенно,
   * все сразу. Глазу не за что зацепиться, и экран читается как картинка,
   * которая была здесь всегда. Волна показывает, что месяц СОБРАН из
   * суток, и заодно даёт полсекунды, за которые видно, где смены.
   *
   * Тот же приём, что на первом экране, но вчетверо быстрее: там месяц
   * один и он предмет разговора, здесь их до двенадцати и они рабочий
   * инструмент. Порядок волны — наискось от левого верхнего угла:
   * привычное направление чтения.
   *
   * Первый экран собирает месяц СВОЕЙ анимацией (`weekdayProps`,
   * `padProps` и класс на клетке) — у него другая длительность, глубина и
   * растворение. Поэтому здесь это отдельный флаг, а не общее правило.
   */
  assemble?: boolean;
}

/**
 * Скос вогнутого угла.
 *
 * Два квадрата со стороной в радиус скругления. Нижний — цвета обычного
 * дня: он достраивает блок до того угла, которого в сетке нет. Верхний —
 * цвета страницы, со скруглением того угла, что смотрит ВНУТРЬ блока: он
 * съедает у нижнего всё, кроме дужки у самого угла.
 *
 * `corner` называет, в каком углу пустой клетки лежит скос: `br` — правый
 * нижний (уступ в начале месяца), `tl` — левый верхний (уступ в конце).
 */
function Fillet({ corner }: { corner: "br" | "tl" }) {
  return (
    <span
      aria-hidden
      className={cn(
        "pointer-events-none absolute size-2.5 bg-paper-raised",
        corner === "br" ? "bottom-0 right-0" : "left-0 top-0",
      )}
    >
      <span
        className={cn(
          // Цвет страницы — тот, что залит на `body` (`bg-paper`), а не
          // самый утопленный тон палитры: за сеткой лежит именно страница.
          "absolute inset-0 bg-paper",
          // Скругляется угол, обращённый к блоку: дуга приходит из центра
          // в противоположном углу — там же, где сходятся клетки.
          corner === "br" ? "rounded-br-lg" : "rounded-tl-lg",
        )}
      />
    </span>
  );
}

export function MonthGrid({
  title,
  meta,
  days,
  renderDay,
  joined,
  weekdayProps,
  padProps,
  dayProps,
  assemble,
}: MonthGridProps) {
  const first = days[0];
  if (first === undefined) return null;

  const offset = weekday(first);
  const filled = (slot: number) => slot >= offset && slot < offset + days.length;

  /** Скругления клетки по её месту в контуре месяца. */
  function corners(slot: number): string {
    if (!joined) return "";
    const column = slot % 7;
    const left = column > 0 && filled(slot - 1);
    const right = column < 6 && filled(slot + 1);
    const up = filled(slot - 7);
    const down = filled(slot + 7);
    return cn(
      !left && !up && "rounded-tl-lg",
      !right && !up && "rounded-tr-lg",
      !left && !down && "rounded-bl-lg",
      !right && !down && "rounded-br-lg",
    );
  }

  /**
   * Класс подложки, закрывающей щели у этой клетки, — по её соседям.
   *
   * Классы записаны целиком: Tailwind ищет имена классов в тексте
   * программы, собрать их из кусков нельзя.
   */
  function bleed(slot: number): string {
    if (!joined) return "";
    const right = slot % 7 < 6 && filled(slot + 1);
    const down = filled(slot + 7);
    if (right && down) return "cell-bleed-rb";
    if (right) return "cell-bleed-r";
    if (down) return "cell-bleed-b";
    return "";
  }

  // Пустые клетки после последнего числа рисуются наравне с ведущими:
  // в первой из них лежит скос нижнего уступа, а без неё её просто не
  // существует в разметке.
  const trailing = (7 - ((offset + days.length) % 7)) % 7;

  /**
   * Место клетки в волне: наискось от левого верхнего угла.
   *
   * Столбец весит вдвое против строки — тогда фронт идёт по диагонали, а
   * не по строкам: сетка собирается как лист, а не как список.
   *
   * Строка недели считается строкой ВЫШЕ первой, потому что она и стоит
   * выше: приходит вместе со своим столбцом, а не отдельным этапом.
   */
  const arriving = (index: number) =>
    assemble
      ? { className: "grid-cell-in", style: { "--i": index } as CSSProperties }
      : null;
  /** Клетка сетки: столбец весит вдвое, строка считается от буквенной. */
  const assembling = (slot: number) =>
    arriving((slot % 7) * 2 + Math.floor(slot / 7) + 1);

  return (
    <section className="space-y-1.5">
      {title ? (
        <div className="flex flex-wrap items-baseline justify-between gap-x-3 border-b border-rule pb-1">
          <h3 className="font-display text-sm font-bold uppercase tracking-wide">{title}</h3>
          {meta ? <p className="font-mono text-[11px] text-ink-muted">{meta}</p> : null}
        </div>
      ) : null}

      <div className={cn("grid grid-cols-7", joined ? "gap-0" : "gap-px")}>
        {WEEKDAY_LABELS.map((name, index) => {
          // Буквы — строка ВЫШЕ первой, поэтому и в волне они на шаг
          // раньше своего столбца.
          const extra = weekdayProps?.(index) ?? arriving(index * 2);
          return (
            <div
              key={name}
              aria-hidden
              className={cn(
                "text-center text-[10px] uppercase text-ink-faint",
                joined ? "pb-1.5" : "pb-0.5",
                extra?.className,
              )}
              style={extra?.style}
            >
              {name}
            </div>
          );
        })}

        {Array.from({ length: offset }, (_, index) => {
          const extra = padProps?.(index) ?? assembling(index);
          return (
            <div
              key={`pad-${index}`}
              aria-hidden
              className={cn("relative", extra?.className)}
              style={extra?.style}
            >
              {/* Скос верхнего уступа — в последней пустой клетке перед
                  первым числом: вогнутый угол блока приходится ровно на её
                  правый нижний угол. */}
              {joined && index === offset - 1 ? <Fillet corner="br" /> : null}
            </div>
          );
        })}

        {days.map((day, index) => {
          const slot = offset + index;
          const extra = dayProps?.(slot) ?? assembling(slot);
          return (
            <div
              key={day}
              className={cn("min-w-0", bleed(slot), extra?.className)}
              style={extra?.style}
            >
              {renderDay(day, corners(offset + index))}
            </div>
          );
        })}

        {Array.from({ length: trailing }, (_, index) => {
          const slot = offset + days.length + index;
          const extra = padProps?.(slot) ?? assembling(slot);
          return (
            <div
              key={`tail-${index}`}
              aria-hidden
              className={cn("relative", extra?.className)}
              style={extra?.style}
            >
              {/* Скос нижнего уступа — в первой пустой клетке после
                  последнего числа, в её левом верхнем углу. */}
              {joined && index === 0 ? <Fillet corner="tl" /> : null}
            </div>
          );
        })}
      </div>
    </section>
  );
}
