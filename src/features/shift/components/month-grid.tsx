import type { CSSProperties, ReactNode } from "react";

import { cn } from "@/lib/utils/cn";

import { weekday, type IsoDate } from "../domain/plain-date";

/**
 * Месяц как в настенном календаре: строка — неделя, столбец — день недели.
 *
 * --- Почему это отдельная деталь ----------------------------------------
 *
 * Так показываются и график смен, и производственный календарь, и это не
 * совпадение: человек сверяет одно с другим глазами, перескакивая между
 * ними, и любое расхождение в раскладке пришлось бы держать в голове.
 * Одна раскладка на оба экрана — единственный способ, чтобы «то же число»
 * оказывалось на том же месте.
 *
 * --- Что здесь считается ------------------------------------------------
 *
 * Ровно одно: сколько пустых клеток поставить перед первым числом, чтобы
 * столбцы совпали с днями недели. Всё остальное — содержимое клетки —
 * решает вызывающий: у графика в клетке часы, у календаря тип дня.
 *
 * --- Месяц как панель (`joined`) ----------------------------------------
 *
 * Клетки стояли врозь, каждая в своей рамке. Сорок бордюров на месяц и
 * четыреста восемьдесят на год — это сетка, которая громче того, что в ней
 * написано: глаз читает решётку, а не смены.
 *
 * Потом они стояли вплотную, одной сплошной плашкой без щелей, и месяц был
 * фигурой с уступом там, где он начинается не с понедельника. Уступ
 * приходилось достраивать скосом, стыки клеток — подкрашивать подложкой от
 * щелей округления, а форму блока считать по соседям каждой клетки.
 *
 * Теперь панель — это КЛЕТКА. Каждые сутки лежат на бумаге отдельным
 * квадратом со скруглением, бликом от лампы по верхней кромке и мягкой
 * тенью вниз (`lit-tile`), а между ними просвет. У месяца своей заливки
 * нет вовсе: он и есть эти клетки, а не плашка под ними.
 *
 * Отсюда сразу три вещи, которых больше нет и объяснять которые не надо:
 * фигура месяца с уступом (клетки стоят врозь, и недостающих дней просто
 * нет), скос вогнутого угла и подложка от щелей между клетками. Просвет и
 * есть то, что раньше протекало между ними как белая нить: он теперь
 * намеренный и одинаковый.
 *
 * Рамка при этом по-прежнему остаётся только у дней, которые что-то
 * означают: вид суток говорит цветом, а толщину даёт свет.
 */

export const WEEKDAY_LABELS = ["пн", "вт", "ср", "чт", "пт", "сб", "вс"];

/**
 * Раскладка года: мерная коробка и сетка месяцев в ней.
 *
 * Два класса, а не один, потому что мерить приходится ПРЕДКА: ширину месяца
 * и кегль в клетке считает сама таблица стилей, запросом к коробке
 * (`100cqw`), а элемент, объявленный мерой самому себе, дал бы кольцо в
 * определении. Правила — в `globals.css`.
 *
 * Здесь они лежат затем, что сеток этих три: график смен, производственный
 * календарь и заглушка рабочего экрана. Разойдись у них раскладка — и
 * заглушка перестала бы совпадать с тем, что встанет на её место, а
 * переключение между графиком и календарём двигало бы клетки под рукой.
 */
export const YEAR_BOX = "year-box min-w-0 flex-1";
export const YEAR_GRID = "year-grid gap-x-6 gap-y-5";

/**
 * Отметка сегодняшних суток — красный контур внутри клетки.
 *
 * --- Зачем ----------------------------------------------------------------
 *
 * На экране до трёхсот шестидесяти пяти одинаковых квадратов, и найти в них
 * себя нечем: числа мелкие, месяцы подписаны, но «где я сейчас» приходится
 * искать счётом. Отметка отвечает на это одним взглядом, и она ровно одна
 * на весь год — потому и работает.
 *
 * --- Почему это не нарушает правило о сигнальном цвете --------------------
 *
 * Правило гласит: сигнальный цвет не украшает. Здесь он и не украшает — он
 * называет ЕДИНСТВЕННУЮ клетку года, от которой человек отсчитывает всё
 * остальное. Это тот же красный, что в знаке сайта, и другого «красного»
 * в палитре нет.
 *
 * --- Почему контур, а не рамка и не заливка --------------------------------
 *
 * Заливка занята видом суток: смена, отпуск, вызов. Рамка занята тоже —
 * пунктирная у отсутствий, сплошная у вызовов. Взяв рамку себе, отметка
 * ПОДМЕНИЛА бы её: сегодняшний отпуск перестал бы отличаться пунктиром от
 * отработанной смены, и это ушло бы из разметки насовсем.
 *
 * `inset-ring` рисуется тенью, то есть отдельным каналом: он ложится
 * поверх клетки, а не вместо чего-то. Рамку сегодняшних суток контур при
 * этом закрывает собой — она под ним, — но закрывает на один день и только
 * в одной клетке года, и вид суток там по-прежнему назван и цветом, и
 * буквой, и подписью.
 *
 * Тень к тому же ничего не занимает в раскладке: клетки в сомкнутом месяце
 * стоят вплотную, и внешнее кольцо налезло бы на соседей.
 */
export const TODAY_MARK = "inset-ring-2 inset-ring-signal";

/**
 * Разделитель в подписи месяца: «8 см | 192 ч | ноч. 64».
 *
 * --- Почему черта, а не косая ----------------------------------------------
 *
 * Была косая. Косая в тексте значит «или» либо дробь — «192,0 ч / ноч. 64,0»
 * читается как отношение одного к другому, будто ночные часы делятся на
 * что-то. Здесь же величины просто стоят рядом, и вертикальная черта именно
 * это и говорит: она разделяет, не связывая. Тот же знак стоит в самом
 * названии приложения между цифрами графика — «1|3».
 *
 * --- Почему отдельной деталью ----------------------------------------------
 *
 * Цвет у черты всегда один и самый тихий (`text-ink-faint`), а величины
 * вокруг — цветные: пропущенные смены красные, вызовы синие, ночные тихие.
 * Раньше разделитель стоял ВНУТРИ цветной вставки и перекрашивался вместе с
 * ней: перед красным числом краснела и косая, и разметка подписи начинала
 * значить то же, что и её содержимое. Вынесенный наружу, он остаётся
 * разметкой.
 *
 * Тот же знак нужен и заглушке рабочего экрана: она обязана занимать ровно
 * то же место, что и подпись расчёта, до доли пикселя.
 */
export function MetaSep() {
  return <span className="text-ink-faint">{" | "}</span>;
}

export interface MonthGridProps {
  /**
   * Заголовок месяца. Необязателен: во всплывающем календаре месяц уже
   * назван в его собственной шапке со стрелками, и вторая подпись под ней
   * была бы повтором.
   */
  title?: ReactNode;
  /** Итог месяца справа от названия: смены, часы, число правок. */
  meta?: ReactNode;
  /** Подряд идущие дни ОДНОГО месяца. */
  days: readonly IsoDate[];
  /**
   * `corners` — классы скругления для этой клетки: у сомкнутого месяца
   * форму держат сами клетки, и знать её может только сетка.
   */
  renderDay: (day: IsoDate, corners: string) => ReactNode;
  /** Месяц одной плашкой: без щелей между клетками, с общим контуром. */
  joined?: boolean;
  /**
   * Добавка к клетке с буквами дня недели — по её месту в неделе.
   *
   * Нужна ровно одному вызывающему: на посадочной странице месяц
   * СОБИРАЕТСЯ, и шапка недели обязана появляться вместе с клетками, а не
   * стоять на месте с первого кадра. Задержку знает только он, а классы
   * раскладки — только эта сетка, поэтому добавка приходит снаружи, а
   * оформление остаётся здесь.
   */
  weekdayProps?: (index: number) => { className?: string; style?: CSSProperties };
  /**
   * Добавка к ПУСТОЙ клетке — по её месту в сетке.
   *
   * Нужна тому же вызывающему, что и `weekdayProps`, и по той же причине:
   * пустые клетки держат строку, и приходить им положено тем же фронтом,
   * что и соседним числам.
   */
  padProps?: (slot: number) => { className?: string; style?: CSSProperties };
  /**
   * Появления у месяца нет вовсе — и это решение, а не пропуск.
   *
   * --- Что здесь перепробовано ------------------------------------------
   *
   * Сперва клетки приходили волной наискось, тем же приёмом, что на первом
   * экране. Потом волну сменило проступание месяца целиком. Обе правки
   * лечили одно и то же и обе промахивались мимо причины.
   *
   * Причина в порядке событий. Пока профиль читается из хранилища, на месте
   * сеток стоит заглушка — и стоит она ровно там же и ровно такой же
   * высоты, до пикселя (`workspace-skeleton.tsx`). Значит, менять её на
   * расчёт нужно НЕЗАМЕТНО: содержимое просто оказывается на месте костей.
   *
   * Любое появление это ломает. Замер по кадрам: заглушка пропадала на 567-й
   * миллисекунде, а месяц в этот миг стоял прозрачным и набирал плотность до
   * 944-й. Между ними — почти четыреста миллисекунд ПУСТОГО места там, где
   * только что была сетка. Это и есть то моргание, ради устранения которого
   * анимацию дважды переделывали: она сама им и была.
   *
   * Поэтому её нет. Сетка появляется тем, что появляется её содержимое, и
   * человек видит не «пусто, потом календарь», а календарь на месте костей.
   */
}

export function MonthGrid({
  title,
  meta,
  days,
  renderDay,
  joined,
  weekdayProps,
  padProps,
}: MonthGridProps) {
  const first = days[0];
  if (first === undefined) return null;

  const offset = weekday(first);

  /**
   * Скругление клетки. Одно на все: клетки лежат на панели врозь, и форму
   * каждая держит сама — по её месту в месяце оно больше не считается.
   */
  const corners = joined ? "rounded-md" : "";

  // Пустые клетки после последнего числа держат строку: без них последняя
  // неделя месяца растянулась бы на всю ширину.
  const trailing = (7 - ((offset + days.length) % 7)) % 7;

  return (
    <section
      // Метка месяца — «ГГГГ-ММ». По ней телефон при открытии находит
      // нынешний месяц и ставит его в середину экрана (`year-view.tsx`):
      // иначе человек каждый раз листает год с января до сегодня. Стоит
      // она на сетке, а не назначается снаружи, потому что сеток три —
      // график, календарь и заглушка, — и метка нужна всем.
      data-month={first.slice(0, 7)}
      className={cn(
        "space-y-1.5",
        // Заливки у месяца нет: панель здесь — КЛЕТКА, а не месяц. Метка
        // нужна лампе: она считает наклон блика по положению блока на
        // экране, и считать его для каждой из четырёхсот клеток значило бы
        // мерить их все на каждую перерисовку. Клетки месяца стоят от
        // лампы на одном и том же расстоянии, поэтому наклон считается
        // один на месяц и наследуется вниз (`--lit-tilt`).
        joined && "lit-aim",
      )}
    >
      {title ? (
        <div className="flex flex-wrap items-baseline justify-between gap-x-3 border-b border-rule pb-1">
          <h3 className="font-display text-sm font-bold uppercase tracking-wide">{title}</h3>
          {meta ? <p className="font-mono text-[11px] text-ink-muted">{meta}</p> : null}
        </div>
      ) : null}

      {/* Просвет между клетками — тот самый, что раньше протекал между
          ними случайной белой нитью от округления долей пикселя. Теперь он
          намеренный и одинаковый, а подкрашивать стыки нечем и незачем. */}
      <div className={cn("grid grid-cols-7", joined ? "gap-0.5 lg:gap-0.75" : "gap-px")}>
        {WEEKDAY_LABELS.map((name, index) => {
          const extra = weekdayProps?.(index);
          return (
            <div
              key={name}
              aria-hidden
              className={cn(
                "text-center text-[10px] uppercase text-ink-faint",
                joined ? "pb-1.5" : "pb-0.5",
                extra?.className,
              )}
              style={extra?.style}
            >
              {name}
            </div>
          );
        })}

        {Array.from({ length: offset }, (_, index) => {
          const extra = padProps?.(index);
          return (
            <div
              key={`pad-${index}`}
              aria-hidden
              className={cn("relative", extra?.className)}
              style={extra?.style}
            />
          );
        })}

        {days.map((day) => (
          <div key={day} className="min-w-0">
            {renderDay(day, corners)}
          </div>
        ))}

        {Array.from({ length: trailing }, (_, index) => {
          const extra = padProps?.(offset + days.length + index);
          return (
            <div
              key={`tail-${index}`}
              aria-hidden
              className={cn("relative", extra?.className)}
              style={extra?.style}
            />
          );
        })}
      </div>
    </section>
  );
}
