import { SettingsPanel } from "./settings-panel";

/**
 * Окно «Создать профиль».
 *
 * --- Почему окно, а не страница с формой ----------------------------------
 *
 * У страницы-анкеты была своя вёрстка тех же вопросов — норма списком с
 * абзацем пояснения, время отсчёта смены отдельным полем. Настройки
 * спрашивают то же самое, и две формы на одни вопросы неизбежно
 * расходятся: пояснение поправили в одной, а человек читает другую.
 *
 * Поэтому вопросы одни, в одном компоненте (`SettingsPanel`), и
 * открываются так же, как из шапки, — окном. Разница только в заголовке:
 * «Создать профиль» вместо «Настроек», и внизу кнопка, которой профиль
 * заводится.
 *
 * --- Почему окно открывается на ГЛАВНОЙ ------------------------------------
 *
 * Раньше кнопка первого экрана вела на `/calculator`, а тот, не найдя
 * профиля, показывал ту же главную с окном поверх. Человек нажимал кнопку
 * и попадал на страницу, которая выглядит как та, с которой он ушёл, — с
 * другим адресом и без единого признака, что он куда-то перешёл. Закрыв
 * окно, он оставался на странице расчёта без расчёта.
 *
 * Теперь окно открывается там, где нажали, и никуда не ведёт. В расчёт
 * человек попадает, когда профиль создан, — то есть когда там есть что
 * показывать.
 *
 * --- Почему возврат из файла — кнопка, а не блок ---------------------------
 *
 * Внизу окна стоял блок «Уже заполняли раньше» — заголовок, две строки
 * пояснения и выбор файла, — и его убрали по делу: человеку, который
 * заводит профиль впервые (а это почти все, кто сюда попадает), он отвечал
 * на вопрос, которого тот не задавал, и отодвигал кнопку «Построить
 * график» на полэкрана вниз.
 *
 * Но вместе с блоком пропал и сам путь, а он нужен ровно здесь. Тот, у кого
 * файл на руках — после чистки браузера, на новом устройстве, — приходит
 * именно в это окно: оно и есть первое, что открывается, когда профиля нет.
 * Проводник, где кнопка «Из файла» стоит, ему при этом недоступен:
 * «Открыть» живёт в шапке расчёта, а расчёта без профиля нет вовсе. Выходило,
 * что восстановить профиль предлагается там, куда без профиля не попасть.
 *
 * Поэтому здесь стоит ОДНА кнопка под главной — без заголовка и пояснений.
 * Она ничего не отодвигает: «Построить график» остаётся на своём месте,
 * а вторую находит тот, кто её ищет.
 *
 * Обе кнопки со значком слева: у главной тот же календарь, что на кнопке первого
 * экрана (человек нажимает ту же дверь, и узнать её должен), у второй —
 * стрелка загрузки. Одна со значком, другая без — выглядело бы недосказанным.
 *
 * Профиль из файла не создаётся заново и не правится этой формой: он
 * открывается как есть, вместе с папками, которые в файле лежат
 * (`storage/library.ts`). Что с ним делать дальше — открыть страницей или
 * положить записью в проводник, — решает тот, кто это окно показал: на
 * главной он становится открытым графиком, в проводнике — ещё одной
 * строкой списка.
 *
 * --- Почему черновик, а не поля по одному ----------------------------------
 *
 * `SettingsPanel` правит профиль, а не набор полей. Поэтому здесь лежит
 * готовый профиль с умолчаниями, панель правит его, а кнопка сохраняет.
 * Заодно исчезает разнобой умолчаний: то, что подставлено в черновике, и
 * есть то, что человек увидит в настройках потом.
 *
 * --- Почему рядом стол с календарём ----------------------------------------
 *
 * Это первое, что человек видит в приложении, и до сих пор он видел форму: пять
 * полей и кнопку, без единого признака, что из этого получится. Отвечать на
 * вопросы вслепую — значит бояться ошибиться, а ошибиться тут легко: поставить
 * смену не на те сутки, выбрать не тот график.
 *
 * Поэтому слева лежит стол (`SchedulePreview`) — ближайшие пять недель его
 * графика теми же клетками, что в расчёте, и итог месяца теми же цифрами. Он
 * перестраивается на каждый ответ, и «тот ли это график» человек узнаёт
 * глазами, не дожидаясь кнопки. Имя графика стоит над сеткой тем же
 * рукописным шрифтом, каким оно встанет в шапке расчёта.
 *
 * Справа — вопросы. На телефоне стол стоит над ними: пока человек не нажал ни
 * одной кнопки, первым он видит свой будущий календарь, а не пустое поле.
 */

const CURRENT_YEAR = new Date().getUTCFullYear();

/** Профиль, каким он будет, если человек не тронет ни одного поля. */
export function blankProfile(): StoredProfile {
  return createProfile({
    displayName: "",
    // Норма приходит одним ответом: человек выбирает основание, а признаки,
    // которые из него следуют, раскладываются по профилю здесь.
    ...weeklyNormGroundFacts("base"),
    // Сегодня — единственная дата, о которой точно известно, что человек её
    // помнит. Свою смену он отмерит от неё.
    firstShiftDate: todayIso(),
    accountingYear: CURRENT_YEAR,
    shiftStartTime: DEFAULT_SHIFT_START,
    // График и продолжительность смены идут парой: второе следует из
    // первого, и подставляются они вместе — здесь и при каждой смене
    // графика в настройках.
    schedulePattern: DEFAULT_SCHEDULE_PATTERN,
    shiftDurationHours: schedulePatternOf(DEFAULT_SCHEDULE_PATTERN).defaultShiftHours,
    // Свой цикл заполнен и у того, кто его не выбирал: числа хранятся
    // всегда, чтобы не пропадать при возврате к заготовке.
    customWorkDays: 1,
    customRestDays: 3,
  });
}

export function CreateProfileModal({
  open,
  onClose,
  onCreated,
  notice,
}: {
  open: boolean;
  onClose: () => void;
  /**
   * Профиль готов.
   *
   * Вторым доводом идут папки из файла, если профиль пришёл файлом: `null`
   * — файл без папок (сохранён прежней версией), `undefined` — профиль
   * заведён здесь же, формой, и никакого файла не было.
   */
  onCreated: (profile: StoredProfile, file?: LibraryFile | null) => void;
  /** Сообщение о нечитаемом профиле, если он был. Место ему — в окне. */
  notice?: ReactNode;
}) {
  const [draft, setDraft] = useState<StoredProfile>(blankProfile);
  const [error, setError] = useState<string | null>(null);

  // Сколько раз окно открывали: номер пересобирает стол, и клетки приходят
  // волной на глазах, а не за закрытой дверью. Номер меняется по ходу
  // отрисовки, а не в эффекте — так в кадре открытия не бывает прежнего стола.
  const [round, setRound] = useState(0);
  const [wasOpen, setWasOpen] = useState(open);
  if (open !== wasOpen) {
    setWasOpen(open);
    if (open) setRound((previous) => previous + 1);
  }

  function submit() {
    setError(null);
    // Пустое имя — не ошибка: обращение нужно человеку, а не расчёту, и
    // отказывать в графике из-за незаполненной строки было бы придиркой.
    const displayName = draft.displayName.trim() || DEFAULT_PROFILE_NAME;
    // Занятое — ошибка, и здесь единственное место, где её можно назвать
    // до того, как профиль заведён: в проводнике два одинаковых имени
    // означают выбор наугад, а удаление — лотерею с данными за год.
    if (nameTaken(displayName)) {
      setError(
        `График «${displayName}» уже есть. Дайте новому другое имя — в проводнике ` +
          `они различаются только им.`,
      );
      return;
    }
    try {
      onCreated({ ...draft, displayName });
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "Не удалось сохранить график.");
    }
  }

  /**
   * Профиль из файла.
   *
   * Имя здесь не проверяется на занятость, в отличие от заведённого формой:
   * файл человек уже выбрал, и «такое имя занято» не пустило бы в
   * приложение его же сохранённый год. Свободное имя подберут там, где
   * профиль ложится в проводник (`importProfileFile`).
   */
  function fromFile() {
    setError(null);
    pickProfileFile(onCreated, setError);
  }

  return (
    <Modal
      open={open}
      onClose={onClose}
      sheet
      title="Создать график"
      // Шире обычного окна: слева стол с календарём, справа вопросы.
      className="w-[min(60rem,calc(100vw-2rem))]"
    >
      <div className="space-y-4">
        {notice}

        <div className="grid gap-5 md:grid-cols-[minmax(0,1fr)_22rem] md:gap-6 lg:grid-cols-[minmax(0,1fr)_24rem]">
          <SchedulePreview profile={draft} round={round} />

          {/* Вопросы — сверху, кнопки — у нижней кромки колонки: стол слева
              тянется во всю высоту окна, и кнопки встают против его итога, а
              не повисают под последним полем с пустотой внизу. */}
          <div className="flex flex-col gap-5">
            <SettingsPanel profile={draft} onChange={setDraft} purpose="create" />

            <div className="mt-auto space-y-3">
              {error ? (
                <p role="alert" className="rounded-xl bg-signal-soft px-4 py-3 text-sm">
                  {error}
                </p>
              ) : null}

              {/* Главная кнопка и возврат из файла — столбиком, а не строкой:
                  строка из двух равных половин уравняла бы их в весе, а это не
                  две равные дороги. Вторая говорит вполголоса (`outline`) и
                  стоит ПОД главной — там, где её ищет тот, кто уже знает, что
                  заполнять ничего не нужно. */}
              <div className="space-y-2">
                <Button type="button" onClick={submit}>
                  <CalendarDays aria-hidden />
                  Построить график
                </Button>
                <Button type="button" variant="outline" onClick={fromFile}>
                  <Upload aria-hidden />
                  Загрузить из файла
                </Button>
              </div>

              <p className="text-center text-xs text-ink-faint">
                Ответы можно поправить в настройках графика.
              </p>
            </div>
          </div>
        </div>
      </div>
    </Modal>
  );
}
