import {
  DEFAULT_SCHEDULE_PATTERN,
  schedulePatternOf,
} from "../domain/schedule-pattern";
import { DEFAULT_SHIFT_START } from "../domain/shift-hours";
import { todayIso } from "../domain/plain-date";
import { weeklyNormGroundFacts } from "../model/derive";
