/**
 * Очертание главной плашки итога с ушком сверху — для `clip-path`.
 *
 * --- Зачем ушко ------------------------------------------------------------
 *
 * В нём стоит выбор периода — того, за который посчитаны три главных
 * числа под ним. Выбор жил кнопкой в строке над сеткой, то есть в
 * стороне от чисел, которые он определяет: человек читал «1972 ч» и не
 * видел рядом, за что это. Ушко ставит ответ на «за какой период»
 * прямо над числами, и плашка с ушком читается одной вещью — папкой с
 * подписанным корешком, тем же образом, что папки в проводнике.
 *
 * --- Почему многоугольник, а не путь SVG -----------------------------------
 *
 * У папок проводника очертание — путь SVG в долях карточки
 * (`objectBoundingBox`), и там это верно: отношение сторон у карточки
 * закреплено. Главная плашка — нет: от 283 точек на планшете до тысячи с
 * лишним на широком мониторе. Путь в долях растягивал бы скругления в
 * овалы, а ушко — в ширину вместе с плашкой.
 *
 * `polygon()` с `calc()` этого лишён: точки ушка отсчитываются от
 * середины в точках, углы тела — от краёв в точках, и форма остаётся
 * той же на любой ширине. Кривые в многоугольнике — ломаные, но в
 * двенадцать звеньев на склон и шесть на угол глаз их не различает.
 *
 * --- Как устроен склон ------------------------------------------------------
 *
 * Кубическая кривая с горизонтальными касательными на обоих концах: от
 * верха тела склон уходит плавно, без излома, и так же плавно ложится в
 * плоский верх ушка. Отдельные скругления у основания и у верха не нужны
 * — кривая и есть скругление.
 *
 * --- Как ушко ужимается -----------------------------------------------------
 *
 * Главная плашка бывает узкой — 291 точка, когда по сторонам стоят мелкие
 * итоги. Ужми там один склон, и ушко вышло бы трапецией с крутыми боками:
 * при постоянном плоском верхе склону оставалось 30 точек на 32 высоты.
 * Поэтому первым уступает плоский верх — от 192 точек до 128, кнопка
 * периода в 128 помещается, — и только потом склон. На узкой плашке он
 * так получает около 60 точек, вдвое больше, и остаётся пологим. Ушко при
 * этом никогда не наезжает на угловые скругления тела.
 */

import type { CSSProperties } from "react";

/** Высота ушка над телом плашки, точек. */
export const TAB_HEIGHT = 32;

/** Половина плоского верха ушка — место под кнопку периода: наибольшая и
 * наименьшая. Самая длинная подпись («2-е полугодие», «Сентябрь 2026»)
 * со знаком и полями — около 140 точек: на наименьшем верхе её края
 * заходят на склон, но там он поднят почти до верха и кнопку не режет. */
const FLAT_MAX = 96;
const FLAT_MIN = 64;
/** Наибольшая ширина склона по горизонтали. */
const SLOPE_MAX = 128;
/** От края тела до начала склона: угловое скругление и зазор после него. */
const EDGE = 18;
/** Скругление углов тела — `rounded-xl`. */
const CORNER = 12;
/** Доля касательных у концов склона: чем больше, тем дольше он «лежит». */
const EASE = 0.5;
/** Звеньев на склон и на угол. */
const SLOPE_STEPS = 12;
const CORNER_STEPS = 6;

/** Число без хвоста нулей: `12.500` → `12.5`, `-0` → `0`. */
function n(value: number): string {
  const text = value.toFixed(3).replace(/\.?0+$/, "");
  return text === "-0" ? "0" : text;
}

/** Половина плоского верха: наибольшая, пока склонам хватает места
 * целиком, а дальше уступает им — до наименьшей. */
const FLAT = `max(${FLAT_MIN}px, min(${FLAT_MAX}px, 50% - ${EDGE + SLOPE_MAX}px))`;

/** Ширина склона: наибольшая, но не больше того, что остаётся у плашки по
 * сторонам плоского верха. */
const SLOPE = `max(0px, min(${SLOPE_MAX}px, 50% - ${EDGE}px - ${FLAT}))`;

/**
 * Многоугольник очертания.
 *
 * `inset` — на сколько точек внутрь: внешний слой (кайма) — ноль, лицо с
 * бумагой — одна. Лицо стоит в кайме с полем в точку со всех сторон
 * (`p-px`), и в своих координатах его ушко совпадает с ушком каймы,
 * сдвинутым на ту же точку вниз: остаток между ними и есть кайма,
 * повторяющая контур. Меняется только скругление углов тела — на точку
 * меньше, чтобы кайма в углах была той же толщины.
 */
export function tabPolygon(inset = 0): string {
  const corner = CORNER - inset;
  const h = TAB_HEIGHT;
  const points: string[] = [];
  const at = (x: string, y: string) => points.push(`${x} ${y}`);

  // Четверть окружности: центр и углы от и до, по часовой стрелке
  // (в координатах экрана ось y смотрит вниз).
  const arc = (
    cx: (dx: number) => string,
    cy: (dy: number) => string,
    from: number,
  ) => {
    for (let step = 0; step <= CORNER_STEPS; step += 1) {
      const angle = ((from + (90 * step) / CORNER_STEPS) * Math.PI) / 180;
      at(cx(corner * Math.cos(angle)), cy(corner * Math.sin(angle)));
    }
  };

  // Доля пути склона по горизонтали и по вертикали при параметре `t`.
  const along = (t: number) =>
    3 * (1 - t) ** 2 * t * EASE + 3 * (1 - t) * t ** 2 * (1 - EASE) + t ** 3;
  const rise = (t: number) => 3 * t ** 2 - 2 * t ** 3;

  // Левый верхний угол тела: от левой кромки к верхней.
  arc(
    (dx) => `${n(corner + dx)}px`,
    (dy) => `${n(h + corner + dy)}px`,
    180,
  );

  // Левый склон: от верха тела к плоскому верху ушка.
  for (let step = 0; step <= SLOPE_STEPS; step += 1) {
    const t = step / SLOPE_STEPS;
    at(
      `calc(50% - ${FLAT} - ${SLOPE} * ${n(1 - along(t))})`,
      `${n(h * (1 - rise(t)))}px`,
    );
  }

  // Правый склон — зеркально: от плоского верха вниз, к телу.
  for (let step = 0; step <= SLOPE_STEPS; step += 1) {
    const t = step / SLOPE_STEPS;
    at(
      `calc(50% + ${FLAT} + ${SLOPE} * ${n(along(t))})`,
      `${n(h * rise(t))}px`,
    );
  }

  // Правый верхний угол тела.
  arc(
    (dx) => `calc(100% - ${n(corner - dx)}px)`,
    (dy) => `${n(h + corner + dy)}px`,
    270,
  );
  // Правый нижний.
  arc(
    (dx) => `calc(100% - ${n(corner - dx)}px)`,
    (dy) => `calc(100% - ${n(corner - dy)}px)`,
    0,
  );
  // Левый нижний.
  arc(
    (dx) => `${n(corner + dx)}px`,
    (dy) => `calc(100% - ${n(corner - dy)}px)`,
    90,
  );

  return `polygon(${points.join(", ")})`;
}

/**
 * Очертание — переменными для `clip-path` (`globals.css`, «Главная плашка
 * итога с ушком»): кайме — внешнее, лицу — на точку внутрь. Считается один
 * раз: многоугольник от данных не зависит, только от ширины плашки, а её
 * браузер подставляет в проценты сам. Одно на плашку расчёта и на её
 * кость в заглушке — иначе разошлись бы и они.
 */
export const TAB_SHAPE_STYLE = {
  "--tab-outer": tabPolygon(0),
  "--tab-inner": tabPolygon(1),
} as CSSProperties;
