"use client";

import { FooterDocuments, FooterEmail } from "@/components/shared/site-footer";

/**
 * Подвал рабочего экрана: документы сайта и обращение к оператору.
 *
 * --- Что отсюда ушло и почему ---------------------------------------------
 *
 * Здесь стоял рассказ о том, где лежат данные, и под ним две кнопки —
 * выгрузка профиля в файл и его удаление с устройства. Ни одной из них тут
 * больше нет, и текста тоже.
 *
 * Рассказ повторял то, что и так сказано на посадочной странице и в
 * условиях использования, — а на рабочем экране, куда человек приходит
 * считать часы, он занимал экран объяснением, которое читают один раз.
 *
 * Кнопки разъехались туда, куда за ними идут. Выгрузка — в шапку: она
 * нужна отовсюду, а не только с самого низа страницы, докуда ещё надо
 * долистать. Удаление — в настройки, рядом со сбросом календаря: это одна
 * и та же мысль «начать заново» на двух глубинах, и выбирать между ними,
 * не видя обеих, было нельзя.
 *
 * Переключатель темы ушёл из подвала в правый нижний угол окна
 * (`ui/theme-toggle.tsx`, `ThemeCorner`): тема относится не к странице, а
 * к окну, и ждать её за всей прокруткой было нечестно — человеку, которому
 * режет глаза, идти до подвала через двенадцать сеток.
 *
 * Строка «Последнее изменение» отсюда тоже ушла. Она отвечала на вопрос
 * «сохранилось ли?» — тот самый, которого у человека нет: запись идёт в
 * браузер при каждой правке, кнопки «Сохранить» у расчёта не существует,
 * и время последней записи не говорит ни о чём, кроме того, что
 * приложение работает.
 *
 * По той же причине ушла и строка «Синхронизировано только что». Она
 * была ссылкой на страницу учётной записи и выглядела кнопкой — то есть
 * предлагала что-то сделать там, где делать нечего: проход случается
 * сам. Синхронизация задумана невидимой, и о ней говорится только тогда,
 * когда без человека она не поедет, — полосой наверху (`sync-notice`).
 *
 * Остаётся то, чему место действительно внизу: перечень документов и
 * адрес для обращений — то же самое и теми же словами, что в подвале
 * остальных страниц.
 */

export function ProfileFooter() {
  return (
    // Подвал стоит после `main`, а не в нём (`workspace.tsx`): тот не ниже
    // окна, и подвал за ним уходит за нижнюю кромку. Отсюда свои поля и
    // ширина — те же, что у `main`, иначе черта над подвалом разошлась бы
    // с краями сетки. Просвет сверху — тот же, что между разделами
    // экрана (`gap-10`), в колонке которых подвал стоял прежде.
    <footer className="mx-auto mt-10 w-full px-6 2xl:max-w-[2000px]">
      <div className="space-y-4 border-t border-rule py-6 text-sm">
        {/* Документы — тем же перечнем, что на остальных страницах
            (`shared/site-footer.tsx`): политика обязана быть доступна с
            любой страницы, а рабочий экран — та, с которой человек уходит
            реже всего. */}
        <FooterDocuments />

        {/* Адрес — той же строкой, что на остальных страницах: спрашивают
            с той страницы, на которой застал вопрос, а не с той, которую
            для этого полагается найти. */}
        <FooterEmail />
      </div>
    </footer>
  );
}
