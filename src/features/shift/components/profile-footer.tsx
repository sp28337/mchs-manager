"use client";

import { FooterDocuments } from "@/components/shared/site-footer";
import { ThemeToggle } from "@/components/ui/theme-toggle";
import { SyncStatus } from "@/features/sync/ui/sync-status";

import type { StoredProfile } from "../storage/profile";

/**
 * Подвал рабочего экрана: тема, условия, время последней правки.
 *
 * --- Что отсюда ушло и почему ---------------------------------------------
 *
 * Здесь стоял рассказ о том, где лежат данные, и под ним две кнопки —
 * выгрузка профиля в файл и его удаление с устройства. Ни одной из них тут
 * больше нет, и текста тоже.
 *
 * Рассказ повторял то, что и так сказано на посадочной странице и в
 * условиях использования, — а на рабочем экране, куда человек приходит
 * считать часы, он занимал экран объяснением, которое читают один раз.
 *
 * Кнопки разъехались туда, куда за ними идут. Выгрузка — в шапку: она
 * нужна отовсюду, а не только с самого низа страницы, докуда ещё надо
 * долистать. Удаление — в настройки, рядом со сбросом календаря: это одна
 * и та же мысль «начать заново» на двух глубинах, и выбирать между ними,
 * не видя обеих, было нельзя.
 *
 * Остаётся то, чему место действительно внизу: переключатель темы,
 * перечень документов (он один на все страницы сайта) и строка о том,
 * когда профиль сохранялся в последний раз.
 */

export interface ProfileFooterProps {
  profile: StoredProfile;
}

export function ProfileFooter({ profile }: ProfileFooterProps) {
  return (
    // `mt-auto` — от колонки страницы (`workspace.tsx`): на коротком
    // содержимом подвал уходит к нижней кромке окна, а не висит под
    // последним блоком посреди экрана.
    <footer className="mt-auto space-y-4 border-t border-rule py-6 text-sm">
      <div className="flex flex-col md:flex-row-reverse justify-between items-center">
        <div className="flex justify-center pt-8 pb-12 md:ml-auto md:pb-8 ">
          <ThemeToggle/>
        </div>

        {/* Строка собрана `div`, а не `p`: внутри перечень документов, а
            это `nav`. Блочный узел внутри абзаца — недопустимая разметка:
            браузер закрывает `p` сам, разметка после гидратации не
            совпадает с разметкой сборки, и React сообщает об ошибке. */}
        <div className="flex flex-wrap items-center justify-center gap-x-4 gap-y-1 text-xs text-ink-muted">
          {/* Документы — тем же перечнем, что на остальных страницах
              (`shared/site-footer.tsx`): политика обязана быть доступна с
              любой страницы, а рабочий экран — та, с которой человек
              уходит реже всего. */}
          <FooterDocuments className="max-sm:justify-items-center" />
          <span>
          Последнее изменение:{" "}
          {new Date(profile.savedAt).toLocaleString("ru-RU", {
            dateStyle: "long",
            timeStyle: "short",
          })}
          .
          </span>
          {/* Состояние синхронизации — здесь же, рядом со временем
              последней правки: вопрос у человека один и тот же («моё
              сохранено? моё уехало?»), и ответы на него должны стоять
              рядом. Без учётной записи строка приглашает её завести, при
              выключенной синхронизации не рисуется вовсе. */}
          <SyncStatus />
        </div>
      </div>
    </footer>
  );
}
