"use client";

import { Save } from "lucide-react";
import { useRef, useState, type ReactNode } from "react";

import { ConfirmDialog } from "@/components/ui/confirm-dialog";

import { profileNeedsExport, type StoredProfile } from "../storage/profile";
import { useSaveToFile } from "./save-to-file";

/**
 * «Сначала сохранить нынешний?» — перед тем как открыть другой профиль.
 *
 * --- Почему вопрос задаётся ПОСЛЕ выбора ----------------------------------
 *
 * Раньше он стоял первым: нажал «Открыть» — ответь про нынешний график, и
 * только потом увидишь, из чего выбирать. Отвечать на такой вопрос нечем,
 * потому что человек ещё не знает, ради чего меняет профиль, — а иногда и
 * вовсе нажал «Открыть», чтобы просто посмотреть список.
 *
 * Теперь первым идёт проводник (`profile-explorer.tsx`), а этот вопрос
 * встаёт в тот миг, когда выбор уже сделан и последствие понятно.
 *
 * --- О чём вопрос на самом деле -------------------------------------------
 *
 * Не о потере профиля: с появлением проводника нынешний график никуда не
 * девается — он остаётся записью в списке, со всеми отпусками и правками.
 * Вопрос о КОПИИ В ФАЙЛЕ: браузеры чистят хранилище сами, и файл — то
 * единственное, что эту чистку переживёт.
 *
 * --- Когда он НЕ задаётся --------------------------------------------------
 *
 * Условия два, и нужны оба.
 *
 * Первое — человек правил открытый профиль (`changed`). Второе — правка не
 * ушла в файл (`profileNeedsExport`), и об этом приложение судит не со
 * слов, а по делу: отметку ставит сама выгрузка.
 *
 * Одного второго было мало, и это была ошибка: отметки о выгрузке нет ни у
 * кого, кто ни разу не сохранял профиль файлом, — а таких большинство.
 * Человек открывал приложение, шёл в проводник за другим графиком и
 * получал вопрос о сохранении того, к чему в этот раз даже не прикасался.
 * Вопрос, который задают всегда, перестают читать — и однажды отвечают
 * «без сохранения» там, где сохранить стоило.
 *
 * --- Почему продолжение приходит извне ------------------------------------
 *
 * Открыть профиль из проводника, открыть файл, завести новый — действия
 * разные, а вопрос перед ними один. Поэтому здесь только вопрос, а что
 * делать после ответа, приносит с собой тот, кто спрашивает.
 */
export function useConfirmSwitch(
  profile: StoredProfile,
  /** Правил ли человек открытый профиль (`useProfile().touched`). */
  changed: boolean,
): {
  /** Спросить, если нужно, и продолжить. */
  ask: (proceed: () => void) => void;
  /** Окна. Ставятся в конце разметки вызывающего. */
  dialogs: ReactNode;
} {
  const [warning, setWarning] = useState(false);
  // Продолжение живёт в ref, а не в состоянии: оно не участвует в
  // отрисовке, и лишний её прогон при каждом выборе профиля не нужен.
  const pending = useRef<(() => void) | null>(null);

  const run = () => {
    const proceed = pending.current;
    pending.current = null;
    proceed?.();
  };

  const save = useSaveToFile(profile, { onSaved: run });

  return {
    ask: (proceed) => {
      if (!changed || !profileNeedsExport(profile)) {
        proceed();
        return;
      }
      pending.current = proceed;
      setWarning(true);
    },
    dialogs: (
      <ConfirmDialog
        open={warning}
        onClose={() => setWarning(false)}
        // Согласие не открывает выбранный профиль — его откроет сама
        // выгрузка, когда файл уйдёт человеку. Открыть сразу значило бы
        // спросить «сохранить?» и не дать сохранить.
        onConfirm={save.ask}
        title="Сохранить профиль в файл?"
        confirm="Сохранить в файл"
        icon={<Save aria-hidden />}
        // Отдельной «Отмены» у окна нет: вопрос здесь не «делать?», а
        // «сначала сохранить?», и отказ от него — не бездействие, а второй
        // путь. Ничего не делать по-прежнему можно крестиком и клавишей Esc.
        decline={{ label: "Открыть без сохранения", onClick: run }}
      >
        <p>
          С последней выгрузки график изменился. Нынешний профиль останется в
          проводнике на этом устройстве, но копии в файле у него не будет.
        </p>
        <p className="text-ink-muted">
          Браузер чистит своё хранилище сам, и файл — единственное, что эту
          чистку переживёт.
        </p>
      </ConfirmDialog>
    ),
  };
}
