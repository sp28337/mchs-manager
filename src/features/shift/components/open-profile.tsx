"use client";

import { Save } from "lucide-react";
import { useRef, useState, type ReactNode } from "react";

import { Button } from "@/components/ui/button";
import { ConfirmDialog } from "@/components/ui/confirm-dialog";
import { Modal } from "@/components/ui/modal";

import {
  importProfile,
  profileNeedsExport,
  type StoredProfile,
} from "../storage/profile";
import { useSaveToFile } from "./save-to-file";

/**
 * Открыть профиль из файла.
 *
 * --- Почему это кнопка шапки, а не поле в настройках ----------------------
 *
 * Выбор файла стоял в настройках, внизу закладки профиля: заголовок,
 * пояснение в две строки, подпись «Выбрать файл профиля» и рядом «Файл не
 * выбран». Четыре строки на действие, которое делают одним движением, — и
 * все четыре нужно было сперва найти, открыв настройки и прокрутив их до
 * конца.
 *
 * При этом действий у профиля ровно три, и они одного рода: настроить,
 * сохранить, открыть. Два из них уже стояли в шапке; третье лежало на два
 * нажатия глубже безо всякой причины — кроме той, что когда-то оно
 * появилось в окне создания и осталось жить рядом.
 *
 * Теперь их три в ряд, и каждое — одно нажатие. Порядок в шапке
 * рассказывает историю профиля слева направо: настроить нынешний, открыть
 * другой, сохранить нынешний.
 *
 * --- Почему спрашивается «сначала сохранить?» -----------------------------
 *
 * Открыть другой профиль — значит заменить нынешний, а нынешний лежит
 * только здесь, в браузере: копии на сервере нет. Если с последней правки
 * график не уносили в файл, вопрос обязателен — но именно вопрос, а не
 * запрет: человек вправе заменить профиль, не сохраняя, и отказ ведёт
 * прямо к выбору файла.
 *
 * А если файл уже сохранён, спрашивать не о чем: выбор открывается сразу.
 * Отметку о выгрузке ставит сама выгрузка (`markProfileExported`), и
 * ответ «да, сохранил» приложение получает не со слов, а по делу.
 *
 * --- Почему поле файла спрятано --------------------------------------------
 *
 * Родная кнопка выбора подписана браузером — «Choose File» даже в русском
 * интерфейсе, — и поменять надпись со страницы нельзя. Поэтому поле лежит
 * рядом невидимым, а зовёт его кнопка шапки. Клавиатуре и программе чтения
 * это ничего не стоит: кнопка своя, обычная, с именем.
 */
export function useOpenProfile(
  profile: StoredProfile,
  onOpened: (profile: StoredProfile) => void,
): {
  /** Спросить, если нужно, и открыть выбор файла. */
  ask: () => void;
  /** Скрытое поле и окна. Ставятся в конце разметки вызывающего. */
  dialogs: ReactNode;
} {
  const input = useRef<HTMLInputElement>(null);
  const [warning, setWarning] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Выбор файла открывается ПРЯМО из нажатия, без круга через состояние:
  // браузер пускает к нему только по живому действию человека.
  const pick = () => input.current?.click();

  const save = useSaveToFile(profile, { onSaved: pick });

  return {
    ask: () => {
      if (profileNeedsExport(profile)) setWarning(true);
      else pick();
    },
    dialogs: (
      <>
        <input
          ref={input}
          type="file"
          accept="application/json,.json"
          className="sr-only"
          // Поле не сбрасывается само: выбрав тот же файл второй раз,
          // человек не получил бы события вовсе — значение не изменилось.
          // А второй раз он его выбирает как раз тогда, когда первый не
          // прочитался.
          onChange={async (event) => {
            const file = event.target.files?.[0];
            event.target.value = "";
            if (!file) return;
            setError(null);
            try {
              onOpened(importProfile(await file.text()));
            } catch (cause) {
              setError(cause instanceof Error ? cause.message : "Файл не прочитан.");
            }
          }}
        />

        <ConfirmDialog
          open={warning}
          onClose={() => setWarning(false)}
          // Согласие не открывает выбор файла — его откроет сама выгрузка,
          // когда файл уйдёт человеку. Открыть сразу значило бы спросить
          // «сохранить?» и не дать сохранить.
          onConfirm={save.ask}
          title="Сначала сохранить нынешний?"
          confirm="Сохранить в файл"
          icon={<Save aria-hidden />}
          // Отдельной «Отмены» у окна нет: вопрос здесь не «делать?», а
          // «сначала сохранить?», и отказ от него — не бездействие, а
          // второй путь. Ничего не делать по-прежнему можно крестиком и
          // клавишей Esc.
          decline={{ label: "Открыть без сохранения", onClick: pick }}
        >
          <p>
            С последней правки график не сохранялся в файл. Открыв другой
            профиль, вы замените нынешний — вместе с отпусками, больничными и
            всем, что отмечено на сетках.
          </p>
          <p className="text-ink-muted">
            Отменить будет нельзя: данные лежат только на этом устройстве,
            копии на сервере нет.
          </p>
        </ConfirmDialog>

        {/* Нечитаемый файл — не молчание и не строка мелким шрифтом где-то
            внизу: человек только что выбрал файл и ждёт свой график.
            Окно называет причину теми же словами, что и разбор профиля, —
            по ним видно, тот ли файл он вообще открыл. */}
        <Modal
          open={error !== null}
          onClose={() => setError(null)}
          title="Файл не открылся"
          className="w-[min(26rem,calc(100vw-2rem))]"
        >
          <div className="space-y-4">
            <div className="space-y-2 rounded-xl bg-paper-raised px-4 py-3 text-sm">
              <p>{error}</p>
              <p className="text-ink-muted">
                Нужен файл, сохранённый этим же приложением, — тот, что уходит
                в загрузки по кнопке «Сохранить». Нынешний профиль остался на
                месте.
              </p>
            </div>
            <Button type="button" size="sm" onClick={() => setError(null)}>
              Понятно
            </Button>
          </div>
        </Modal>

        {save.dialog}
      </>
    ),
  };
}
