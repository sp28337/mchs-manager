/**
 * Настройки на двух закладках: их общий тип и имена.
 *
 * --- Почему закладки, а не один свиток ------------------------------------
 *
 * В настройках лежат две вещи разной природы. Первая — ответы анкеты: кто
 * человек, по какому графику работает, с какого числа. Их правят редко и
 * по одному. Вторая — всё, что он отметил на сетках за год: отпуска,
 * больничные, вызовы, переносы смен. Их накапливается два десятка, и
 * смотрят на них не тогда же и не за тем же.
 *
 * Сложенные в один свиток, они мешают друг другу: за анкетой приходится
 * прокручивать перечень, а за перечнем — анкету. Закладки разводят их по
 * двум ответам на вопрос «зачем я сюда открыл»: поправить себя или
 * посмотреть, что наотмечал.
 *
 * --- Почему здесь остались только имена ------------------------------------
 *
 * Сама дорожка закладок рисуется полосой цифр (`period-summary.tsx`): при
 * открытых настройках итог периода уступает ей своё место на странице.
 * Здесь же лежало второе её воплощение — для плавающего окна настроек, —
 * и вместе с окном оно ушло: способ показать настройки теперь один, на
 * всех ширинах.
 *
 * Имена остались общими нарочно: их читает и дорожка, и заголовок раздела
 * под ней (`workspace.tsx`), и разойтись им нельзя.
 */
export type SettingsTab = "profile" | "changes";

export const SETTINGS_TAB_LABEL: Record<SettingsTab, string> = {
  profile: "Настройки профиля",
  changes: "Внесённые изменения",
};
