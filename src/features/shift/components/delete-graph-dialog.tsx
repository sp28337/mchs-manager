"use client";

import { Trash2 } from "lucide-react";

import { ConfirmDialog } from "@/components/ui/confirm-dialog";

/**
 * Вопрос «Удалить график?» — один на всё приложение.
 *
 * Спрашивают в двух местах: в настройках (открытый график) и в «Графиках»
 * (любой из списка). Окно там и там одно и то же, потому что и вопрос один:
 * разное окно для одного действия человек читает как разное действие, а
 * удаление — то место, где ошибиться про смысл нельзя.
 *
 * Имя — тем же рукописным шрифтом, что названия графика в шапке расчёта
 * (`profile-name.tsx`): человек узнаёт свой график по написанию, а не по
 * строке чужого шрифта. Без кавычек: другая гарнитура и так отделяет имя от
 * текста. Рукописная гарнитура мельче печатной при том же кегле, поэтому она
 * на ступень крупнее окружающего текста. Длинное имя переносится, а не
 * выталкивает окно.
 *
 * Имя приходит снимком, а не живым значением: после «Удалить» открывается
 * соседний график, а окно закрывается дольше, чем меняется страница, — с
 * живым именем в тексте на глазах менялось то, что только что стёрли. Снимок
 * делает вызывающий в момент, когда окно открывает.
 */
export function DeleteGraphDialog({
  open,
  name,
  onClose,
  onConfirm,
}: {
  open: boolean;
  /** Имя графика на момент, когда о нём спросили. */
  name: string;
  onClose: () => void;
  onConfirm: () => void;
}) {
  return (
    <ConfirmDialog
      open={open}
      onClose={onClose}
      onConfirm={onConfirm}
      title="Удалить график?"
      confirm="Удалить"
      icon={<Trash2 aria-hidden />}
      destructive
    >
      <p>
        График{" "}
        <span className="font-hand text-xl leading-none break-words text-ink">
          {name || "Имя графика"}
        </span>{" "}
        и все его данные будут удалены без возможности восстановления.
      </p>
    </ConfirmDialog>
  );
}
