import { describe, expect, it } from "vitest";

import { TAB_HEIGHT, tabPolygon } from "./tab-shape";

/**
 * Очертание плашки с ушком.
 *
 * Многоугольник собран из строк `calc()`, и опечатка в одной из них
 * браузер не остановит — он молча отбросит весь `clip-path`, и плашка
 * останется прямоугольником. Поэтому проверяется сама строка: что точек
 * столько, сколько задумано, что ушко начинается и кончается на верху
 * тела, а вершина его — на нуле, и что склоны зеркальны.
 */
describe("очертание плашки с ушком", () => {
  // Точки разделены запятыми, но запятые есть и внутри `max(…, min(…))`:
  // делить можно только там, где все скобки уже закрыты.
  const точки = (polygon: string) => {
    const тело = polygon.replace(/^polygon\(/, "").replace(/\)$/, "");
    const out: string[] = [];
    let глубина = 0;
    let начало = 0;
    for (let i = 0; i < тело.length; i += 1) {
      if (тело[i] === "(") глубина += 1;
      else if (тело[i] === ")") глубина -= 1;
      else if (тело[i] === "," && глубина === 0) {
        out.push(тело.slice(начало, i).trim());
        начало = i + 1;
      }
    }
    out.push(тело.slice(начало).trim());
    return out;
  };

  it("многоугольник из четырёх углов и двух склонов", () => {
    // Четыре угла по семь точек и два склона по тринадцать.
    expect(точки(tabPolygon())).toHaveLength(4 * 7 + 2 * 13);
  });

  it("склон начинается у верха тела и поднимается до нуля", () => {
    const склон = точки(tabPolygon()).slice(7, 7 + 13);
    expect(склон[0]).toMatch(new RegExp(` ${TAB_HEIGHT}px$`));
    expect(склон.at(-1)).toMatch(/ 0px$/);
  });

  it("склоны зеркальны: высоты левого — те же, что у правого наоборот", () => {
    const все = точки(tabPolygon());
    const высота = (p: string) => p.split(" ").at(-1);
    const левый = все.slice(7, 7 + 13).map(высота);
    const правый = все.slice(7 + 13, 7 + 26).map(высота);
    expect(правый).toEqual([...левый].reverse());
  });

  it("у лица скругления на точку меньше, а ушко то же", () => {
    const кайма = tabPolygon(0);
    const лицо = tabPolygon(1);
    expect(кайма).toContain("calc(100% - 12px)");
    expect(лицо).toContain("calc(100% - 11px)");
    // Склоны одинаковы в своих координатах.
    const склоны = (p: string) => точки(p).slice(7, 7 + 26);
    expect(склоны(лицо)).toEqual(склоны(кайма));
  });

  // Координата точки на плашке заданной ширины: `calc()`, `min()`, `max()`
  // и проценты — тем же счётом, что у браузера.
  const x = (point: string | undefined, width: number) => {
    if (point === undefined) throw new Error("точки нет в многоугольнике");
    const выражение = point
      .replace(/ [\d.]+px$/, "")
      .replace(/calc\(/g, "(")
      .replace(/([\d.]+)%/g, `($1 * ${width} / 100)`)
      .replace(/px/g, "")
      .replace(/\b(min|max)\(/g, "Math.$1(");
    return Number(new Function(`return ${выражение};`)());
  };

  it.each([
    // Узкая — когда по сторонам стоят мелкие итоги: верх уступил склонам.
    { ширина: 291, верх: 128, склон: 63.5 },
    // Широкая: обе меры наибольшие.
    { ширина: 518, верх: 192, склон: 128 },
    { ширина: 1138, верх: 192, склон: 128 },
  ])("на плашке в $ширина точек верх $верх, склон $склон", ({ ширина, верх, склон }) => {
    const левый = точки(tabPolygon()).slice(7, 7 + 13);
    const правый = точки(tabPolygon()).slice(7 + 13, 7 + 26);
    const основание = x(левый[0], ширина);
    const начало = x(левый.at(-1), ширина);
    expect(начало - основание).toBeCloseTo(склон, 3);
    expect(x(правый[0], ширина) - начало).toBeCloseTo(верх, 3);
    // Склон не наезжает на скругление угла тела.
    expect(основание).toBeGreaterThanOrEqual(18);
  });

  it("в строке нет нечисел и минус-нулей", () => {
    expect(tabPolygon()).not.toMatch(/NaN|Infinity|-0px/);
  });
});
