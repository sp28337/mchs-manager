"use client";

import { User } from "lucide-react";
import { useEffect, useId, useRef, useState } from "react";

import { cn } from "@/lib/utils/cn";
import { MENU_LIST, MENU_ROW_HOVER } from "@/components/ui/menu-row";

import type { LibraryEntry } from "../storage/library";
import type { StoredProfile } from "../storage/profile";

/**
 * Имя профиля — водяным знаком, и через него же — выбор другого профиля.
 *
 * --- Почему имя больше не правится нажатием --------------------------------
 *
 * Правилось: нажатие превращало водяной знак в поле, и имя менялось прямо
 * на месте. Удобно, пока на имя нажимают ради правки, — но нажимали на
 * него и случайно, и чтобы переключиться на другой профиль, и в обоих
 * случаях получали курсор в чужом слове. Имя — такое же свойство профиля,
 * как график и норма, и правится оно там же, где они: в настройках.
 *
 * --- Что делает нажатие теперь ---------------------------------------------
 *
 * Открывает перечень ДРУГИХ профилей — тех, что лежат в проводнике, — и
 * выбранный открывается вместо нынешнего. Имя стоит там, где человек и так
 * смотрит, и «этот график не тот» — ровно тот вопрос, с которым на него
 * смотрят. Через проводник то же самое стоило трёх нажатий: меню, «Открыть
 * профиль», строка.
 *
 * Других профилей нет — нажимать незачем, и имя остаётся просто надписью:
 * без указателя-«пальца» и без отклика на наведение. Кнопка, открывающая
 * пустой перечень, обещала бы выбор, которого нет.
 *
 * Открытие идёт тем же путём, что из проводника (`workspace.tsx`,
 * `askOpenEntry`): с вопросом, не сохранить ли нынешний в файл, если он
 * правился, и с переставленным указателем на открытую запись.
 *
 * --- Почему такое бледное ------------------------------------------------
 *
 * Имя — подпись к экрану, а не заголовок, и спорить с цифрами ему не за
 * что. Цвет у него — обычные чернила при двадцати процентах: водяной знак,
 * нейтральный серый на обеих темах. Одно время имя красили цветом полос
 * меню — тогда ещё тёплым серым, — и рядом с холодной бумагой оно
 * читалось желтоватым; теперь знаки шапки сами нарисованы чернилами
 * (`MARK_EMPTY`), и оттенок у имени с ними один, а бледнее оно потому,
 * что это надпись во всю строку, а не тонкий контур.
 *
 * Тот же цвет и над цифрами на узком экране: имя одно, и выглядеть оно
 * обязано одинаково.
 *
 * Под указателем оно тускнеет вдвое, до десяти процентов, — если на него
 * можно нажать. Прежде было наоборот: бледное в покое и ярче под указателем;
 * теперь в покое оно читается, а нажимаемость выдаёт отклик на наведение.
 */
/**
 * Простор для рукописных букв внутри обрезки.
 *
 * `truncate` обрезает всё, что выходит за рамку узла, а у рукописной
 * гарнитуры буквы выходят за строку: замер в 30 точках — до 29 над
 * линией букв и 12 под ней, сорок одна точка краски при строке в
 * тридцать. Строка шапки к тому же `leading-none`, и рамка узла
 * начинается на 7 точек ниже верха «Ё» и кончается на 4 выше низа «Щ».
 * Обрезка срезала верх у прописных «Т» и «П» — имя «Тараканов П.Н.»
 * читалось с плоской крышей. По горизонтали росчерк первой буквы выходит
 * влево на точку.
 *
 * По вертикали поля внутрь и столько же отрицательных полей наружу
 * расширяют рамку, по которой режет `truncate`, и не трогают раскладку:
 * строка остаётся высотой в тридцать точек, и имя стоит на той же линии,
 * что «ГРАФИК». Десять точек — с запасом на надстрочные знаки (`Й`, `Ё`).
 *
 * По горизонтали так нельзя, и это проверено замером. Ширина кнопки
 * ограничена шириной заголовка (`max-w-full`), а заголовок по ширине —
 * это кнопка за вычетом её отрицательных полей. Круг замыкался на
 * четыре точки меньше, чем нужно тексту: кнопка 219 при содержимом 223,
 * и многоточие съедало последнюю букву имени. Поэтому у кнопки по
 * горизонтали только поле внутрь — две точки на росчерк первой буквы,
 * а имя от этого отодвигается от «ГРАФИК» на те же две, что незаметно.
 * У самого заголовка (он режет надпись, когда имя не кнопка) поля
 * парные: его ширину ничто снаружи не ограничивает по нему самому.
 */
const ПРОСТОР_ЗАГОЛОВКА = "-my-2.5 py-2.5 -mx-0.5 px-0.5";
const ПРОСТОР_КНОПКИ = "-my-2.5 py-2.5 px-0.5";

export function ProfileName({
  profile,
  others,
  onPick,
  place = "page",
}: {
  profile: StoredProfile;
  /** Другие профили проводника — те, на которые можно переключиться. */
  others: readonly LibraryEntry[];
  /** Открыть выбранный профиль вместо нынешнего. */
  onPick: (entry: LibraryEntry) => void;
  /**
   * Где стоит имя.
   *
   * `page` — над цифрами, крупно: так оно стоит на узком экране, где в
   * шапке места нет.
   *
   * `header` — в строке шапки, сразу за знаком сайта, в размер букв
   * «ГРАФИК 1|3».
   */
  place?: "page" | "header";
}) {
  const [открыто, setОткрыто] = useState(false);
  const гнездо = useRef<HTMLDivElement>(null);
  const id = useId();
  const вШапке = place === "header";
  const имя = profile.displayName || "Имя графика";
  const выбор = others.length > 0;

  // Закрывается всеми способами, какими обязано: `Esc`, нажатие мимо, уход
  // фокуса. Те же три, что у меню в шапке и у легенды.
  useEffect(() => {
    if (!открыто) return;

    const закрыть = () => setОткрыто(false);
    const мимо = (событие: PointerEvent) => {
      if (!гнездо.current?.contains(событие.target as Node)) закрыть();
    };
    const клавиша = (событие: KeyboardEvent) => {
      if (событие.key === "Escape") закрыть();
    };
    const фокус = (событие: FocusEvent) => {
      if (!гнездо.current?.contains(событие.target as Node)) закрыть();
    };

    document.addEventListener("pointerdown", мимо);
    document.addEventListener("keydown", клавиша);
    document.addEventListener("focusin", фокус);

    return () => {
      document.removeEventListener("pointerdown", мимо);
      document.removeEventListener("keydown", клавиша);
      document.removeEventListener("focusin", фокус);
    };
  }, [открыто]);

  // По алфавиту, а не по свежести: место профиля в перечне не должно
  // меняться от того, какой правили последним, — тогда рука запоминает,
  // где он.
  const перечень = [...others].sort((a, b) => a.name.localeCompare(b.name, "ru"));

  return (
    // Окошко — вне заголовка, а не внутри: у имени в шапке стоит
    // `truncate`, и всё, что выходит за его рамку, обрезалось бы вместе с
    // длинным именем.
    <div ref={гнездо} className={cn("relative min-w-0", !вШапке && "text-center")}>
      <h1
        className={cn(
          // Цвет — на заголовке, а не на буквах внутри: у длинного имени
          // многоточие рисует тот узел, что обрезает, и цветом ЭТОГО узла.
          // Стоял бы цвет на внутренней надписи — многоточие вышло бы
          // цветом обычного текста, ярким пятном на конце бледного имени.
          "font-hand text-ink",
          вШапке
            ? // Рукописная гарнитура мельче печатной при том же кегле: её
              // строчные — в полроста прописных, а росчерки уходят вверх и
              // вниз. В тех же 20 точках, что «ГРАФИК», имя читалось бы
              // сноской; в 30 высота строчных встаёт вровень с высотой
              // прописных названия. `truncate` — длинное имя обрезается, а
              // не выталкивает меню за край строки.
              cn("min-w-0 truncate text-3xl leading-none", ПРОСТОР_ЗАГОЛОВКА)
            : "text-3xl leading-tight sm:text-5xl",
        )}
      >
        {выбор ? (
          <button
            type="button"
            onClick={() => setОткрыто((было) => !было)}
            aria-expanded={открыто}
            aria-controls={id}
            // Имя кнопки — само имя профиля и то, что нажатие делает:
            // «Петров И. С.» без продолжения не говорит, что за ним выбор.
            aria-label={`${имя}. Выбрать другой график`}
            className={cn(
              // Указатель над текстом везде стрелка (`globals.css`), и
              // «палец» — единственный признак нажимаемого. У имени он тем
              // нужнее, что на кнопку оно не похоже вовсе.
              "max-w-full cursor-pointer truncate rounded-sm transition-opacity",
              ПРОСТОР_КНОПКИ,
              // Двадцать процентов, под указателем и при открытом выборе —
              // десять: надпись отзывается, уходя в тень, а не вспыхивая.
              "opacity-20 hover:opacity-10",
              открыто && "opacity-10",
              // В фокусе с клавиатуры — в полную силу: прозрачность кнопки
              // гасит и её обводку, а рамка фокуса обязана быть видна.
              "focus-visible:opacity-100 focus-visible:outline-2 focus-visible:outline-offset-4 focus-visible:outline-ink",
            )}
          >
            {имя}
          </button>
        ) : (
          <span className="opacity-20">{имя}</span>
        )}
      </h1>

      {открыто && (
        <div
          id={id}
          role="group"
          aria-label="Другие графики"
          className={cn(
            // `lit modal-lift` — та же живая кайма и тень, что у меню в
            // шапке: окошко лежит поверх страницы на той же высоте. Выше
            // полосы цифр (`z-40`), иначе на узком экране оно уходило бы
            // под неё.
            "lit modal-lift absolute top-full z-50 mt-2 w-64 max-w-[calc(100vw-3rem)]",
            "pop-in [--pop-y:-6px]",
            "max-h-[60svh] overflow-y-auto rounded-xl bg-paper-raised p-1.5 text-left",
            MENU_LIST,
            // В шапке — от левого края имени, вниз; над цифрами — по
            // середине, под самим именем: оно там стоит по центру.
            вШапке ? "left-0" : "left-1/2 -translate-x-1/2",
          )}
        >
          <p className="px-2.5 pt-1.5 pb-0.5 text-xs text-ink-muted">Открыть другой график</p>
          {перечень.map((entry) => (
            <button
              key={entry.id}
              type="button"
              onClick={() => {
                setОткрыто(false);
                onPick(entry);
              }}
              className={cn(
                "flex w-full items-center gap-2.5 rounded-lg px-2.5 py-2 text-left text-sm text-ink",
                "cursor-pointer",
                MENU_ROW_HOVER,
                "focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-ink",
              )}
            >
              <User aria-hidden className="size-4 shrink-0 text-ink-muted" />
              <span className="min-w-0 truncate">{entry.name || "Без имени"}</span>
            </button>
          ))}
        </div>
      )}
    </div>
  );
}
