"use client";

import { useEffect } from "react";

import { Button } from "@/components/ui/button";
import { LoadingScreen } from "@/components/ui/loading-mark";
import { useNavigate } from "@/components/shared/navigation-loading";
import { SiteHeader } from "@/components/shared/site-header";
import { RegisterForm } from "./register-form";
import { Workspace } from "./workspace";
import { useProfile } from "../storage/use-profile";

/**
 * Экран калькулятора: либо анкета, либо расчёт.
 *
 * --- Почему один адрес, а не `/p/{id}` ----------------------------------
 *
 * Раньше профиль лежал на сервере, и адрес с его идентификатором был
 * единственным способом к нему вернуться — а заодно и единственной
 * защитой: у кого ссылка, тот и видит чужие больничные. Профиль живёт в
 * браузере, поэтому и адрес не нужен, и защищать ссылкой нечего.
 *
 * --- Почему клиентский компонент ----------------------------------------
 *
 * Что показать — анкету или расчёт — известно только из `localStorage`, а
 * его на сервере нет. Отрисовать на сервере догадку и заменить её в
 * браузере значило бы мигнуть человеку анкетой поверх готового расчёта.
 *
 * --- Что человек видит, пока профиля нет --------------------------------
 *
 * Пока профиль читается — знак загрузки по центру (`LoadingScreen`), клетки
 * которого по очереди горят цветами событий. Прежде здесь стояла заглушка
 * рабочего экрана: кости на тех же местах и тех же размеров, что числа и
 * сетки. Она обязана была совпадать с расчётом до точки, и каждая правка
 * экрана тянула правку заглушки; она осталась в `workspace-skeleton.tsx`,
 * но экран ею пока не пользуется.
 *
 * Если профиля НЕТ — этой странице показывать нечего, и человек
 * возвращается на главную. Там его и ждёт окно «Создать профиль»: оно
 * открывается кнопкой первого экрана, на месте, без перехода. Раньше
 * расчёт в этом случае показывал ту же главную поверх своего адреса, и
 * получалось, что нажатие кнопки уводит на страницу, неотличимую от
 * покинутой; закрыв окно, человек оставался на расчёте без расчёта.
 *
 * Тем же путём уходит и тот, кто удалил ПОСЛЕДНИЙ график: удаление опустошает
 * хранилище, и возврат на главную получается сам собой — отдельного
 * перехода для него писать не нужно. Если же в проводнике остались другие
 * графики, на экран встаёт самый свежий из них (`useProfile`, `forget`), и
 * сюда дело не доходит: удалить один график — не значит остаться без
 * графиков.
 *
 * Исключение одно — испорченное хранилище (`corrupt`). Тут уводить
 * нельзя: человек пришёл к своему расчёту, и вместе с объяснением он
 * потерял бы единственную кнопку, которая спасает данные.
 *
 * --- Почему шапку рисует не этот экран, а рабочий ------------------------
 *
 * У расчёта в шапке стоят настройки и выгрузка профиля, а обеим нужен
 * профиль ВЫБРАННОГО периода — он живёт в рабочем экране вместе с выбором.
 * Поднять его сюда значило бы поднять сюда и половину рабочего экрана. Поэтому
 * рабочий экран отдаёт шапку и содержимое разом, а здесь остаётся шапка
 * единственного состояния, где она нужна, — испорченного хранилища, и в ней
 * ничего, кроме знака, нет. Загрузка — знак по центру, без шапки: она
 * появилась бы без меню и названия и тут же сменилась бы настоящей.
 */
export function CalculatorScreen() {
  const { state, save, update, forget, touched } = useProfile();
  const navigate = useNavigate();

  // Уход на главную — в эффекте, а не по ходу отрисовки: переход меняет
  // состояние маршрутизатора, и делать это, пока React рисует, нельзя.
  const empty = state.status === "empty";
  useEffect(() => {
    if (empty) navigate.replace("/");
  }, [empty, navigate]);

  if (state.status === "ok") {
    return (
      <Workspace
        profile={state.profile}
        onChange={update}
        onReplace={save}
        touched={touched}
        onForget={forget}
      />
    );
  }

  // Пока профиль читается, и те доли секунды, пока идёт возврат на главную, —
  // знак по центру. Пустая страница на его месте читалась бы как поломка.
  if (state.status !== "corrupt") {
    return (
      <LoadingScreen label={empty ? "Графика нет, открываем главную" : "Открываем ваш график"} />
    );
  }

  return (
    <>
      <SiteHeader />
      <RegisterForm
        onCreated={save}
        notice={<CorruptNotice reason={state.reason} raw={state.raw} />}
      />
    </>
  );
}

/**
 * Испорченное хранилище.
 *
 * Профиль не читается, но выбрасывать его молча нельзя: там мог быть год
 * внесённых отпусков. Поэтому предлагается забрать содержимое как есть —
 * пусть даже разбирать его придётся вручную, это лучше, чем потерять.
 */
function CorruptNotice({ reason, raw }: { reason: string; raw: string }) {
  return (
    <section className="space-y-3 rounded-xl bg-signal-soft px-4 py-3 text-sm">
      <p>
        <strong>Сохранённый график не читается</strong> ({reason}). Заполните
        анкету заново — или сначала заберите старые данные файлом, чтобы
        внесённые отпуска не пропали.
      </p>
      <Button
        type="button"
        variant="outline"
        size="sm"
        onClick={() => {
          const url = URL.createObjectURL(new Blob([raw], { type: "application/json" }));
          const link = document.createElement("a");
          link.href = url;
          link.download = "график-повреждён.json";
          link.click();
          URL.revokeObjectURL(url);
        }}
      >
        Скачать как есть
      </Button>
    </section>
  );
}
