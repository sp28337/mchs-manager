import { useEffect, useLayoutEffect, useRef } from "react";

/** Раздел, который показан на месте графика. */
export type Section = "calendar" | "settings" | "stats" | "events" | "explorer";

/**
 * Сколько гаснет прежнее содержимое, прежде чем сменится раздел.
 *
 * Достаточно, чтобы уход читался движением, и мало, чтобы нажатие не казалось
 * медленным: человек ждёт ответа на нажатие, а не красивого выхода. Тот же срок
 * у стилей (`globals.css`, «Смена раздела на рабочем экране»).
 */
export const SECTION_EXIT_MS = 140;

/** Признак цели на корне страницы: его читают стили, а не разметка. */
const EXIT_ATTRIBUTE = "data-exit-to";

/**
 * Смена раздела: сперва прежнее гаснет, потом встаёт новое.
 *
 * --- Что было ---------------------------------------------------------------
 *
 * Смена выполнялась в тот же миг, как нажали: прежнее содержимое пропадало
 * рывком, полоса цифр, имя, нижний ряд знаков и колонка справа — тоже, а новое
 * проступало триста миллисекунд, у настроек и проводника — ещё и после паузы
 * в двести двадцать (на пустой странице). Глазу это читалось как «что-то
 * сразу, что-то плавно и с задержкой». Замер показал, что размытие слова в
 * шапке (`Materialize`) тут ни при чём: без него кадров столько же.
 *
 * --- Как теперь -------------------------------------------------------------
 *
 * Нажатие ничего не перерисовывает: на корне страницы ставится только признак
 * цели (`data-exit-to`), и стили гасят старое содержимое и те части экрана, что
 * в новом разделе не нужны (`globals.css`, «Смена раздела на рабочем экране»).
 * Через `SECTION_EXIT_MS` выполняется сама смена — когда экран уже тёмный. Это
 * не мелочь: тяжёлая отрисовка (календарь — две-три тысячи узлов) приходится на
 * момент, когда смотреть не на что, а не на середину проступания, как раньше.
 * Приходящее проступает само (`FadeIn`, `[data-piece]`).
 *
 * Перерисовка на нажатие была бы здесь хуже пользы: она пересчитывает тот же
 * календарь, который сейчас гаснет, и задерживает начало ухода на десятки
 * миллисекунд — человек увидел бы, что нажатие не отозвалось.
 *
 * --- Что с повторным нажатием ------------------------------------------------
 *
 * Оно не ждёт: пока идёт уход, нажатие лишь меняет цель, а срок ухода остаётся
 * прежним. Нажали на тот же раздел второй раз — цель «график», как у обычного
 * переключателя: считается от того раздела, куда идёт уход, а не от того, что
 * на экране.
 *
 * При `prefers-reduced-motion` ухода нет: смена выполняется сразу.
 *
 * Прокрутку к началу выполняет сам `apply` — в момент смены, а не нажатия:
 * страница под гаснущим содержимым не видна, и скачок не заметен.
 */
export function useSectionSwap(
  current: Section,
  apply: (next: Section) => void,
): (target: Section) => void {
  // Свежие значения для таймера: он заведён в одном проходе отрисовки, а
  // сработает в другом, и закрытие над прежними `current` и `apply` дало бы
  // смену от устаревшего раздела.
  const latest = useRef({ current, apply });
  useLayoutEffect(() => {
    latest.current = { current, apply };
  });

  /** Раздел, на который идёт смена; `null` — смены нет. */
  const pending = useRef<Section | null>(null);
  const timer = useRef(0);

  // Страница закрылась посреди ухода — признак на корне не должен остаться.
  useEffect(
    () => () => {
      window.clearTimeout(timer.current);
      timer.current = 0;
      pending.current = null;
      document.documentElement.removeAttribute(EXIT_ATTRIBUTE);
    },
    [],
  );

  return (target: Section) => {
    const from = pending.current ?? latest.current.current;
    const next: Section = from === target ? "calendar" : target;

    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      latest.current.apply(next);
      return;
    }

    pending.current = next;
    document.documentElement.setAttribute(EXIT_ATTRIBUTE, next);
    // Уход уже идёт — сменилась только цель.
    if (timer.current !== 0) return;

    timer.current = window.setTimeout(() => {
      timer.current = 0;
      const to = pending.current;
      pending.current = null;
      document.documentElement.removeAttribute(EXIT_ATTRIBUTE);
      if (to !== null) latest.current.apply(to);
    }, SECTION_EXIT_MS);
  };
}
