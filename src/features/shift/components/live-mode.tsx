"use client";

import { MARK_EMPTY_CLASS } from "@/components/shared/header-action";
import { KNOB, KNOB_ICON, KNOB_NEST, KnobLabel } from "@/components/ui/knob";
import { Switch } from "@/components/ui/switch";
import { cn } from "@/lib/utils/cn";

import type { StoredProfile } from "../storage/profile";

/**
 * Режим «веду учёт».
 *
 * --- Зачем режим ----------------------------------------------------------
 *
 * Учётный период — полугодие или год, и его итог станет известен только в
 * конце. А человек ведёт учёт СЕЙЧАС: ему нужно знать, сколько
 * переработки набежало к сегодняшнему дню. Без такого режима расчёт до
 * декабря показывает норму, которую ещё не время было отрабатывать, и
 * «недоработку» в сотни часов — число верное по формуле и бессмысленное
 * по сути.
 *
 * --- Почему один компонент на два места ----------------------------------
 *
 * Тумблер нужен и в нижнем ряду знаков (он меняет то, что в сетке
 * нарисовано), и в настройках (человек, настраивающий профиль впервые,
 * ищет его там). Две копии разошлись бы подписью или пояснением, а хуже
 * подписи, обещающей не то, что делает переключатель, нет ничего.
 *
 * --- Где дорожка, а где знак ---------------------------------------------
 *
 * В настройках — дорожка с кружком: там строка «вопрос слева, ответ
 * справа», рядом такие же строки с полями и списками, и тумблер в этом
 * ряду — такой же ответ, как они. Подпись там обычным текстом, как у
 * соседних вопросов.
 *
 * В нижнем ряду — знак (`LiveSignal`): это ряд не текста, а ОРГАНОВ
 * УПРАВЛЕНИЯ, и стоят в нём знаки — легенда, сетки, год, тема. Дорожка
 * была бы там единственной деталью своего рода: широкая, лежащая поперёк,
 * с состоянием, которое читается положением кружка. На её месте такой же
 * знак, как соседние, и состояние показывает он сам — цветом и формой.
 */

export function LiveModeSwitch({
  profile,
  onChange,
  className,
}: {
  profile: StoredProfile;
  onChange: (change: (previous: StoredProfile) => StoredProfile) => void;
  className?: string;
}) {
  return (
    <span className={cn("inline-flex items-center gap-1.5", className)}>
      <Switch
        checked={profile.liveMode}
        onChange={(liveMode) => onChange((previous) => ({ ...previous, liveMode }))}
        // Видимую подпись даёт строка настроек — там же, где знак вопроса
        // с пояснением. Тумблеру она всё равно нужна: без неё программа
        // чтения произнесёт одно состояние, не назвав, чего оно касается.
        label={<span className="sr-only">Онлайн</span>}
      />
    </span>
  );
}

/**
 * Знак режима: точка и волны от неё.
 *
 * --- Почему знак, а не дорожка с кружком ----------------------------------
 *
 * В нижнем ряду стоят знаки одного вида — без плашек и подписей. Тумблер
 * — деталь другого рода: он широкий, лежит поперёк и состояние показывает
 * ПОЛОЖЕНИЕМ кружка, которое читается только вблизи. В ряду знаков он
 * выглядел бы вставкой из настроек.
 *
 * Здесь состояние показывает сам знак, и показывает двумя способами разом:
 * цветом (тихий серый против зелёного — того же, каким на сетке отмечены
 * смены) и формой. Одного цвета мало: им нельзя пользоваться как
 * единственным различием.
 *
 * --- Что означает форма ---------------------------------------------------
 *
 * Выключено — одна точка: счёт идёт по всему периоду, ничего не
 * передаётся. Включено — от точки расходятся волны: расчёт «в эфире», он
 * обрезан сегодняшним днём и меняется вместе с ним. Это тот же знак, каким
 * везде обозначают прямую передачу, и объяснять его не нужно.
 *
 * Волны не появляются рывком: они выезжают из точки и разбегаются наружу
 * (`signal-pulse` в `globals.css`), то есть нажатие ВИДНО как движение, а
 * не только как смену цвета. При отключённой анимации волны просто стоят
 * на месте — правило `prefers-reduced-motion` в начале таблицы стилей
 * гасит и разбег, и переход, а конечный кадр у них полный.
 */
export function LiveSignal({ on, className }: { on: boolean; className?: string }) {
  return (
    <svg
      aria-hidden
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      className={cn("signal size-5.5", className)}
      data-on={on ? "" : undefined}
    >
      {/* Ближняя пара волн и дальняя. Разбегаются они по очереди, и порядок
          задаётся задержкой у дальней — отсюда и разные классы. */}
      <path className="signal__wave" d="M8.4 16.6Q4 12 8.4 7.4" />
      <path className="signal__wave" d="M15.6 7.4Q20 12 15.6 16.6" />
      <path className="signal__wave signal__wave--far" d="M5.2 19Q-0.4 12 5.2 5" />
      <path className="signal__wave signal__wave--far" d="M18.8 5Q24.4 12 18.8 19" />
      {/* Середина знака: кольцо, пока режим выключен, и залитая точка,
          когда включён. Пустое кольцо — это «ничего не передаётся», и
          заливка при включении заметна даже там, где волны закрыл палец. */}
      <circle className="signal__dot" cx="12" cy="12" r="3.2" />
    </svg>
  );
}

/**
 * Режим «Онлайн» знаком нижнего ряда (`grid-dock.tsx`).
 *
 * `role="switch"` остаётся тем же, что у дорожки в настройках: для
 * программы чтения это по-прежнему переключатель со включённым и
 * выключенным положением. Меняется только то, чем состояние показано
 * глазу: выключено — точка цветом пустых клеток знака сайта, как у
 * соседей по ряду; включено — зелёные волны, тем же цветом, каким на сетке
 * отмечены смены.
 */
export function LiveModeKnob({
  profile,
  onChange,
}: {
  profile: StoredProfile;
  onChange: (change: (previous: StoredProfile) => StoredProfile) => void;
}) {
  const on = profile.liveMode;
  return (
    <div className={KNOB_NEST}>
      <button
        type="button"
        role="switch"
        aria-checked={on}
        aria-label="Онлайн: считать по сегодняшний день"
        onClick={() => onChange((previous) => ({ ...previous, liveMode: !on }))}
        className={KNOB}
      >
        <span className={KNOB_ICON}>
          <LiveSignal on={on} className={on ? "text-verify" : MARK_EMPTY_CLASS} />
        </span>
        <KnobLabel>Онлайн</KnobLabel>
      </button>
    </div>
  );
}
