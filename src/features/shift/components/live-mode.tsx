"use client";

import { Switch } from "@/components/ui/switch";
import { cn } from "@/lib/utils/cn";

import type { StoredProfile } from "../storage/profile";

/**
 * Режим «веду учёт».
 *
 * --- Зачем режим ----------------------------------------------------------
 *
 * Учётный период — полугодие или год, и его итог станет известен только в
 * конце. А человек ведёт учёт СЕЙЧАС: ему нужно знать, сколько
 * переработки набежало к сегодняшнему дню. Без такого режима расчёт до
 * декабря показывает норму, которую ещё не время было отрабатывать, и
 * «недоработку» в сотни часов — число верное по формуле и бессмысленное
 * по сути.
 *
 * --- Почему один компонент на два места ----------------------------------
 *
 * Тумблер нужен и в панели над сеткой (он меняет то, что в ней
 * нарисовано), и в настройках (человек, настраивающий профиль впервые,
 * ищет его там). Две копии разошлись бы подписью или пояснением, а хуже
 * подписи, обещающей не то, что делает переключатель, нет ничего.
 *
 * --- Почему подпись набрана по-разному в этих двух местах -----------------
 *
 * В панели над сеткой она стоит в одном ряду с «Масштабом» — и это ряд не
 * текста, а ОРГАНОВ УПРАВЛЕНИЯ: узкая гарнитура, одиннадцать точек,
 * прописные, приглушённый тон. Набранная обычным текстом строчными, она
 * читалась там единственной подписью своего рода, будто попала в ряд из
 * другого места.
 *
 * В настройках всё наоборот: там строка «вопрос слева, ответ справа», и
 * рядом стоят подписи обычным текстом. Прописные в этом ряду выделяли бы
 * один вопрос из десятка одинаковых без всякой причины. Поэтому вид
 * подписи задаёт `spread` — тот же признак, что разводит подпись и дорожку
 * по краям строки.
 */
const PANEL_LABEL =
  "font-display text-[11px] font-bold uppercase tracking-wide text-ink-muted";

export function LiveModeSwitch({
  profile,
  onChange,
  spread,
  className,
}: {
  profile: StoredProfile;
  onChange: (change: (previous: StoredProfile) => StoredProfile) => void;
  /** Подпись слева, дорожка справа — для строки настроек. */
  spread?: boolean;
  className?: string;
}) {
  return (
    <span className={cn("inline-flex items-center gap-1.5", spread && "w-full", className)}>
      <Switch
        checked={profile.liveMode}
        onChange={(liveMode) => onChange((previous) => ({ ...previous, liveMode }))}
        label={spread ? "Онлайн" : <span className={PANEL_LABEL}>Онлайн</span>}
        spread={spread}
      />
    </span>
  );
}
