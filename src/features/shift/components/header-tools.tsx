import { useSaveToFile } from "./save-to-file";

/**
 * Настройки, статистика и выгрузка — из шапки.
 *
 * --- Почему не колонкой сбоку --------------------------------------------
 *
 * Колонка была: слева ввод, справа вывод. Она честно работала, но платила
 * за это девятнадцатью ремами ширины — у графика на год и двенадцати
 * календарных сеток это самое дорогое, что можно отнять.
 *
 * Из того, что в ней стояло, почти всё нашло себе место ближе к делу:
 * период переехал в панель над сеткой, которой он и управляет, отпуска и
 * выходы помимо графика вносятся нажатием по самому дню, а ответы анкеты
 * — дата смены, норма, время её начала — ушли в настройки.
 *
 * --- Почему в шапке четыре кнопки ----------------------------------------
 *
 * Действий у профиля ровно три, и они одного рода: настроить нынешний,
 * открыть другой, сохранить нынешний. Два стояли здесь, третье — выбор
 * файла — лежало на дне настроек, четырьмя строками с пояснением, безо
 * всякой причины, кроме той, что когда-то оно завелось в окне создания
 * профиля и осталось жить рядом.
 *
 * «Открыть» с тех пор перестало означать «выбрать файл»: оно показывает
 * проводник по сохранённым графикам (`profile-explorer.tsx`), а файл стал
 * одним из способов пополнить его — наравне с новым профилем. Кнопка от
 * этого не изменилась ни местом, ни значком: действие то же самое, просто
 * выбирать теперь есть из чего.
 *
 * Четвёртая — статистика за год: не действие над профилем, а чтение его,
 * и стоит она сразу за настройками, потому что отвечает на тот же вопрос
 * с другой стороны — что из заданного вышло.
 *
 * Порядок тот, в каком читается история профиля: настроить, посмотреть,
 * открыть другой, сохранить. «Открыть» стоит посередине намеренно — это
 * единственное действие, уносящее нынешний профиль, и соседство с
 * «Сохранить» справа тут кстати.
 *
 * --- Почему на узком экране остаются значки ------------------------------
 *
 * Кнопок четыре, и в меню их сворачивать незачем: четыре значка занимают
 * меньше места, чем один значок меню, и ведут прямо к делу, а не к списку
 * из четырёх пунктов. Подписи появляются, как только для них хватает
 * ширины, — порог назначен замером и стоит в `LABELS_FROM`.
 *
 * --- Кнопки, которые не открывают окно ------------------------------------
 *
 * «Открыть», «Настройки» и «Статистика» ничего не показывают поверх
 * страницы: они переключают то, что на этой странице показано
 * (`workspace.tsx` решает, что́ именно, — знак сайта рядом читает
 * «Настройки», «Статистика» или «Профили» вместо «График 1 3»). Экран не
 * сменился ни на миг, и открывать его окном означало бы утверждать
 * обратное.
 *
 * Плавающее окно на столе тут было до тех пор, пока довод звучал так:
 * колонки и панели по бокам никуда не прячутся, окно лишь дополняет их.
 * Но и настройки, и статистика — про ТОТ САМЫЙ график, что лежит под
 * ними, и окно закрывало собой ровно то, ради чего его открыли. Теперь
 * порядок один на всех ширинах и один на все три раздела: содержимое
 * страницы подменяется на месте.
 *
 * Значок кнопки при этом меняется сам, шестерня или столбики на крестик:
 * та же кнопка, которой открыли, и закрывает. Отдельного крестика в углу
 * листа, как у прежнего окна, тут нет и не может быть — самого листа
 * больше нет.
 *
 * --- Почему ряд не дёргается ----------------------------------------------
 *
 * Рядов у шапки два, и встают они на одно и то же место: обычный —
 * «Настройки, Статистика, Открыть, Сохранить», и ряд проводника —
 * «Папка, Профиль, Из файла, Закрыть». Слова у них разной длины, и пока
 * ширину кнопки задавало её собственное слово, открытие проводника
 * перекладывало весь ряд: кнопки разъезжались под курсором, и человек,
 * целившийся в «Закрыть», попадал в «Из файла».
 *
 * Поэтому ширину каждого МЕСТА ряда держит самое длинное из слов, какие
 * на нём вообще могут стоять (`words` ниже): все они лежат в одной ячейке
 * грида, видно из них одно, остальные спрятаны `invisible` — место
 * занимают, но не читаются ни глазом, ни программой чтения. Тем же
 * приёмом и по той же причине кнопка настроек не ужимается на слове
 * «Закрыть».
 */

type ToolId = "settings" | "stats" | "open" | "save";

/**
 * Подпись на кнопке и имя для программы чтения — разные строки.
 *
 * На кнопке нужно короткое имя: их четыре в ряд, и рядом ещё знак с
 * названием сайта. Имя, которое произносит диктор, называет действие
 * целиком — «Сохранить в файл» вместо «Сохранить».
 */
type Tool = { label: string; title: string; Icon: LucideIcon };

const TOOL_META: Record<ToolId, Tool> = {
  settings: { label: "Настройки", title: "Настройки", Icon: Settings },
  stats: { label: "Статистика", title: "Статистика за год", Icon: ChartColumn },
  open: { label: "Открыть", title: "Открыть профиль", Icon: FolderOpen },
  save: { label: "Сохранить", title: "Сохранить в файл", Icon: Save },
};

const TOOL_ORDER: readonly ToolId[] = ["settings", "stats", "open", "save"];

/** Чем кнопка называет себя, пока тем же нажатием закрывают открытое ей. */
const CLOSE_LABEL = "Закрыть";

/**
 * Ряд проводника — по кнопке на каждое место обычного ряда.
 *
 * Порядок здесь не сам по себе: он привязан к обычному ряду по МЕСТУ, и
 * от этой привязки зависит ширина (см. `words`). Закрытие стоит в конце
 * намеренно — открывали проводник кнопкой из середины, но закрывают его
 * после того, как всё остальное сделано.
 */
const EXPLORER_ROW: readonly (Tool & {
  /** Что нажатие делает: действие проводника или его закрытие. */
  act: "newFolder" | "newProfile" | "importFile" | "close";
})[] = [
  { label: "Папка", title: "Создать папку", Icon: FolderPlus, act: "newFolder" },
  { label: "Профиль", title: "Создать профиль", Icon: Plus, act: "newProfile" },
  {
    label: "Из файла",
    title: "Загрузить профиль из файла",
    Icon: Upload,
    act: "importFile",
  },
  { label: CLOSE_LABEL, title: "Закрыть проводник", Icon: X, act: "close" },
];

/**
 * Четыре места ряда: что на каждом стоит и какие слова на нём бывают.
 *
 * `words` — весь список, а не только нынешнее слово: из него берётся
 * ширина места, и потому в нём и слово обычного ряда, и слово проводника,
 * и «Закрыть», в которое обращаются кнопки разделов. Порядок слов внутри
 * значения не имеет — важно лишь, что самое длинное из них там есть.
 *
 * Вынесен наружу: тот же ряд повторяют кости заглушки
 * (`workspace-skeleton.tsx`), и разойтись им нельзя — иначе в миг
 * подстановки шапка дёрнулась бы ровно там, где заглушка и существует,
 * чтобы этого не случилось.
 */
export const TOOL_ROW: readonly (Tool & { id: ToolId; words: readonly string[] })[] =
  TOOL_ORDER.map((id, place) => ({
    id,
    ...TOOL_META[id],
    words: [
      ...new Set([TOOL_META[id].label, EXPLORER_ROW[place]!.label, CLOSE_LABEL]),
    ],
  }));

/**
 * С какой ширины у кнопок появляются подписи.
 *
 * Замером: четыре плашки с подписями занимают 477 точек и ещё 24 на
 * просветы между ними, знак сайта — 170, поля страницы — 48. Итого 719, и
 * порог `md` (768) даёт запас в полсотни точек.
 *
 * Лестница у порога своя история. При двух кнопках он стоял на `xs` (448),
 * при трёх переехал на `sm` (640), при четвёртой — сюда. Каждый раз по
 * одному и тому же поводу: строка в шапке ОДНА и переноситься не может
 * (см. `site-header.tsx`), а знак сайта ужимается (`min-w-0`) и потому не
 * упирается в кнопки, а молча уезжает под них — обрезанное «ГРАФИ» вместо
 * названия. Проверять порог надо именно этим: не переполнением строки, а
 * тем, помещается ли в знак его собственный текст.
 *
 * Значки при этом остаются все четыре и на самом узком телефоне: 4 × 42 и
 * три просвета — это 192 точки, и на 320 от знака до них остаётся 16. Ниже
 * порога подписи не показаны вовсе, и ряды совпадают шириной сами собой —
 * значок у всех кнопок один и тот же размером.
 *
 * `grid`, а не `inline`: слова стоят стопкой в одной ячейке, и видно из
 * них одно (`ToolLabel`).
 */
const LABELS_FROM = "hidden md:grid";

/** Значок кнопки — один размер и один цвет на все четыре. */
const ICON = "size-4.5 shrink-0 text-ink-muted";

/**
 * Слово на кнопке — вместе со всеми, какие на её месте бывают.
 *
 * Спрятанные (`invisible`) держат ширину и молчат: `visibility: hidden`
 * убирает узел и с экрана, и из дерева доступности, так что диктор
 * прочитает только имя кнопки (`aria-label`).
 */
export function ToolLabel({
  word,
  words,
}: {
  word: string;
  words: readonly string[];
}) {
  return (
    // Слово стоит по середине своего места, а не с левого края: разница
    // между самым длинным словом и нынешним иначе целиком уходила бы в
    // правое поле, и кнопка выглядела бы сдвинутой влево.
    <span className={cn(LABELS_FROM, "justify-items-center")}>
      {words.map((it) => (
        <span
          key={it}
          className={cn("col-start-1 row-start-1", it !== word && "invisible")}
        >
          {it}
        </span>
      ))}
    </span>
  );
}

/**
 * Общий вид кнопки шапки.
 *
 * Рядов у неё два — обычный («Настройки», «Статистика», «Открыть»,
 * «Сохранить») и ряд проводника, встающий на то же место, — и разойтись
 * им нельзя: это одна и та же строка экрана, просто с разными действиями.
 *
 * Поля ужаты ниже 360 точек: там ряд проводника из четырёх кнопок в строку
 * со знаком сайта иначе не встаёт.
 */
const TOOL_BUTTON = cn(
  // `lit` — кнопка ловит свет лампы. Стоит она у правого края, дальше
  // конца трубки, и блик ложится не сверху, а по верхней и левой кромке:
  // сторону считает сама лампа замером (`shared/lamp.tsx`).
  //
  // Им же объяснено и наведение: кромка загорается по всему периметру, а
  // под курсором на ней встаёт блик (`globals.css`, `.lit`). Прежде
  // наведение меняло заливку — приём из интерфейсов без источника света, и
  // здесь он спорил с тем, чем объяснён весь остальной вид кнопки.
  "lit",
  "inline-flex h-9 shrink-0 cursor-pointer items-center gap-2 rounded-xl",
  "bg-paper-raised px-2 min-[360px]:px-3 text-sm font-medium",
  "text-ink",
  "focus-visible:outline-2 focus-visible:outline-offset-2",
  "focus-visible:outline-ink",
);

function ToolButton({
  icon,
  word,
  words,
  title,
  expanded,
  onClick,
}: {
  icon: ReactNode;
  /** Слово, которое видно сейчас. */
  word: string;
  /** Все слова этого места ряда: из них ширина. */
  words: readonly string[];
  /** Имя для программы чтения: называет действие целиком. */
  title: string;
  /** Кнопка закрывает то, что сейчас показано вместо страницы. */
  expanded?: boolean;
  onClick: () => void;
}) {
  return (
    <button
      type="button"
      onClick={onClick}
      // Имя кнопки не зависит от того, видна подпись или нет: на узком
      // экране от кнопки остаётся значок, и без имени она стала бы для
      // программы чтения безымянной.
      aria-label={title}
      aria-expanded={expanded}
      title={title}
      className={TOOL_BUTTON}
    >
      {icon}
      <ToolLabel word={word} words={words} />
    </button>
  );
}

/**
 * Значок кнопки раздела: свой знак и крестик в одной ячейке грида.
 *
 * Проступают друг в друга — тот же приём, что у слова рядом со знаком
 * сайта (`site-header.tsx`): один толкует то же самое действие
 * («настройки»/«закрыть»), не сдвигая соседей.
 */
function SwapIcon({ Icon, pressed }: { Icon: LucideIcon; pressed: boolean }) {
  return (
    <span className="grid">
      <Materialize
        show={!pressed}
        durationClassName="duration-200"
        className="col-start-1 row-start-1"
      >
        <Icon aria-hidden className={ICON} />
      </Materialize>
      <Materialize
        show={pressed}
        durationClassName="duration-200"
        className="col-start-1 row-start-1"
      >
        <X aria-hidden className={ICON} />
      </Materialize>
    </span>
  );
}

/** Чем кнопка раздела называет закрытие. */
const CLOSE_TITLE: Partial<Record<ToolId, string>> = {
  settings: "Закрыть настройки",
  stats: "Закрыть статистику",
};

export function HeaderTools({
  profile,
  className,
  settingsOpen,
  onToggleSettings,
  statsOpen,
  onToggleStats,
  explorerOpen,
  onToggleExplorer,
  explorerTools,
}: {
  /** Нужен выгрузке в файл: она здесь и остаётся. */
  profile: StoredProfile;
  className?: string;
  /** Показаны ли сейчас настройки вместо графика. */
  settingsOpen: boolean;
  onToggleSettings: () => void;
  /** Показана ли сейчас статистика за год вместо графика. */
  statsOpen: boolean;
  onToggleStats: () => void;
  /** Показан ли сейчас проводник по профилям вместо календаря. */
  explorerOpen: boolean;
  onToggleExplorer: () => void;
  /** Действия проводника: пока он открыт, они стоят на месте обычных. */
  explorerTools: ExplorerTools;
}) {
  const save = useSaveToFile(profile);

  // Пока открыт проводник, страница занята другим — и кнопки у неё другие:
  // не «настроить, посмотреть, открыть, сохранить», а «папка, профиль, из
  // файла, закрыть». Ширину мест при этом держит обычный ряд (`words`), и
  // подмена ничего под курсором не сдвигает.
  if (explorerOpen) {
    return (
      <div
        role="group"
        aria-label="Проводник: папка, профиль, из файла, закрыть"
        className={cn("flex items-center gap-2", className)}
      >
        {EXPLORER_ROW.map((tool, place) => (
          <ToolButton
            key={tool.act}
            icon={<tool.Icon aria-hidden className={ICON} />}
            word={tool.label}
            words={TOOL_ROW[place]!.words}
            title={tool.title}
            expanded={tool.act === "close" ? true : undefined}
            onClick={
              tool.act === "close" ? onToggleExplorer : explorerTools[tool.act]
            }
          />
        ))}
      </div>
    );
  }

  return (
    <>
      <div
        role="group"
        aria-label="Профиль: настройки, статистика, открыть, сохранить"
        className={cn("flex items-center gap-2", className)}
      >
        {TOOL_ROW.map((tool) => {
          // Настройки и статистика не открывают окно, а переключают то,
          // что показано на самой странице, и сами превращаются в кнопку
          // закрытия. Имя и подсказка называют то действие, которое
          // нажатие СЕЙЧАС совершит.
          const toggling = tool.id === "settings" || tool.id === "stats";
          const pressed =
            tool.id === "settings"
              ? settingsOpen
              : tool.id === "stats"
                ? statsOpen
                : false;
          return (
            <ToolButton
              key={tool.id}
              icon={
                toggling ? (
                  <SwapIcon Icon={tool.Icon} pressed={pressed} />
                ) : (
                  <tool.Icon aria-hidden className={ICON} />
                )
              }
              word={pressed ? CLOSE_LABEL : tool.label}
              words={tool.words}
              title={pressed ? CLOSE_TITLE[tool.id]! : tool.title}
              expanded={toggling ? pressed : undefined}
              onClick={() => {
                if (tool.id === "save") save.ask();
                else if (tool.id === "open") onToggleExplorer();
                else if (tool.id === "stats") onToggleStats();
                else onToggleSettings();
              }}
            />
          );
        })}
      </div>

      {save.dialog}
    </>
  );
}
