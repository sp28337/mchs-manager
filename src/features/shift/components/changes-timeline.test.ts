import { describe, expect, it } from "vitest";

import type { IsoDate } from "../domain/plain-date";
import {
  dayRu,
  eventsRu,
  groupsOf,
  monthTitleRu,
  periodRu,
  phaseOf,
  spanDays,
  spanRu,
  timeline,
  type TimelineRow,
} from "./changes-timeline";

const d = (iso: string) => iso as IsoDate;

describe("отрезок дат словами", () => {
  it("одни сутки — одной датой с днём недели", () => {
    // 10 февраля 2026 — вторник.
    expect(periodRu(d("2026-02-10"), d("2026-02-10"))).toBe("10 февраля, вт");
    expect(dayRu(d("2026-07-06"))).toBe("6 июля, пн");
  });

  it("внутри месяца — числа через тире, месяц один раз", () => {
    expect(periodRu(d("2026-07-06"), d("2026-07-26"))).toBe("6–26 июля");
  });

  it("через границу месяца — две даты со словами", () => {
    expect(periodRu(d("2026-06-28"), d("2026-07-03"))).toBe("28 июня — 3 июля");
  });

  it("через Новый год — с годами, иначе читается как почти целый год", () => {
    expect(periodRu(d("2026-12-28"), d("2027-01-03"))).toBe("28 декабря 2026 — 3 января 2027");
  });

  it("с длительностью: у отрезка — число суток, у одних суток — только дата", () => {
    expect(spanRu(d("2026-07-06"), d("2026-07-26"))).toBe("6–26 июля · 21 дн.");
    expect(spanRu(d("2026-06-28"), d("2026-07-03"))).toBe("28 июня — 3 июля · 6 дн.");
    expect(spanRu(d("2026-02-10"), d("2026-02-10"))).toBe("10 февраля, вт");
  });

  it("в подписи нет ни года у обычного отрезка, ни ведущего нуля", () => {
    const text = periodRu(d("2026-03-01"), d("2026-03-09"));
    expect(text).toBe("1–9 марта");
    expect(text).not.toMatch(/2026|\b0\d/);
  });
});

describe("длительность и фаза", () => {
  it("суток считаются с обоими краями, одни сутки — одни", () => {
    expect(spanDays(d("2026-07-06"), d("2026-07-26"))).toBe(21);
    expect(spanDays(d("2026-02-10"), d("2026-02-10"))).toBe(1);
    // Конец раньше начала — не отрицательный срок, а одни сутки.
    expect(spanDays(d("2026-02-10"), d("2026-02-01"))).toBe(1);
  });

  it("кончившееся вчера — прошлое, начнётся завтра — впереди, накрывает сегодня — идёт", () => {
    const today = d("2026-10-22");
    expect(phaseOf(d("2026-10-10"), d("2026-10-21"), today)).toBe("past");
    expect(phaseOf(d("2026-10-23"), d("2026-10-30"), today)).toBe("ahead");
    expect(phaseOf(d("2026-10-10"), d("2026-10-22"), today)).toBe("now");
    expect(phaseOf(d("2026-10-22"), d("2026-10-30"), today)).toBe("now");
    expect(phaseOf(d("2026-10-22"), d("2026-10-22"), today)).toBe("now");
  });

  it("месяц называется с годом и с заглавной", () => {
    expect(monthTitleRu("2026-07")).toBe("Июль 2026");
    expect(monthTitleRu("2027-01")).toBe("Январь 2027");
  });

  it("счёт событий склоняется, включая «одиннадцать» и «двадцать одно»", () => {
    const words = [1, 2, 4, 5, 11, 12, 14, 21, 22, 25, 111].map(eventsRu);
    expect(words).toEqual([
      "1 событие",
      "2 события",
      "4 события",
      "5 событий",
      "11 событий",
      "12 событий",
      "14 событий",
      "21 событие",
      "22 события",
      "25 событий",
      "111 событий",
    ]);
  });
});

const row = (id: string, day: string, endDay = day, ghost?: boolean): TimelineRow => ({
  id,
  day: d(day),
  endDay: d(endDay),
  ...(ghost === undefined ? {} : { ghost }),
});

/** Ленту — в короткую запись: М — месяц, С — строка, Т — линия «сегодня». */
function sketch(rows: TimelineRow[], today: string): string[] {
  return timeline(rows, d(today)).map((entry) =>
    entry.type === "month"
      ? `М:${entry.key}:${entry.count}`
      : entry.type === "today"
        ? "Т"
        : `С:${entry.row.id}:${entry.phase}`,
  );
}

describe("лента: месяцы и линия «сегодня»", () => {
  it("над каждым новым месяцем — заголовок со счётом строк", () => {
    expect(
      sketch([row("a", "2026-02-10"), row("b", "2026-02-20"), row("c", "2026-03-10", "2026-03-20")], "2026-01-01"),
    ).toEqual(["М:2026-02:2", "С:a:ahead", "С:b:ahead", "М:2026-03:1", "С:c:ahead"]);
  });

  it("линия встаёт перед первой строкой, что начинается сегодня или позже", () => {
    expect(
      sketch([row("a", "2026-09-01"), row("b", "2026-10-05"), row("c", "2026-10-22"), row("d", "2026-10-30")], "2026-10-22"),
    ).toEqual(["М:2026-09:1", "С:a:past", "М:2026-10:3", "С:b:past", "Т", "С:c:now", "С:d:ahead"]);
  });

  it("если первая строка после линии открывает месяц, линия стоит перед его заголовком", () => {
    expect(sketch([row("a", "2026-09-18"), row("b", "2026-11-03")], "2026-10-22")).toEqual([
      "М:2026-09:1",
      "С:a:past",
      "Т",
      "М:2026-11:1",
      "С:b:ahead",
    ]);
  });

  it("идущий отпуск, начатый раньше, остаётся над линией и помечен «идёт»", () => {
    // Отпуск 10–30 октября идёт, вызов 25-го впереди. Линия — перед вызовом,
    // потому что порядок хронологический по началу и отпуск начался раньше.
    expect(
      sketch([row("x", "2026-10-02"), row("v", "2026-10-10", "2026-10-30"), row("c", "2026-10-25")], "2026-10-22"),
    ).toEqual(["М:2026-10:3", "С:x:past", "С:v:now", "Т", "С:c:ahead"]);
  });

  it("строка внутри идущего отпуска, уже прошедшая, не оказывается под линией", () => {
    // Вызов 15-го прошёл, но стоит после отпуска, начатого 10-го. Линии между
    // ними нет: ниже неё не должно быть ничего, что началось раньше сегодня.
    expect(
      sketch([row("v", "2026-10-10", "2026-10-30"), row("c", "2026-10-15"), row("n", "2026-11-02")], "2026-10-22"),
    ).toEqual(["М:2026-10:2", "С:v:now", "С:c:past", "Т", "М:2026-11:1", "С:n:ahead"]);
  });

  it("всё позади или всё впереди — линии нет: ей нечего разделять", () => {
    expect(sketch([row("a", "2026-01-10"), row("b", "2026-02-10")], "2026-10-22")).not.toContain("Т");
    expect(sketch([row("a", "2026-11-10"), row("b", "2026-12-10")], "2026-10-22")).not.toContain("Т");
  });

  it("убранные строки не входят в счёт месяца", () => {
    expect(sketch([row("a", "2026-03-10"), row("g", "2026-03-12", "2026-03-12", true)], "2026-01-01")).toEqual([
      "М:2026-03:1",
      "С:a:ahead",
      "С:g:ahead",
    ]);
  });

  it("пустой перечень — пустая лента", () => {
    expect(timeline([], d("2026-10-22"))).toEqual([]);
  });
});

describe("группы фильтра", () => {
  it("только непустые, в порядке кнопок, со счётом", () => {
    expect(
      groupsOf([{ group: "note" }, { group: "absence" }, { group: "absence" }, { group: "note" }, { group: "callout" }]),
    ).toEqual([
      { group: "absence", count: 2 },
      { group: "callout", count: 1 },
      { group: "note", count: 2 },
    ]);
  });

  it("убранные в счёт не идут", () => {
    expect(groupsOf([{ group: "note", ghost: true }, { group: "edit" }])).toEqual([{ group: "edit", count: 1 }]);
  });
});
