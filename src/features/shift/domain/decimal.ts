import DecimalJs from "decimal.js";

/**
 * Точная десятичная арифметика для часов.
 *
 * --- Почему не обычные числа --------------------------------------------
 *
 * `7.2 * 118` в двоичной плавающей точке даёт 849.5999999999999, а норма
 * при 36-часовой неделе считается ровно так. Показать человеку
 * «849,60 ч» и получить при сравнении с табелем расхождение из ниоткуда —
 * значит подорвать доверие к инструменту на пустом месте.
 *
 * --- Почему именно такие настройки ---------------------------------------
 *
 * 28 значащих цифр и банковское округление — это в точности контекст
 * `decimal` в Python по умолчанию, а расчёт переносился оттуда. Совпадение
 * настроек означает, что перенос можно ПРОВЕРИТЬ: те же входные данные
 * обязаны дать те же числа до последней цифры, и расхождение будет
 * ошибкой переноса, а не разницей в арифметике.
 *
 * Клон, а не глобальная настройка: `Decimal.set` изменил бы поведение
 * библиотеки во всём приложении, включая код, который об этом решении не
 * знает.
 */
export const Dec = DecimalJs.clone({
  precision: 28,
  rounding: DecimalJs.ROUND_HALF_EVEN,
  // Часы никогда не записываются экспонентой: «1.97e+3» вместо «1970» в
  // доводе для начальника выглядит как ошибка программы.
  toExpNeg: -9e15,
  toExpPos: 9e15,
});

export type Decimal = InstanceType<typeof Dec>;

export const ZERO: Decimal = new Dec(0);

/**
 * Число из строки или `null`, если это не число.
 *
 * --- Зачем обёртка -------------------------------------------------------
 *
 * `decimal.js` сообщает о непригодной строке НЕ значением, а исключением:
 * `new Dec("и")` бросает `DecimalError: Invalid argument`. Проверка вида
 * `value.isFinite()` до него не доживает — до неё дело не доходит.
 *
 * Разбор при этом вызывается на каждое нажатие клавиши в поле часов
 * работы помимо графика, то есть строка «не число» — не редкость, а нормальное
 * промежуточное состояние: человек стёр всё и набирает заново, случайно
 * задел букву, вставил «12 ч». Исключение в этом месте роняло весь
 * экран расчёта, и вместе с ним — введённые отпуска на экране.
 *
 * Поэтому непригодная строка обязана возвращаться значением, и вся работа
 * с `decimal.js` из пользовательского ввода идёт только через эту функцию.
 */
export function toDecimal(input: string): Decimal | null {
  let value: Decimal;
  try {
    value = new Dec(input);
  } catch {
    return null;
  }
  // `new Dec("NaN")` не бросает, а возвращает NaN — это тоже не число.
  return value.isNaN() ? null : value;
}

/** Наибольшее из двух — нужно там, где величина не имеет права уйти в минус. */
export function atLeastZero(value: Decimal): Decimal {
  return value.isNegative() ? ZERO : value;
}

/**
 * Часы для показа человеку: две цифры после запятой, разделитель — запятая.
 *
 * Две цифры, а не сколько получится: ночные часы смены на стыке месяцев
 * дают 5,333333…, и такое число в доводе выглядит несерьёзно.
 */
export function formatHours(value: Decimal | number | string): string {
  return new Dec(value).toFixed(1).replace(".", ",");
}

/**
 * Часы без нулевого хвоста: «16», но «15,5».
 *
 * Десятая доля показывается тогда, когда она есть. Ноль после запятой не
 * говорит ничего: он не уточняет число и не обещает точности, которой у
 * целых часов и так больше, — зато делает «1972,0 ч» на треть длиннее
 * «1972 ч» и тем мельче на экране.
 *
 * Так набраны и клетка календаря, где число стоит без подписи и без
 * единицы, и главные числа полосы итогов. Прежде в полосе хвост держали
 * ради того, чтобы числа в столбце были одной формы, — но столбца там
 * давно нет: числа стоят порознь, каждое на своей плашке.
 */
export function formatHoursTrim(value: Decimal | number | string): string {
  return formatHours(value).replace(/,0$/, "");
}

/**
 * Часы в смене по умолчанию.
 *
 * Двадцать четыре — это продолжительность суточной смены, а не
 * астрономические сутки: «переработка сменами» отвечает на вопрос «сколько
 * смен я отработал сверх нормы», и мерить её чем-то другим бессмысленно.
 * У графиков с другой сменой число приходит извне.
 *
 * Оно стоит здесь, а не берётся из `SHIFT_DURATION_HOURS`: этот модуль —
 * основание для всего остального, включая сам домен, и обратной зависимости
 * у него быть не может.
 */
const HOURS_IN_SHIFT = 24;

/** Часы, разложенные на целые сутки и остаток. */
export interface DaysAndHours {
  days: number;
  hours: Decimal;
}

/**
 * Часы как «смены и часы»: 212 при суточной смене → 8 смен и 20 часов.
 *
 * Вместо «8,8 смены». Десятая доля суточной смены — это два часа с
 * четвертью, и пересчитывать её в голове человеку приходится ровно тогда,
 * когда он собрался что-то с этой переработкой делать: отгул берут сменами
 * и часами, а не десятыми долями.
 *
 * Длина смены приходит параметром: у графика «два через два» она
 * двенадцать часов, и делить его переработку на сутки значило бы называть
 * человеку число смен, которых он не работал.
 */
export function splitIntoDays(
  value: Decimal,
  hoursInShift: number = HOURS_IN_SHIFT,
): DaysAndHours {
  const per = hoursInShift > 0 ? hoursInShift : HOURS_IN_SHIFT;
  const days = value.dividedToIntegerBy(per);
  return { days: days.toNumber(), hours: value.minus(days.times(per)) };
}

/**
 * «Сутки» при числе: 1 сутки, 8 суток, 21 сутки.
 *
 * У слова нет единственного числа, и форма зависит от последней цифры —
 * кроме одиннадцати, где она обманывает.
 */
export function daysWord(days: number): string {
  return days % 10 === 1 && days % 100 !== 11 ? "сутки" : "суток";
}

/**
 * «Смена» при числе: 1 смена, 2 смены, 8 смен.
 *
 * Нужна там, где смена не суточная: «8 суток» у графика «два через два»
 * назвало бы вдвое больше времени, чем человек отработал.
 */
export function shiftsWord(count: number): string {
  const tens = count % 100;
  if (tens >= 11 && tens <= 14) return "смен";
  const ones = count % 10;
  if (ones === 1) return "смена";
  if (ones >= 2 && ones <= 4) return "смены";
  return "смен";
}

/** То же одной строкой — для подписей, где разметки нет. */
export function formatDaysAndHours(value: Decimal): string {
  const { days, hours } = splitIntoDays(value);
  if (days === 0) return `${formatHoursTrim(hours)} ч`;
  if (hours.isZero()) return `${days} ${daysWord(days)}`;
  return `${days} ${daysWord(days)} ${formatHoursTrim(hours)} ч`;
}

/** Разбор числа, введённого человеком: и «168,5», и «168.5». */
export function parseHours(input: string): Decimal | null {
  const normalised = input.trim().replace(",", ".");
  if (normalised === "") return null;
  const value = toDecimal(normalised);
  return value !== null && value.isFinite() ? value : null;
}
