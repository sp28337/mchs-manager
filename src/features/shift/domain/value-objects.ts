/**
 * График смен: ОДНА известная дата выхода.
 *
 * --- Почему дата, и почему любая -----------------------------------------
 *
 * Здесь стояла «дата первой смены в году», и человека спрашивали именно о
 * ней: одни из первых четырёх суток января. Спрашивали о том, чего он не
 * помнит. Первое января прошлого года — это не событие, а вычисление, и
 * человек его проделывал в голове, отсчитывая четвёрками от смены, которую
 * помнит.
 *
 * Цикл четырёхдневный и потому одинаков в обе стороны: любая известная
 * смена задаёт его целиком — и вперёд, и назад. Значит, спрашивать нужно о
 * том, что человек знает точно: «завтра я на смене». Отсчёт назад делает
 * приложение, которое в арифметике не ошибается.
 */
export interface ShiftCycle {
  /**
   * Любые сутки, в которые человек выходил на смену или выйдет.
   *
   * У графиков, где рабочих суток подряд несколько, это ПЕРВЫЕ сутки
   * череды: вторые из них цикл достроит сам.
   */
  readonly knownShiftDate: IsoDate;
  /**
   * Какой это график — уже СОБРАННЫЙ, а не его опознание.
   *
   * Собранный намеренно: у своего графика числа лежат в профиле, и из
   * одного опознания он не восстанавливается. Собирает его тот, кто читает
   * профиль (`patternOfProfile`), — здесь домен получает готовое.
   *
   * Необязательное с умолчанием: расчёт без указанного графика идёт по
   * «суткам через трое», единственному, который был раньше.
   */
  readonly pattern?: SchedulePattern;
  /**
   * Рабочие дни производственного календаря — для графиков, которые
   * строятся по нему, а не по циклу (пятидневка).
   *
   * Множество обязано накрывать ВЕСЬ просматриваемый отрезок, включая
   * сутки перед началом периода: смена, начавшаяся накануне, отдаёт
   * периоду свой хвост.
   */
  readonly workingDays?: ReadonlySet<IsoDate>;
  /**
   * Правки графика: сутки, назначенные сменой или снятые с неё.
   *
   * Цикл описывает график, а не жизнь. Подмены, переносы и снятия со
   * смены случаются постоянно, и человек, у которого одна смена ушла на
   * три дня вперёд, до сих пор не мог сказать этого приложению вовсе:
   * весь остальной год у него правильный, а эти сутки — нет.
   *
   * Правка называет ИСКЛЮЧЕНИЕ, а не переписывает цикл: снять смену
   * четвёртого и поставить седьмого — это две записи, а не новый график.
   * Цикл остаётся тем же и дальше строится сам.
   */
  readonly overrides?: ReadonlyMap<IsoDate, ShiftOverride>;
}

/**
 * Что человек сказал про эти сутки: смена или выходной.
 *
 * Третьего значения нет намеренно — «как в цикле» это ОТСУТСТВИЕ записи.
 * Иначе профиль копил бы правки, ничего не меняющие, и «сколько я
 * переставил смен» перестало бы быть вопросом с ответом.
 */
export type ShiftOverride = "shift" | "off";

/**
 * Приходится ли на эти сутки смена ПО ЦИКЛУ, без правок.
 *
 * Нужно и расчёту, и разметке: правка, совпавшая с циклом, не хранится, и
 * узнать это можно только здесь.
 */
export function onShiftCycle(
  knownShiftDate: IsoDate,
  day: IsoDate,
  pattern?: SchedulePattern,
  workingDays?: ReadonlySet<IsoDate>,
): boolean {
  return onPatternCycle(
    knownShiftDate,
    day,
    pattern ?? schedulePatternOf(undefined),
    workingDays,
  );
}

/**
 * Даты НАЧАЛА смен в полуинтервале `[periodStart, periodEnd)`.
 *
 * Возвращается только день начала. Смена длится сутки, поэтому кончается
 * она уже в следующих сутках, и часть её часов принадлежит им — поэтому
 * «сколько смен в марте» и «сколько часов в марте» это разные вопросы.
 * Раскладку по суткам делает `shift-hours.ts`.
 *
 * Известная смена может лежать и ПОСЛЕ периода: цикл продолжается в обе
 * стороны, и график за январь по смене, назначенной на август, строится
 * так же, как по январской.
 */
export function shiftDates(
  cycle: ShiftCycle,
  periodStart: IsoDate,
  periodEnd: IsoDate,
): IsoDate[] {
  if (periodEnd <= periodStart) return [];

  const pattern = cycle.pattern ?? schedulePatternOf(undefined);
  const dates = patternShiftDates(
    cycle.knownShiftDate,
    pattern,
    periodStart,
    periodEnd,
    cycle.workingDays,
  );

  // Правки поверх цикла. Их обычно единицы на год, поэтому перебирается
  // не период, а они сами: снятые сутки уходят из списка, назначенные
  // добавляются, если цикл их и так не даёт.
  const overrides = cycle.overrides;
  if (overrides === undefined || overrides.size === 0) return dates;

  const kept = dates.filter((day) => overrides.get(day) !== "off");
  for (const [day, override] of overrides) {
    if (override !== "shift") continue;
    if (day < periodStart || day >= periodEnd) continue;
    if (onPatternCycle(cycle.knownShiftDate, day, pattern, cycle.workingDays)) continue;
    kept.push(day);
  }
  // Порядок дат — часть договора: по ним идёт разбор смен подряд.
  return kept.sort();
}
