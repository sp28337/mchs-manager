// --------------------------------------------------------------- норма

/** Приказ № 308 п. 1 (ч. 2 ст. 54 ФЗ-141); Приказ № 307 п. 3 (ч. 2 ст. 91 ТК РФ). */
export const FULL_WEEKLY_HOURS = new Dec(40);

/** Приказ № 308 п. 1 и Приказ № 307 пп. 4, 6. */
export const REDUCED_WEEKLY_HOURS = new Dec(36);

/** Приказ № 307 п. 5 (абз. 4 ч. 1 ст. 92 ТК РФ) — инвалиды I или II группы. */
export const DISABILITY_WEEKLY_HOURS = new Dec(35);

/**
 * Недельная норма вместе с основанием, по которому она получена.
 *
 * Основание хранится рядом с числом намеренно. Весь смысл этой системы в
 * том, чтобы человек мог возразить работодателю; «36 часов» без ссылки на
 * норму — это мнение, а «36 часов, Приказ МЧС России от 24.04.2026 № 308
 * п. 1» — довод.
 */
export interface WeeklyNorm {
  readonly hours: Decimal;
  readonly basis: string;
}

export function isReduced(norm: WeeklyNorm): boolean {
  return norm.hours.lessThan(FULL_WEEKLY_HOURS);
}

export interface WeeklyNormInput {
  employment: EmploymentKind;
  gender: Gender;
  conditions: WorkingConditions;
  northernLocality: boolean;
  disabilityGroupIorII?: boolean;
}

/**
 * Недельная норма по признакам человека.
 *
 * Источники — приказы МЧС России от 24.04.2026 № 307 (работники без
 * званий) и № 308 (сотрудники), оба специально о СМЕННОЙ работе, то есть
 * ровно о том режиме, который считает это приложение.
 *
 * --- Порядок проверок ----------------------------------------------------
 *
 * Сокращения не складываются: два основания по 36 часов дают 36, а не 32.
 * Поэтому проверки идут по убыванию силы основания, и первое сработавшее
 * и есть ответ. Инвалидность проверяется первой, потому что даёт самую
 * короткую неделю — 35 часов; поставь её ниже, и работник с инвалидностью
 * во вредных условиях получил бы 36 вместо 35.
 *
 * --- Северное сокращение у сотрудников и работников разное ---------------
 *
 * У работника (Приказ № 307 п. 4, ст. 320 ТК РФ) это районы Крайнего
 * Севера и приравненные к ним местности. У сотрудника (Приказ № 308 п. 1,
 * ч. 4 ст. 54 ФЗ-141) круг шире: добавлены «другие местности с
 * неблагоприятными климатическими или экологическими условиями, в том
 * числе отдалённые». Разница существенна для того, кто служит вне Севера,
 * но в отдалённой местности: у него норма 36, а не 40.
 */
export function deriveWeeklyNorm({
  employment,
  gender,
  conditions,
  northernLocality,
  disabilityGroupIorII = false,
}: WeeklyNormInput): WeeklyNorm {
  if (disabilityGroupIorII && employment === "civilian") {
    return {
      hours: DISABILITY_WEEKLY_HOURS,
      basis:
        "Приказ МЧС России № 307 п. 5 (абз. 4 ч. 1 ст. 92 ТК РФ), " +
        "инвалидность I или II группы",
    };
  }

  if (conditions === "harmful_or_dangerous") {
    return {
      hours: REDUCED_WEEKLY_HOURS,
      basis:
        employment === "attested"
          ? "Приказ МЧС России № 308 п. 1 (ч. 2 ст. 54 ФЗ-141), " +
            "вредные или опасные условия"
          : "Приказ МЧС России № 307 п. 6 (абз. 5 ч. 1 ст. 92 ТК РФ), " +
            "вредные условия 3-4 степени либо опасные",
    };
  }

  if (gender === "female" && northernLocality) {
    return {
      hours: REDUCED_WEEKLY_HOURS,
      basis:
        employment === "attested"
          ? "Приказ МЧС России № 308 п. 1 (ч. 4 ст. 54 ФЗ-141): женщины в " +
            "районах Крайнего Севера, приравненных к ним и других местностях " +
            "с неблагоприятными условиями"
          : "Приказ МЧС России № 307 п. 4 (ст. 320 ТК РФ): женщины в " +
            "районах Крайнего Севера и приравненных к ним местностях",
    };
  }

  return {
    hours: FULL_WEEKLY_HOURS,
    basis:
      employment === "attested"
        ? "Приказ МЧС России № 308 п. 1 (ч. 2 ст. 54 ФЗ-141)"
        : "Приказ МЧС России № 307 п. 3 (ч. 2 ст. 91 ТК РФ)",
  };
}

// -------------------------------------------- основание недельной нормы

/**
 * Основание сокращённой недели — то, ЧЕМ норма вызвана.
 *
 * --- Зачем оно понадобилось ----------------------------------------------
 *
 * В настройках норма выбирается напрямую: 40, 36 или 35 часов. Но само по
 * себе число в этом приложении ничего не стоит — весь смысл в том, чтобы
 * человек мог возразить работодателю, а «36 часов» без ссылки на норму
 * это мнение. Значит, выбирая число, человек обязан выбирать вместе с ним
 * и основание.
 *
 * Оснований на 36 часов ровно два, и они разные по существу: вредные
 * условия по спецоценке и работа на Севере. Свести их в один пункт «36»
 * значило бы подставить в довод не ту статью — ту самую ошибку, из-за
 * которой довод в кабинете и рассыпается.
 *
 * --- Почему список здесь, а не в разметке --------------------------------
 *
 * Он обязан совпадать с `deriveWeeklyNorm` по порядку и по составу: если
 * они разойдутся, человек увидит в настройках «36 часов», а в расчёте
 * получит 40. Оба живут в одном файле и покрыты общим тестом.
 */
export type WeeklyNormGround = "base" | "harmful" | "northern" | "disability";

export const WEEKLY_NORM_GROUND_LABELS: Record<WeeklyNormGround, string> = {
  base: "40 часов — общая норма",
  harmful: "36 часов — вредные (3-4 степень) или опасные условия",
  northern: "36 часов — Крайний Север и приравненные местности",
  disability: "35 часов — инвалидность I или II группы",
};

/**
 * Кому какое основание вообще доступно.
 *
 * Северное сокращение оба приказа (№ 308 п. 1, № 307 п. 4) дают женщинам;
 * инвалидность I-II группы даёт 35 часов только работнику (№ 307 п. 5) —
 * службу в ФПС ГПС инвалид I или II группы не проходит. Предлагать
 * недоступное основание значило бы дать выбрать норму, которой человек не
 * получит.
 */
export function weeklyNormGroundApplies(
  ground: WeeklyNormGround,
  who: { employment: EmploymentKind; gender: Gender },
): boolean {
  if (ground === "northern") return who.gender === "female";
  if (ground === "disability") return who.employment === "civilian";
  return true;
}

/** Признаки, которые задаёт выбранное основание. */
export function weeklyNormGroundToFacts(ground: WeeklyNormGround): {
  conditions: WorkingConditions;
  northernLocality: boolean;
  disabilityGroupIorII: boolean;
} {
  return {
    conditions: ground === "harmful" ? "harmful_or_dangerous" : "normal",
    northernLocality: ground === "northern",
    disabilityGroupIorII: ground === "disability",
  };
}

/**
 * Обратное чтение: какое основание сейчас действует.
 *
 * Порядок проверок ТОТ ЖЕ, что в `deriveWeeklyNorm`, и это не совпадение,
 * а требование: иначе у человека с инвалидностью во вредных условиях
 * настройки показали бы «36», а расчёт взял бы 35.
 */
export function weeklyNormGroundOf(input: WeeklyNormInput): WeeklyNormGround {
  if (input.disabilityGroupIorII && input.employment === "civilian") return "disability";
  if (input.conditions === "harmful_or_dangerous") return "harmful";
  if (input.gender === "female" && input.northernLocality) return "northern";
  return "base";
}

// ------------------------------------------------------------- дежурство

/** Сутки через трое: заступил — и через четверо суток снова. */
export const SHIFT_CYCLE_DAYS = 4;

/**
 * Приказ № 308 п. 3 и Приказ № 307 п. 8: продолжительность смены
 * рассчитывается исходя из 24 часов, не включая время смены караулов.
 */
export const SHIFT_DURATION_HOURS = new Dec(24);

/* Время развода и раскладка смены по суткам живут в `shift-hours.ts`:
   развод назначает подразделение, и константой оно быть не может. */

/**
 * Приказ № 307 п. 10: перерывы для отдыха и питания общей
 * продолжительностью НЕ БОЛЕЕ ДВУХ ЧАСОВ, которые в рабочее время не
 * включаются (ч. 1 ст. 108 ТК РФ).
 *
 * Оговорка есть только у РАБОТНИКОВ. Приказ № 308 п. 5 требует сотруднику
 * перерывы не менее 30 минут, но из служебного времени их не исключает.
 * При этом п. 11 Приказа № 307 и п. 6 Приказа № 308 говорят одно: там, где
 * перерыв предоставить невозможно, отдых происходит ВО ВРЕМЯ исполнения
 * обязанностей. Для караула на дежурстве это обычный случай, поэтому
 * умолчание здесь — ноль.
 */
export const MAX_UNPAID_BREAK_HOURS = new Dec(2);

/**
 * График караула на год: номер караула и дата его первой смены.
 *
 * Номер караула сам по себе цикл не задаёт. В одной части первый караул
 * заступает 1 января, в другой — 3-го, и «караул № 1» в этих двух частях
 * дежурит в разные сутки. Дата первой смены — единственное, что
 * однозначно привязывает цикл к календарю; номер остаётся тем, как человек
 * свой караул называет.
 */
export interface GuardCycle {
  readonly guard: GuardNumber;
  readonly firstShiftDate: IsoDate;
}

/**
 * Даты ЗАСТУПЛЕНИЯ в полуинтервале `[periodStart, periodEnd)`.
 *
 * Возвращается только день ЗАСТУПЛЕНИЯ. Смена длится сутки с развода,
 * поэтому кончается она уже в следующих сутках, и часть её часов
 * принадлежит им — поэтому «сколько смен в марте» и «сколько часов в
 * марте» это разные вопросы. Раскладку по суткам делает `shift-hours.ts`.
 */
export function shiftDates(
  cycle: GuardCycle,
  periodStart: IsoDate,
  periodEnd: IsoDate,
): IsoDate[] {
  if (periodEnd <= periodStart) return [];

  // Ближайшее заступление не раньше начала периода. Считается
  // арифметикой, а не перебором с первой смены: перебор по году — 365
  // итераций там, где хватает одного деления, и он молча ломается на
  // периоде, начинающемся раньше первой смены.
  const delta = daysBetween(cycle.firstShiftDate, periodStart);
  const steps = delta > 0 ? Math.ceil(delta / SHIFT_CYCLE_DAYS) : 0;

  const dates: IsoDate[] = [];
  let cursor = addDays(cycle.firstShiftDate, steps * SHIFT_CYCLE_DAYS);
  while (cursor < periodEnd) {
    if (cursor >= periodStart) dates.push(cursor);
    cursor = addDays(cursor, SHIFT_CYCLE_DAYS);
  }
  return dates;
}
