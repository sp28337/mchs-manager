// --------------------------------------------------------------- норма

/** Ч. 2 ст. 91 ТК РФ — общая продолжительность рабочей недели. */
export const FULL_WEEKLY_HOURS = new Dec(40);

/** Абз. 5 ч. 1 ст. 92 ТК РФ — вредные 3-4 степени либо опасные условия. */
export const REDUCED_WEEKLY_HOURS = new Dec(36);

/** Абз. 4 ч. 1 ст. 92 ТК РФ — инвалиды I или II группы. */
export const DISABILITY_WEEKLY_HOURS = new Dec(35);

/**
 * Недельная норма вместе с основанием, по которому она получена.
 *
 * Основание хранится рядом с числом намеренно. Весь смысл этой системы в
 * том, чтобы человек мог возразить работодателю; «36 часов» без ссылки на
 * норму — это мнение, а «36 часов, абз. 5 ч. 1 ст. 92 ТК РФ» — довод.
 */
export interface WeeklyNorm {
  readonly hours: Decimal;
  readonly basis: string;
}

export interface WeeklyNormInput {
  conditions: WorkingConditions;
  disabilityGroupIorII?: boolean;
}

/**
 * Недельная норма по основанию сокращения.
 *
 * Источник один — ст. 91 и 92 ТК РФ, и он общий для всех: график «сутки
 * через трое» ведут в самых разных местах, а норма недели от места
 * работы не зависит.
 *
 * --- Почему приложение не спрашивает, кто человек ------------------------
 *
 * Спрашивало: должность, пол, местность. Ответы нужны были ровно для
 * того, чтобы РЕШИТЬ ЗА ЧЕЛОВЕКА, какое сокращение ему положено.
 *
 * Решение это, во-первых, не всегда верное: человек с приказом на руках
 * знает свою норму точнее, чем анкета из двух вопросов. Во-вторых, ошибка
 * в нём тихая: она не спорит с человеком, а молча подставляет другое
 * число.
 *
 * Поэтому вопросов больше нет: норму человек выбирает сам, а приложение
 * при ней называет статью — чтобы выбор было чем подтвердить.
 *
 * --- Порядок проверок ----------------------------------------------------
 *
 * Сокращения не складываются. Проверки идут по убыванию силы основания,
 * и первое сработавшее и есть ответ: инвалидность стоит первой, потому
 * что даёт самую короткую неделю — 35 часов; поставь её ниже, и человек с
 * инвалидностью во вредных условиях получил бы 36 вместо 35.
 */
export function deriveWeeklyNorm({
  conditions,
  disabilityGroupIorII = false,
}: WeeklyNormInput): WeeklyNorm {
  if (disabilityGroupIorII) {
    return {
      hours: DISABILITY_WEEKLY_HOURS,
      basis:
        "Абз. 4 ч. 1 ст. 92 ТК РФ: инвалидность I или II группы",
    };
  }

  if (conditions === "harmful_or_dangerous") {
    return {
      hours: REDUCED_WEEKLY_HOURS,
      basis:
        "Абз. 5 ч. 1 ст. 92 ТК РФ: вредные условия 3-4 степени " +
        "либо опасные условия по результатам спецоценки",
    };
  }

  return {
    hours: FULL_WEEKLY_HOURS,
    basis: "Ч. 2 ст. 91 ТК РФ: нормальная продолжительность рабочего времени",
  };
}

