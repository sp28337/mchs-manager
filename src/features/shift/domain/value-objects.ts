/**
 * Уменьшает ли отсутствие НОРМУ периода.
 *
 * У всех видов, кроме отгула, ответ «да»: это освобождение с сохранением
 * места, и часы по норме за эти дни исключаются (письмо Роструда от
 * 01.03.2010 № 550-6-1).
 *
 * Отгул — исключение, и по существу, а не по недосмотру. Он даётся ЗА УЖЕ
 * ОТРАБОТАННОЕ сверх нормы (ст. 55 ФЗ-141, ст. 152 ТК РФ), то есть
 * расплачивается накопленной переработкой. Уменьшить за него ещё и норму
 * значило бы заплатить человеку дважды: сначала снять часы с нормы, потом
 * не зачесть их в переработку. Поэтому норма остаётся прежней, смена не
 * отрабатывается — и переработка сама уменьшается ровно на часы отгула.
 */
export const ABSENCE_REDUCES_NORM: Record<AbsenceKind, boolean> = {
  annual_leave: true,
  extra_leave: true,
  sick_leave: true,
  study_leave: true,
  time_off_in_lieu: false,
};

