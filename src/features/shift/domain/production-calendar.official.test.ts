const OFFICIAL_YEARS = Object.entries(OFFICIAL).map(
  ([year, rows]) => [Number(year), rows] as const,
);

const pad = (value: number) => String(value).padStart(2, "0");

function monthFacts(year: number, month: number) {
  const nextYear = month === 12 ? year + 1 : year;
  const nextMonth = month === 12 ? 1 : month + 1;
  return calendarFactsFor(
    `${year}-${pad(month)}-01` as IsoDate,
    `${nextYear}-${pad(nextMonth)}-01` as IsoDate,
    new Map(),
  );
}

function norm(weeklyHours: number, facts: { workingDays: number; preHolidayDays: number }) {
  return Number(
    baseNormHours(
      { hours: new Dec(weeklyHours), basis: "сверка" },
      { workingDays: facts.workingDays, preHolidayDays: facts.preHolidayDays },
    ).toFixed(1),
  );
}

describe.each(OFFICIAL_YEARS)("производственный календарь %i года", (year, rows) => {
  test("рабочие дни и нормы совпадают помесячно", () => {
    // Сравниваются сразу все двенадцать месяцев, а не по одному: увидеть,
    // что разъехался ровно май, куда полезнее, чем узнать про первый
    // попавшийся месяц и запускать тест заново.
    const actual = rows.map((row, index) => {
      const facts = monthFacts(year, index + 1);
      return [
        facts.workingDays,
        norm(40, facts),
        norm(36, facts),
        row[3] === null ? null : norm(35, facts),
      ];
    });
    expect(actual).toEqual(rows.map((row) => [...row]));
  });

  test("годовая норма совпадает с суммой месяцев календаря", () => {
    const facts = calendarFactsFor(
      `${year}-01-01` as IsoDate,
      `${year + 1}-01-01` as IsoDate,
      new Map(),
    );
    expect(facts.workingDays).toBe(rows.reduce((sum, [days]) => sum + days, 0));
    expect(norm(40, facts)).toBe(
      Number(rows.reduce((sum, row) => sum + row[1], 0).toFixed(1)),
    );
  });
});

