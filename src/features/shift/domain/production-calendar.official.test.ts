const OFFICIAL_YEARS = Object.entries(OFFICIAL).map(
  ([year, rows]) => [Number(year), rows] as const,
);

const pad = (value: number) => String(value).padStart(2, "0");

function monthFacts(year: number, month: number) {
  const nextYear = month === 12 ? year + 1 : year;
  const nextMonth = month === 12 ? 1 : month + 1;
  return calendarFactsFor(
    `${year}-${pad(month)}-01` as IsoDate,
    `${nextYear}-${pad(nextMonth)}-01` as IsoDate,
    new Map(),
  );
}

function norm(weeklyHours: number, facts: { workingDays: number; preHolidayDays: number }) {
  return Number(
    baseNormHours(
      { hours: new Dec(weeklyHours), basis: "сверка" },
      { workingDays: facts.workingDays, preHolidayDays: facts.preHolidayDays },
    ).toFixed(1),
  );
}

describe.each(OFFICIAL_YEARS)("производственный календарь %i года", (year, rows) => {
  test("рабочие дни и нормы совпадают помесячно", () => {
    // Сравниваются сразу все двенадцать месяцев, а не по одному: увидеть,
    // что разъехался ровно май, куда полезнее, чем узнать про первый
    // попавшийся месяц и запускать тест заново.
    const actual = rows.map((_, index) => {
      const facts = monthFacts(year, index + 1);
      return [facts.workingDays, norm(40, facts), norm(36, facts), norm(35, facts)];
    });
    expect(actual).toEqual(rows.map((row) => [...row]));
  });

  test("годовая норма совпадает с суммой месяцев календаря", () => {
    const facts = calendarFactsFor(
      `${year}-01-01` as IsoDate,
      `${year + 1}-01-01` as IsoDate,
      new Map(),
    );
    expect(facts.workingDays).toBe(rows.reduce((sum, [days]) => sum + days, 0));
    expect(norm(40, facts)).toBe(
      Number(rows.reduce((sum, row) => sum + row[1], 0).toFixed(1)),
    );
  });
});

/**
 * Дни, которыми год отличается от «суббота, воскресенье и ст. 112».
 *
 * Списки короткие, и в этом их ценность: здесь ровно то, что задало
 * постановление о переносе выходных, и сверить их с текстом постановления
 * можно глазами. Сводная таблица месяца такой ошибки не поймает — в
 * ноябре 2025 рабочая суббота и перенесённый выходной стоят в одном
 * месяце и в сумме дают то же число рабочих дней.
 */
interface YearTransfers {
  readonly workingWeekends: readonly string[];
  readonly weekdaysOff: readonly string[];
}

const TRANSFERS: Record<number, YearTransfers> = {
  2023: {
    workingWeekends: [],
    // 24 февраля и 8 мая — перенос новогодних выходных; 6 ноября — ст. 112
    // ч. 2, потому что 4 ноября пришлось на субботу.
    weekdaysOff: ["2023-02-24", "2023-05-08", "2023-11-06"],
  },
  2024: {
    workingWeekends: ["2024-04-27", "2024-11-02", "2024-12-28"],
    weekdaysOff: ["2024-04-29", "2024-04-30", "2024-05-10", "2024-12-30", "2024-12-31"],
  },
  2025: {
    workingWeekends: ["2025-11-01"],
    // 24 февраля и 10 марта рабочие: выходные за 23 февраля и 8 марта
    // постановление отдало 8 мая и 13 июня, а не следующему дню.
    weekdaysOff: ["2025-05-02", "2025-05-08", "2025-06-13", "2025-11-03", "2025-12-31"],
  },
  2026: {
    workingWeekends: [],
    // 9 марта и 11 мая — ст. 112 ч. 2; 9 января и 31 декабря — перенос
    // новогодних выходных.
    weekdaysOff: ["2026-01-09", "2026-03-09", "2026-05-11", "2026-12-31"],
  },
  2027: {
    workingWeekends: ["2027-02-20"],
    // 3, 10 мая и 14 июня — ст. 112 ч. 2; 22 февраля, 5 ноября и
    // 31 декабря — постановление.
    weekdaysOff: [
      "2027-02-22",
      "2027-05-03",
      "2027-05-10",
      "2027-06-14",
      "2027-11-05",
      "2027-12-31",
    ],
  },
};

const TRANSFER_YEARS = Object.entries(TRANSFERS).map(
  ([year, transfers]) => [Number(year), transfers] as const,
);

describe.each(TRANSFER_YEARS)("перенос выходных в %i году", (year, transfers) => {
  test("рабочие субботы ровно те, что назвало постановление", () => {
    const calendar = statutoryCalendar(year);
    const actual = [...calendar]
      .filter(([day, type]) => isWeekend(day) && (type === "working" || type === "pre_holiday"))
      .map(([day]) => day);
    expect(actual).toEqual(transfers.workingWeekends);
  });

  test("нерабочие будни ровно те, что назвали закон и постановление", () => {
    // Праздники ст. 112 ч. 1 отброшены: они одинаковы каждый год и
    // проверяются в соседнем файле. Здесь интересны только те будни,
    // которые стали нерабочими сверх них.
    const statutory = new Set(
      ["01-01", "01-02", "01-03", "01-04", "01-05", "01-06", "01-07", "01-08",
        "02-23", "03-08", "05-01", "05-09", "06-12", "11-04"]
        .map((tail) => `${year}-${tail}`),
    );
    const actual = [...statutoryCalendar(year)]
      .filter(
        ([day, type]) =>
          !isWeekend(day) && type !== "working" && type !== "pre_holiday" && !statutory.has(day),
      )
      .map(([day]) => day);
    expect(actual).toEqual(transfers.weekdaysOff);
  });

  test("перенесённый выходной не остаётся предпраздничным", () => {
    // Сокращать на час день, который стал нерабочим, незачем. Порядок
    // шагов в построении календаря следит именно за этим.
    const calendar = statutoryCalendar(year);
    for (const day of transfers.weekdaysOff) {
      expect(calendar.get(day as IsoDate)).not.toBe("pre_holiday");
    }
  });
});
