describe.each(TRANSFER_YEARS)("перенос выходных в %i году", (year, transfers) => {
  test("рабочие субботы ровно те, что назвало постановление", () => {
    const calendar = statutoryCalendar(year);
    const actual = [...calendar]
      .filter(([day, type]) => isWeekend(day) && (type === "working" || type === "pre_holiday"))
      .map(([day]) => day);
    expect(actual).toEqual(transfers.workingWeekends);
  });

  test("нерабочие будни ровно те, что назвали закон и постановление", () => {
    // Праздники ст. 112 ч. 1 отброшены: они одинаковы каждый год и
    // проверяются в соседнем файле. Здесь интересны только те будни,
    // которые стали нерабочими сверх них.
    const statutory = new Set(
      ["01-01", "01-02", "01-03", "01-04", "01-05", "01-06", "01-07", "01-08",
        "02-23", "03-08", "05-01", "05-09", "06-12", "11-04"]
        .map((tail) => `${year}-${tail}`),
    );
    const actual = [...statutoryCalendar(year)]
      .filter(
        ([day, type]) =>
          !isWeekend(day) && type !== "working" && type !== "pre_holiday" && !statutory.has(day),
      )
      .map(([day]) => day);
    expect(actual).toEqual(transfers.weekdaysOff);
  });

  test("перенесённый выходной не остаётся предпраздничным", () => {
    // Сокращать на час день, который стал нерабочим, незачем. Порядок
    // шагов в построении календаря следит именно за этим.
    const calendar = statutoryCalendar(year);
    for (const day of transfers.weekdaysOff) {
      expect(calendar.get(day as IsoDate)).not.toBe("pre_holiday");
    }
  });
});

/**
 * Нерабочие дни по указам Президента 2020 и 2021 годов.
 *
 * В календарях они помечены двумя и более звёздочками, и соблазн внести
 * их сюда велик — но норму они не уменьшают, а смены в эти дни шли
 * как обычно. Проверка стоит здесь, чтобы это решение нельзя было
 * «починить» молча: если такой день когда-нибудь станет нерабочим,
 * человек, отдежуривший тогда сутки, недосчитается переработки.
 */
const PRESIDENTIAL_NON_WORKING = {
  // Указы от 25.03.2020 № 206, от 02.04.2020 № 239, от 28.04.2020 № 294 —
  // 30 марта — 30 апреля и 6-8 мая; от 29.05.2020 № 345 — 24 июня;
  // от 01.06.2020 № 354 — 1 июля.
  2020: [
    "2020-03-30", "2020-03-31", "2020-04-01", "2020-04-15", "2020-04-29",
    "2020-05-06", "2020-05-07", "2020-06-24", "2020-07-01",
  ],
  // Указы от 23.04.2021 № 242 — 4-7 мая; от 20.10.2021 № 595 —
  // 30 октября — 7 ноября.
  2021: ["2021-05-04", "2021-05-05", "2021-05-06", "2021-05-07", "2021-11-01", "2021-11-02"],
} as const;

describe("нерабочие дни по указам Президента", () => {
  test("остаются рабочими: норма от них не уменьшается", () => {
    for (const [year, days] of Object.entries(PRESIDENTIAL_NON_WORKING)) {
      const calendar = statutoryCalendar(Number(year));
      for (const day of days) {
        const type = calendar.get(day as IsoDate);
        expect([day, type]).toEqual([day, expect.stringMatching(/^(working|pre_holiday)$/u)]);
      }
    }
  });

  test("30 апреля и 8 мая 2020 остались сокращёнными, а не нерабочими", () => {
    // Сноска календаря: «в организациях, для которых 30 апреля, 8 мая
    // являются рабочими днями, продолжительность работы в эти дни
    // сокращается на 1 час». Для непрерывного дежурства это и есть тот
    // самый случай. То же и с 3 ноября 2021 года.
    const y2020 = statutoryCalendar(2020);
    expect(y2020.get("2020-04-30")).toBe("pre_holiday");
    expect(y2020.get("2020-05-08")).toBe("pre_holiday");
    expect(statutoryCalendar(2021).get("2021-11-03")).toBe("pre_holiday");
  });
});
