/**
 * Календарь приложения против ОФИЦИАЛЬНЫХ производственных календарей.
 *
 * --- Зачем эта проверка отдельно ----------------------------------------
 *
 * Соседний файл проверяет, что календарь построен ПО ПРАВИЛАМ. Этот
 * проверяет, что получившееся совпадает с бумагой, которую человек держит
 * в руках. Разница существенная: правила приложение выбирает само, а
 * бумагу — нет. Расхождение в один рабочий день это восемь часов нормы, и
 * человек с нашим расчётом окажется неправ в разговоре, ради которого
 * расчёт и делался.
 *
 * --- Что здесь лежит ----------------------------------------------------
 *
 * Сводные таблицы производственных календарей 2018-2027 годов, по строке
 * на месяц: рабочих дней и норма при 40-, 36- и 35-часовой неделе. Числа
 * взяты из самих календарей и не пересчитаны — иначе проверка сверяла бы
 * приложение с приложением. В календарях 2018 и 2019 годов колонки
 * 35-часовой недели нет вовсе, и на её месте стоит `null`.
 *
 * Норма при сокращённой неделе тоже проверяется, и не для полноты:
 * 36 часов у женщин в сельской местности и 35 у инвалидов I-II группы
 * считаются по той же таблице, и ошибка в предпраздничных днях видна там
 * так же, как при сорока часах.
 *
 * Отдельно перечислены дни, отличающиеся от «суббота, воскресенье и
 * ст. 112»: перенос выходных постановлением задаёт именно их, и сводная
 * таблица месяца молчит, когда рабочая суббота и перенесённый выходной
 * попали в один месяц и погасили друг друга.
 */

