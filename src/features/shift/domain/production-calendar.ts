/**
 * Производственный календарь: какие дни года рабочие.
 *
 * --- Почему он считается, а не хранится ---------------------------------
 *
 * Раньше календарь лежал в базе на сервере, куда его клал сид-скрипт. Но
 * почти весь он ВЫВОДИМ ИЗ ЗАКОНА: праздники ст. 112 ТК РФ — фиксированные
 * даты, выходные — суббота и воскресенье, предпраздничные — ст. 95, а
 * перенос выходного, совпавшего с праздником, задан ст. 112 ч. 2. Всё это
 * одинаково считается в любом браузере, и держать ради него сервер незачем.
 *
 * Побочное следствие важнее удобства: раз календарь считается на месте,
 * приложению больше не нужно ничего спрашивать у сервера, и персональные
 * данные никуда не уходят.
 *
 * Вручную набранная таблица на 365 строк — это, кроме прочего, ровно та
 * вещь, которая приобретает опечатку, замеченную только когда норма выйдет
 * неверной.
 *
 * --- Что из закона не выводится -----------------------------------------
 *
 * Ежегодное постановление Правительства «О переносе выходных дней». Оно
 * меняется каждый год и переносит выходные куда захочет: новогодние,
 * попавшие внутрь каникул 1-8 января, и заодно те, из которых удобно
 * склеить длинные выходные. Поэтому оно лежит здесь ТАБЛИЦЕЙ — по одной
 * записи на год, слово в слово по тексту постановления. Внесены годы с
 * 2023 по 2027; соседний тест сверяет их с официальными производственными
 * календарями до последнего дня.
 *
 * Года, которого в таблице нет, приложение не угадывает. Цена молчания
 * названа честно: `pendingTransfers` даёт список новогодних дней,
 * оставшихся без компенсирующего выходного, и экран обязан это показать —
 * каждый такой день это 8 часов лишней нормы.
 */

import {
  addDays,
  datesOfYear,
  isWeekend,
  makeDate,
  type IsoDate,
} from "./plain-date";

export type DayType = "working" | "weekend" | "holiday" | "pre_holiday";

/** ТК РФ ст. 112 ч. 1 — фиксированные даты, одинаковые каждый год. */
const STATUTORY_HOLIDAYS: readonly (readonly [number, number])[] = [
  [1, 1], [1, 2], [1, 3], [1, 4], [1, 5], [1, 6], [1, 7], [1, 8], // новогодние + Рождество
  [2, 23], // День защитника Отечества
  [3, 8],  // Международный женский день
  [5, 1],  // Праздник Весны и Труда
  [5, 9],  // День Победы
  [6, 12], // День России
  [11, 4], // День народного единства
];

const NEW_YEAR_BLOCK_DAYS = 8;

/**
 * Постановление о переносе выходных дней, разобранное на части.
 *
 * Постановление всегда говорит одно и то же: «перенести выходной день с
 * ТАКОГО-ТО на ТАКОЙ-ТО». Отсюда три списка, и каждый нужен отдельно.
 */
interface WeekendTransferDecree {
  /**
   * Дни, СТАВШИЕ НЕРАБОЧИМИ, — то, куда выходной перенесли.
   *
   * Размечаются как праздничные. На норму тип не влияет: и выходной, и
   * праздничный одинаково не входят в число рабочих дней. Различие видно
   * в двух местах — в подписи клетки календаря и в счётчике «праздничные
   * часы», куда попадут часы смены, пришедшейся на такой день.
   */
  readonly daysOff: readonly IsoDate[];
  /**
   * Субботы и воскресенья, СТАВШИЕ РАБОЧИМИ, — то, откуда выходной взяли.
   *
   * Без них год недосчитается рабочих дней: постановление переносит
   * выходной, а не дарит его.
   */
  readonly workingWeekends?: readonly IsoDate[];
  /**
   * Праздники, чей выходной постановление перенесло ЯВНО.
   *
   * К ним не применяется автоматический перенос ст. 112 ч. 2. Иначе день
   * отдыха достался бы человеку дважды: и по кодексу назавтра, и по
   * постановлению через три месяца. Так, в 2025 году выходной за
   * воскресенье 23 февраля отдан четвергу 8 мая — и понедельник
   * 24 февраля остался рабочим.
   */
  readonly movedHolidays?: readonly IsoDate[];
  /**
   * Рабочие субботы, которые официальный календарь всё-таки сокращает
   * на час.
   *
   * Из ст. 95 это не выводится: сокращается день, «непосредственно
   * предшествующий» празднику, а между такой субботой и праздником лежат
   * ещё день-два выходных. Тем не менее производственный календарь их
   * сокращает — 2 ноября 2024, 1 ноября 2025, 20 февраля 2027, — а
   * 27 апреля и 28 декабря 2024 не сокращает. Правила, объясняющего оба
   * случая, нет, поэтому данные, а не вывод.
   */
  readonly shortenedWeekends?: readonly IsoDate[];
}

/**
 * Перенос выходных дней по годам.
 *
 * Источник каждой записи назван рядом. Сверять записи следует с текстом
 * постановления, а не с чьим-то календарём: календари перепечатывают друг
 * друга вместе с ошибками.
 */
const DECREES: Record<number, WeekendTransferDecree> = {
  // Постановление Правительства РФ от 29.08.2022 № 1505.
  // С воскресенья 1 января — на пятницу 24 февраля;
  // с воскресенья 8 января — на понедельник 8 мая.
  2023: {
    daysOff: ["2023-02-24", "2023-05-08"],
  },

  // Постановление Правительства РФ от 10.08.2023 № 1314.
  // С субботы 6 января — на пятницу 10 мая;
  // с воскресенья 7 января — на вторник 31 декабря;
  // с субботы 27 апреля — на понедельник 29 апреля;
  // с субботы 2 ноября — на вторник 30 апреля;
  // с субботы 28 декабря — на понедельник 30 декабря.
  2024: {
    daysOff: ["2024-04-29", "2024-04-30", "2024-05-10", "2024-12-30", "2024-12-31"],
    workingWeekends: ["2024-04-27", "2024-11-02", "2024-12-28"],
    shortenedWeekends: ["2024-11-02"],
  },

  // Постановление Правительства РФ от 04.10.2024 № 1335.
  // С субботы 4 января — на пятницу 2 мая;
  // с воскресенья 5 января — на среду 31 декабря;
  // с воскресенья 23 февраля — на четверг 8 мая;
  // с субботы 8 марта — на пятницу 13 июня;
  // с субботы 1 ноября — на понедельник 3 ноября.
  2025: {
    daysOff: ["2025-05-02", "2025-05-08", "2025-06-13", "2025-11-03", "2025-12-31"],
    workingWeekends: ["2025-11-01"],
    movedHolidays: ["2025-02-23", "2025-03-08"],
    shortenedWeekends: ["2025-11-01"],
  },

  // Постановление Правительства РФ от 24.09.2025 № 1466.
  // С субботы 3 января — на пятницу 9 января;
  // с воскресенья 4 января — на четверг 31 декабря.
  2026: {
    daysOff: ["2026-01-09", "2026-12-31"],
  },

  // ПРОЕКТ постановления, подготовленный Минтрудом 01.04.2026: с субботы
  // 2 января — на пятницу 5 ноября; с воскресенья 3 января — на пятницу
  // 31 декабря; с субботы 20 февраля — на понедельник 22 февраля. Само
  // постановление выйдет до декабря 2026 года, и эту запись нужно будет
  // сверить с его текстом: пока это проект, а не действующий акт.
  2027: {
    daysOff: ["2027-02-22", "2027-11-05", "2027-12-31"],
    workingWeekends: ["2027-02-20"],
    shortenedWeekends: ["2027-02-20"],
  },
};

export function statutoryHolidays(year: number): Set<IsoDate> {
  return new Set(STATUTORY_HOLIDAYS.map(([month, day]) => makeDate(year, month, day)));
}

function newYearBlock(year: number): Set<IsoDate> {
  return new Set(
    Array.from({ length: NEW_YEAR_BLOCK_DAYS }, (_, index) => makeDate(year, 1, index + 1)),
  );
}

/**
 * Базовый календарь года по одному только закону.
 *
 * Порядок шагов существенен и повторяет порядок норм: сначала выходные по
 * дням недели, затем праздники поверх них, затем перенос по ст. 112 ч. 2,
 * и только в самом конце предпраздничные — иначе день, ставший выходным
 * при переносе, мог бы получить признак предпраздничного, которым он не
 * является.
 */
export function statutoryCalendar(year: number): Map<IsoDate, DayType> {
  const holidays = statutoryHolidays(year);
  const newYear = newYearBlock(year);
  const decree = DECREES[year];
  const movedByDecree = new Set<IsoDate>(decree?.movedHolidays ?? []);

  // 1. Основа: выходные по дням недели, остальное рабочее.
  const types = new Map<IsoDate, DayType>(
    datesOfYear(year).map((day) => [day, isWeekend(day) ? "weekend" : "working"] as const),
  );

  // 2. Праздники перекрывают основу.
  for (const holiday of holidays) types.set(holiday, "holiday");

  // 3. Ст. 112 ч. 2 — выходной, совпавший с нерабочим праздничным днём,
  //    переносится на следующий рабочий день. Правило НЕ применяется к
  //    новогодним каникулам и к тем праздникам, чей перенос постановление
  //    назначило само: иначе выходной достался бы дважды.
  for (const holiday of [...holidays].sort()) {
    if (newYear.has(holiday) || movedByDecree.has(holiday) || !isWeekend(holiday)) continue;
    let cursor = addDays(holiday, 1);
    while (types.get(cursor) !== "working") {
      cursor = addDays(cursor, 1);
      if (cursor.slice(0, 4) !== String(year)) break;
    }
    if (types.get(cursor) === "working") types.set(cursor, "weekend");
  }

  // 4. Постановление. Сначала субботы, отданные под перенос, — они
  //    становятся рабочими; затем дни, куда выходной перенесли. Порядок
  //    важен на случай, когда постановление переносит выходной с субботы
  //    на понедельник той же недели.
  for (const day of decree?.workingWeekends ?? []) {
    if (types.has(day)) types.set(day, "working");
  }
  for (const day of decree?.daysOff ?? []) {
    if (types.has(day)) types.set(day, "holiday");
  }

  // 5. Ст. 95 — РАБОЧИЙ день непосредственно перед нерабочим праздничным
  //    короче на час. Считается только от праздников, никогда от
  //    перенесённых выходных; 31 декабря смотрит через границу года.
  const nextNewYear = makeDate(year + 1, 1, 1);
  for (const [day, type] of [...types]) {
    if (type !== "working") continue;
    const following = addDays(day, 1);
    if (holidays.has(following) || following === nextNewYear) {
      types.set(day, "pre_holiday");
    }
  }

  // 6. Рабочие субботы, сокращённые официальным календарём вопреки шагу 5.
  for (const day of decree?.shortenedWeekends ?? []) {
    if (types.get(day) === "working") types.set(day, "pre_holiday");
  }

  return types;
}

/**
 * Новогодние выходные, оставшиеся без компенсирующего выходного дня.
 *
 * Столько дней в году приложение считает рабочими сверх официального
 * календаря, пока человек не внесёт перенос. Каждый такой день — 8 часов
 * лишней нормы.
 */
export function pendingTransfers(year: number): IsoDate[] {
  // Год в таблице — постановление внесено целиком, недостачи нет. Считать
  // тут нечего: запись содержит весь перенос, а не только новогодний.
  if (DECREES[year]) return [];
  return [...newYearBlock(year)].filter(isWeekend).sort();
}

/** Откуда взят тип дня. Человек должен различать закон и свою правку. */
export type DaySource = "statutory" | "override";

export interface CalendarDay {
  readonly day: IsoDate;
  readonly dayType: DayType;
  readonly source: DaySource;
}

/**
 * Календарь года с наложенными правками человека.
 *
 * Правка выигрывает всегда: базовый календарь — это закон без
 * постановления о переносах, а человек держит перед глазами настоящий
 * производственный календарь и знает точнее.
 */
export function calendarWithOverrides(
  year: number,
  overrides: ReadonlyMap<IsoDate, DayType>,
): CalendarDay[] {
  return [...statutoryCalendar(year)].map(([day, dayType]) => {
    const override = overrides.get(day);
    return override === undefined
      ? { day, dayType, source: "statutory" as const }
      : { day, dayType: override, source: "override" as const };
  });
}

export interface CalendarFactsForPeriod {
  readonly workingDays: number;
  readonly preHolidayDays: number;
  readonly holidays: Set<IsoDate>;
  /** Сами рабочие дни, а не только их число: по ним считается, сколько
   *  нормы приходится на отпуск. */
  readonly workingDaySet: Set<IsoDate>;
  readonly preHolidayDaySet: Set<IsoDate>;
}

/**
 * Что даёт календарь за полуинтервал `[periodStart, periodEnd)`.
 *
 * Предпраздничный день попадает И в рабочие, И в предпраздничные:
 * производственный календарь считает его рабочим, просто сокращённым на
 * час (ст. 95 ТК РФ). Исключить его из рабочих значило бы вычесть за него
 * девять часов вместо одного.
 *
 * Период может пересекать границу года — полугодие и год у людей с первой
 * сменой в начале января не пересекают, но месяц декабрь-январь при ручном
 * выборе пересечь может, — поэтому календарь берётся по всем затронутым
 * годам, а не по одному.
 */
export function calendarFactsFor(
  periodStart: IsoDate,
  periodEnd: IsoDate,
  overridesByYear: ReadonlyMap<number, ReadonlyMap<IsoDate, DayType>>,
): CalendarFactsForPeriod {
  let workingDays = 0;
  let preHolidayDays = 0;
  const holidays = new Set<IsoDate>();
  const workingDaySet = new Set<IsoDate>();
  const preHolidayDaySet = new Set<IsoDate>();

  const firstYear = Number(periodStart.slice(0, 4));
  // `periodEnd` исключающая: период, кончающийся 1 января, последнего года
  // не захватывает, и строить для него календарь незачем.
  const lastYear = Number(addDays(periodEnd, -1).slice(0, 4));

  for (let year = firstYear; year <= lastYear; year += 1) {
    const overrides = overridesByYear.get(year) ?? new Map<IsoDate, DayType>();
    for (const { day, dayType } of calendarWithOverrides(year, overrides)) {
      if (day < periodStart || day >= periodEnd) continue;
      if (dayType === "working" || dayType === "pre_holiday") {
        workingDays += 1;
        workingDaySet.add(day);
      }
      if (dayType === "pre_holiday") {
        preHolidayDays += 1;
        preHolidayDaySet.add(day);
      }
      if (dayType === "holiday") holidays.add(day);
    }
  }

  return { workingDays, preHolidayDays, holidays, workingDaySet, preHolidayDaySet };
}
