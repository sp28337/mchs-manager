const NEW_YEAR_BLOCK_DAYS = 8;

/**
 * Одна строка постановления: «перенести выходной день с ТАКОГО на ТАКОЙ».
 *
 * Пара, а не два независимых списка, — потому что из связи между её
 * концами выводится всё остальное, включая то, какой день окажется
 * сокращённым. Подробнее в `statutoryCalendar`.
 */
interface WeekendTransfer {
  /** Откуда выходной взяли: суббота, воскресенье или праздник. */
  readonly from: IsoDate;
  /** Куда его перенесли: рабочий день, ставший нерабочим. */
  readonly to: IsoDate;
}

