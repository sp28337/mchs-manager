/**
 * График сменности: сколько суток подряд рабочих и сколько за ними выходных.
 *
 * --- Почему это стало настройкой -----------------------------------------
 *
 * Приложение начиналось с одного графика — «сутки через трое», — и цикл был
 * константой в четыре дня. Но арифметика у всех сменных графиков одна и та
 * же: цикл повторяется, отсутствия уменьшают норму, переработка считается
 * за учётный период. Отличаются они ровно двумя числами — длиной цикла и
 * тем, сколько суток в нём рабочих.
 *
 * Значит, держать «сутки через трое» в константе означало отказывать всем
 * остальным в расчёте, который для них уже написан.
 *
 * --- Почему «5|2» устроен иначе -------------------------------------------
 *
 * Скользящим циклом его сделать нельзя, и это не мелочь. Пятидневка — не
 * «пять суток подряд, потом двое», а РАБОЧАЯ НЕДЕЛЯ, и определяет её не
 * арифметика, а производственный календарь: восьмого марта человек не
 * работает, а в перенесённую субботу работает. Цикл в семь дней об этом не
 * знает и в первый же праздник разъезжается с календарём навсегда — с
 * каждым следующим переносом ошибка накапливается.
 *
 * Поэтому у 5|2 рабочие дни берутся ПРЯМО ИЗ КАЛЕНДАРЯ: рабочий день по
 * календарю — смена, выходной или праздник — нет. Переносы и правки
 * человека при этом учтены сами собой: календарь их уже знает.
 *
 * Известная дата смены для такого графика не нужна вовсе — её не у чего
 * спрашивать, и настройки её не показывают.
 *
 * --- Почему есть «свой график» --------------------------------------------
 *
 * Четырёх заготовок мало. Встречаются 3|1, 2|1, сутки через двое, 4|4 на
 * вахте — перечислить все нельзя, а отказывать человеку в расчёте из-за
 * того, что его цикла не оказалось в списке, тем более. Заготовки поэтому
 * остаются как БЫСТРЫЙ ОТВЕТ на частый случай, а не как перечень
 * допустимого: рядом с ними стоит «свой», где цикл называется двумя
 * числами.
 *
 * Своим графиком нельзя описать только пятидневку — её задаёт календарь, а
 * не арифметика, и подделать её парой чисел невозможно в принципе.
 *
 * --- Почему у графика своя продолжительность смены ------------------------
 *
 * Она из него следует, а не выбирается независимо: сутки через трое — это
 * смена в 24 часа, два через два — в 12, пятидневка — в 8. Поэтому смена
 * графика подставляет и продолжительность.
 *
 * Подставляет, а НЕ навязывает: у двенадцатичасовых смен встречается
 * одиннадцать с половиной (обед за свой счёт), а у суточных — 23. Число
 * остаётся полем, которое человек правит; график только называет обычное
 * для себя значение.
 */

import type { IsoDate } from "./plain-date";
import { addDays, daysBetween } from "./plain-date";

/**
 * Опознание графика. Записывается в профиль, поэтому строкой, а не числом.
 *
 * `custom` — цикл, названный человеком: сами числа лежат в профиле
 * отдельно, потому что в опознание их не уместить.
 */
export type SchedulePatternId = "1|3" | "2|2" | "5|2" | "1|4" | "custom";

/** Опознание своего графика — одно место на всё приложение. */
export const CUSTOM_PATTERN_ID = "custom" satisfies SchedulePatternId;

/**
 * Как графики назывались раньше: «1/3» вместо «1|3».
 *
 * --- Почему знак поменялся ------------------------------------------------
 *
 * Косая черта читается как дробь — «одна третья», — а речь не о дроби, а о
 * двух числах рядом: столько-то работаем, столько-то отдыхаем. Тем же
 * знаком, вертикальной чертой, пара цифр разделена в самом названии сайта
 * и в его знаке, и разнобой между вывеской и настройками объяснить было
 * нечем.
 *
 * --- Почему старые опознания остаются -------------------------------------
 *
 * Они записаны в профилях, которые лежат в браузерах у людей, и профиль,
 * не открывшийся из-за смены знака в служебной строке, — это потерянный
 * год внесённых отпусков. Поэтому старое опознание читается наравне с
 * новым и молча заменяется новым при первой же записи: человек ничего не
 * делает и ничего не замечает.
 *
 * Список замкнутый и расти не будет: это ровно те четыре заготовки, что
 * существовали до смены знака.
 */
export const LEGACY_PATTERN_IDS: Readonly<Record<string, SchedulePatternId>> = {
  "1/3": "1|3",
  "1/4": "1|4",
  "2/2": "2|2",
  "5/2": "5|2",
};

/**
 * Опознание графика в нынешнем написании.
 *
 * Неизвестное — не ошибка: сюда приходит строка из профиля, а профиль мог
 * быть записан версией с другим списком. Что делать с неопознанным, решает
 * не эта функция, а тот, кто её позвал.
 */
export function migrateSchedulePatternId(id: string): string {
  return LEGACY_PATTERN_IDS[id] ?? id;
}

/**
 * Пределы своего цикла.
 *
 * Ноль рабочих суток — это не график, а его отсутствие; ноль выходных —
 * работа без единого выходного, чего трудовое законодательство не знает.
 * Верхний предел взят с запасом: месячная вахта в него укладывается, а
 * дальше цикл перестаёт быть циклом.
 */
export const MIN_CUSTOM_DAYS = 1;
export const MAX_CUSTOM_DAYS = 31;

/**
 * Откуда берутся рабочие дни.
 *
 * `cycle` — из повторяющегося цикла вокруг названной смены.
 * `calendar` — из производственного календаря, вместе с переносами.
 */
export type ScheduleSource = "cycle" | "calendar";

export interface SchedulePattern {
  readonly id: SchedulePatternId;
  readonly source: ScheduleSource;
  /** Длина цикла в сутках: рабочие плюс выходные. */
  readonly cycleDays: number;
  /** Сколько суток подряд рабочих с начала цикла. */
  readonly workDays: number;
  /** Обычная для этого графика продолжительность смены, в часах. */
  readonly defaultShiftHours: string;
  /** Как график называют: «1|3». */
  readonly label: string;
  /** Как он читается словами — для подписи и для программы чтения. */
  readonly title: string;
}

