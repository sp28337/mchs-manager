/**
 * График сменности: сколько суток подряд рабочих и сколько за ними выходных.
 *
 * --- Почему это стало настройкой -----------------------------------------
 *
 * Приложение начиналось с одного графика — «сутки через трое», — и цикл был
 * константой в четыре дня. Но арифметика у всех сменных графиков одна и та
 * же: цикл повторяется, отсутствия уменьшают норму, переработка считается
 * за учётный период. Отличаются они ровно двумя числами — длиной цикла и
 * тем, сколько суток в нём рабочих.
 *
 * Значит, держать «сутки через трое» в константе означало отказывать всем
 * остальным в расчёте, который для них уже написан.
 *
 * --- Что такое «5/2» в этой модели ----------------------------------------
 *
 * Тот же скользящий цикл: пять суток подряд рабочих, двое выходных, и
 * дальше по кругу. Привычная рабочая неделя получается из него сама, если
 * известной сменой назвать ПОНЕДЕЛЬНИК: цикл семидневный, и выходные тогда
 * навсегда встают на субботу с воскресеньем.
 *
 * Отдельного «графика по дням недели» поэтому нет. Он был бы вторым
 * способом описать то же самое — и первым же расхождением между тем, что
 * человек выбрал, и тем, что посчитано.
 *
 * --- Почему у графика своя продолжительность смены ------------------------
 *
 * Она из него следует, а не выбирается независимо: сутки через трое — это
 * смена в 24 часа, два через два — в 12, пятидневка — в 8. Поэтому смена
 * графика подставляет и продолжительность.
 *
 * Подставляет, а НЕ навязывает: у двенадцатичасовых смен встречается
 * одиннадцать с половиной (обед за свой счёт), а у суточных — 23. Число
 * остаётся полем, которое человек правит; график только называет обычное
 * для себя значение.
 */

import type { IsoDate } from "./plain-date";
import { addDays, daysBetween } from "./plain-date";

/** Опознание графика. Записывается в профиль, поэтому строкой, а не числом. */
export type SchedulePatternId = "1/3" | "2/2" | "5/2" | "1/4";

export interface SchedulePattern {
  readonly id: SchedulePatternId;
  /** Длина цикла в сутках: рабочие плюс выходные. */
  readonly cycleDays: number;
  /** Сколько суток подряд рабочих с начала цикла. */
  readonly workDays: number;
  /** Обычная для этого графика продолжительность смены, в часах. */
  readonly defaultShiftHours: string;
  /** Как график называют: «1/3». */
  readonly label: string;
  /** Как он читается словами — для подписи и для программы чтения. */
  readonly title: string;
}

/**
 * Все графики списком, от самого частого к редкому.
 *
 * Порядок виден человеку: он же порядок пунктов в настройках.
 */
export const SCHEDULE_PATTERNS: readonly SchedulePattern[] = [
  {
    id: "1/3",
    cycleDays: 4,
    workDays: 1,
    defaultShiftHours: "24",
    label: "1/3",
    title: "Сутки через трое",
  },
  {
    id: "1/4",
    cycleDays: 5,
    workDays: 1,
    defaultShiftHours: "24",
    label: "1/4",
    title: "Сутки через четверо",
  },
  {
    id: "2/2",
    cycleDays: 4,
    workDays: 2,
    defaultShiftHours: "12",
    label: "2/2",
    title: "Два через два",
  },
  {
    id: "5/2",
    cycleDays: 7,
    workDays: 5,
    defaultShiftHours: "8",
    label: "5/2",
    title: "Пять через два",
  },
];

/** График по умолчанию — тот, с которого приложение начиналось. */
export const DEFAULT_SCHEDULE_PATTERN: SchedulePatternId = "1/3";

const BY_ID = new Map(SCHEDULE_PATTERNS.map((pattern) => [pattern.id, pattern]));

/**
 * График по опознанию.
 *
 * Неизвестное значение — не исключение, а график по умолчанию: сюда
 * приходит строка из профиля, а профиль мог быть записан версией, в
 * которой список был другим. Белый экран вместо расчёта человек починить
 * не сможет, а неверный график — увидит и исправит.
 */
export function schedulePatternOf(id: string | undefined): SchedulePattern {
  return BY_ID.get(id as SchedulePatternId) ?? BY_ID.get(DEFAULT_SCHEDULE_PATTERN)!;
}

/** Положение суток внутри цикла: 0 — первые рабочие сутки. */
function positionInCycle(anchor: IsoDate, day: IsoDate, cycleDays: number): number {
  const delta = daysBetween(anchor, day);
  return ((delta % cycleDays) + cycleDays) % cycleDays;
}

/**
 * Приходится ли на эти сутки смена ПО ЦИКЛУ, без правок.
 *
 * Известная смена задаёт НАЧАЛО рабочей череды, а не просто одну смену: у
 * графика «два через два» названные человеком сутки — первые из двух.
 * Иначе вторые сутки пришлось бы называть отдельно, и график перестал бы
 * достраиваться сам.
 */
export function onPatternCycle(
  anchor: IsoDate,
  day: IsoDate,
  pattern: SchedulePattern,
): boolean {
  return positionInCycle(anchor, day, pattern.cycleDays) < pattern.workDays;
}

/**
 * Даты начала смен по циклу в полуинтервале `[from, to)`.
 *
 * Отсчёт идёт от ближайшего начала цикла НЕ ПОЗЖЕ левой границы, а дальше
 * циклами: так известная смена может лежать где угодно — хоть в августе
 * при расчёте за январь, — и работает это в обе стороны.
 */
export function patternShiftDates(
  anchor: IsoDate,
  pattern: SchedulePattern,
  from: IsoDate,
  to: IsoDate,
): IsoDate[] {
  if (to <= from) return [];

  const { cycleDays, workDays } = pattern;
  // Начало цикла, накрывающего левую границу: сдвигаемся назад на
  // положение границы внутри цикла. `Math.floor` по отрицательной разнице
  // здесь не нужен — положение уже приведено к неотрицательному.
  let cursor = addDays(from, -positionInCycle(anchor, from, cycleDays));

  const dates: IsoDate[] = [];
  while (cursor < to) {
    for (let i = 0; i < workDays; i++) {
      const day = addDays(cursor, i);
      if (day >= from && day < to) dates.push(day);
    }
    cursor = addDays(cursor, cycleDays);
  }
  return dates;
}
