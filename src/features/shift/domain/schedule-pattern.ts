/** График по умолчанию — тот, с которого приложение начиналось. */
export const DEFAULT_SCHEDULE_PATTERN: SchedulePatternId = "1/3";

const BY_ID = new Map(SCHEDULE_PATTERNS.map((pattern) => [pattern.id, pattern]));

/**
 * График по опознанию.
 *
 * Неизвестное значение — не исключение, а график по умолчанию: сюда
 * приходит строка из профиля, а профиль мог быть записан версией, в
 * которой список был другим. Белый экран вместо расчёта человек починить
 * не сможет, а неверный график — увидит и исправит.
 */
export function schedulePatternOf(id: string | undefined): SchedulePattern {
  return BY_ID.get(id as SchedulePatternId) ?? BY_ID.get(DEFAULT_SCHEDULE_PATTERN)!;
}

/** Положение суток внутри цикла: 0 — первые рабочие сутки. */
function positionInCycle(anchor: IsoDate, day: IsoDate, cycleDays: number): number {
  const delta = daysBetween(anchor, day);
  return ((delta % cycleDays) + cycleDays) % cycleDays;
}

/**
 * Приходится ли на эти сутки смена ПО ГРАФИКУ, без правок человека.
 *
 * У цикличных графиков известная смена задаёт НАЧАЛО рабочей череды, а не
 * просто одну смену: у «два через два» названные сутки — первые из двух.
 * Иначе вторые пришлось бы называть отдельно, и график перестал бы
 * достраиваться сам.
 *
 * У пятидневки ответ даёт производственный календарь. Нет календаря — нет
 * и смен: выдумать рабочий день, не зная, не праздник ли он, нельзя, а
 * молча показать его сменой значило бы соврать.
 */
export function onPatternCycle(
  anchor: IsoDate,
  day: IsoDate,
  pattern: SchedulePattern,
  workingDays?: ReadonlySet<IsoDate>,
): boolean {
  if (pattern.source === "calendar") return workingDays?.has(day) ?? false;
  return positionInCycle(anchor, day, pattern.cycleDays) < pattern.workDays;
}

/**
 * Даты начала смен по графику в полуинтервале `[from, to)`.
 *
 * У цикличных графиков отсчёт идёт от ближайшего начала цикла НЕ ПОЗЖЕ
 * левой границы, а дальше циклами: так известная смена может лежать где
 * угодно — хоть в августе при расчёте за январь, — и работает это в обе
 * стороны.
 *
 * У пятидневки перебираются сами сутки периода, а рабочие из них называет
 * календарь. Перебор здесь не расточительство: за год это триста
 * шестьдесят пять проверок в множестве, то есть ничто, — а вот вывести
 * рабочие дни года формулой нельзя в принципе, потому что переносы
 * назначают постановлением.
 */
export function patternShiftDates(
  anchor: IsoDate,
  pattern: SchedulePattern,
  from: IsoDate,
  to: IsoDate,
  workingDays?: ReadonlySet<IsoDate>,
): IsoDate[] {
  if (to <= from) return [];

  if (pattern.source === "calendar") {
    if (workingDays === undefined) return [];
    const dates: IsoDate[] = [];
    for (let day = from; day < to; day = addDays(day, 1)) {
      if (workingDays.has(day)) dates.push(day);
    }
    return dates;
  }

  const { cycleDays, workDays } = pattern;
  // Начало цикла, накрывающего левую границу: сдвигаемся назад на
  // положение границы внутри цикла. `Math.floor` по отрицательной разнице
  // здесь не нужен — положение уже приведено к неотрицательному.
  let cursor = addDays(from, -positionInCycle(anchor, from, cycleDays));

  const dates: IsoDate[] = [];
  while (cursor < to) {
    for (let i = 0; i < workDays; i++) {
      const day = addDays(cursor, i);
      if (day >= from && day < to) dates.push(day);
    }
    cursor = addDays(cursor, cycleDays);
  }
  return dates;
}
