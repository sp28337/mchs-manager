"use client";

import { useCallback, useSyncExternalStore } from "react";

import { LEGAL_VERSIONS } from "@/features/sync/legal";

/**
 * Ответ человека про аналитику: спросили один раз, помним, даём сменить.
 *
 * --- Почему это вообще нужно ------------------------------------------------
 *
 * Счётчик посещений ставит cookie и собирает IP-адрес — то есть сведения, по
 * которым человека можно выделить среди прочих. Значит, нужно согласие
 * (п. 1 ч. 1 ст. 6 152-ФЗ), конкретное и информированное (ч. 1 ст. 9), и
 * отзываемое в любое время (ч. 2 ст. 9). Отсюда три требования к этому
 * хранилищу: до ответа счётчик не грузится вовсе, ответ хранится вместе с
 * датой и редакцией документа, сменить его можно на странице `/cookies`.
 *
 * --- Почему в `localStorage`, а не в cookie ---------------------------------
 *
 * Потому что это ответ браузера самому себе: серверу он не нужен — счётчик
 * грузится или не грузится на стороне человека. Cookie же уехала бы в каждом
 * запросе к серверу, то есть ради отказа от лишних данных появились бы
 * лишние данные.
 *
 * --- Почему редакция хранится рядом с ответом -------------------------------
 *
 * Согласие даётся на конкретный текст. Изменится состав собираемого — выйдет
 * новая редакция документа о cookie, и прежний ответ перестанет быть
 * согласием на новое: тогда вопрос задаётся заново. Это не придирка, а прямое
 * требование к информированности согласия.
 */

/** Что человек ответил. */
export type CookieChoice = "all" | "necessary";

interface Запись {
  choice: CookieChoice;
  /** Когда ответил — ISO. */
  at: string;
  /** Редакция документа о cookie, на которую отвечали. */
  version: string;
}

const КЛЮЧ = "grafik13.cookies";

/**
 * Своё событие для своей же вкладки.
 *
 * `storage` браузер шлёт только ОСТАЛЬНЫМ вкладкам, а полоса с вопросом и
 * страница настроек живут в той же, где нажали.
 */
const СОБЫТИЕ = "grafik13:cookies";

function прочитать(): Запись | null {
  try {
    const строка = localStorage.getItem(КЛЮЧ);
    if (строка === null) return null;

    const запись = JSON.parse(строка) as Partial<Запись>;

    if (запись.choice !== "all" && запись.choice !== "necessary") return null;
    // Ответ на прежнюю редакцию — не ответ на нынешнюю.
    if (запись.version !== LEGAL_VERSIONS.cookies) return null;

    return { choice: запись.choice, at: String(запись.at ?? ""), version: запись.version };
  } catch {
    // Приватное окно, запрет на хранилище, чужая строка в ключе — всё это
    // означает одно: ответа нет, спросим.
    return null;
  }
}

/** Запомнить ответ и сказать об этом всем, кто слушает. */
export function answerCookies(choice: CookieChoice): void {
  const запись: Запись = {
    choice,
    at: new Date().toISOString(),
    version: LEGAL_VERSIONS.cookies,
  };

  try {
    localStorage.setItem(КЛЮЧ, JSON.stringify(запись));
  } catch {
    // Хранилище закрыто — ответ проживёт до перезагрузки страницы. Это
    // хуже, чем хотелось бы, но лучше, чем сломанная кнопка: счётчик всё
    // равно слушает то же событие.
  }

  window.dispatchEvent(new CustomEvent(СОБЫТИЕ));
}

function подписаться(заметить: () => void): () => void {
  window.addEventListener(СОБЫТИЕ, заметить);
  window.addEventListener("storage", заметить);

  return () => {
    window.removeEventListener(СОБЫТИЕ, заметить);
    window.removeEventListener("storage", заметить);
  };
}

/**
 * Ответ как строка — она же снимок для `useSyncExternalStore`.
 *
 * Снимок обязан быть сравнимым по значению: вернуть новый объект на каждый
 * вызов значило бы зациклить отрисовку. Поэтому строка «ответ|дата», а
 * разбирают её те, кому нужна дата.
 */
function снимок(): string {
  const запись = прочитать();

  return запись === null ? "" : `${запись.choice}|${запись.at}`;
}

/** На сервере и до гидратации ответа нет: разметка одна на всех. */
function наСервере(): string {
  return "";
}

export interface CookieState {
  /** `null` — человек ещё не отвечал (или отвечал на прежнюю редакцию). */
  choice: CookieChoice | null;
  /** Когда ответил, ISO; пусто, если не отвечал. */
  at: string;
}

export function useCookieConsent(): CookieState {
  const строка = useSyncExternalStore(
    // Обёртка в `useCallback` с телом-стрелкой — требование правила
    // `react-hooks`: ему нужно видеть функцию на месте, а не ссылку на
    // неё. Подписка от этого не пересоздаётся: список зависимостей пуст.
    useCallback((заметить: () => void) => подписаться(заметить), []),
    снимок,
    наСервере,
  );

  if (строка === "") return { choice: null, at: "" };

  const [choice = "", at = ""] = строка.split("|");

  return { choice: choice === "all" ? "all" : "necessary", at };
}
