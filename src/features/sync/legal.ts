/**
 * Версии документов, которые человек принимает при регистрации.
 *
 * Согласие доказуемо ровно настолько, насколько известно, С ЧЕМ человек
 * согласился: в записи о согласии сервер хранит по строке на каждый из трёх
 * документов — версию, хэш текста, время и адрес IP. Доказывать получение
 * согласия обязан оператор (ч. 3 ст. 9 152-ФЗ), а само согласие оформляется
 * отдельно от иных документов (ч. 1 ст. 9). Версия — дата редакции из
 * головного блока файла в `docs/legal/`.
 *
 * Перечень лежит здесь, а не приходит с сервера, по той же причине, что и
 * на сервере (`api/src/grafik_api/core/legal.py`): до шага 12 ручки
 * `GET /legal/documents` нет, а сверяет их тест (`legal.test.ts`) — с
 * теми же файлами. Разойтись перечни не должны: сервер отвергнет
 * регистрацию с устаревшей версией, и человек увидит отказ, причины
 * которого в интерфейсе нет.
 */

export const LEGAL_VERSIONS = {
  policy: "2026-10-24",
  consent: "2026-10-24",
  terms: "2026-10-24",
  /**
   * Документ о cookie — в перечне, но не в согласии при регистрации.
   *
   * Согласие на аналитику человек даёт отдельно и до всякой регистрации
   * (полосой внизу страницы), и подшивать его к записи о регистрации
   * нельзя: это разные согласия, их дают в разное время и отзывают
   * порознь.
   */
  cookies: "2026-10-24",
} as const;

/** Адреса документов на сайте. Страницы появятся на шаге 12. */
export const LEGAL_URLS = {
  policy: "/privacy",
  consent: "/consent",
  terms: "/terms",
  cookies: "/cookies",
} as const;

/**
 * Какие из двух отметок человек поставил.
 *
 * Отметок две, потому что согласие на обработку оформляется отдельно от
 * соглашения и политики (ч. 1 ст. 9 152-ФЗ): «принимаю соглашение и политику»
 * и «даю согласие на обработку».
 */
export interface ConsentActs {
  termsAndPolicy: boolean;
  personalData: boolean;
}

/**
 * То, что уходит в `POST /auth/register`.
 *
 * Версии трёх документов, а не четырёх: согласие на аналитику к учётной записи
 * отношения не имеет. И явные признаки двух действий: версии без них говорили
 * бы лишь «браузер знает, какие сейчас редакции», а не «человек что-то
 * отметил». Признаки берутся из настоящих отметок формы, а не подставляются
 * истиной: если кнопку когда-нибудь нажмут без отметки, сервер откажет.
 */
export function consentPayload(acts: ConsentActs) {
  return {
    policy_version: LEGAL_VERSIONS.policy,
    consent_version: LEGAL_VERSIONS.consent,
    terms_version: LEGAL_VERSIONS.terms,
    accepted_terms_and_policy: acts.termsAndPolicy,
    accepted_personal_data: acts.personalData,
  };
}

/**
 * То, что уходит в `POST /account/consents` — повторное принятие.
 *
 * Спрашивается одно согласие на обработку: политика и соглашение заново не
 * принимаются (`api/src/grafik_api/services/consents.py` — почему). Поэтому
 * версия одна и отметка одна, и берётся она из настоящей отметки, а не
 * подставляется истиной: нажатая без отметки кнопка не должна записать согласие.
 */
export function renewalPayload(personalData: boolean) {
  return {
    consent_version: LEGAL_VERSIONS.consent,
    accepted_personal_data: personalData,
  };
}
