/**
 * Нужно ли сказать человеку о синхронизации — и что именно.
 *
 * Решение отделено от полосы (`sync-notice.tsx`) затем, что это правило, а
 * не вид: его можно прочитать целиком в двадцати строках и проверить
 * тестом, не поднимая браузера.
 *
 * --- Правило в одном предложении -------------------------------------------
 *
 * Говорим только тогда, когда синхронизация ВСТАЛА САМА и дальше без
 * человека не поедет.
 *
 * Отсюда всё остальное:
 *
 * * **нет сети** — не повод: правки уедут, когда сеть вернётся, а
 *   приложение работает полностью и без сервера. Полоса здесь сообщала бы
 *   о беде, которой нет;
 * * **есть неотправленные правки** — не повод по той же причине: это
 *   обычное состояние между правкой и проходом;
 * * **человек сам нажал «войти» и ошибся паролем** — не повод: он стоит
 *   на той форме, и отказ ему показывает она. Полоса на рабочем экране
 *   повторяла бы сказанное в другом месте;
 * * **вход не выполнен и ничего не случилось** — не повод: человек не
 *   заводил учётной записи, и предлагать её посреди работы незачем. Для
 *   приглашения есть строка в подвале;
 * * **сессия кончилась в фоне** (`stalled`) — повод: человек об этом не
 *   знает, правки молча перестали уезжать, и вернуть их на место может
 *   только он;
 * * **сервер отказал на проходе** (`stalled`) — повод по той же причине.
 */

import type { SyncPhase } from "./sync-provider";

/** Что сказать и что предложить сделать. */
export interface Повод {
  /** Беда словами человека — та же строка, что показывает экран входа. */
  текст: string;
  /** Подпись ссылки на страницу учётной записи. */
  действие: string;
}

/** Часть состояния синхронизации, от которой зависит решение. */
export interface Обстоятельства {
  enabled: boolean;
  phase: SyncPhase;
  error: string | null;
  stalled: boolean;
}

export function поводСказать({
  enabled,
  phase,
  error,
  stalled,
}: Обстоятельства): Повод | null {
  if (!enabled || !stalled || error === null) return null;

  if (phase === "signed-out") {
    // Ключ данных в этом браузере остался, но ходить с ним некуда:
    // нужен вход. Поэтому «войти снова», а не «войти».
    return { текст: error, действие: "Войти снова" };
  }

  if (phase === "error") {
    return { текст: error, действие: "Открыть учётную запись" };
  }

  // Остальные состояния до полосы не доходят: `stalled` ставится только
  // в двух случаях выше. Проверка оставлена нарочно — чтобы добавленное
  // когда-нибудь третье состояние молча не превратилось в полосу с
  // неподходящей подписью.
  return null;
}
