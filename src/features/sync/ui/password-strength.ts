/**
 * Крепость пароля: считается здесь, в браузере, и только здесь.
 *
 * --- Почему на сервере этой проверки нет и быть не может -------------------
 *
 * Сервер пароля не видит ни разу. На него уходит `verifier` —
 * результат argon2id от пароля (раздел 2.1 контракта), — и отличить
 * «11111111» от двадцати случайных знаков по нему нельзя: оба выглядят
 * как 32 байта шума. Это цена сквозного шифрования, и платится она
 * сознательно: пароль, который сервер мог бы проверить, он мог бы и
 * записать.
 *
 * Значит, крепость — дело браузера, и спрашивается она ровно там, где
 * пароль ПРИДУМЫВАЮТ: при регистрации, при смене пароля и при
 * восстановлении доступа. На входе не спрашивается никогда: человек с
 * паролем, заведённым до появления этой проверки, обязан войти.
 *
 * --- Что именно проверяется ------------------------------------------------
 *
 * Не «буквы, цифры и спецсимвол» — такие правила давно признаны вредными:
 * они дают «Пароль1!» и не дают ничего больше. Проверяется то, что
 * проверять советует NIST SP 800-63B (п. 5.1.1.2): длина, списки самых
 * частых паролей, повторы, последовательности и слова, связанные с самим
 * человеком — в нашем случае его адрес почты. Набор знаков не ограничен
 * ничем: пробелы, кириллица, знаки препинания, эмодзи — всё годится и всё
 * считается в оценку.
 *
 * Оценка — не «проходной балл за сложность», а прикидка того, сколько
 * попыток нужно на перебор: длина, очищенная от повторов и
 * последовательностей, умноженная на разрядность набора знаков. Величина
 * приблизительная по природе, поэтому порог один и низкий — отсечь явно
 * негодное, а не учить человека жить.
 */

/** Насколько пароль крепок — словами, какие показываются человеку. */
export type Крепость = "слабый" | "средний" | "хороший" | "отличный";

export interface Оценка {
  /** Прикидка стойкости к перебору, бит. */
  биты: number;
  уровень: Крепость;
  /** Чем именно плох пароль; `null` — годен. */
  причина: string | null;
  /** Можно ли таким паролем завести учётную запись. */
  годится: boolean;
}

/**
 * Порог годности, бит.
 *
 * Тридцать шесть — это восемь случайных строчных букв (8 × log₂26 ≈ 37,6):
 * ровно тот минимум, который приложение обещает строкой «не меньше восьми
 * знаков». Восемь цифр (26,6) ниже порога и не пройдут — и правильно: их
 * перебирают за секунды.
 */
const ПОРОГ = 36;

/**
 * Самые частые пароли — короткий список, а не словарь на сто тысяч строк.
 *
 * Длинные списки нужны тому, кто ломает; здесь довольно верхушки, потому
 * что всё остальное отсекают повторы, последовательности и счёт битов.
 * Смысл этого перечня один: не пустить пароль, который стоит в первой
 * сотне любого слитого списка и потому проверяется нападающим первым.
 *
 * Русские слова здесь не для порядка: подбирают по спискам, слитым с
 * русских же сайтов, и «любовь» в них стоит там же, где «iloveyou».
 */
const ЧАСТЫЕ = new Set([
  "password", "passw0rd", "qwerty", "qwertyui", "qwerty123", "123456", "1234567",
  "12345678", "123456789", "1234567890", "111111", "000000", "121212", "123123",
  "112233", "654321", "1q2w3e4r", "1q2w3e", "qazwsx", "qazwsxedc", "zxcvbn",
  "zxcvbnm", "asdfgh", "asdfghjk", "iloveyou", "letmein", "welcome", "monkey",
  "dragon", "sunshine", "princess", "football", "baseball", "superman", "batman",
  "master", "shadow", "michael", "jennifer", "hunter", "trustno1", "starwars",
  "whatever", "computer", "internet", "samsung", "google", "apple", "admin",
  "administrator", "root", "test", "guest", "login", "secret", "abc123",
  "a1b2c3d4", "qwe123", "asd123", "zaq12wsx",
  "пароль", "пароль123", "парольь", "йцукен", "йцукенг", "фывапр", "ячсмить",
  "привет", "любовь", "люблю", "солнышко", "котёнок", "котенок", "зайка",
  "россия", "москва", "спартак", "зенит", "динамо", "наташа", "марина",
  "сергей", "александр", "андрей", "максим", "дмитрий", "натали", "кристина",
]);

/**
 * Ряды клавиатуры и алфавиты — из них растут последовательности.
 *
 * Клавиатурные ряды даны в обеих раскладках: «ghbdtn» — это «привет»,
 * набранное по-английски, и для подбирающего оно ничем не отличается.
 */
const ДОРОЖКИ = [
  "1234567890",
  "qwertyuiop",
  "asdfghjkl",
  "zxcvbnm",
  "abcdefghijklmnopqrstuvwxyz",
  "йцукенгшщзхъ",
  "фывапролджэ",
  "ячсмитьбю",
  "абвгдеёжзийклмнопрстуфхцчшщъыьэюя",
];

/** Что на какой клавише: латиница ↔ кириллица, чтобы «ghbdtn» нашлось. */
const РАСКЛАДКА: Record<string, string> = {};
{
  const лат = "qwertyuiop[]asdfghjkl;'zxcvbnm,.";
  const кир = "йцукенгшщзхъфывапролджэячсмитьбю";
  for (const [i, знак] of [...лат].entries()) РАСКЛАДКА[знак] = кир[i]!;
}

/** `ghbdtn` → `привет`. Знаки, которых на клавиатуре нет, остаются собой. */
function вКириллицу(строка: string): string {
  return [...строка].map((знак) => РАСКЛАДКА[знак] ?? знак).join("");
}

/** `p@ssw0rd` → `password`: подмены, которые считают хитростью. */
function безПодмен(строка: string): string {
  const замены: Record<string, string> = {
    "0": "o", "1": "i", "3": "e", "4": "a", "5": "s", "7": "t",
    "@": "a", "$": "s", "!": "i", "+": "t",
  };

  return [...строка].map((знак) => замены[знак] ?? знак).join("");
}

/**
 * Разрядность набора знаков: сколько вариантов приходится на знак.
 *
 * Считается по тому, какие наборы в пароле ВСТРЕТИЛИСЬ, а не по тому,
 * какие разрешены: подбирающий начинает с узкого набора и расширяет его,
 * только когда узкий не дал результата.
 */
function разрядность(пароль: string): number {
  let всего = 0;

  if (/[a-z]/.test(пароль)) всего += 26;
  if (/[A-Z]/.test(пароль)) всего += 26;
  if (/[а-яё]/.test(пароль)) всего += 33;
  if (/[А-ЯЁ]/.test(пароль)) всего += 33;
  if (/[0-9]/.test(пароль)) всего += 10;
  if (/ /.test(пароль)) всего += 1;
  // Всё остальное — знаки препинания, скобки, валюты, эмодзи — одной
  // кучей: их на клавиатуре около трёх десятков, и разбирать подробнее
  // незачем, оценка и без того приблизительная.
  if (/[^a-zA-Zа-яёА-ЯЁ0-9 ]/.test(пароль)) всего += 33;

  return Math.max(всего, 2);
}

/**
 * Длина за вычетом того, что длиной не является.
 *
 * Знак, повторяющий предыдущий, и знак, продолжающий дорожку
 * («1234», «qwer», «абвг»), подбирающему достаются даром: он идёт по
 * шаблону, а не перебирает. Такие знаки в счёт не идут.
 */
function рабочаяДлина(пароль: string): number {
  const знаки = [...пароль];
  let длина = 0;

  for (const [i, знак] of знаки.entries()) {
    if (i === 0) {
      длина += 1;
      continue;
    }

    const прежний = знаки[i - 1]!;

    if (знак === прежний) continue;
    if (подряд(прежний, знак)) continue;

    длина += 1;
  }

  return длина;
}

/** Идут ли два знака подряд по дорожке — в любую сторону. */
function подряд(первый: string, второй: string): boolean {
  const а = первый.toLowerCase();
  const б = второй.toLowerCase();

  return ДОРОЖКИ.some((дорожка) => {
    const i = дорожка.indexOf(а);

    return i !== -1 && (дорожка[i + 1] === б || дорожка[i - 1] === б);
  });
}

/** Весь пароль — одна дорожка или один знак по кругу. */
function сплошнойШаблон(пароль: string): boolean {
  return рабочаяДлина(пароль) <= 2 && пароль.length >= 4;
}

/** Пароль — это одно и то же, повторённое несколько раз («абвабвабв»). */
function поКругу(пароль: string): boolean {
  for (let кусок = 1; кусок <= пароль.length / 2; кусок += 1) {
    if (пароль.length % кусок !== 0) continue;

    const образец = пароль.slice(0, кусок);

    if (образец.repeat(пароль.length / кусок) === пароль) return true;
  }

  return false;
}

/** Есть ли пароль в списке самых частых — с поправкой на хитрости. */
function изСписка(пароль: string): boolean {
  const нижний = пароль.toLowerCase();
  const варианты = [
    нижний,
    безПодмен(нижний),
    вКириллицу(нижний),
    вКириллицу(безПодмен(нижний)),
    // Хвост из цифр отбрасывается: «qwerty2024» подбирается тем же
    // списком, только с перебором года.
    нижний.replace(/\d+$/, ""),
    безПодмен(нижний).replace(/\d+$/, ""),
    вКириллицу(нижний).replace(/\d+$/, ""),
  ];

  return варианты.some((вариант) => вариант.length > 0 && ЧАСТЫЕ.has(вариант));
}

/** Куски адреса почты, которые нельзя повторять в пароле. */
function куски(email: string): string[] {
  const нижний = email.trim().toLowerCase();
  const [имя = "", домен = ""] = нижний.split("@");

  return [имя, домен.split(".")[0] ?? "", ...имя.split(/[._-]+/)].filter(
    (кусок) => кусок.length >= 4,
  );
}

export function оценить(
  пароль: string,
  { email = "" }: { email?: string } = {},
): Оценка {
  const пусто: Оценка = { биты: 0, уровень: "слабый", причина: null, годится: false };

  if (пароль === "") return пусто;

  const биты = Math.round(рабочаяДлина(пароль) * Math.log2(разрядность(пароль)));
  const уровень: Крепость =
    биты < ПОРОГ ? "слабый" : биты < 60 ? "средний" : биты < 80 ? "хороший" : "отличный";

  const отказ = (причина: string): Оценка => ({
    биты,
    уровень: "слабый",
    причина,
    годится: false,
  });

  if (пароль.length < 8) return отказ("Не меньше восьми знаков.");

  if (поКругу(пароль) || сплошнойШаблон(пароль)) {
    return отказ("Знаки идут подряд или по кругу — такое подбирают за секунды.");
  }

  if (изСписка(пароль)) {
    return отказ("Такой пароль стоит в первых строках списков для подбора.");
  }

  const нижний = пароль.toLowerCase();

  if (куски(email).some((кусок) => нижний.includes(кусок))) {
    return отказ("В пароле ваш адрес почты — его подставят первым.");
  }

  if (биты < ПОРОГ) {
    return отказ("Слишком короткий для такого набора знаков. Добавьте слов или знаков.");
  }

  return { биты, уровень, причина: null, годится: true };
}
