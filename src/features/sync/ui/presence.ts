/**
 * Как учётная запись называет себя на экране.
 *
 * Мест, где о ней говорят, стало три: знак в шапке с его меню
 * (`account-entry.tsx`), строка в подвале рабочего экрана
 * (`sync-status.tsx`) и страница учётной записи (`account-screen.tsx`).
 * Слова у них обязаны быть одни: человек видит их в одном сеансе рядом, и
 * «Синхронизировано» в подвале при «Отложено» в меню — это не два взгляда
 * на одно состояние, а поломка на вид.
 *
 * Поэтому здесь правила, а не оформление: чистые функции без React и без
 * сети, с тестами рядом (`presence.test.ts`). Вид — в компонентах.
 */

import type { SyncPhase } from "./sync-provider";

/** Из чего складываются слова о состоянии. */
export interface Обстановка {
  phase: SyncPhase;
  /** Есть правки, которые ещё не уехали. */
  dirty: boolean;
  /** Когда последний проход закончился удачей. */
  syncedAt: string | null;
  /** Принято с другого устройства в последний проход. */
  принято?: number;
}

/**
 * Что показать там, где места на одну строку.
 *
 * Отвечает на единственный вопрос, который человек задаёт синхронизации:
 * «моё уехало?». Поэтому «нет связи» сказано так же спокойно, как
 * «синхронизировано», — делать человеку в этом случае нечего, расчёт и
 * правки работают в браузере, а уехать они успеют сами.
 */
export function короткоОСинхронизации(
  обстановка: Обстановка,
  сейчас: number = Date.now(),
): string {
  const { phase, dirty, syncedAt } = обстановка;
  const принято = обстановка.принято ?? 0;

  if (phase === "connecting") return "Подключение…";
  if (phase === "syncing") return "Синхронизация…";
  if (phase === "offline") return "Нет связи — правки уедут позже";
  if (phase === "error") return "Синхронизация отложена";
  if (phase === "signed-out") return "Вход не выполнен";
  if (dirty) return "Есть изменения — уедут через мгновение";
  if (принято > 0) return `Синхронизировано · принято: ${принято}`;
  if (syncedAt === null) return "Синхронизация настроена";

  return `Синхронизировано ${когда(syncedAt, сейчас)}`;
}

/**
 * Каким цветом горит точка у знака учётной записи.
 *
 * Цветов ровно три, и сигнальный из них — только там, где от человека
 * что-то нужно: правило приложения «сигнальный цвет не украшает» на
 * учётную запись распространяется так же, как на расчёт. Отсутствие связи
 * сигналом не является.
 */
export type Огонёк = "ok" | "wait" | "attention";

export function огонёк(обстановка: Обстановка & { stalled?: boolean }): Огонёк {
  if (обстановка.stalled === true) return "attention";
  if (обстановка.phase === "idle" && !обстановка.dirty) return "ok";

  return "wait";
}

/**
 * Буква в знаке учётной записи.
 *
 * Берётся из адреса почты: ничего другого о человеке сервис не знает —
 * ни имени, ни фамилии, и заводить их ради кружка в шапке незачем.
 * Буква латиницы и буква кириллицы в одном знаке смотрятся одинаково
 * ровно, а вот цифра или точка — нет: адрес, начинающийся не с буквы,
 * получает знак без буквы вовсе (его рисует значок человека).
 */
export function инициал(email: string): string | null {
  const первая = email.trim().slice(0, 1).toUpperCase();

  return /\p{L}/u.test(первая) ? первая : null;
}

/** `2026-10-14T08:00:00Z` → «только что», «12 мин назад», дата и время. */
export function когда(время: string, сейчас: number = Date.now()): string {
  const прошло = сейчас - Date.parse(время);

  if (Number.isNaN(прошло)) return время;
  if (прошло < 60_000) return "только что";
  if (прошло < 60 * 60_000) return `${Math.round(прошло / 60_000)} мин назад`;

  return new Date(время).toLocaleString("ru-RU", {
    dateStyle: "short",
    timeStyle: "short",
  });
}
