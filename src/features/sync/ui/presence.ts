/**
 * Как учётная запись называет время на экране.
 *
 * Здесь жила и короткая строка о состоянии — «Синхронизировано только
 * что», «Нет связи — правки уедут позже», — для подвала рабочего экрана и
 * для строки под адресом на странице учётной записи. Обе убраны:
 * синхронизация задумана невидимой, и одна и та же строка, стоявшая
 * ссылкой в подвале, читалась кнопкой, предлагающей сделать то, что
 * приложение и так делает само.
 *
 * Когда синхронизация встала и без человека не поедет, об этом сообщает
 * полоса наверху рабочего экрана (`sync-notice.tsx`). Время последнего
 * прохода остаётся в разделе «Синхронизация» на странице учётной записи —
 * для того, кто пришёл его проверить.
 *
 * Правила здесь — чистые функции без React и без сети, с тестами рядом
 * (`presence.test.ts`).
 */

/** `2026-10-14T08:00:00Z` → «только что», «12 мин назад», дата и время. */
export function когда(время: string, сейчас: number = Date.now()): string {
  const прошло = сейчас - Date.parse(время);

  if (Number.isNaN(прошло)) return время;
  if (прошло < 60_000) return "только что";
  if (прошло < 60 * 60_000) return `${Math.round(прошло / 60_000)} мин назад`;

  return new Date(время).toLocaleString("ru-RU", {
    dateStyle: "short",
    timeStyle: "short",
  });
}
