"use client";

import Link from "next/link";

import { короткоОСинхронизации } from "./presence";
import { useSync } from "./sync-provider";

/**
 * Одна строка о состоянии синхронизации.
 *
 * Стоит в подвале рабочего экрана, рядом со временем последней правки:
 * вопрос у человека один и тот же — «моё сохранено? моё уехало?», — и
 * ответы на него должны стоять рядом.
 *
 * --- Зачем она, когда знак есть в шапке ------------------------------------
 *
 * Знак в шапке (`account-entry.tsx`) отвечает цветом точки, то есть на
 * вопрос «всё ли в порядке». Здесь ответ словами и со временем — на
 * вопрос «а точно уехало и когда». Это не два места об одном: точка
 * видна всегда и потому молчалива, строка в подвале читается тогда, когда
 * за ней пришли.
 *
 * --- Почему «нет связи» сказано так же спокойно, как «синхронизировано»
 *
 * Потому что делать человеку в этом случае нечего: расчёт, правки и
 * проводник работают в браузере, как работали до появления аккаунта, а
 * уехать правки успеют сами. Красным цветом и восклицательным знаком
 * здесь сообщалось бы о беде, которой нет.
 */
export function SyncStatus() {
  const { enabled, phase, account, syncedAt, dirty, report } = useSync();

  if (!enabled) return null;

  if (phase === "signed-out" || account === null) {
    return (
      <span className="text-ink-faint">
        <Link href="/account" className="hover:underline">
          Синхронизация между устройствами
        </Link>
      </span>
    );
  }

  // Слова — общие для шапки, подвала и страницы учётной записи
  // (`presence.ts`): человек видит их в одном сеансе рядом.
  const слова = короткоОСинхронизации({
    phase,
    dirty,
    syncedAt,
    принято: report === null ? 0 : report.received + report.deleted,
  });

  return (
    <span className="text-ink-faint">
      <Link href="/account" className="hover:underline">
        {слова}
      </Link>
    </span>
  );
}
