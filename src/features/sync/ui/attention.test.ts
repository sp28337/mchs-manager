/**
 * Когда о синхронизации говорят, а когда молчат.
 *
 * Правило проверяется здесь, а вид полосы — браузером: смысл не в том,
 * как она выглядит, а в том, что она не появляется там, где человеку
 * ничего делать не надо. Полоса, вылезающая на каждое отключение сети,
 * перестаёт читаться ровно к тому дню, когда скажет что-то важное.
 */

import { describe, expect, it } from "vitest";

import { поводСказать, type Обстоятельства } from "./attention";
import { СЕССИЯ_КОНЧИЛАСЬ } from "./messages";

const ОБЫЧНО: Обстоятельства = {
  enabled: true,
  phase: "idle",
  error: null,
  stalled: false,
};

describe("молчим, когда человеку делать нечего", () => {
  it("всё хорошо", () => {
    expect(поводСказать(ОБЫЧНО)).toBeNull();
  });

  it("нет сети — правки уедут сами", () => {
    expect(
      поводСказать({
        ...ОБЫЧНО,
        phase: "offline",
        error: "Нет связи с сервером.",
      }),
    ).toBeNull();
  });

  it("вход не выполнен, и ничего не случилось", () => {
    expect(поводСказать({ ...ОБЫЧНО, phase: "signed-out" })).toBeNull();
  });

  it("человек сам ошибся паролем в форме входа", () => {
    // `stalled` здесь ложь: отказ пришёл на его собственное действие, и
    // объясняет его та же форма. Полоса повторяла бы сказанное.
    expect(
      поводСказать({
        ...ОБЫЧНО,
        phase: "signed-out",
        error: "Неверный адрес или пароль.",
      }),
    ).toBeNull();
  });

  it("синхронизация выключена сборкой", () => {
    expect(
      поводСказать({
        enabled: false,
        phase: "signed-out",
        error: "Сервер ответил отказом.",
        stalled: true,
      }),
    ).toBeNull();
  });
});

describe("говорим, когда без человека не поедет", () => {
  it("сессия кончилась в фоне — просим войти снова", () => {
    const повод = поводСказать({
      ...ОБЫЧНО,
      phase: "signed-out",
      error: СЕССИЯ_КОНЧИЛАСЬ,
      stalled: true,
    });

    expect(повод).not.toBeNull();
    expect(повод?.действие).toBe("Войти снова");
    // Слова берутся из состояния, а не придумываются здесь: одна беда —
    // одна строка и в полосе, и на странице учётной записи.
    expect(повод?.текст).toBe(СЕССИЯ_КОНЧИЛАСЬ);
  });

  it("сервер отказал на проходе — ведём в учётную запись", () => {
    const повод = поводСказать({
      ...ОБЫЧНО,
      phase: "error",
      error: "Место, отведённое учётной записи, кончилось.",
      stalled: true,
    });

    expect(повод?.действие).toBe("Открыть учётную запись");
  });

  it("без слов не говорим ничего", () => {
    // `stalled` без объяснения — это недосмотр в провайдере, и полоса без
    // текста человеку ничего не сообщает.
    expect(поводСказать({ ...ОБЫЧНО, phase: "error", stalled: true })).toBeNull();
  });
});
