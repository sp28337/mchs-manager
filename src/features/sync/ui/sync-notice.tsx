"use client";

import { CloudAlert } from "lucide-react";
import Link from "next/link";

import { поводСказать } from "./attention";
import { useSync } from "./sync-provider";

/**
 * Полоса о том, что синхронизация встала и ждёт человека.
 *
 * Стоит наверху рабочего экрана и в обычной жизни не видна вовсе: решение,
 * когда ей появляться, целиком в `attention.ts`, и сводится оно к одному —
 * синхронизация встала САМА, и без человека дальше не поедет.
 *
 * --- Почему наверху, а не строкой в подвале --------------------------------
 *
 * Строка в подвале (`sync-status.tsx`) отвечает на вопрос «моё уехало?»
 * тому, кто спросил: она спокойная, серая и ждёт, пока на неё посмотрят.
 * Для беды этого мало. Сессия, кончившаяся в фоне, выглядит как обычная
 * работа: человек правит график, правки ложатся в браузер, а на сервер
 * ничего не уезжает — и узнать об этом, долистав до подвала, он может
 * через неделю. Поэтому о таком говорится там, куда человек смотрит, и
 * говорится один раз: полоса гаснет сама, как только проход удался.
 *
 * --- Почему без красного и без восклицательных знаков ----------------------
 *
 * Данные человека целы: они в этом браузере, расчёт работает, ничего не
 * потеряно. Случилось одно — копия на сервере отстала. Красная полоса
 * поверх графика сообщала бы о катастрофе, а тут нужна просьба зайти в
 * учётную запись.
 */
export function SyncNotice() {
  const { enabled, phase, error, stalled } = useSync();

  const повод = поводСказать({ enabled, phase, error, stalled });

  if (повод === null) return null;

  return (
    // `role="status"`, а не `alert`: диктор дочитает нынешнюю фразу и
    // только потом прочтёт полосу. `alert` перебивает — он для того, что
    // случилось от нажатия человека, а это пришло само.
    <div
      role="status"
      className="mb-8 flex flex-wrap items-center gap-x-3 gap-y-1 rounded-xl border border-signal/40 bg-paper-raised px-4 py-3 text-sm text-ink"
    >
      <CloudAlert aria-hidden className="size-4.5 shrink-0 text-ink-muted" />
      <span className="min-w-0">{повод.текст}</span>
      <Link href="/account" className="font-medium underline hover:no-underline">
        {повод.действие}
      </Link>
    </div>
  );
}
