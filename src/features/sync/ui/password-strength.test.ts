/**
 * Что приложение откажется принять как пароль.
 *
 * Проверка живёт только в браузере — сервер пароля не видит
 * (`password-strength.ts`), — поэтому её поведение описано тестами
 * подробно: больше свериться не с чем.
 */

import { describe, expect, it } from "vitest";

import { оценить } from "./password-strength";

const годится = (пароль: string, email = "petrov@example.com") =>
  оценить(пароль, { email }).годится;

describe("не принимаем", () => {
  it("один знак по кругу", () => {
    expect(годится("11111111")).toBe(false);
    expect(годится("аааааааааа")).toBe(false);
  });

  it("последовательность с клавиатуры и из цифр", () => {
    expect(годится("12345678")).toBe(false);
    expect(годится("qwertyui")).toBe(false);
    expect(годится("abcdefgh")).toBe(false);
  });

  it("повторённый кусок", () => {
    expect(годится("абвабвабвабв")).toBe(false);
    expect(годится("ab12ab12")).toBe(false);
  });

  it("самые частые пароли — и с хитростями", () => {
    expect(годится("password")).toBe(false);
    expect(годится("P@ssw0rd")).toBe(false);
    expect(годится("qwerty2024")).toBe(false);
    // «ghbdtn» — это «привет», набранное в другой раскладке: для
    // подбирающего разницы нет.
    expect(годится("ghbdtnghbdtn")).toBe(false);
  });

  it("короче восьми знаков", () => {
    expect(годится("Ab3$x")).toBe(false);
  });

  it("восемь цифр — это не восемь знаков", () => {
    expect(годится("90210743")).toBe(false);
  });

  it("свой же адрес почты", () => {
    expect(годится("petrov-smena-2026")).toBe(false);
    expect(годится("example-smena-2026")).toBe(false);
  });
});

describe("принимаем", () => {
  it("длинную фразу по-русски", () => {
    const оценка = оценить("мой длинный пароль 42", { email: "petrov@example.com" });

    expect(оценка.годится).toBe(true);
    expect(оценка.уровень).toBe("отличный");
  });

  it("восемь случайных строчных букв — нижняя граница обещанного", () => {
    expect(годится("kwpfzrbd")).toBe(true);
  });

  it("знаки препинания и пробелы не мешают, а помогают", () => {
    expect(годится("сел-за-руль,7 утра")).toBe(true);
  });

  it("эмодзи — такой же знак, как любой другой", () => {
    expect(годится("смена🚒через трое")).toBe(true);
  });
});

describe("слова, которые видит человек", () => {
  it("пустое поле — ни оценки, ни упрёка", () => {
    const оценка = оценить("");

    expect(оценка.причина).toBeNull();
    expect(оценка.годится).toBe(false);
    expect(оценка.биты).toBe(0);
  });

  it("у негодного пароля причина названа", () => {
    expect(оценить("11111111").причина).toBeTruthy();
  });

  it("уровень растёт вместе с длиной", () => {
    const короткий = оценить("kwpfzrbd").уровень;
    const длинный = оценить("смена в среду, подмена в пятницу").уровень;

    expect(короткий).toBe("средний");
    expect(длинный).toBe("отличный");
  });
});
