/**
 * Слова о синхронизации — одни на все три места, где о ней говорят.
 *
 * Проверяется не оформление, а именно правило: что человек прочтёт при
 * таком-то состоянии. Вид знака и меню — браузером.
 */

import { describe, expect, it } from "vitest";

import { когда, короткоОСинхронизации } from "./presence";

const СЕЙЧАС = Date.parse("2026-10-14T12:00:00Z");

const ОБЫЧНО = { phase: "idle", dirty: false, syncedAt: null } as const;

describe("строка о состоянии", () => {
  it("вход не выполнен", () => {
    expect(короткоОСинхронизации({ ...ОБЫЧНО, phase: "signed-out" }, СЕЙЧАС)).toBe(
      "Вход не выполнен",
    );
  });

  it("нет связи — сказано спокойно и без просьб", () => {
    expect(короткоОСинхронизации({ ...ОБЫЧНО, phase: "offline" }, СЕЙЧАС)).toBe(
      "Нет связи — правки уедут позже",
    );
  });

  it("правки ещё не уехали", () => {
    expect(короткоОСинхронизации({ ...ОБЫЧНО, dirty: true }, СЕЙЧАС)).toBe(
      "Есть изменения — уедут через мгновение",
    );
  });

  it("проход был — называет время", () => {
    expect(
      короткоОСинхронизации(
        { ...ОБЫЧНО, syncedAt: "2026-10-14T11:48:00Z" },
        СЕЙЧАС,
      ),
    ).toBe("Синхронизировано 12 мин назад");
  });

  it("принятое с другого устройства важнее времени", () => {
    expect(
      короткоОСинхронизации(
        { ...ОБЫЧНО, syncedAt: "2026-10-14T11:59:50Z", принято: 2 },
        СЕЙЧАС,
      ),
    ).toBe("Синхронизировано · принято: 2");
  });

  it("вошли, но проход ещё не заканчивался", () => {
    expect(короткоОСинхронизации(ОБЫЧНО, СЕЙЧАС)).toBe("Синхронизация настроена");
  });
});

describe("когда", () => {
  it("только что", () => {
    expect(когда("2026-10-14T11:59:30Z", СЕЙЧАС)).toBe("только что");
  });

  it("давнее называет датой", () => {
    expect(когда("2026-10-01T09:00:00Z", СЕЙЧАС)).toMatch(/01\.10\.2026/);
  });
});
