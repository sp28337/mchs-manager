/**
 * Ошибки криптомодуля: три случая, и каждый человеку о разном.
 *
 * Отдельные классы, а не строки сообщений, потому что решение «что
 * показать человеку» принимает экран (шаг 11), а не вычисление. Текст
 * внутри — для разработчика и для журнала браузера; человеку экран скажет
 * своими словами.
 *
 * --- Почему «не тот пароль» и «данные повреждены» — одна ошибка ----------
 *
 * AES-GCM не различает эти случаи и не может: проверка целостности либо
 * прошла, либо нет, а почему — в шифротексте не написано. Заводить две
 * ошибки значило бы обещать различение, которого нет; поэтому одна, и в
 * её тексте сказаны оба случая.
 */

/** Общий корень: по нему ловится всё, что бросает криптомодуль. */
export class CryptoError extends Error {
  constructor(message: string) {
    super(message);
    this.name = new.target.name;
  }
}

/** Значение не похоже на то, что мы писали: не base64url, не та длина. */
export class CryptoFormatError extends CryptoError {}

/** Расшифровка не прошла: не тот ключ либо данные изменены. */
export class CryptoKeyMismatchError extends CryptoError {
  constructor(message = "не удалось расшифровать: не тот пароль или данные повреждены") {
    super(message);
  }
}

/** Ключ восстановления переписан с ошибкой. */
export class RecoveryKeyError extends CryptoError {}
