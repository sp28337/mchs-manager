/**
 * Ключ восстановления: 128 бит, которые человек переписывает на бумагу.
 *
 * ```
 * K7M2Q-9XJ4T-W1BR8-ZC6NY-H3VD5-PQ
 * ```
 *
 * Им развёрнута вторая обёртка ключа данных — та, что выручает, когда
 * пароль забыт. Показывается он один раз, при регистрации, и больше не
 * хранится нигде: ни на сервере, ни в браузере (раздел 2.4 контракта).
 *
 * --- Почему буквы и цифры, а не слова BIP-39 ------------------------------
 *
 * Английские слова русскоязычному человеку переписывать на бумагу труднее,
 * чем знаки: двенадцать незнакомых слов он перепишет с ошибкой в
 * раскладке, а потом не узнает своё же `abandon`. Crockford base32 для
 * этого и придуман: в алфавите нет `I`, `L`, `O`, `U` — то есть нет пар,
 * которые путаются от руки (`1/I/l`, `0/O`), и нет случайных слов из трёх
 * букв. При вводе `I` и `L` читаются как `1`, `O` — как `0`: так
 * переписанное с ошибкой узнавания всё равно сработает.
 *
 * --- Зачем 27-й знак ------------------------------------------------------
 *
 * 128 бит укладываются в 26 знаков, 27-й — контрольный. Он нужен, чтобы
 * ошибку в записи было видно СРАЗУ: без него человек, переписавший знак
 * неверно, узнал бы об этом через полгода, когда забыл пароль и пришёл
 * восстанавливать доступ, — и выяснил бы, что данные потеряны. С
 * контрольным знаком экран говорит «ключ записан с ошибкой» в тот момент,
 * когда ключ ещё есть на бумаге.
 *
 * Считается он как остаток взвешенной суммы по модулю 37 и ловит **любую**
 * одиночную опечатку и **любую** перестановку двух соседних знаков — то
 * есть именно те две ошибки, которые делают, когда переписывают от руки.
 *
 * Модуль 37, а не 32, именно ради этого «любую». Со степенью двойки
 * гарантии не выходит: при модуле 32 перестановка знаков `0` и `Z`
 * остаётся незамеченной (та же слепая зона, что у Луна mod 10 у пары
 * `0`/`9`), а 37 — простое и больше алфавита, поэтому ни одиночная
 * разница значений, ни разница весов не обращаются в нуль по модулю.
 *
 * Плата: остаток бывает от 0 до 36, а знаков в алфавите 32, — значит
 * примерно каждый восьмой случайный ключ записать нечем, и генератор
 * такие отбрасывает. Энтропии это стоит 0,2 бита из 128 (`log2(32/37)`),
 * то есть ничего.
 */

import type { Bytes } from "./bytes";
import { RecoveryKeyError } from "./errors";

/** Crockford base32: без `I`, `L`, `O`, `U`. */
const ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
const BASE = ALPHABET.length;

/** Модуль контрольной суммы: простое число больше алфавита. */
const CHECK_MOD = 37;

/** 128 бит в пяти битах на знак — 26 знаков, плюс контрольный. */
const DATA_CHARS = 26;
const KEY_BYTES = 16;
const GROUP = 5;

/** Как человек прочитает похожие начертания. */
const CONFUSABLES: Record<string, string> = { I: "1", L: "1", O: "0" };

/** Новый ключ восстановления в канонической записи (27 знаков, без тире). */
export function generateRecoveryKey(): string {
  // Пока не попадётся ключ, которому есть чем дописать контрольный знак
  // (см. головной блок: остаток по модулю 37 должен уложиться в алфавит).
  for (;;) {
    const данные = encode(crypto.getRandomValues(new Uint8Array(KEY_BYTES)));
    const знак = checkChar(данные);

    if (знак !== null) {
      return данные + знак;
    }
  }
}

/** Печатный вид: группами по пять, через тире. */
export function formatRecoveryKey(canonical: string): string {
  const groups: string[] = [];

  for (let i = 0; i < canonical.length; i += GROUP) {
    groups.push(canonical.slice(i, i + GROUP));
  }

  return groups.join("-");
}

/**
 * Разобрать то, что человек ввёл, в каноническую запись.
 *
 * Прощается всё, что не меняет смысла: тире, пробелы, нижний регистр,
 * путаница `I`/`L`/`1` и `O`/`0`. Не прощается опечатка — о ней и
 * сообщает контрольный знак.
 */
export function parseRecoveryKey(input: string): string {
  const cleaned = [...input.toUpperCase()]
    .filter((знак) => знак !== "-" && !/\s/.test(знак))
    .map((знак) => CONFUSABLES[знак] ?? знак)
    .join("");

  if (cleaned.length !== DATA_CHARS + 1) {
    throw new RecoveryKeyError(
      `в ключе восстановления ${DATA_CHARS + 1} знаков, а введено ${cleaned.length}`,
    );
  }

  for (const знак of cleaned) {
    if (!ALPHABET.includes(знак)) {
      throw new RecoveryKeyError(`знака «${знак}» в ключе восстановления быть не может`);
    }
  }

  const data = cleaned.slice(0, DATA_CHARS);

  if (cleaned.slice(DATA_CHARS) !== checkChar(data)) {
    throw new RecoveryKeyError("ключ восстановления записан с ошибкой");
  }

  // Последний знак несёт три бита ключа и два пустых. Ненулевые пустые
  // биты — это запись, которой наш генератор не выдавал.
  if (value(data[DATA_CHARS - 1] as string) % 4 !== 0) {
    throw new RecoveryKeyError("ключ восстановления записан с ошибкой");
  }

  return cleaned;
}

/** Байты ключа восстановления — для вывода ключа обёртки. */
export function recoveryKeyBytes(canonical: string): Bytes {
  const data = parseRecoveryKey(canonical).slice(0, DATA_CHARS);
  const bytes = new Uint8Array(KEY_BYTES);

  let накоплено = 0;
  let бит = 0;
  let индекс = 0;

  for (const знак of data) {
    накоплено = (накоплено << 5) | value(знак);
    бит += 5;

    if (бит >= 8) {
      бит -= 8;
      bytes[индекс] = (накоплено >> бит) & 0xff;
      индекс += 1;
    }
  }

  return bytes;
}

function encode(bytes: Uint8Array): string {
  let out = "";
  let накоплено = 0;
  let бит = 0;

  for (const байт of bytes) {
    накоплено = (накоплено << 8) | байт;
    бит += 8;

    while (бит >= 5) {
      бит -= 5;
      out += ALPHABET[(накоплено >> бит) & 0x1f];
    }
  }

  if (бит > 0) {
    // Последние два бита — пустые: 128 бит не делятся на пять.
    out += ALPHABET[(накоплено << (5 - бит)) & 0x1f];
  }

  return out;
}

/**
 * Контрольный знак или `null`, если остаток в алфавит не уложился.
 *
 * Вес знака — его номер слева, остаток — по модулю 37. Веса разные и ни
 * один не кратен 37, значения знаков тоже меньше 37 — поэтому любая
 * одиночная подмена и любая перестановка двух соседних знаков меняют
 * остаток, то есть видны.
 */
function checkChar(data: string): string | null {
  let сумма = 0;

  for (let i = 0; i < data.length; i += 1) {
    сумма += (i + 1) * value(data[i] as string);
  }

  const остаток = сумма % CHECK_MOD;

  return остаток < BASE ? (ALPHABET[остаток] as string) : null;
}

function value(знак: string): number {
  return ALPHABET.indexOf(знак);
}
