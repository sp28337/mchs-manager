/**
 * Длительности, общие для нескольких мест приложения.
 *
 * --- Почему отдельным файлом ----------------------------------------------
 *
 * `COUNT_MS` — свойство счётчика чисел, и жить ему естественнее в
 * `counted-number.tsx`. Но тот помечен `"use client"`, а длительность счёта
 * нужна и коду, что считает расписания (как расписание первого экрана,
 * `hero-story.ts`), и серверным компонентам: импорт из клиентского модуля
 * дал бы им не число, а ссылку на клиентский экспорт, и арифметика по ней
 * молча развалилась бы.
 *
 * Поэтому длительность лежит в обычном модуле, а оба берут её отсюда.
 */

