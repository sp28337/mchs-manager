"use client";

import { useCallback, useSyncExternalStore } from "react";

/**
 * Ширина окна как значение, а не как класс.
 *
 * --- Когда это оправдано --------------------------------------------------
 *
 * Почти никогда: обычно раскладку меняют классами `lg:`, и это надёжнее —
 * работает до загрузки скриптов и не знает про гидратацию. Здесь другой
 * случай: на широком экране и на телефоне у боковой колонки РАЗНАЯ
 * разметка, а не разные отступы. На широком это столбец раскрытых блоков,
 * на телефоне — полоска значков, открывающая по одному блоку в окне.
 *
 * Показать классами оба варианта означало бы держать в документе две копии
 * одних и тех же форм: два поля времени, два списка причин отсутствия. Это
 * не только лишние узлы, но и два независимых состояния у каждой формы.
 *
 * --- Почему здесь нет расхождения при гидратации -------------------------
 *
 * Обычно `matchMedia` в разметке приводит к тому, что сервер отрисовал
 * одно, а браузер — другое. Здесь этого не случается: экран расчёта вообще
 * не существует до чтения профиля из `localStorage`, то есть до первого
 * эффекта в браузере. На сервере на его месте «Открываем ваш профиль…».
 *
 * --- Почему `useSyncExternalStore` ---------------------------------------
 *
 * `matchMedia` — внешний источник, у которого есть и подписка, и
 * мгновенное текущее значение. Это ровно то, для чего сделан этот хук: он
 * читает значение в той же отрисовке, что и подписывается, поэтому первого
 * кадра с неверной раскладкой не бывает. На сервере возвращается `false` —
 * значение оттуда всё равно никто не увидит.
 */
export function useMediaQuery(query: string): boolean {
  const subscribe = useCallback(
    (onChange: () => void) => {
      const list = window.matchMedia(query);
      list.addEventListener("change", onChange);
      return () => list.removeEventListener("change", onChange);
    },
    [query],
  );

  return useSyncExternalStore(
    subscribe,
    () => window.matchMedia(query).matches,
    () => false,
  );
}
