"use client";

import { useCallback, type PointerEvent as ReactPointerEvent, type RefObject } from "react";

/**
 * Прокрутка вбок мышью: схватил дорожку и потянул.
 *
 * --- Зачем это нужно вообще -------------------------------------------------
 *
 * Дорожка, которая не вмещает своё содержимое, на телефоне листается сама:
 * палец по ней ведёт, и браузер прокручивает. У мыши такого жеста нет. Есть
 * колесо, но оно крутит страницу вниз, а не ряд вбок; есть полоса прокрутки,
 * но она у этих дорожек спрятана намеренно — узкая серая черта под кнопками
 * читалась бы вторым предметом там, где предмет один.
 *
 * Выходит, что на компьютере часть кнопок просто недостижима, и человек об
 * этом даже не узнаёт: обрезанной кнопки не видно. Протягивание мышью
 * закрывает эту дыру, ничего не добавляя на экран, — жест тот же, что
 * пальцем, только рука держит мышь.
 *
 * --- Почему ничего не добавляется на вид ------------------------------------
 *
 * Ни курсора-ладони, ни стрелок по краям, ни проявляющейся полосы. Всё это —
 * новые предметы в строке управления, а строка эта стоит над числами, ради
 * которых человек пришёл. Жест же обнаруживается сам: первое движение с
 * прижатой кнопкой уводит ряд, и больше объяснять нечего.
 *
 * --- Почему только мышь -----------------------------------------------------
 *
 * У пальца прокрутка своя, родная, и она лучше любой самодельной: у неё есть
 * инерция, упор у края и всё то, чего вручную не сделать. Перебивать её
 * своим расчётом — верный способ получить дорожку, которая листается хуже
 * соседних. У пера жест тоже родной. Поэтому ловится ровно `mouse`, и ровно
 * левой кнопкой: правая занята своим меню, средняя — своей прокруткой.
 *
 * --- Почему слушатели ставятся на окно, а не на саму дорожку ----------------
 *
 * Рука, тянущая ряд влево, выходит за его кромку почти всегда: ряд короткий,
 * а тянуть приходится на всю его длину. Слушатель на дорожке к этому мигу
 * перестаёт получать движения, и ряд встаёт на полпути.
 *
 * Обычный ответ на это — `setPointerCapture`, но он здесь недопустим: после
 * захвата и нажатие, и отпускание достаются дорожке, а не кнопке под
 * курсором, и щелчок приходит НА ДОРОЖКУ — то есть кнопки перестают
 * нажиматься вовсе. Окно даёт то же самое без этой платы.
 *
 * --- Почему щелчок после протягивания гасится -------------------------------
 *
 * Ряд собран из кнопок, и тянут его, держа палец как раз на кнопке. Отпустив,
 * человек получил бы нажатие — и статистика переключилась бы на чужой профиль
 * только потому, что ряд листали. Поэтому ровно один щелчок после
 * протягивания снимается на перехвате, до того как его увидит кнопка.
 */

/** Сдвиг, после которого движение считается протягиванием, а не дрожью руки. */
const SLOP = 6;

/**
 * Ссылка на дорожку приходит снаружи, а не заводится здесь.
 *
 * Хук, возвращающий ссылку в своём наборе, разметка читала бы прямо во время
 * отрисовки — а это ровно то, за что `react-hooks/refs` ругается, и по делу:
 * ссылка живёт вне отрисовки. Снаружи она стоит обычным `useRef`, попадает в
 * `ref` напрямую, и читает её только обработчик — то есть уже после.
 */
export function useDragScroll<T extends HTMLElement>(
  /** Сама дорожка — та, у которой `overflow-x`. */
  ref: RefObject<T | null>,
): (event: ReactPointerEvent<T>) => void {
  return useCallback((event: ReactPointerEvent<T>) => {
    if (event.pointerType !== "mouse" || event.button !== 0) return;

    const box = ref.current;
    if (box === null) return;
    // Вмещается целиком — ловить нечего: разбор каждого нажатия по кнопке
    // ради жеста, которого здесь быть не может, ничего не даёт.
    if (box.scrollWidth - box.clientWidth < 1) return;

    const fromX = event.clientX;
    const fromLeft = box.scrollLeft;
    const pointerId = event.pointerId;
    let dragging = false;

    const move = (it: PointerEvent) => {
      if (it.pointerId !== pointerId) return;

      const dx = it.clientX - fromX;
      if (!dragging) {
        // До порога это ещё нажатие, а не жест: мышь дрожит на всяком
        // щелчке, и ряд, съезжающий на точку от простого нажатия, выглядел
        // бы неисправным.
        if (Math.abs(dx) < SLOP) return;
        dragging = true;
        // Выделение — единственное, что мышь делает с зажатой кнопкой сама,
        // и посреди жеста оно заливает синим подписи кнопок. Снимается на
        // время протягивания и возвращается сразу после.
        box.style.userSelect = "none";
      }

      it.preventDefault();
      box.scrollLeft = fromLeft - dx;
    };

    const up = () => {
      window.removeEventListener("pointermove", move);
      window.removeEventListener("pointerup", up);
      window.removeEventListener("pointercancel", up);
      if (!dragging) return;

      box.style.removeProperty("user-select");

      const swallow = (click: Event) => {
        click.stopPropagation();
        click.preventDefault();
      };
      box.addEventListener("click", swallow, { capture: true, once: true });
      // Щелчка может не быть вовсе — например, курсор ушёл с дорожки и
      // отпустили уже вне неё. Оставленный слушатель съел бы тогда
      // следующее настоящее нажатие, когда бы оно ни случилось, поэтому он
      // снимается на ближайшем кадре: щелчок за своим отпусканием приходит
      // тем же кадром, а человеческое нажатие — заведомо позже.
      requestAnimationFrame(() => {
        box.removeEventListener("click", swallow, { capture: true });
      });
    };

    window.addEventListener("pointermove", move, { passive: false });
    window.addEventListener("pointerup", up);
    window.addEventListener("pointercancel", up);
  }, [ref]);
}
