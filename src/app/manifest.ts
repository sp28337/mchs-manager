import type { MetadataRoute } from "next";

/**
 * Манифест приложения.
 *
 * --- Зачем он здесь, если приложения нет ---------------------------------
 *
 * Приложения в магазине действительно нет и не будет: расчёт живёт в
 * браузере, ставить нечего. Но человек, который пользуется расчётом каждую
 * смену, кладёт его на домашний экран — и вот тут выясняется, что без
 * манифеста Android берёт первое, что найдёт, и рисует ярлык с буквой
 * «Г» на белом кружке.
 *
 * Манифест этого не допускает: он называет иконки поимённо и говорит, что
 * с ними делать.
 *
 * --- Почему две иконки одного размера ------------------------------------
 *
 * `any` — иконка как есть, со своей подложкой и своими углами. Так её
 * показывают в списке приложений и в переключателе задач.
 *
 * `maskable` — та же иконка, но со знаком, ужатым в центральные три пятых.
 * Android вырезает из неё форму на свой вкус: круг, каплю, скруглённый
 * квадрат — какой выберет производитель оболочки. Отдай ему обычную —
 * срежет углы вместе с клетками; отдай только маскируемую — в списке
 * приложений она будет с широкими полями. Поэтому обе.
 *
 * --- Почему `standalone`, а не `browser` ---------------------------------
 *
 * С домашнего экрана расчёт открывается без адресной строки — как
 * приложение. Это не косметика: страница объявлена `viewport-fit=cover`, и
 * без строки браузера ей достаётся весь экран, ради чего безопасные зоны и
 * размечались.
 */
/**
 * Манифест — файл, а не обработчик.
 *
 * У проекта `output: "export"`: сборка кладёт в `out/` готовые файлы, и
 * процесса, который отвечал бы на запрос, в проде нет вовсе. Next.js по
 * умолчанию считает манифест маршрутом и на статическом экспорте
 * останавливает сборку прямо с этим требованием — объявить, что он
 * постоянный. Объявляем: содержимое манифеста от запроса не зависит
 * ничем.
 */
export const dynamic = "force-static";

export default function manifest(): MetadataRoute.Manifest {
  return {
    name: "График 1 3 — норма и переработка",
    short_name: "График 1 3",
    description:
      "График «сутки через трое» на год: смены, отпуска, больничные, работа " +
      "помимо графика. Норма по производственному календарю. Расчёт идёт в браузере.",
    start_url: "/",
    display: "standalone",
    lang: "ru",
    dir: "ltr",
    orientation: "portrait-primary",
    // ЦВЕТОВ ЗДЕСЬ НЕТ, и это не забывчивость.
    //
    // Манифест умеет объявить и цвет заставки, и цвет верхней полосы
    // браузера, и однажды он их объявлял — а верх на айфоне после этого
    // застыл намертво. Причина оказалась простой и неприятной: пока
    // страница не называет цвет полосы, сафари красит его ПО СТРАНИЦЕ и
    // перекрашивает вместе с ней. Стоит назвать — берёт названное, а
    // перечитывает названное один раз, при загрузке. Смена темы после
    // этого верх уже не трогает: он показывает тему на момент открытия, и
    // чинится только полной перезагрузкой.
    //
    // Манифест же описывает ПРИЛОЖЕНИЕ, а не текущий его вид, и цвет в нём
    // может быть только один на обе темы. Поэтому — никакого.
    icons: [
      { src: "/icons/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
      { src: "/icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
      {
        src: "/icons/icon-maskable-512.png",
        sizes: "512x512",
        type: "image/png",
        purpose: "maskable",
      },
    ],
  };
}
