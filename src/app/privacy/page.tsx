import type { Metadata } from "next";

import { loadLegalDocument } from "@/features/legal/documents";
import { LegalPage } from "@/features/legal/legal-page";

/**
 * Политика в отношении обработки персональных данных.
 *
 * Отдельным адресом, а не разделом соглашения, по двум причинам. Первая
 * формальная: оператор обязан опубликовать политику или иным образом
 * обеспечить к ней неограниченный доступ (ч. 2 ст. 18.1 152-ФЗ), и у
 * такого документа должна быть постоянная ссылка. Вторая по делу: на неё
 * ссылаются согласие, форма регистрации и письма, а ссылаться на середину
 * чужого документа — значит однажды уехать не туда.
 */
const документ = loadLegalDocument("policy");

export const metadata: Metadata = {
  title: "Политика обработки персональных данных",
  description:
    "Какие данные обрабатывает «График 1 3», зачем, на каком основании и " +
    "сколько они живут. Содержимое графиков хранится зашифрованным: ключа " +
    "от него у оператора нет.",
  alternates: { canonical: "/privacy" },
};

export default function PrivacyPage() {
  return <LegalPage document={документ} />;
}
