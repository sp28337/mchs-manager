import type { Metadata, Viewport } from "next";
import {
  Great_Vibes,
  IBM_Plex_Mono,
  IBM_Plex_Sans,
  PT_Sans_Narrow,
} from "next/font/google";

import { Lamp } from "@/components/shared/lamp";
import { VeilAnchor } from "@/components/shared/veil-anchor";

import { Providers } from "./providers";
import "./globals.css";

/* Кириллица подключена явно у всех трёх гарнитур: интерфейс русскоязычный
   целиком, и латинского подмножества ему недостаточно. */
const display = PT_Sans_Narrow({
  subsets: ["cyrillic", "latin"],
  weight: ["400", "700"],
  variable: "--font-pt-sans-narrow",
  display: "swap",
});

const sans = IBM_Plex_Sans({
  subsets: ["cyrillic", "latin"],
  weight: ["400", "500", "600"],
  variable: "--font-plex-sans",
  display: "swap",
});

const mono = IBM_Plex_Mono({
  subsets: ["cyrillic", "latin"],
  weight: ["400", "500"],
  variable: "--font-plex-mono",
  display: "swap",
});

/* Четвёртая гарнитура — рукописная, и ровно на одну строку.
   -----------------------------------------------------------------------
   «Бесплатно и без регистрации» — не заголовок и не подпись к полю: это
   слово от автора, сказанное человеку до всякого расчёта. Набранное тем
   же деловым шрифтом, что и остальное, оно читается как ещё один пункт
   регламента — и теряется рядом с крупным заголовком.

   Great Vibes — каллиграфический курсив с настоящей кириллицей: тонкий
   волосяной штрих, сильный нажим и росчерки. Рукописных гарнитур в вебе
   много, а рукописных С КИРИЛЛИЦЕЙ, где «д», «з» и «я» нарисованы, а не
   подставлены из латиницы, — единицы, и каллиграфических среди них
   считаные: у соседних по духу Parisienne, Pinyon Script и Tangerine
   кириллицы нет вовсе.

   Начертание одно, четырёхсотое: у гарнитуры другого и нет, да и у
   надписи на странице одно место и один вес. Тонкость штриха здесь от
   рисунка пера, а не от насыщенности, — жирного пера не бывает. */
const hand = Great_Vibes({
  subsets: ["cyrillic", "latin"],
  weight: ["400"],
  variable: "--font-great-vibes",
  display: "swap",
});

export const metadata: Metadata = {
  // Шаблон, а не готовая строка: каждая страница подставляет своё, и
  // название приложения не приходится повторять руками.
  //
  // Название стоит вторым, а не первым: в выдаче первыми читаются слова
  // запроса, а «График 1 3» ни в один запрос не входит — по нему приходят
  // только те, кто уже знает, куда идёт.
  title: {
    default: "График 1 3 — норма и переработка при графике сутки через трое",
    template: "%s — График 1 3",
  },
  description:
    "График 1 3 на год: смены, отпуска, больничные, работа помимо графика. " +
    "Норма по производственному календарю. Расчёт идёт в браузере.",
  applicationName: "График 1 3",
  // Подпись под ярлыком на домашнем экране айфона. Без неё туда идёт
  // `title`, а он длиной в строку поиска: под иконкой от него остаётся
  // «График 1 3 — норма и…».
  appleWebApp: { title: "График 1 3" },
  // Ссылки в разметке страниц относительные; без базы Open Graph получил
  // бы неполный адрес и не открылся бы при пересылке.
  metadataBase: new URL(process.env.NEXT_PUBLIC_SITE_URL ?? "http://localhost:3000"),
};

/* Окно страницы — весь экран телефона, вместе с полосой под часами и
   полосой над чёрточкой.
   -------------------------------------------------------------------------
   По умолчанию браузер отдаёт странице прямоугольник МЕЖДУ ними, а сами
   полосы рисует сам. Содержимое при прокрутке уезжает под них и там видно —
   а вот всё, что закреплено по кромке окна, до полос не достаёт: за
   пределами окна их просто нет. Оттуда и бралась прореха над лампой, из-за
   которой уезжающий вверх текст переставал растворяться и снова становился
   чётким.

   С `cover` полосы принадлежат странице: растворение доходит до верха
   экрана тем же слоем, что и под шапкой, и никакой особой точки на кромке
   больше нет. Взамен всё, что стояло по кромке, отступает от неё на высоту
   полосы — это `--safe-top` и `--safe-bottom` в `globals.css`. */
export const viewport: Viewport = {
  viewportFit: "cover",
};

export default function RootLayout({
  children,
}: Readonly<{ children: React.ReactNode }>) {
  return (
    <html
      lang="ru"
      className={`${display.variable} ${sans.variable} ${mono.variable} ${hand.variable}`}
      suppressHydrationWarning
    >
      <body className="min-h-dvh bg-paper text-ink">
        {/* Продолжение дымки над кромкой окна — липким слоем, в потоке
            страницы. Стоит ПЕРВЫМ и только здесь: липкий слой держится за
            своё место в потоке, и из любого другого места до верха
            страницы он бы не дотянулся. Зачем он вообще нужен и почему
            закреплённого слоя для этого мало — в самом компоненте. */}
        <VeilAnchor />

        {/* Обёртка нужна ради полос во всю ширину окна — сейчас это
            первый экран, который шире колонки `main`.

            Обрезать такое приходится настоящим элементом: `overflow-x` на
            `body` всплывает на область просмотра, сам `body` остаётся
            необрезанным, и страница начинает ездить вбок на ширину полосы
            прокрутки. Ширина этой обёртки — 100% страницы, полосу
            прокрутки она не включает, поэтому лишнее срезается по краю
            содержимого.

            Именно `clip`, а не `hidden`: `hidden` создал бы контейнер
            прокрутки со всеми последствиями для `position: sticky`.
            Шапку это не задевает — она `fixed`, а такие элементы
            обрезаются только своим блоком-контейнером.

            Сама шапка рисуется страницами, а не здесь: у лендинга и
            калькулятора в ней разное главное действие, и общая шапка на
            оба означала бы либо пустое место, либо кнопку не к месту. */}
        <div className="overflow-x-clip">
          <Providers>{children}</Providers>
        </div>

        {/* Дымка под закреплёнными полосами: у шапки и полосы с числами
            больше нет заливки, и то, что проезжает под ними, растворяется
            здесь — уходит в цвет бумаги и теряет чёткость. Слой один на
            всё приложение, высоту он берёт по тому, что на странице
            закреплено (`globals.css`). */}
        <div aria-hidden className="veil" />

        {/* И её продолжение выше кромки окна — там, где браузер показывает
            страницу под полупрозрачной верхней строкой. Отдельным слоем,
            а не той же дымкой: размывающему слою за кромку окна вылезать
            нельзя, движок сафари рисует его там как попало
            (`globals.css`). */}
        <div aria-hidden className="veil-over" />

        {/* Затемнение под открытым окном. Своим слоем, а не родным
            `::backdrop`: тот рисуется в верхнем слое браузера, выше любого
            `z-index`, и утягивал за собой лампу — вместе со страницей
            гасла и она. Слой один на все окна: они вкладываются друг в
            друга, и два затемнения сложились бы в одно вдвое темнее. */}
        <div aria-hidden className="scrim" />

        {/* Лампа принадлежит ОКНУ, а не странице: она светит и на главной,
            и в расчёте, и в условиях использования — комната одна.

            Стоит последней намеренно. Она интерактивна, то есть попадает в
            обход по клавише, и с любого другого места оказалась бы
            остановкой ПЕРЕД содержимым: человек, идущий с клавиатуры к
            расчёту, натыкался бы сперва на светильник. Место у неё
            закреплённое и от порядка в разметке не зависит. */}
        <Lamp />
      </body>
    </html>
  );
}
