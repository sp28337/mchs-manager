"use client";

import { ThemeProvider } from "next-themes";

/**
 * Провайдеры приложения.
 *
 * Остался один. Здесь был `QueryClientProvider` с настройками кеша и
 * комментарием о том, что общий на сервере экземпляр отдал бы расчёт
 * одного человека другому, — запросов больше нет, делить между
 * пользователями нечего. `TooltipProvider` ушёл следом за последней
 * подсказкой: пояснения к числам стоят рядом с ними текстом, а не
 * прячутся под наведение, которого нет на телефоне.
 */
/**
 * Почему тёмная по умолчанию, а не «как в системе».
 *
 * Приложение придумано под лампу: страница — лист на столе, над ним висит
 * светильник, и всё остальное — блики на кромках блоков, тень под ними,
 * тёплый налёт на бумаге — следствие того, что он светит. На графите это
 * работает целиком, на белой бумаге вполовину: поднять яркость свету там
 * некуда, остаётся одна подкраска, а её глаз ловит куда хуже.
 *
 * «Как в системе» приводило к тому, что БОЛЬШИНСТВО открывало приложение в
 * том виде, где от замысла остаётся половина, — и не по своему выбору, а
 * по настройке телефона, поставленной для чего-то другого. Своё положение
 * «как в системе» при этом никуда не делось: оно третье в переключателе и
 * выбирается одним нажатием.
 */
export function Providers({ children }: { children: React.ReactNode }) {
  return (
    <ThemeProvider attribute="class" defaultTheme="dark" enableSystem disableTransitionOnChange>
      {children}
    </ThemeProvider>
  );
}
