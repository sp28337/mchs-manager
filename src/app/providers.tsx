"use client";

import { ThemeProvider } from "next-themes";

import { SyncProvider } from "@/features/sync/ui/sync-provider";

/**
 * Провайдеры приложения.
 *
 * Их два: тема и синхронизация. `QueryClientProvider` здесь был и ушёл
 * вместе с прежним сервером, а новый его не вернул: обращения к серверу
 * синхронизации делает свой слой (`features/sync/`), и кеш запросов ему
 * не нужен — источник истины у приложения один, и он в браузере.
 *
 * `SyncProvider` стоит вокруг всех страниц, а не только вокруг страницы
 * учётной записи, по двум причинам: строка состояния живёт в подвале
 * рабочего экрана, а вопрос о расхождении настроек должен всплывать там,
 * где человек в этот миг находится. Выключенная синхронизация
 * (`NEXT_PUBLIC_SYNC_ENABLED`) не рисует ничего и не открывает ни одного
 * соединения — провайдер в этом случае просто отдаёт детей дальше.
 *
 * --- Почему умолчание — тёмная, а не системная ----------------------------
 *
 * Приложение нарисовано тёмным: бумага цвета остывшего графита, лампа над
 * страницей, блик по верхней кромке у каждой поднятой поверхности. Светлая
 * тема — честный перевод этого языка, но именно перевод; впервые открывший
 * сайт должен увидеть подлинник.
 *
 * Системная настройка при этом никуда не делась: `enableSystem` оставлен, и
 * «Как в системе» стоит третьим положением переключателя в подвале
 * (`ui/theme-toggle.tsx`). Меняется одно — что показывать тому, кто ещё
 * ничего не выбрал.
 *
 * Мигания от этого не будет: `next-themes` кладёт класс своим сценарием в
 * шапке документа, до первой отрисовки, и с тёмным умолчанием кладёт его
 * сразу — а не после опроса системы.
 */
export function Providers({ children }: { children: React.ReactNode }) {
  return (
    <ThemeProvider attribute="class" defaultTheme="dark" enableSystem disableTransitionOnChange>
      <SyncProvider>{children}</SyncProvider>
    </ThemeProvider>
  );
}
