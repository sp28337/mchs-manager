"""Вырезает светильник из фотографии в четыре слоя для `.lamp__tube`.

Исходник — снимок голой люминесцентной лампы на стене. Нужно из него
получить светильник без стены, в размер нашего света, и так, чтобы цвет
лампы на сайте продолжал работать.

--- Почему слоёв четыре, а не один --------------------------------------

Наша лампа несравнимо стройнее снятой: у нас длина к толщине под сто к
одному, на снимке — двадцать пять к одному. Растянуть снимок целиком —
значит размазать патроны в плоские кляксы; нарезать его на «концы и
середину» и растянуть одну середину — значит получить шов.

Шов не умозрительный, он был и мерился: на стыке двух полупрозрачных
кусков налёт складывается сам с собой и даёт светлую полосу в четыре
точки (замер: 328 против 249 уровней), а если класть куски встык без
нахлёста — тёмную нить в точку, потому что крайний столбец растянутой
картинки браузер домешивает с пустотой за её кромкой.

Отсюда разложение, в котором стыков нет вовсе:

  СВЕТ (`glow`) — налёт вокруг лампы и общий силуэт. Одной картинкой во
  всю длину, тянется. Стыков нет, потому что кусок один; растяжка ему не
  вредит, потому что вдоль он гладкий.

  ТРУБКА (`tube`) — стекло с рейкой, взятое из однородной середины.
  Тянется во всю длину. Непрозрачное.

  ПАТРОНЫ (`cap-left`, `cap-right`) — по концам, в своей пропорции,
  поверх трубки. Непрозрачные, а непрозрачное поверх непрозрачного
  никаких стыков не даёт: верхнее просто закрывает нижнее.

--- Почему цвет отделён от железа ---------------------------------------

Железо обесцвечено: свой цвет светильнику даёт лампа сайта, а не съёмка.
У света цвет белый, а сила уведена в прозрачность — тогда на графите это
свет, на белой бумаге ничто, а цвет лампы виден сквозь него заливкой
снизу. Слой `glow` служит заодно и маской для этой заливки: он и есть
силуэт всего предмета вместе с его налётом.

Запускать из папки со снимком: python3 tools/cut-lamp.py
"""

from PIL import Image, ImageFilter
import numpy as np

src = Image.open("photo-src.png").convert("RGB")
a = np.asarray(src).astype(np.float64)
L = a @ [0.2126, 0.7152, 0.0722]
h, w = L.shape

# --- Границы светильника на снимке ------------------------------------------
BAND_TOP, BAND_BOT = 97, 136  # трубка с рейкой, во всю длину
CAP_TOP, CAP_BOT = 93, 140  # патроны: выше и ниже трубки
GLASS_TOP, GLASS_BOT = 99, 133  # светящееся стекло — по нему сажаем на место
X_LEFT, X_RIGHT = 58, 1201
CAP_L_END, CAP_R_START = 106, 1158
UNIFORM = (300, 900)  # участок, где трубка вдоль однородна

CROP = (30, 0, 1229, GLASS_BOT)  # общая рамка всех слоёв
CAP_W = 130  # ширина куска с патроном, в точках вырезки

# --- Стена: линейная модель по столбцам (сверху вниз она светлеет) ----------
top = L[0:10].mean(axis=0)
bot = L[218:228].mean(axis=0)
ys = np.arange(h)[:, None] / (h - 1)
wall = top[None, :] * (1 - ys) + bot[None, :] * ys

# --- Свет: превышение над стеной -------------------------------------------
glow = np.clip((L - wall) / np.clip(200.0 - wall, 1, None), 0, 1) * 0.78
# Штукатурку в свете не оставляем: фактура стены — примета СТЕНЫ, а стены на
# странице нет. Свет от неё отделяем размытием.
glow = (
    np.asarray(
        Image.fromarray((glow * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(7))
    ).astype(np.float64)
    / 255.0
)

# --- Края вырезки: свести в ноль -------------------------------------------
# У кромки кадра налёт обрывается на своей силе — у нижнего края это целых
# двенадцать сотых. На стене такого обрыва нет, там просто кончился кадр; на
# странице он читался бы прямой линией поперёк свечения. Растушёвка считается
# от кромок ВЫРЕЗКИ, а не кадра, и по бокам начинается раньше патронов —
# чтобы задеть только свет и не тронуть сам светильник.
#
# Снизу растушёвки нет и быть не должно: там вырезка кончается ровно по низу
# стекла, то есть по кромке окна. Ниже неё светильника не видно ни в одном
# браузере, а свет продолжает уже сама трубка на странице.
ramp_x = np.ones(w)
ramp_x[: CROP[0]] = 0
ramp_x[CROP[0] : X_LEFT - 4] = np.linspace(0, 1, X_LEFT - 4 - CROP[0]) ** 0.7
ramp_x[X_RIGHT + 4 : CROP[2]] = np.linspace(1, 0, CROP[2] - X_RIGHT - 4) ** 0.7
ramp_x[CROP[2] :] = 0
ramp_y = np.ones(h)
ramp_y[:14] = np.linspace(0, 1, 14)
ramp_y[CROP[3] :] = 0
glow *= np.minimum(ramp_x[None, :], ramp_y[:, None])


def feather(mask, radius=1.6):
    """Смягчает край силуэта: голая ступенька на таком уменьшении рвётся."""
    return (
        np.asarray(
            Image.fromarray((mask * 255).astype(np.uint8)).filter(
                ImageFilter.GaussianBlur(radius)
            )
        ).astype(np.float64)
        / 255.0
    )


# --- Силуэты ----------------------------------------------------------------
tube_band = np.zeros((h, w))
tube_band[BAND_TOP:BAND_BOT, :] = 1.0  # во всю длину: этот слой тянется
tube_band = feather(tube_band)

whole = np.zeros((h, w))
whole[BAND_TOP:BAND_BOT, X_LEFT:X_RIGHT] = 1.0
whole[CAP_TOP:CAP_BOT, X_LEFT:CAP_L_END] = 1.0
whole[CAP_TOP:CAP_BOT, CAP_R_START:X_RIGHT] = 1.0
whole = feather(whole)

caps = np.zeros((h, w))
caps[CAP_TOP:CAP_BOT, X_LEFT:CAP_L_END] = 1.0
caps[CAP_TOP:CAP_BOT, CAP_R_START:X_RIGHT] = 1.0
caps = feather(caps)

grey = np.clip(L * 1.06, 0, 255)


def layer(rgb_grey, alpha):
    rgb = np.stack([rgb_grey] * 3, axis=-1) if rgb_grey is not None else np.full((h, w, 3), 255.0)
    out = np.concatenate([rgb, alpha[..., None] * 255], axis=-1)
    return Image.fromarray(np.clip(out, 0, 255).astype(np.uint8), "RGBA")


# СВЕТ: белый, силуэт всего предмета в придачу — он же маска для заливки.
glow_img = layer(None, np.maximum(glow, whole)).crop(CROP)
# ТРУБКА: только однородная середина, дальше её растянут.
tube_img = layer(grey, tube_band).crop((UNIFORM[0], CROP[1], UNIFORM[1], CROP[3]))
# ПАТРОНЫ: каждый со своим куском, в своей пропорции.
cap_l = layer(grey, caps).crop((CROP[0], CROP[1], CROP[0] + CAP_W, CROP[3]))
cap_r = layer(grey, caps).crop((CROP[2] - CAP_W, CROP[1], CROP[2], CROP[3]))

cw, ch = glow_img.size
print("вырезка:", cw, ch)
print("стекло в вырезке: верх", GLASS_TOP - CROP[1], "низ", GLASS_BOT - CROP[1])
print("ширина куска с патроном:", CAP_W)

# На экране вырезка идёт впятеро мельче своих точек, поэтому полный размер
# был бы весом впустую. Свет вдобавок гладкий — ему хватает и трети ширины.
K = 0.8
th = round(ch * K)
pieces = {
    "glow": glow_img.resize((400, th), Image.LANCZOS),
    "tube": tube_img.resize((320, th), Image.LANCZOS),
    "cap-left": cap_l.resize((round(CAP_W * K), th), Image.LANCZOS),
    "cap-right": cap_r.resize((round(CAP_W * K), th), Image.LANCZOS),
}
for name, piece in pieces.items():
    piece.save(f"lamp-{name}.webp", quality=86, method=6)
    piece.save(f"lamp-{name}.png")
    print(name, piece.size)
