"""Собирает полный комплект иконок приложения из одного описания знака.

Знак один и тот же везде — четыре клетки, из которых закрашена одна, то
есть буквально график «сутки через трое». Меняется только оправа, и
меняется она не для красоты, а под требования конкретного места:

  ФАВИКОН (16—48 точек). Здесь знак живёт рядом с полутора десятками
  чужих вкладок и должен узнаваться в размер буквы. Пустые сутки поэтому
  ЗАЛИТЫ, а не обведены: обводка в полторы двадцать четвёртых доли на
  шестнадцати точках — это меньше точки, она пропадает совсем, и от знака
  остаётся один красный квадрат.

  ПЛИТКА ДЛЯ ДОМАШНЕГО ЭКРАНА (apple-touch-icon, 180). Углы скругляет
  сама система, поэтому подложка идёт до самого края: своё скругление
  внутри системного дало бы двойную рамку.

  МАСКИРУЕМАЯ (Android, 512). Система вырезает из иконки круг, каплю или
  скруглённый квадрат — какой захочет производитель. Безопасная зона у
  такой иконки — центральные четыре пятых, и знак ужат до трёх пятых:
  всё, что снаружи, может быть срезано.

Подложка темнее бумаги тёмной темы намеренно: пустые клетки взяты
приподнятой бумагой (`--fps-paper-raised`), и на самой бумаге они бы с
ней слились. Разводить их цветом было нельзя — цвет клеток задан, — а
подложку можно: у иконки её собственной темы нет.

Запуск: python3 tools/make-icons.py (из корня проекта)
"""

from PIL import Image, ImageDraw
import os

PLATE = (18, 19, 22)  # подложка: темнее бумаги, чтобы клетки на ней читались
SIGNAL = (219, 14, 23)  # --fps-signal тёмной темы: дежурные сутки
IDLE = (42, 44, 47)  # --fps-paper-raised тёмной темы: пустые сутки

SS = 8  # во столько раз рисуем крупнее и потом уменьшаем — это и есть сглаживание


def mark(size, inset, radius_ratio, plate_radius):
    """Знак на подложке. `inset` — доля холста, отданная полям."""
    n = size * SS
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, n - 1, n - 1], radius=plate_radius * n, fill=PLATE)

    # Поле знака внутри подложки.
    pad = inset * n
    side = n - 2 * pad
    # Сетка два на два с промежутком в восьмую долю стороны.
    gap = side * 0.11
    cell = (side - gap) / 2
    r = cell * radius_ratio
    for row in range(2):
        for col in range(2):
            x = pad + col * (cell + gap)
            y = pad + row * (cell + gap)
            fill = SIGNAL if (row, col) == (0, 0) else IDLE
            d.rounded_rectangle([x, y, x + cell, y + cell], radius=r, fill=fill)
    return img.resize((size, size), Image.LANCZOS)


def save(img, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path)
    print(path, img.size)


# --- Вкладка браузера, вектором ---------------------------------------------
# Тот же знак и та же геометрия, что у растровых, — считается одной и той же
# формулой, чтобы комплект не разъехался при правке.
def svg(inset, radius_ratio, plate_radius, n=24):
    pad = inset * n
    side = n - 2 * pad
    gap = side * 0.11
    cell = (side - gap) / 2
    r = cell * radius_ratio
    rects = []
    for row in range(2):
        for col in range(2):
            x = pad + col * (cell + gap)
            y = pad + row * (cell + gap)
            fill = "#db0e17" if (row, col) == (0, 0) else "#2a2c2f"
            rects.append(
                f'  <rect x="{x:.2f}" y="{y:.2f}" width="{cell:.2f}" '
                f'height="{cell:.2f}" rx="{r:.2f}" fill="{fill}"/>'
            )
    body = "\n".join(rects)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {n} {n}">\n'
        f'  <rect width="{n}" height="{n}" rx="{plate_radius * n:.2f}" fill="#121316"/>\n'
        f"{body}\n"
        f"</svg>\n"
    )


with open("src/app/icon.svg", "w") as f:
    f.write(svg(0.13, 0.20, 0.16))
print("src/app/icon.svg")

# --- Вкладка браузера -------------------------------------------------------
# Три размера в одном .ico: 16 для вкладки, 32 для панели закладок, 48 для
# ярлыка на рабочем столе Windows. Скругление у подложки слабое: на
# шестнадцати точках сильное съедает углы клеток.
ico = mark(256, 0.10, 0.20, 0.16)
ico.save("src/app/favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)])
print("src/app/favicon.ico 16/32/48")

# --- Домашний экран айфона --------------------------------------------------
# Подложка во всю плитку, скругления нет: его накладывает система.
save(mark(180, 0.17, 0.20, 0.0), "src/app/apple-icon.png")

# --- Android и установка как приложение -------------------------------------
save(mark(192, 0.13, 0.20, 0.16), "public/icons/icon-192.png")
save(mark(512, 0.13, 0.20, 0.16), "public/icons/icon-512.png")
# Маскируемая: знак ужат в центральные три пятых, подложка во всю площадь.
save(mark(512, 0.21, 0.20, 0.0), "public/icons/icon-maskable-512.png")
