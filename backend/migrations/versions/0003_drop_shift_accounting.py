"""Удаление схемы `shift_accounting` — персональные данные с сервера уходят.

Revision ID: 0003
Revises: 0002

--- Почему 0003, а не «убрать 0002 из истории» --------------------------

Соблазн был: миграция 0002 создаёт таблицу, которую 0003 тут же
удаляет, и выглядит это глупо. Но у того, кто уже накатил 0002, в
`alembic_version` стоит именно `0002`, и переиспользовать этот номер для
удаления нельзя — alembic решит, что миграция уже применена, ничего не
сделает и отрапортует `head`. Персональные данные при этом остались бы в
базе, а человек был бы уверен, что их нет.

Проверено воспроизведением: с номером `0002` команда `alembic upgrade
head` на такой базе завершилась успехом, `alembic current` показал
`0002 (head)`, а `select count(*) from shift_accounting.profile` вернул
73 строки.
"""

from __future__ import annotations

from alembic import op

revision = "0003"
down_revision = "0002"
branch_labels = None
depends_on = None


def upgrade() -> None:
    """Схема удаляется вместе с данными, и это намеренно.

    В `shift_accounting.profile` лежали пол и признак инвалидности I-II
    группы, а в `shift_accounting.absence` — даты больничных. Сведения о
    состоянии здоровья — специальная категория персональных данных
    (ст. 10 ФЗ-152), и хранение их на сервере тянуло за собой уведомление
    Роскомнадзора (ст. 22), согласие в письменной форме (ст. 10 ч. 2),
    локализацию базы в РФ (ч. 5 ст. 18) и меры защиты по ПП РФ № 1119.

    Расчёт и хранение переехали в браузер, поэтому серверу эти таблицы не
    нужны. Оставить их «на всякий случай» было бы худшим из решений:
    неиспользуемая база со сведениями о здоровье — это обязанности без
    пользы и утечка без причины.

    `CASCADE` убирает и таблицы, и перечислимые типы, и ограничение
    исключения по диапазонам дат — всё, что схема за собой тянет.
    """
    op.execute("DROP SCHEMA IF EXISTS shift_accounting CASCADE")


def downgrade() -> None:
    """Отката нет, и подделывать его нельзя.

    Пустая схема без данных — это не прежнее состояние, а видимость
    отката: приложение, откатившееся сюда, увидело бы структуру без
    профилей и решило, что их и не было. Данные удалены сознательно и
    восстановлению не подлежат; кому нужна прежняя схема — берёт её из
    миграции 0001 в истории репозитория.
    """
    raise NotImplementedError(
        "Откат невозможен: схема удалена вместе с персональными данными "
        "намеренно (ФЗ-152 ст. 10). Прежняя структура — в миграции 0001."
    )
