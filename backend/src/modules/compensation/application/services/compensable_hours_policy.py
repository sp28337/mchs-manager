"""Приказ МЧС России от 24.09.2018 № 410, пп. 11, 13, 14 — какие часы
вообще подлежат компенсации.

Появился, когда приказ добавили в проект (`docs/MCHS_RF_N_410.pdf`).
До того Алгоритм К компенсировал все четыре категории часов подряд, и это
прямо противоречило двум его пунктам.

--- п. 14: главное ограничение ----------------------------------------

    «За выполнение сотрудниками федеральной противопожарной службы
    служебных обязанностей в ночное время, в выходные и нерабочие
    праздничные дни **при суммированном учете служебного времени
    (должности с посменным несением дежурства) в пределах нормальной
    продолжительности** служебного времени компенсация в виде
    дополнительного времени отдыха, дополнительных дней отдыха **не
    предоставляется**.»

Для сменного и суточного режима это означает: ночные, праздничные и
выходные часы, уложившиеся в норму периода, не компенсируются вовсе.
Ночь и праздник у караула — не привлечение сверх нормы, а сам характер
службы, и норма уже посчитана с их учётом (ФЗ-141 ст. 55, суммированный
учёт).

Компенсируется у них только переработка — превышение нормы периода, о
котором говорит п. 10 приказа.

Это отменяет прежнее поведение полностью: раньше караул получал бы
компенсацию за каждую ночную смену, то есть за то, ради чего он и
существует.

--- п. 13: ненормированный служебный день ------------------------------

    «За выполнение указанными сотрудниками служебных обязанностей сверх
    установленной для них нормальной продолжительности служебного
    времени компенсация не предоставляется.»

Вместо неё — дополнительный отпуск (раздел V приказа), то есть предмет
`leave_management`, а не этого модуля. Поэтому у режима
`unstandardized` компенсируемых часов нет ни одного, и дело о
компенсации по такому сотруднику заводить не из чего.

--- п. 11: пятидневка --------------------------------------------------

    «Сотруднику, привлеченному к выполнению служебных обязанностей сверх
    установленной нормальной продолжительности служебного времени, в
    ночное время, предоставляется дополнительное время отдыха, равное
    продолжительности... Сотруднику, привлеченному к службе в выходной
    или нерабочий праздничный день, предоставляется дополнительный день
    отдыха.»

Для пятидневного режима ограничения п. 14 нет: у него ночная смена и
работа в выходной — именно привлечение, а не обычный порядок службы.
Компенсируются все четыре категории.

--- Чего эта политика НЕ делает ---------------------------------------

Не решает, деньгами или отдыхом: это п. 18 и волеизъявление сотрудника
(Алгоритм К шаги 4-6), и живёт оно в `RuleVersion`. Здесь только
отбор — ЧТО подлежит компенсации, а не В КАКОЙ ФОРМЕ.
"""

from __future__ import annotations

from decimal import Decimal

from src.modules.compensation.domain.value_objects import CompensableHours

# Режимы из `personnel.regime_type`. Строками, а не импортом чужого enum
# (Architecture разд. 4.2): значение приходит из контракта `personnel`
# такой же строкой.
FIVE_DAY_WEEK = "five_day_week"
SHIFT_SCHEDULE = "shift_schedule"
TWENTY_FOUR_HOUR_DUTY = "twenty_four_hour_duty"
UNSTANDARDIZED = "unstandardized"

# Режимы, ведущиеся суммированным учётом служебного времени — те самые
# «должности с посменным несением дежурства» п. 14.
SUMMARISED_ACCOUNTING_REGIMES = frozenset({SHIFT_SCHEDULE, TWENTY_FOUR_HOUR_DUTY})


class CompensableHoursPolicy:
    """Отбирает из `HoursBreakdown` то, что подлежит компенсации."""

    def compensable(
        self, *, breakdown: CompensableHours, regime_type: str
    ) -> CompensableHours:
        if regime_type == UNSTANDARDIZED:
            # п. 13: компенсация не предоставляется. Дополнительный отпуск
            # за ненормированный служебный день — раздел V приказа и
            # предмет `leave_management`.
            return _nothing()

        if regime_type in SUMMARISED_ACCOUNTING_REGIMES:
            # п. 14: ночные, праздничные и выходные часы в пределах нормы
            # не компенсируются. Остаётся переработка — превышение нормы
            # периода (п. 10).
            return CompensableHours(
                night_hours=Decimal(0),
                holiday_hours=Decimal(0),
                weekend_hours=Decimal(0),
                overtime_hours=breakdown.overtime_hours,
            )

        # Пятидневка (и всё, что не названо выше): п. 11 без изъятий.
        return breakdown


def _nothing() -> CompensableHours:
    return CompensableHours(
        night_hours=Decimal(0),
        holiday_hours=Decimal(0),
        weekend_hours=Decimal(0),
        overtime_hours=Decimal(0),
    )
