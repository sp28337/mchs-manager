"""Доменные исключения Compensation."""

from __future__ import annotations


class CompensationDomainError(Exception):
    """База для всех ошибок доменного слоя этого модуля."""


class TimesheetNotApprovedError(CompensationDomainError):
    """Domain Model инвариант 7.1.1: дело о компенсации не может быть
    создано, пока табель того же сотрудника и периода не утверждён —
    компенсация не может опережать факт.

    Факт межмодульный (статус живёт в `time_accounting`), поэтому
    проверяется обработчиком через контракт, а не агрегатом.
    Отображается в 422."""


class CompensationExceedsFactError(CompensationDomainError):
    """Domain Model инвариант 7.1.2: сумма часов компенсации по категории
    не может превышать соответствующее значение `HoursBreakdown`.

    Формулировка документа — «компенсация не может „придумывать" часы
    сверх зафиксированного факта». Это и есть главный инвариант всего
    модуля: он отделяет начисление от выдумки. Отображается в 422."""


class CaseFinalizedError(CompensationDomainError):
    """Domain Model инвариант 7.1.4: финализированное дело неизменяемо.

    В отличие от табеля, у дела нет «переоткрытия»: начисление уже
    произошло — деньги выплачены или сутки зачтены в баланс ДДО, — и
    отменить его задним числом нельзя. Исправление оформляется НОВЫМ
    делом-корректировкой со ссылкой на исправляемое. Отображается в 423."""


class ElectionNotApplicableError(CompensationDomainError):
    """Domain Model инвариант 7.1.3: выбор формы запрашивается только у
    тех категорий, чья действующая `RuleVersion` его допускает.

    ТК РФ ст. 152 и 153 дают работнику выбор между повышенной оплатой и
    дополнительным временем отдыха, но не для всякой категории часов, и
    применимость выбора — атрибут ПРАВИЛА, а не жёстко закодированное
    условие. Отображается в 422."""


class EmptyCompensationCaseError(CompensationDomainError):
    """Финализировать дело без единой строки нельзя.

    Пустое дело означало бы «компенсация определена окончательно и равна
    ничему», что неотличимо от «расчёт не выполнялся». Если компенсировать
    нечего, дело просто не заводится (Алгоритм К шаг 2 — только непустые
    категории). Отображается в 422."""


class CaseNotFoundError(CompensationDomainError):
    """Дело не найдено. Отображается в 404."""


class CaseAlreadyExistsError(CompensationDomainError):
    """`uq_compensation_case_employee_period` — на пару «сотрудник +
    период» действующее дело одно. Отображается в 409."""
