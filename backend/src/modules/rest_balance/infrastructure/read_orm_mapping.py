"""RB003/RB007 — read-сторона: материализованное представление остатка.

Отдельный `MetaData` от write-стороны и никакого маппинга на класс:
`current_balance` — не сущность, а сумма журнала, и загружать её в
агрегат означало бы завести второй ответ на вопрос «каков остаток».

--- Зачем оно вообще, если агрегат считает сам ------------------------

Затем, что вопросы разные. Агрегату остаток нужен, чтобы ОТКАЗАТЬ в
списании, и считать его он обязан по журналу — иначе проверка опирается
на данные, отставшие на неизвестное время.

Экрану сотрудника остаток нужен, чтобы ПОКАЗАТЬ. Загружать ради этого
весь журнал службы на каждое открытие страницы значило бы платить за
точность, которой у показанного числа всё равно нет: пока страница
рисуется, движение может появиться.

--- Чем это отличается от денормализации -------------------------------

Тем, что представление невозможно рассинхронизировать правкой:
`REFRESH` пересчитывает его из журнала целиком. Хранимая колонка
`balance_days` требовала бы, чтобы каждый пишущий её обновил, и первый же
забытый путь дал бы расхождение, которое никто не заметит.
"""

from __future__ import annotations

from sqlalchemy import Column, MetaData, Numeric, Table
from sqlalchemy.dialects.postgresql import UUID as PgUUID

read_metadata = MetaData(schema="rest_balance")

current_balance_view = Table(
    "current_balance",
    read_metadata,
    Column("employee_id", PgUUID(as_uuid=True), primary_key=True),
    Column("balance_days", Numeric(8, 2), nullable=False),
)
