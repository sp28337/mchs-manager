"""Доменные исключения LeaveManagement."""

from __future__ import annotations


class LeaveManagementDomainError(Exception):
    """База для всех ошибок доменного слоя этого модуля."""


class LeavePeriodOverlapError(LeaveManagementDomainError):
    """Domain Model инвариант 9.1.1: периоды отпуска одного сотрудника не
    пересекаются.

    Смежные периоды пересечением НЕ являются — документ называет это
    «присоединением... стыковкой границ», и полуинтервал `[start, end)`
    выражает разницу сам. Отказ здесь означает настоящее наложение, а не
    стык.

    Отображается в 409 (`openapi.yaml`: «пересечение с существующим
    отпуском сотрудника»)."""


class OncePerServiceLeaveError(LeaveManagementDomainError):
    """Domain Model инвариант 9.1.2: отпуск по личным обстоятельствам при
    стаже 20+ лет (ФЗ-141 ст. 64 ч. 1 п. 2) выдаётся не более одного раза
    за весь период службы.

    Проверка межагрегатная — нужна вся история предоставлений
    сотрудника, — поэтому выполняется доменным сервисом
    (`LeaveEligibilityService`, Domain Model разд. 10.4), а последнее
    слово остаётся за частичным уникальным индексом: два одновременных
    приказа увидели бы одинаковое «ещё не выдавался».

    Отображается в 422."""


class ScheduleConflictError(LeaveManagementDomainError):
    """Domain Model инвариант 9.1.4: отпуск не может быть предоставлен на
    даты уже утверждённой плановой смены того же сотрудника без отмены
    или переноса этой смены.

    Согласованность между контекстами обеспечивается доменным сервисом, а
    не ссылкой между агрегатами разных контекстов: `leave_management`
    спрашивает `scheduling` через контракт и получает проекцию, а не
    чужой агрегат.

    Отображается в 409: это конфликт состояния, а не ошибка ввода —
    запрос станет исполнимым, как только смену перенесут."""


class LeaveGrantNotFoundError(LeaveManagementDomainError):
    """Отпуск не найден. Отображается в 404."""


class LeaveNotRecallableError(LeaveManagementDomainError):
    """Отозвать можно только из действующего отпуска.

    Отзыв из завершённого означал бы прерывание того, что уже
    закончилось; из отменённого — того, чего не было. Повторный отзыв из
    уже прерванного отпуска тоже отвергается: сотрудник в него не
    возвращался, прерывать нечего.

    Отображается в 422."""


class RecallOutsideLeaveError(LeaveManagementDomainError):
    """Дата прерывания обязана попадать в период отпуска.

    Отзыв «с даты», лежащей вне отпуска, не прерывает ничего: либо
    сотрудник ещё не ушёл, либо уже вышел. И то и другое означает, что
    приказ оформлен не тем документом.

    Отображается в 422."""


class LeaveImmutableError(LeaveManagementDomainError):
    """Сотрудник, тип и период предоставления неизменяемы.

    Ошибочное предоставление отменяется и оформляется заново, а не
    переписывается: приказ об отпуске — документ, и правка его содержания
    задним числом означала бы подмену документа. Зеркало
    `trg_leave_grant_immutability`.

    Отображается в 423."""
