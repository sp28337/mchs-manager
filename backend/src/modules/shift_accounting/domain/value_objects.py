"""Кем человек работает и по какой норме — величины, из которых
выводится весь расчёт.

Ни Pydantic, ни SQLAlchemy: домен не зависит от инфраструктуры.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date, timedelta
from decimal import Decimal
from enum import StrEnum


class EmploymentKind(StrEnum):
    """Основание, по которому человек несёт службу или работает.

    Различие не формальное: от него зависит, каким законом считается
    время. Сотрудник ФПС ГПС служит по ФЗ-141, вольнонаёмный работник
    той же части работает по Трудовому кодексу, и нормы у них разные —
    вплоть до того, что одни и те же часы у двоих в одном карауле
    компенсируются по-разному.
    """

    ATTESTED = "attested"
    """Аттестованный сотрудник ФПС ГПС. ФЗ-141 от 23.05.2016."""

    CIVILIAN = "civilian"
    """Вольнонаёмный работник. Трудовой кодекс РФ."""


class Gender(StrEnum):
    """Пол.

    Нужен не для анкеты. Приказ МЧС России от 24.04.2026 № 308 п. 1 даёт
    36-часовую неделю сотрудницам, проходящим службу в районах Крайнего
    Севера, приравненных к ним и других местностях с неблагоприятными
    условиями; Приказ № 307 п. 4 — то же работницам по ст. 320 ТК РФ.
    Без этого признака их норма считалась бы по 40 часам, то есть
    завышенной, а завышенная норма прячет переработку.
    """

    MALE = "male"
    FEMALE = "female"


class WorkingConditions(StrEnum):
    """Условия по результатам специальной оценки.

    `HARMFUL_OR_DANGEROUS` — вредные условия 3-й или 4-й степени либо
    опасные: Приказ № 308 п. 1 и Приказ № 307 п. 6 дают в этом случае 36
    часов в неделю.
    """

    NORMAL = "normal"
    HARMFUL_OR_DANGEROUS = "harmful_or_dangerous"


class AccountingPeriodKind(StrEnum):
    """Учётный период при суммированном учёте.

    Состав вариантов РАЗНЫЙ у сотрудников и работников, и это не
    придирка: Приказ № 308 п. 2 допускает сотруднику только полугодие или
    год, тогда как Приказ № 307 п. 7 разрешает работнику ещё и три
    месяца. Предлагать сотруднику квартал значило бы предлагать период, в
    котором его переработку считать нельзя.
    """

    QUARTER = "quarter"
    HALF_YEAR = "half_year"
    YEAR = "year"


ACCOUNTING_PERIODS: dict[EmploymentKind, tuple[AccountingPeriodKind, ...]] = {
    EmploymentKind.ATTESTED: (AccountingPeriodKind.HALF_YEAR, AccountingPeriodKind.YEAR),
    EmploymentKind.CIVILIAN: (
        AccountingPeriodKind.QUARTER,
        AccountingPeriodKind.HALF_YEAR,
        AccountingPeriodKind.YEAR,
    ),
}


class GuardNumber(StrEnum):
    """Номер караула: при дежурстве сутки через трое их ровно четыре.

    Караул — не должность и не подразделение, а место в цикле. Он
    определяет одно: в какие сутки человек заступает.
    """

    FIRST = "1"
    SECOND = "2"
    THIRD = "3"
    FOURTH = "4"


class AbsenceKind(StrEnum):
    """Причина отсутствия на смене.

    Все перечисленные — освобождение от исполнения обязанностей С
    СОХРАНЕНИЕМ места работы, и это их общее свойство важнее различий:
    именно оно означает, что часы по графику, попавшие в такой период,
    ИСКЛЮЧАЮТСЯ ИЗ НОРМЫ учётного периода (письмо Роструда от 01.03.2010
    № 550-6-1).

    Отсюда же и различие с прогулом, которого в этом перечне нет:
    неуважительное отсутствие норму не уменьшает.
    """

    ANNUAL_LEAVE = "annual_leave"
    """Основной отпуск (ст. 63 ФЗ-141, ст. 114 ТК РФ)."""

    SICK_LEAVE = "sick_leave"
    """Временная нетрудоспособность."""

    STUDY_LEAVE = "study_leave"
    """Учебный отпуск (ст. 173-177 ТК РФ)."""

    UNPAID_LEAVE = "unpaid_leave"
    """Отпуск без сохранения денежного довольствия или заработной платы."""

    BUSINESS_TRIP = "business_trip"
    """Служебная командировка."""

    OTHER_EXCUSED = "other_excused"
    """Иное освобождение с сохранением места службы или работы."""


ABSENCE_KIND_BASIS: dict[AbsenceKind, str] = {
    AbsenceKind.ANNUAL_LEAVE: "ст. 63 ФЗ-141; ст. 114 ТК РФ",
    AbsenceKind.SICK_LEAVE: "ст. 65 ФЗ-141; ст. 183 ТК РФ",
    AbsenceKind.STUDY_LEAVE: "ст. 173-177 ТК РФ",
    AbsenceKind.UNPAID_LEAVE: "ст. 64 ФЗ-141; ст. 128 ТК РФ",
    AbsenceKind.BUSINESS_TRIP: "ст. 166-168 ТК РФ",
    AbsenceKind.OTHER_EXCUSED: "письмо Роструда от 01.03.2010 № 550-6-1",
}


# --------------------------------------------------------------- норма

FULL_WEEKLY_HOURS = Decimal("40")
"""Приказ № 308 п. 1 (ч. 2 ст. 54 ФЗ-141); Приказ № 307 п. 3 (ч. 2 ст. 91 ТК РФ)."""

REDUCED_WEEKLY_HOURS = Decimal("36")
"""Приказ № 308 п. 1 и Приказ № 307 пп. 4, 6."""

DISABILITY_WEEKLY_HOURS = Decimal("35")
"""Приказ № 307 п. 5 (абз. 4 ч. 1 ст. 92 ТК РФ) — инвалиды I или II группы."""


@dataclass(frozen=True)
class WeeklyNorm:
    """Недельная норма вместе с основанием, по которому она получена.

    Основание хранится рядом с числом намеренно. Весь смысл этой системы
    в том, чтобы человек мог возразить работодателю; «36 часов» без
    ссылки на норму — это мнение, а «36 часов, Приказ МЧС России от
    24.04.2026 № 308 п. 1» — довод.
    """

    hours: Decimal
    basis: str

    @property
    def is_reduced(self) -> bool:
        return self.hours < FULL_WEEKLY_HOURS


def derive_weekly_norm(
    *,
    employment: EmploymentKind,
    gender: Gender,
    conditions: WorkingConditions,
    northern_locality: bool,
    disability_group_i_or_ii: bool = False,
) -> WeeklyNorm:
    """Недельная норма по признакам человека.

    Источники — приказы МЧС России от 24.04.2026 № 307 (работники без
    званий) и № 308 (сотрудники), оба специально о СМЕННОЙ работе, то
    есть ровно о том режиме, который считает это приложение.

    --- Порядок проверок --------------------------------------------------

    Сокращения не складываются: два основания по 36 часов дают 36, а не
    32. Поэтому проверки идут по убыванию силы основания, и первое
    сработавшее и есть ответ. Инвалидность проверяется первой, потому что
    даёт самую короткую неделю — 35 часов; поставь её ниже, и работник с
    инвалидностью во вредных условиях получил бы 36 вместо 35.

    --- Северное сокращение у сотрудников и работников разное -------------

    У работника (Приказ № 307 п. 4, ст. 320 ТК РФ) это районы Крайнего
    Севера и приравненные к ним местности. У сотрудника (Приказ № 308
    п. 1, ч. 4 ст. 54 ФЗ-141) круг шире: к ним добавлены «другие
    местности с неблагоприятными климатическими или экологическими
    условиями, в том числе отдалённые». Разница существенна для того, кто
    служит вне Севера, но в отдалённой местности: у него норма 36, а не
    40, и по Трудовому кодексу этого сокращения не было бы.
    """
    if disability_group_i_or_ii and employment is EmploymentKind.CIVILIAN:
        return WeeklyNorm(
            hours=DISABILITY_WEEKLY_HOURS,
            basis="Приказ МЧС России № 307 п. 5 (абз. 4 ч. 1 ст. 92 ТК РФ), "
            "инвалидность I или II группы",
        )

    if conditions is WorkingConditions.HARMFUL_OR_DANGEROUS:
        basis = (
            "Приказ МЧС России № 308 п. 1 (ч. 2 ст. 54 ФЗ-141), "
            "вредные или опасные условия"
            if employment is EmploymentKind.ATTESTED
            else "Приказ МЧС России № 307 п. 6 (абз. 5 ч. 1 ст. 92 ТК РФ), "
            "вредные условия 3-4 степени либо опасные"
        )
        return WeeklyNorm(hours=REDUCED_WEEKLY_HOURS, basis=basis)

    if gender is Gender.FEMALE and northern_locality:
        basis = (
            "Приказ МЧС России № 308 п. 1 (ч. 4 ст. 54 ФЗ-141): женщины в "
            "районах Крайнего Севера, приравненных к ним и других местностях "
            "с неблагоприятными условиями"
            if employment is EmploymentKind.ATTESTED
            else "Приказ МЧС России № 307 п. 4 (ст. 320 ТК РФ): женщины в "
            "районах Крайнего Севера и приравненных к ним местностях"
        )
        return WeeklyNorm(hours=REDUCED_WEEKLY_HOURS, basis=basis)

    basis = (
        "Приказ МЧС России № 308 п. 1 (ч. 2 ст. 54 ФЗ-141)"
        if employment is EmploymentKind.ATTESTED
        else "Приказ МЧС России № 307 п. 3 (ч. 2 ст. 91 ТК РФ)"
    )
    return WeeklyNorm(hours=FULL_WEEKLY_HOURS, basis=basis)


# ------------------------------------------------------------- дежурство

SHIFT_CYCLE_DAYS = 4
"""Сутки через трое: заступил — и через четверо суток снова."""

SHIFT_DURATION_HOURS = Decimal("24")
"""Приказ № 308 п. 3 и Приказ № 307 п. 8: продолжительность смены
рассчитывается исходя из 24 часов, не включая время смены караулов."""

MAX_UNPAID_BREAK_HOURS = Decimal("2")
"""Приказ № 307 п. 10: перерывы для отдыха и питания общей
продолжительностью НЕ БОЛЕЕ ДВУХ ЧАСОВ и не менее 30 минут, которые в
рабочее время не включаются (ч. 1 ст. 108 ТК РФ).

Оговорка есть только у РАБОТНИКОВ. Приказ № 308 п. 5 требует
сотруднику перерывы не менее 30 минут, но из служебного времени их не
исключает — и это не оплошность составителя, а разница в природе
отношений.

При этом п. 11 Приказа № 307 и п. 6 Приказа № 308 говорят одно: там, где
перерыв предоставить невозможно, отдых и приём пищи происходят ВО ВРЕМЯ
исполнения обязанностей — то есть внутри смены. Для караула на дежурстве
это обычный случай, поэтому умолчание здесь — ноль."""

SHIFT_START_HOUR = 8
"""Развод караула — 08:00. Смена длится ровно сутки, до 08:00 следующего дня."""

NIGHT_HOURS_PER_SHIFT = Decimal("8")
"""С 22:00 до 06:00 (ст. 96 ТК РФ) — внутри суточной смены это ровно 8 часов."""


@dataclass(frozen=True)
class GuardCycle:
    """График караула на год: номер караула и дата его первой смены.

    --- Почему хранится дата, а не только номер ---------------------------

    Номер караула сам по себе цикл не задаёт. В одной части первый караул
    заступает 1 января, в другой — 3-го, и «караул № 1» в этих двух
    частях дежурит в разные сутки. Дата первой смены — единственное, что
    однозначно привязывает цикл к календарю; номер остаётся тем, как
    человек свой караул называет.
    """

    guard: GuardNumber
    first_shift_date: date

    def shift_dates(self, period_start: date, period_end: date) -> list[date]:
        """Даты ЗАСТУПЛЕНИЯ в полуинтервале `[period_start, period_end)`.

        Возвращается день начала смены. Смена заканчивается в 08:00
        следующих суток, и последние 8 часов приходятся уже на него —
        поэтому «сколько смен в марте» и «сколько часов в марте» это
        разные вопросы (см. `hours_falling_in`).
        """
        if period_end <= period_start:
            return []

        # Ближайшее заступление не раньше начала периода. Считается
        # арифметикой, а не перебором с первой смены: перебор по году —
        # 365 итераций там, где хватает одного деления, и он молча
        # ломается на периоде, начинающемся раньше первой смены.
        delta = (period_start - self.first_shift_date).days
        steps = -(-delta // SHIFT_CYCLE_DAYS) if delta > 0 else 0
        cursor = self.first_shift_date + timedelta(days=steps * SHIFT_CYCLE_DAYS)

        dates: list[date] = []
        while cursor < period_end:
            if cursor >= period_start:
                dates.append(cursor)
            cursor += timedelta(days=SHIFT_CYCLE_DAYS)
        return dates
